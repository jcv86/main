export type Language = keyof typeof translations
export type TranslationKey = keyof typeof translations.es

export function getTranslation(key: TranslationKey, language: Language = "es"): string {
  return translations[language][key] || translations.es[key] || key
}

// Chilean-specific formatting functions
export function formatChileanCurrency(amount: number): string {
  return new Intl.NumberFormat("es-CL", {
    style: "currency",
    currency: "CLP",
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount)
}

export function formatChileanDate(date: Date): string {
  return new Intl.DateTimeFormat("es-CL", {
    year: "numeric",
    month: "long",
    day: "numeric",
  }).format(date)
}

export function formatChileanPhone(phone: string): string {
  // Format Chilean phone numbers (+56 9 XXXX XXXX)
  const cleaned = phone.replace(/\D/g, "")
  if (cleaned.length === 8) {
    return `${cleaned.slice(0, 4)} ${cleaned.slice(4)}`
  } else if (cleaned.length === 9 && cleaned.startsWith("9")) {
    return `9 ${cleaned.slice(1, 5)} ${cleaned.slice(5)}`
  } else if (cleaned.length === 11 && cleaned.startsWith("569")) {
    return `+56 9 ${cleaned.slice(3, 7)} ${cleaned.slice(7)}`
  }
  return phone
}

// Chilean RUT validation and formatting
export function formatChileanRUT(rut: string): string {
  const cleaned = rut.replace(/[^0-9kK]/g, "")
  if (cleaned.length < 2) return cleaned

  const body = cleaned.slice(0, -1)
  const dv = cleaned.slice(-1).toUpperCase()

  const formatted = body.replace(/\B(?=(\d{3})+(?!\d))/g, ".")
  return `${formatted}-${dv}`
}

export function validateChileanRUT(rut: string): boolean {
  const cleaned = rut.replace(/[^0-9kK]/g, "")
  if (cleaned.length < 2) return false

  const body = cleaned.slice(0, -1)
  const dv = cleaned.slice(-1).toUpperCase()

  let sum = 0
  let multiplier = 2

  for (let i = body.length - 1; i >= 0; i--) {
    sum += Number.parseInt(body[i]) * multiplier
    multiplier = multiplier === 7 ? 2 : multiplier + 1
  }

  const remainder = sum % 11
  const calculatedDV = remainder < 2 ? remainder.toString() : remainder === 10 ? "K" : (11 - remainder).toString()

  return dv === calculatedDV
}

// Chilean address formatting
export function formatChileanAddress(address: {
  street: string
  number: string
  commune: string
  city: string
  region: string
}): string {
  return `${address.street} ${address.number}, ${address.commune}, ${address.city}, ${address.region}`
}

// Chilean work schedule formatting
export function formatChileanWorkSchedule(schedule: {
  start: string
  end: string
  lunchBreak?: boolean
}): string {
  const lunchText = schedule.lunchBreak ? " (con colación)" : ""
  return `${schedule.start} a ${schedule.end}${lunchText}`
}

