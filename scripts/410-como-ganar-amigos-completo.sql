## PARTE 3: LOGRE QUE LOS DEMÁS PIENSEN COMO USTED

### PRINCIPIO 1: La Única Forma de Salir Ganando de una Discusión es Evitándola

**La Verdad Sobre las Discusiones:**
No puedes ganar una discusión. Si pierdes, pierdes. Si ganas, pierdes (porque la otra persona se resiente).

**Ejemplo - Benjamin Franklin:**
En su juventud, Franklin era argumentativo. Un amigo le dijo: "Ben, tus opiniones tienen tanto peso como un plomo. Nadie te escucha porque siempre estás discutiendo."

Franklin cambió su enfoque y se convirtió en uno de los diplomáticos más efectivos de la historia.

**Cómo Evitar Discusiones:**

1. **Acepta el Desacuerdo:**
   - "Entiendo tu punto de vista"
   - "Esa es una perspectiva interesante"

2. **Busca Puntos en Común:**
   - "Estamos de acuerdo en que..."
   - "Ambos queremos..."

3. **Pospón la Decisión:**
   - "Déjame pensar en eso"
   - "Consideremos ambas opciones"

4. **Agradece la Opinión:**
   - "Gracias por compartir tu perspectiva"
   - "Aprecio que me hayas hecho pensar en esto"

**Cuando Alguien Te Ataca:**
- No te defiendas inmediatamente
- Escucha completamente
- Busca la verdad en su crítica
- Agradece su honestidad

### PRINCIPIO 2: Demuestra Respeto por las Opiniones Ajenas. Jamás Digas "Estás Equivocado"

**Por Qué Nunca Decir "Estás Equivocado":**
Cuando dices "estás equivocado", realmente estás diciendo: "Soy más inteligente que tú." Esto hiere el orgullo y crea resistencia.

**Alternativas Efectivas:**

En lugar de: "Estás equivocado"
Di: "Puede ser que yo esté equivocado. Frecuentemente lo estoy. Examinemos los hechos."

En lugar de: "Eso no funcionará"
Di: "Entiendo tu punto. ¿Has considerado...?"

En lugar de: "Esa es una mala idea"
Di: "Esa es una perspectiva interesante. ¿Qué opinas de esta alternativa?"

**La Técnica de Sócrates:**
Sócrates nunca decía "estás equivocado". En su lugar, hacía preguntas que llevaban a la persona a su propia conclusión.

**Ejemplo:**
Persona: "Deberíamos lanzar el producto mañana."
Tú: "¿Hemos completado todas las pruebas de calidad?"
Persona: "Bueno, no todas..."
Tú: "¿Qué podría pasar si lanzamos sin completar las pruebas?"
Persona: "Supongo que podríamos tener problemas... Quizás deberíamos esperar."

### PRINCIPIO 3: Si Te Equivocas, Admítelo Rápida y Enfáticamente

**El Poder de la Admisión:**
Cuando admites un error rápidamente, desarmas a tu crítico y a menudo conviertes una situación negativa en positiva.

**Ejemplo - Dale Carnegie:**
Carnegie paseaba a su perro sin correa (violando la ley). Un policía lo confrontó. En lugar de hacer excusas, Carnegie dijo:

"Oficial, tiene toda la razón y yo estoy completamente equivocado. No tengo excusa. Este perro ha desobedecido la ley varias veces."

El policía respondió: "Bueno, sé que es un perro bueno. Solo manténgalo con correa en esta área."

**Cómo Admitir Errores:**

1. **Hazlo Rápidamente:**
   - No esperes a que te descubran
   - Admite el error tan pronto como lo notes

2. **Hazlo Completamente:**
   - No minimices
   - No hagas excusas
   - Toma responsabilidad total

3. **Hazlo Sinceramente:**
   - "Cometí un error"
   - "Fue mi culpa"
   - "Lo siento"

4. **Ofrece una Solución:**
   - "Aquí está cómo lo corregiré"
   - "Esto es lo que haré para que no vuelva a pasar"

**Beneficios:**
- Desarma la crítica
- Genera respeto
- Resuelve conflictos rápidamente
- Te libera de la culpa

### PRINCIPIO 4: Empieza de Manera Amigable

**El Principio:**
"Una gota de miel caza más moscas que un galón de hiel."

**Ejemplo - John D. Rockefeller Jr.:**
Cuando los trabajadores de Rockefeller estaban en huelga y amenazaban con violencia, Rockefeller no los confrontó. En su lugar, dio un discurso que comenzaba:

"Este es un día rojo en mi vida. Es la primera vez que tengo el placer de reunirme con los representantes de los empleados de esta gran compañía..."

Continuó con elogios y amabilidad. La huelga terminó pacíficamente.

**Cómo Empezar Amigablemente:**

1. **Sonríe:**
   - Comienza con una sonrisa genuina

2. **Encuentra Terreno Común:**
   - "Ambos queremos lo mejor para la empresa"
   - "Sé que ambos valoramos la calidad"

3. **Elogia Primero:**
   - "Aprecio todo el trabajo que has hecho"
   - "Valoro tu dedicación"

4. **Usa un Tono Amigable:**
   - Cálido, no frío
   - Conversacional, no confrontacional

**Ejemplo Práctico:**

**Mal Enfoque:**
"Tu reporte está lleno de errores. Necesitas rehacerlo."

**Buen Enfoque:**
"Gracias por trabajar en este reporte. Veo que pusiste mucho esfuerzo. Encontré algunas áreas donde podemos mejorar la precisión. ¿Podemos revisarlas juntos?"

### PRINCIPIO 5: Consigue que la Otra Persona Diga "Sí, Sí" Inmediatamente

**La Técnica Socrática:**
Comienza haciendo preguntas con las que la otra persona estará de acuerdo. Esto crea momentum positivo.

**Por Qué Funciona:**
Cuando alguien dice "sí", su mente y cuerpo se mueven en dirección de aceptación. Es psicológicamente difícil cambiar de "sí" a "no".

**Ejemplo - Vendedor:**

**Mal Enfoque:**
"¿Quieres comprar este producto?"

**Buen Enfoque:**
"¿Estás buscando una solución que ahorre tiempo?" (Sí)
"¿Te gustaría reducir costos?" (Sí)
"¿Valoras la calidad?" (Sí)
"Entonces déjame mostrarte cómo este producto hace exactamente eso."

**Cómo Aplicarlo:**

1. **Identifica Puntos de Acuerdo:**
   - ¿En qué están de acuerdo ambos?

2. **Haz Preguntas que Generen "Sí":**
   - "¿Estás de acuerdo en que...?"
   - "¿No es cierto que...?"

3. **Construye Momentum:**
   - Varias respuestas "sí" seguidas

4. **Presenta Tu Punto:**
   - Después de establecer acuerdo

**Advertencia:**
No manipules. Usa esto éticamente para encontrar terreno común genuino.

### PRINCIPIO 6: Permite que la Otra Persona Hable Más

**La Verdad:**
Las personas prefieren hablar que escuchar. Déjalas.

**Beneficios:**

1. **Obtienen Información:**
   - Aprendes lo que realmente piensan
   - Descubres sus verdaderas preocupaciones

2. **Reducen Resistencia:**
   - Desahogan sus frustraciones
   - Se sienten escuchados

3. **Llegan a Sus Propias Conclusiones:**
   - A menudo se convencen a sí mismos
   - Las conclusiones propias son más poderosas

**Ejemplo - Terapeuta:**
Los buenos terapeutas hablan poco. Hacen preguntas y escuchan. El paciente hace el trabajo de descubrimiento.

**Cómo Aplicarlo:**

1. **Haz Preguntas Abiertas:**
   - "¿Qué piensas sobre...?"
   - "¿Cómo te sientes acerca de...?"
   - "Cuéntame más sobre..."

2. **Escucha Activamente:**
   - No interrumpas
   - No planees tu respuesta mientras hablan
   - Realmente escucha

3. **Anima a Continuar:**
   - "Interesante, continúa"
   - "¿Y luego qué pasó?"
   - Asiente y muestra interés

4. **Resiste el Impulso de Hablar:**
   - Los silencios están bien
   - Deja que piensen

### PRINCIPIO 7: Permite que la Otra Persona Sienta que la Idea es Suya

**El Principio:**
Las personas apoyan sus propias ideas con mucho más entusiasmo que las ideas de otros.

**Ejemplo - Coronel Edward House:**
House era asesor del Presidente Woodrow Wilson. Su método para influir en Wilson:

Plantaba una idea casualmente en conversación. Semanas después, Wilson presentaba la misma idea como propia. House nunca reclamaba crédito.

Resultado: House fue uno de los asesores más influyentes en la historia de EE.UU.

**Cómo Aplicarlo:**

1. **Planta Semillas:**
   - "¿Qué opinas de...?"
   - "Me pregunto si..."
   - "¿Has considerado...?"

2. **Haz Preguntas que Guíen:**
   - "¿Cómo podríamos mejorar esto?"
   - "¿Qué pasaría si...?"

3. **Deja que Desarrollen la Idea:**
   - No la presentes completamente formada
   - Deja espacio para su contribución

4. **Dales Crédito:**
   - "Esa es una gran idea que tuviste"
   - "Me encanta cómo pensaste en eso"

**Ejemplo Práctico:**

**Quieres:** Que tu equipo implemente un nuevo sistema

**Mal Enfoque:**
"Vamos a implementar este nuevo sistema que encontré."

**Buen Enfoque:**
"Nuestro sistema actual tiene algunos desafíos. ¿Qué ideas tienen para mejorarlo?"
[Escucha sus ideas]
"Esas son excelentes sugerencias. ¿Qué piensan de combinarlas con...?"
[Guía hacia tu solución]
"¡Excelente! Implementemos el sistema que diseñamos juntos."

### PRINCIPIO 8: Trata Honradamente de Ver las Cosas desde el Punto de Vista de la Otra Persona

**La Clave de las Relaciones:**
"Ver las cosas desde el punto de vista de la otra persona y despertar en ella un deseo vehemente."

**Cómo Desarrollar Esta Habilidad:**

1. **Pregúntate:**
   - "¿Por qué piensa así?"
   - "¿Qué experiencias lo llevaron a esta conclusión?"
   - "¿Qué necesidades está tratando de satisfacer?"

2. **Escucha para Entender:**
   - No para responder
   - No para juzgar
   - Para realmente comprender

3. **Valida Sus Sentimientos:**
   - "Entiendo por qué te sientes así"
   - "En tu situación, yo probablemente sentiría lo mismo"

4. **Busca la Lógica:**
   - Toda persona tiene razones para sus acciones
   - Encuentra esas razones

**Ejemplo - Conflicto Laboral:**

**Situación:** Un empleado llega tarde constantemente

**Enfoque Pobre:**
"Eres irresponsable. Si sigues llegando tarde, te despediré."

**Enfoque Empático:**
"He notado que has llegado tarde últimamente. ¿Está todo bien? ¿Hay algo con lo que pueda ayudarte?"

[Descubres que tiene problemas de cuidado infantil]

"Entiendo. Eso debe ser muy estresante. ¿Qué te parecería si ajustamos tu horario para que comiences 30 minutos más tarde y termines 30 minutos más tarde? Así podrías dejar a tu hijo en la guardería."

### PRINCIPIO 9: Muestra Simpatía por las Ideas y Deseos de la Otra Persona

**La Frase Mágica:**
"No te culpo por sentirte así. Si yo estuviera en tu lugar, me sentiría exactamente igual."

**Por Qué Funciona:**
- Valida sus sentimientos
- Reduce defensividad
- Crea conexión
- Abre la puerta al diálogo

**Cómo Aplicarlo:**

1. **Reconoce Sus Sentimientos:**
   - "Veo que estás frustrado"
   - "Entiendo que esto es importante para ti"

2. **Valida Sus Sentimientos:**
   - "Tienes derecho a sentirte así"
   - "Tus sentimientos son completamente comprensibles"

3. **Muestra Empatía:**
   - "Si yo estuviera en tu situación, probablemente me sentiría igual"
   - "Puedo imaginar lo difícil que debe ser esto para ti"

4. **Ofrece Apoyo:**
   - "¿Cómo puedo ayudarte?"
   - "¿Qué necesitas de mí?"

**Ejemplo - Cliente Enojado:**

Cliente: "¡Este producto no funciona! ¡Quiero mi dinero de vuelta!"

**Respuesta Pobre:**
"El producto funciona perfectamente. Probablemente lo estás usando mal."

**Respuesta Empática:**
"Entiendo completamente tu frustración. Si yo comprara algo que no funcionara como esperaba, también estaría molesto. Déjame ver cómo puedo resolver esto para ti. ¿Puedes contarme exactamente qué está pasando?"

### PRINCIPIO 10: Apela a los Motivos Más Nobles

**El Principio:**
Toda persona tiene dos razones para hacer algo: una razón que suena bien y la razón real. La persona misma pensará en la razón real. Tú apela a la razón noble.

**Ejemplo - J.P. Morgan:**
Cuando Morgan quería que alguien hiciera algo, apelaba a su sentido de honor, justicia o servicio.

**Cómo Aplicarlo:**

1. **Identifica el Motivo Noble:**
   - Justicia
   - Honestidad
   - Servicio
   - Excelencia
   - Integridad

2. **Apela a Ese Motivo:**
   - "Sé que valoras la honestidad..."
   - "Como alguien que se preocupa por la calidad..."
   - "Dado tu compromiso con la excelencia..."

3. **Confía en Su Mejor Naturaleza:**
   - Asume que quieren hacer lo correcto
   - Dales la oportunidad de estar a la altura

**Ejemplo - Inquilino Ruidoso:**

**Enfoque Pobre:**
"Si no dejas de hacer ruido, llamaré a la policía."

**Enfoque Noble:**
"Sé que eres una persona considerada y que te importan tus vecinos. Probablemente no te das cuenta, pero el ruido después de las 10 PM está afectando a las familias con niños pequeños. Estoy seguro de que, como buen vecino, querrás ayudar a mantener un ambiente tranquilo para todos."

### PRINCIPIO 11: Dramatiza Tus Ideas

**El Principio:**
La verdad por sí sola no es suficiente. Debe ser vívida, interesante, dramática.

**Por Qué Funciona:**
- Captura atención
- Es memorable
- Emociona
- Persuade

**Cómo Dramatizar:**

1. **Usa Demostraciones:**
   - Muestra, no solo digas
   - Haz que sea visual

2. **Cuenta Historias:**
   - Las historias son más memorables que los hechos
   - Usa ejemplos concretos

3. **Usa Contrastes:**
   - Antes y después
   - Con y sin tu solución

4. **Crea Experiencias:**
   - Deja que experimenten el beneficio
   - Haz que sea tangible

**Ejemplo - Vendedor de Ratones para Computadora:**

**Enfoque Aburrido:**
"Este ratón tiene 1200 DPI y es ergonómico."

**Enfoque Dramático:**
[Coloca el ratón viejo y el nuevo lado a lado]
"Mira esto. Con tu ratón actual, necesitas mover tu mano 6 pulgadas para cruzar la pantalla. Con este, solo 2 pulgadas. Multiplica eso por las miles de veces que mueves el ratón cada día. Estás ahorrando millas de movimiento de mano cada semana. Menos fatiga, más productividad, menos riesgo de lesiones."

### PRINCIPIO 12: Lanza un Reto

**El Principio:**
A todos nos gusta superar obstáculos, ganar, sentir que somos importantes.

**Ejemplo - Charles Schwab:**
Schwab tenía un gerente cuyo equipo no estaba produciendo. En lugar de criticar, Schwab preguntó: "¿Cuántas unidades produjo tu equipo hoy?"

"Seis," respondió el gerente.

Schwab escribió un gran "6" en el piso con tiza y se fue sin decir nada.

Cuando el turno de noche llegó y vio el "6", preguntaron qué significaba. El turno de día explicó que el jefe había escrito cuántas unidades habían producido.

Al día siguiente, el turno de noche había borrado el "6" y escrito un "7".

Cuando el turno de día regresó y vio el "7", se sintieron desafiados. Trabajaron duro y escribieron un "10".

La producción se disparó.

**Cómo Lanzar un Reto:**

1. **Apela al Orgullo:**
   - "Sé que puedes hacer esto"
   - "Eres la persona perfecta para este desafío"

2. **Crea Competencia Amistosa:**
   - Entre equipos
   - Contra estándares previos
   - Contra la industria

3. **Establece Metas Desafiantes:**
   - No imposibles, pero difíciles
   - Que requieran esfuerzo extra

4. **Reconoce el Logro:**
   - Celebra cuando se alcanza
   - Hazlo público

**Ejemplo - Motivando a un Equipo:**

"Equipo, el año pasado procesamos 1,000 pedidos al mes. Este año, nuestro objetivo es 1,500. Sé que suena ambicioso, pero he visto lo que pueden hacer. Ustedes son el mejor equipo que he tenido. Si alguien puede lograr esto, son ustedes. ¿Están listos para el desafío?"

