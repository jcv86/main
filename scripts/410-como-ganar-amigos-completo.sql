## PARTE 4: SEA UN LÍDER - CÓMO CAMBIAR A LOS DEMÁS SIN OFENDERLOS NI DESPERTAR RESENTIMIENTOS

### PRINCIPIO 1: Comienza con Elogio y Aprecio Sincero

**El Principio:**
Es más fácil escuchar cosas desagradables después de haber escuchado elogios sobre nuestras buenas cualidades.

**La Analogía del Dentista:**
El dentista usa anestesia antes de perforar. Tú debes usar elogio antes de criticar.

**Cómo Aplicarlo:**

1. **Encuentra Algo Genuino para Elogiar:**
   - Debe ser sincero
   - Debe ser específico
   - Debe ser relevante

2. **Elogia Primero:**
   - Antes de mencionar el problema
   - Con sinceridad y detalle

3. **Luego Aborda el Problema:**
   - De manera constructiva
   - Con sugerencias específicas

**Ejemplo - Empleado con Bajo Rendimiento:**

**Mal Enfoque:**
"Tu trabajo ha sido terrible últimamente. Necesitas mejorar."

**Buen Enfoque:**
"Juan, realmente aprecio tu dedicación y cómo siempre llegas temprano. Tu actitud positiva es un gran activo para el equipo. Quiero hablar contigo sobre cómo podemos mejorar la calidad de tus reportes. ¿Tienes tiempo para que revisemos algunos ejemplos juntos?"

### PRINCIPIO 2: Llama la Atención sobre los Errores de Manera Indirecta

**El Principio:**
Llamar la atención indirectamente sobre los errores funciona maravillosamente con personas sensibles que se resienten ante la crítica directa.

**La Palabra Mágica: "Y"**

En lugar de "pero", usa "y".

**Ejemplo:**

**Con "Pero":**
"Hiciste un gran trabajo en la presentación, PERO necesitas trabajar en tu dicción."
(El "pero" borra todo lo positivo que vino antes)

**Con "Y":**
"Hiciste un gran trabajo en la presentación, Y si trabajas en tu dicción, serás aún más efectivo."
(El "y" mantiene lo positivo y agrega una sugerencia constructiva)

**Otras Técnicas Indirectas:**

1. **Haz Preguntas:**
   - "¿Qué opinas de este enfoque?"
   - "¿Cómo crees que podríamos mejorar esto?"

2. **Comparte Tu Propia Experiencia:**
   - "Cuando yo empecé, cometía el mismo error..."
   - "Aprendí que..."

3. **Usa Ejemplos Generales:**
   - "He notado que a veces en la industria..."
   - "Un error común es..."

**Ejemplo - Corrigiendo un Reporte:**

**Directo (Pobre):**
"Este reporte está mal. Los números están equivocados."

**Indirecto (Mejor):**
"Este reporte tiene mucha información valiosa. Cuando revises los números de la sección 3, ¿podrías verificar las fuentes? Quiero asegurarme de que tengamos la información más precisa posible."

### PRINCIPIO 3: Habla de Tus Propios Errores Antes de Criticar los de los Demás

**El Principio:**
Admitir tus propios errores hace que sea más fácil para otros aceptar críticas.

**Por Qué Funciona:**
- Reduce defensividad
- Muestra humildad
- Crea conexión
- Hace la crítica más aceptable

**Cómo Aplicarlo:**

1. **Comparte un Error Similar:**
   - "Cuando yo estaba en tu posición, cometí el mismo error..."
   - "Recuerdo cuando yo..."

2. **Admite Imperfección:**
   - "No soy perfecto en esto tampoco..."
   - "Todavía estoy aprendiendo..."

3. **Luego Ofrece Guía:**
   - "Lo que aprendí fue..."
   - "Lo que me ayudó fue..."

**Ejemplo - Mentor a Aprendiz:**

**Sin Admitir Errores Propios:**
"Necesitas ser más organizado. Tu escritorio es un desastre."

**Admitiendo Errores Propios:**
"Sabes, cuando empecé en esta empresa, mi escritorio era un caos total. Perdía documentos importantes constantemente. Finalmente aprendí que invertir 10 minutos al final de cada día organizando me ahorraba horas de búsqueda. ¿Te gustaría que te muestre el sistema que uso?"

### PRINCIPIO 4: Haz Preguntas en Lugar de Dar Órdenes Directas

**El Principio:**
Las preguntas hacen que las órdenes sean más aceptables y a menudo estimulan la creatividad.

**Beneficios:**

1. **Reduce Resentimiento:**
   - No se sienten mandados
   - Sienten que participan en la decisión

2. **Estimula Creatividad:**
   - Piensan en soluciones
   - Pueden encontrar mejores formas

3. **Aumenta Compromiso:**
   - Se sienten dueños de la solución
   - Más motivados a ejecutar

**Ejemplos:**

**Orden Directa:**
"Reescribe este reporte."

**Pregunta:**
"¿Qué opinas de este reporte? ¿Cómo crees que podríamos hacerlo más claro?"

**Orden Directa:**
"Necesitas llegar más temprano."

**Pregunta:**
"¿Qué podríamos hacer para asegurar que todos los proyectos comiencen a tiempo?"

**Orden Directa:**
"Limpia tu área de trabajo."

**Pregunta:**
"¿Cómo podríamos mantener el espacio de trabajo más organizado?"

### PRINCIPIO 5: Permite que la Otra Persona Salve Su Prestigio

**El Principio:**
Aun cuando tengas razón y la otra persona esté claramente equivocada, solo destruirás su ego si la haces sentir inferior.

**Ejemplo - General Electric:**
Cuando GE tenía que despedir a un ejecutivo, no lo humillaban. Le pedían su renuncia y le permitían anunciar que se iba para "perseguir otras oportunidades".

**Cómo Aplicarlo:**

1. **Ofrece una Salida Digna:**
   - "Entiendo que las circunstancias cambiaron..."
   - "Sé que tenías buenas intenciones..."

2. **No Humilles Públicamente:**
   - Crítica en privado
   - Elogio en público

3. **Permite Explicaciones:**
   - "¿Qué pasó desde tu perspectiva?"
   - "Ayúdame a entender..."

4. **Enfócate en el Futuro:**
   - "¿Cómo podemos avanzar desde aquí?"
   - "¿Qué haremos diferente la próxima vez?"

**Ejemplo - Empleado que Cometió Error Costoso:**

**Mal Enfoque:**
"¡Cometiste un error de $10,000! ¿Cómo pudiste ser tan descuidado?"

**Buen Enfoque:**
"Sé que este proyecto era complejo y había muchas variables. El error nos costó $10,000, pero entiendo que estabas trabajando bajo presión. Hablemos sobre qué sistemas podemos implementar para prevenir esto en el futuro. Tu experiencia será valiosa para diseñar esos sistemas."

### PRINCIPIO 6: Elogia el Más Pequeño Progreso y Cada Progreso. Sé "Caluroso en tu Aprobación y Generoso en tu Elogio"

**El Principio:**
Las habilidades se marchitan bajo la crítica; florecen bajo el estímulo.

**La Psicología:**
- Las personas se mueven hacia lo que se reconoce
- El elogio refuerza el comportamiento deseado
- El reconocimiento aumenta la motivación

**Cómo Aplicarlo:**

1. **Elogia Progreso, No Solo Perfección:**
   - "Veo que estás mejorando en..."
   - "Ese fue un buen primer paso..."

2. **Sé Específico:**
   - No: "Buen trabajo"
   - Sí: "La forma en que manejaste esa objeción del cliente fue excelente. Tu paciencia y creatividad resolvieron el problema."

3. **Hazlo Inmediato:**
   - Elogia tan pronto como veas el comportamiento
   - No esperes a la revisión anual

4. **Hazlo Público (Cuando Sea Apropiado):**
   - Reconoce logros frente al equipo
   - Comparte éxitos en reuniones

**Ejemplo - Entrenando a Alguien:**

**Enfoque Pobre:**
[Silencio cuando hacen algo bien, crítica cuando se equivocan]

**Enfoque Efectivo:**
"¡Excelente! Esa es exactamente la técnica correcta. Veo que estás aplicando lo que practicamos ayer. Si sigues así, dominarás esto en poco tiempo."

### PRINCIPIO 7: Atribuye a la Otra Persona una Buena Reputación para que se Interese en Mantenerla

**El Principio:**
Si quieres que alguien mejore en cierta área, actúa como si ya tuviera esa cualidad.

**Ejemplo - Niño "Problemático":**
Un maestro tenía un estudiante que constantemente interrumpía la clase. En lugar de etiquetarlo como "problemático", el maestro le dijo:

"Johnny, he notado que eres un líder natural. Los otros niños te escuchan. Me gustaría que uses ese liderazgo para ayudarme a mantener la clase enfocada. ¿Puedes ser mi asistente?"

Johnny se transformó. Ahora tenía una reputación que mantener.

**Cómo Aplicarlo:**

1. **Identifica la Cualidad Deseada:**
   - ¿Qué quieres que desarrollen?

2. **Atribúyeles Esa Cualidad:**
   - "Sé que eres una persona muy organizada..."
   - "Dado tu atención al detalle..."
   - "Como alguien que valora la puntualidad..."

3. **Dales Oportunidad de Demostrarlo:**
   - Asigna tareas que requieran esa cualidad
   - Confía en que la demostrarán

4. **Reconoce Cuando lo Hacen:**
   - "Sabía que podía contar con tu organización"
   - "Tu atención al detalle realmente brilló aquí"

**Ejemplo - Empleado Desorganizado:**

**Enfoque Pobre:**
"Eres tan desorganizado. Necesitas mejorar."

**Enfoque Efectivo:**
"He notado que cuando te enfocas, eres muy meticuloso con los detalles. Me gustaría que apliques esa misma atención a la organización de tus archivos. Sé que puedes ser tan organizado como eres detallista."

### PRINCIPIO 8: Alienta a la Otra Persona. Haz que los Errores Parezcan Fáciles de Corregir

**El Principio:**
Dile a tu hijo, esposo o empleado que es estúpido o tonto en cierta cosa, que no tiene talento para ello, y habrás destruido casi todo incentivo para tratar de mejorar.

**El Poder del Aliento:**
- Aumenta confianza
- Reduce miedo al fracaso
- Motiva a intentar
- Acelera aprendizaje

**Cómo Aplicarlo:**

1. **Minimiza la Dificultad:**
   - "Esto es más fácil de lo que parece"
   - "Con un poco de práctica, lo dominarás"

2. **Comparte Ejemplos de Éxito:**
   - "Otros en tu posición han aprendido esto rápidamente"
   - "Vi a alguien dominar esto en una semana"

3. **Divide en Pasos Pequeños:**
   - "Comencemos con solo esta parte"
   - "Una vez que domines esto, el resto será fácil"

4. **Expresa Confianza:**
   - "Sé que puedes hacer esto"
   - "Tienes todo lo necesario para tener éxito"

**Ejemplo - Enseñando Nueva Habilidad:**

**Enfoque Desalentador:**
"Esto es muy complicado. La mayoría de las personas tardan meses en aprenderlo. Probablemente tendrás dificultades."

**Enfoque Alentador:**
"Esto puede parecer complejo al principio, pero una vez que entiendes los conceptos básicos, todo encaja. He visto a personas con tu nivel de habilidad dominar esto en un par de semanas. Vamos a dividirlo en pasos simples. Comenzaremos con lo más fácil y construiremos desde ahí. Sé que lo lograrás."

### PRINCIPIO 9: Haz que la Otra Persona se Sienta Satisfecha de Hacer lo que Sugieres

**El Principio:**
Las personas están más dispuestas a hacer lo que sugieres cuando ven cómo les beneficia.

**Cómo Aplicarlo:**

1. **Conecta con Sus Metas:**
   - "Esto te ayudará a lograr..."
   - "Esto te acercará a..."

2. **Muestra Beneficios Personales:**
   - "Aprenderás..."
   - "Desarrollarás..."
   - "Ganarás..."

3. **Hazlo Atractivo:**
   - Pinta una imagen positiva
   - Enfócate en el resultado deseado

4. **Dales Autonomía:**
   - "La decisión es tuya"
   - "¿Qué te parece?"

**Ejemplo - Asignando Proyecto Difícil:**

**Enfoque Pobre:**
"Necesito que hagas este proyecto. Es urgente."

**Enfoque Efectivo:**
"Tengo un proyecto que creo que sería perfecto para ti. Es desafiante, pero te dará exposición directa con la alta gerencia. También te permitirá desarrollar habilidades en [área de interés]. Si lo haces bien, y sé que lo harás, podría abrir puertas para tu carrera. ¿Te interesa?"

