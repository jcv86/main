## PARTE 1: TÉCNICAS FUNDAMENTALES PARA TRATAR CON LAS PERSONAS

### PRINCIPIO 1: No Critiques, No Condenes, No Te Quejes

**La Verdad Fundamental:**
La crítica es inútil porque pone a una persona a la defensiva y hace que se esfuerce por justificarse. La crítica es peligrosa porque hiere el orgullo de la persona y despierta resentimiento.

**Ejemplo Histórico - Abraham Lincoln:**
En su juventud, Lincoln criticaba abiertamente a sus oponentes. Una vez escribió una carta tan mordaz que llevó a un duelo. Después de esa experiencia, nunca más escribió una carta crítica ni criticó a nadie públicamente.

Durante la Guerra Civil, cuando sus generales cometían errores, Lincoln no los criticaba. En lugar de eso, decía: "No los juzgues. Nosotros habríamos hecho lo mismo en circunstancias similares."

**Por Qué Funciona:**
- La crítica no cambia a las personas
- La crítica crea resentimiento
- Las personas se justifican a sí mismas
- Todos creemos que tenemos razón

**Qué Hacer en Su Lugar:**
- Trata de entender a la persona
- Busca las razones detrás de sus acciones
- Ten compasión y tolerancia

**Aplicación Práctica:**
En lugar de decir: "¡Siempre llegas tarde! Eres irresponsable."
Di: "Noté que has llegado tarde últimamente. ¿Hay algo con lo que pueda ayudarte?"

### PRINCIPIO 2: Demuestra Aprecio Honesto y Sincero

**El Deseo Más Profundo:**
El deseo más profundo de la naturaleza humana es el deseo de ser importante, de ser apreciado.

**La Diferencia Entre Aprecio y Adulación:**
- **Aprecio:** Sincero, viene del corazón, específico
- **Adulación:** Falso, manipulador, genérico

**Ejemplo - Charles Schwab:**
Charles Schwab ganaba $1 millón al año (en 1921) no por su conocimiento del acero, sino por su habilidad para tratar con personas.

Su secreto: "Soy entusiasta en mi aprecio y generoso en mi elogio."

**Cómo Aplicarlo:**
1. **Sé Específico:**
   - No: "Buen trabajo"
   - Sí: "La forma en que manejaste esa situación difícil con el cliente fue excepcional. Tu paciencia y creatividad resolvieron el problema perfectamente."

2. **Sé Sincero:**
   - Solo elogia cuando realmente lo sientes
   - Encuentra algo genuino que admirar

3. **Hazlo Público:**
   - Elogia en público cuando sea apropiado
   - Critica en privado (o mejor, no critiques)

**Ejercicio Diario:**
Cada día, encuentra algo específico para apreciar en al menos tres personas.

### PRINCIPIO 3: Despierta en los Demás un Deseo Vehemente

**El Principio Fundamental:**
La única manera de influir en otras personas es hablar acerca de lo que ellos quieren y mostrarles cómo conseguirlo.

**Henry Ford:**
"Si hay un secreto del éxito, reside en la capacidad para apreciar el punto de vista del prójimo y ver las cosas desde ese punto de vista así como del propio."

**Cómo Aplicarlo:**

**Paso 1: Pregúntate**
"¿Por qué habría de querer esta persona hacer lo que sugiero?"

**Paso 2: Piensa en Sus Beneficios**
No en los tuyos, en los de ellos.

**Paso 3: Presenta Tu Idea en Términos de Sus Deseos**

**Ejemplo - Vendiendo una Casa:**
- **Mal:** "Esta casa tiene 3 habitaciones y está cerca de mi trabajo."
- **Bien:** "Esta casa tiene un patio grande donde sus hijos pueden jugar de forma segura, y está en un vecindario con excelentes escuelas."

**Ejemplo - Motivando a un Empleado:**
- **Mal:** "Necesito que termines este reporte para mi reunión."
- **Bien:** "Este reporte te dará visibilidad con la alta gerencia y mostrará tus habilidades analíticas. Podría ser un gran paso para tu carrera."

