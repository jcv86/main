Esta filosofía es adaptarse a la aptitud de cambiar a un modo de trabajo profundo en un momento de aviso.

Ejemplo: El periodista Walter Isaacson podía escribir en cualquier momento, en cualquier lugar, cambiando instantáneamente al modo de trabajo profundo.

