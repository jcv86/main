Los animales recompensados por buen comportamiento aprenden mucho más rápidamente y retienen más efectivamente que los animales castigados por mal comportamiento.

Estudios posteriores mostraron que esto se aplica a humanos también: La crítica es esencialmente inútil porque pone a una persona a la defensiva.

**Regla 1: No critique, condene o se queje.**

### Principio 2: Dé Aprecio Honesto y Sincero

Solo hay una manera bajo el cielo de conseguir que alguien haga algo: Haciendo que la otra persona quiera hacerlo.

**El Deseo Más Profundo:**

El famoso psicólogo Sigmund Freud dijo que todo lo que haces surge de dos motivos: el impulso sexual y el deseo de ser grande.

John Dewey, el filósofo más profundo de América, lo frasea diferente: El impulso más profundo en la naturaleza humana es "el deseo de ser importante."

**Cómo Alimentar Este Deseo:**

Charles Schwab fue pagado un millón de dólares al año por U.S. Steel. ¿Por qué? Porque era un genio manejando personas.

"Considero mi habilidad para despertar entusiasmo entre las personas como el mayor activo que poseo, y la forma de desarrollar lo mejor en una persona es mediante aprecio y aliento."

**La Diferencia Entre Aprecio y Adulación:**

Aprecio es sincero. Adulación es insincera. Uno viene del corazón; el otro de los dientes afuera.

Emerson dijo: "Cada hombre que conozco es superior a mí en alguna forma. En esa forma, aprendo de él."

**Regla 2: Dé aprecio honesto y sincero.**

### Principio 3: Despierte en la Otra Persona un Deseo Vehemente

**El Secreto del Éxito:**

Henry Ford dijo: "Si hay un secreto del éxito, radica en la habilidad de obtener el punto de vista de la otra persona y ver las cosas desde su ángulo tanto como desde el tuyo."

**La Historia del Pescador:**

¿Por qué hablar sobre lo que queremos? Eso es infantil. Absurdo. Por supuesto, estás interesado en lo que quieres. Siempre lo has estado. Pero nadie más está interesado. El resto de nosotros somos como tú: estamos interesados en lo que queremos.

Así que la única manera en la tierra de influenciar a otras personas es hablar sobre lo que ellas quieren y mostrarles cómo conseguirlo.

Cuando vas a pescar, no piensas en lo que tú quieres. Piensas en lo que el pez quiere. No pones fresas en el anzuelo. Pones gusanos o saltamontes.

**Aplicación en Negocios:**

Un padre estaba preocupado porque su hijo no quería ir a la escuela. En lugar de sermonear sobre la importancia de la educación (lo que el padre quería), preguntó al hijo qué quería hacer ese día. El hijo dijo que quería jugar.

"¿No preferirías estar con otros niños jugando en lugar de quedarte en casa solo?" El niño inmediatamente quiso ir a la escuela.

**Regla 3: Despierte en la otra persona un deseo vehemente.**

## Parte II: Seis Maneras de Agradar a los Demás

### Principio 1: Interésese Genuinamente en las Otras Personas

Puedes hacer más amigos en dos meses interesándote en otras personas de los que puedes hacer en dos años tratando de que otras personas se interesen en ti.

**El Poder del Interés Genuino:**

Alfred Adler, el famoso psicólogo vienés, escribió: "El individuo que no está interesado en sus semejantes es quien tiene las mayores dificultades en la vida y proporciona las mayores heridas a otros. Es de tales individuos que surgen todos los fracasos humanos."

**La Historia del Perro:**

¿Alguna vez te has preguntado por qué los perros tienen tantos amigos? Es porque están genuinamente emocionados de verte. Mueven su cola. Te lamen la cara.

Un perro es el único animal que no tiene que trabajar para vivir. Una gallina tiene que poner huevos, una vaca tiene que dar leche, un canario tiene que cantar. Pero un perro gana su sustento solo por dar amor.

**En los Negocios:**

Charles Eliot, quien fue presidente de Harvard, dijo que no hay misterio sobre el éxito en las relaciones humanas. "No hay nada tan halagador como la atención personalizada."

**Regla 1: Interésese genuinamente en las otras personas.**

### Principio 2: Sonría

Las acciones hablan más fuerte que las palabras, y una sonrisa dice: "Me gustas. Me haces feliz. Me alegro de verte."

**El Valor de una Sonrisa:**

William B. Steinhardt, un corredor de bolsa de Nueva York, pasó por una cirugía mayor. Su rostro quedó paralizado en el lado derecho. Su boca era una torcida masa de cicatriz.

"Puedo sonreír solo con el lado izquierdo de mi cara," dijo, "pero es mejor que nada."

Los efectos fueron sorprendentes. Las personas respondieron calurosamente. Su negocio prosperó.

**Sonreír por Teléfono:**

Tu "sonrisa" sale en tu voz. Las compañías telefónicas han capacitado a sus operadores para sonreír mientras hablan porque realmente hace una diferencia en el tono de voz.

**Pero Debe Ser Genuina:**

Una sonrisa falsa engaña a nadie. Debe venir del corazón. Como dice el antiguo proverbio chino: "Un hombre sin cara sonriente no debe abrir una tienda."

**Regla 2: Sonría.**

### Principio 3: Recuerde que el Nombre de una Persona es para Esa Persona el Sonido Más Dulce e Importante

Jim Farley ayudó a Franklin D. Roosevelt a convertirse en presidente. Su secreto: Recordaba nombres.

**El Sistema de Jim Farley:**

Cuando conocía a alguien nuevo, averiguaba su nombre completo, tamaño de su familia, naturaleza de su negocio y opinión política. Fijaba todo esto en su mente. La próxima vez que veía a esa persona, podía darle un saludo personal.

**Andrew Carnegie:**

Carnegie usó este principio para construir su imperio de acero. Cuando era joven, criaba conejos. Necesitaba trébol para alimentarlos. Dijo a los niños del vecindario: "Si traen suficiente trébol para alimentar a estos conejos, nombraré un conejito bebé después de ustedes."

Los niños trabajaron duro. Carnegie nunca olvidó esta lección: Las personas están tan interesadas en sus propios nombres que responderán a ellos de maneras extraordinarias.

**Regla 3: Recuerde que el nombre de una persona es para esa persona el sonido más dulce e importante en cualquier idioma.**

### Principio 4: Sea un Buen Oyente. Anime a Otros a Hablar de Sí Mismos

Los estudios de la Harvard Business School encontraron que incluso en las conversaciones de negocios, el escuchar es más importante que hablar.

**La Historia del Botánico:**

Fui a una cena donde conocí a un botánico. Nunca había conocido a uno antes. Lo encontré fascinante. Me senté en el borde de mi silla por horas escuchándolo hablar sobre plantas exóticas y jardines interiores.

Después, él le dijo al anfitrión que yo era un "conversador más estimulante" y que era "muy inteligente."

Pero yo no había dicho casi nada. Simplemente había escuchado con atención y mostrado interés genuino.

**Charles W. Eliot:**

"No hay misterio sobre el éxito en las relaciones humanas," dijo Charles W. Eliot, ex presidente de Harvard. "Es la habilidad de mostrar interés en otros."

**Regla 4: Sea un buen oyente. Anime a otros a hablar de sí mismos.**

### Principio 5: Hable en Términos de los Intereses de la Otra Persona

Theodore Roosevelt sabía que la manera segura al corazón de una persona es hablar sobre las cosas que él o ella más valora.

**La Preparación de Roosevelt:**

Cada vez que Roosevelt esperaba un visitante, se quedaba despierto hasta tarde leyendo sobre el tema en el que sabía que su invitado estaba particularmente interesado.

Sabía que el camino real al corazón de una persona es hablar sobre las cosas que él o ella más valora.

**Vendiendo Seguros:**

Edward Chalif estaba tratando de vender seguros a un hombre que rechazaba verlo. Chalif descubrió que el prospecto había estado en la universidad al mismo tiempo que él. También descubrió que este hombre era presidente de una sociedad de ex-alumnos.

Chalif escribió una carta mencionando esto y obtuvo la cita inmediatamente. Vendió el seguro hablando sobre la universidad y ex-alumnos.

**Regla 5: Hable en términos de los intereses de la otra persona.**

### Principio 6: Haga que la Otra Persona se Sienta Importante - y Hágalo Sinceramente

Todos queremos aprobación. Todos queremos reconocimiento. Nadie quiere escuchar críticas.

**La Ley de la Vida:**

William James dijo: "El principio más profundo en la naturaleza humana es el anhelo de ser apreciado."

**Pequeños Actos de Bondad:**

Un día, fui a la oficina de correos. El empleado estaba pesando paquetes, sellando cartas, haciendo cambio, realizando una operación monótona tras otra. Lo miré y dije: "Desearía tener tu cabello."

Se sorprendió, sonrió ampliamente. Le di sincero aprecio. Él estaba radiante.

**Verdadera Grandeza:**

Rockefeller desarrolló el hábito de elogiar a sus socios. "Encuentro que el pago de cumplidos sinceros puede hacer que la gente se sienta importante y de hecho es importante."

La diferencia entre aprecio y adulación es simple: Uno es sincero, el otro no. Uno viene del corazón, el otro de los dientes.

**Regla 6: Haga que la otra persona se sienta importante - y hágalo sinceramente.**

## Parte III: Cómo Lograr que los Demás Piensen Como Usted

### Principio 1: La Única Manera de Ganar una Discusión es Evitándola

No puedes ganar una discusión. Si la pierdes, la pierdes; si la ganas, la pierdes.

**Por Qué:**

Supongamos que triunfas sobre el otro y demuelas sus argumentos. Entonces, ¿qué? Te sentirás bien. Pero, ¿qué de él? Lo has hecho sentirse inferior. Has herido su orgullo. Se resentirá de tu triunfo.

Un hombre convencido contra su voluntad es de la misma opinión todavía.

**La Historia de Patrick O''Haire:**

Patrick era vendedor de camiones. Un granjero lo atacó verbalmente sobre cierta marca de camiones. O''Haire argumentó. Defendió vehementemente su producto.

¿El resultado? El granjero no compró. Perdió un cliente por ganar una discusión.

Más tarde O''Haire aprendió que cuando alguien dice algo negativo, responde: "Bueno, ahora escucha. Tienes un punto. Déjame pensarlo." Esto desarma a la persona y abre la comunicación.

**Cómo Evitar Discusiones:**

1. Bienvenida el desacuerdo
2. Desconfía de tu primera reacción instintiva
3. Controla tu temperamento
4. Escucha primero
5. Busca áreas de acuerdo
6. Sé honesto
7. Promete pensar sobre las ideas de otros
8. Agradece sinceramente a otros por su interés
9. Pospone la acción para dar tiempo a ambos lados

**Regla 1: La única manera de ganar una discusión es evitándola.**

### Principio 2: Muestre Respeto por las Opiniones de Otros. Nunca Diga "Estás Equivocado"

Si vas a probar algo, no dejes que nadie lo sepa. Hazlo tan sutilmente que nadie piense que lo estás haciendo.

**Las Palabras Mágicas:**

Ben Franklin solía decir: "Nunca uso palabras como 'ciertamente,' 'indudablemente,' u otras que dan aire de positividad a una opinión. En su lugar digo, 'lo concibo' o 'lo aprehendo' o 'lo imagino' o 'así me parece.'"

**Un Caso Legal:**

Un abogado joven desafió al juez diciendo: "Señoría, la ley está en el lado de mi cliente, y las autoridades muestran..."

El juez lo interrumpió: "La corte está consciente de lo que dice la ley y las autoridades. Continúa con tu argumento."

Otro abogado dijo: "Su Señoría puede creer que estoy equivocado. Frecuentemente lo estoy. Pero déjeme explicar mi posición." Ganó el caso.

**Regla 2: Muestre respeto por las opiniones de otros. Nunca diga "Estás equivocado."**

### Principio 3: Si Está Equivocado, Admítalo Rápida y Enfáticamente

Di sobre ti mismo todas las cosas despectivas que sabes que la otra persona está pensando o quiere decir - y dilo antes que él tenga oportunidad de decirlo.

**La Historia del Perro:**

Una mañana estaba caminando por el parque sin correa para mi perro, algo contra las regulaciones. Un policía se acercó amenazadoramente.

Corrí hacia él antes que pudiera hablar. "Oficial," dije, "me atrapó con las manos en la masa. Soy culpable. No tengo excusa."

El policía respondió suavemente: "Bueno, sé que es tentador dejar correr a un perrito cuando hay tan pocas personas alrededor."

"Claro que es tentador," dije, "pero es contra la ley."

"Bueno," dijo, "solo esta vez, llévalo al otro lado de la colina donde no pueda verte - y no te atrapes otra vez."

**El Poder de la Humildad:**

Cualquier tonto puede tratar de defender sus errores - y la mayoría de los tontos lo hacen - pero eleva a uno por encima de la multitud admitir los errores propios.

**Regla 3: Si está equivocado, admítalo rápida y enfáticamente.**

### Principio 4: Comience de Manera Amigable

Esopo tenía razón hace miles de años: La amabilidad y la aabilidad son siempre más fuertes que la furia y la fuerza.

**La Historia de Lincoln:**

Lincoln tuvo problemas con los generales durante la Guerra Civil. Uno de los peores fue George Meade. Después de la batalla de Gettysburg, Meade permitió que el ejército de Lee escapara.

Lincoln escribió una carta de reprimenda mordaz. Pero nunca la envió. En su lugar, fue amable con Meade en persona. La historia habría sido diferente si hubiera enviado esa carta.

**En Ventas:**

Un vendedor de seguros tenía problemas colectando pagos. Envió cartas agresivas: "Debe pagar inmediatamente." No funcionó.

Luego probó un enfoque diferente: "Nos preocupa su situación. ¿Hay algo que podamos hacer?" Las respuestas fluyeron. La gente pagó.

**Regla 4: Comience de manera amigable.**

### Principio 5: Consiga que la Otra Persona Diga "Sí, Sí" Inmediatamente

Sócrates, el filósofo griego, era uno de los más grandes persuasores que el mundo haya visto. ¿Qué hizo? Preguntó preguntas con las cuales su oponente tendría que estar de acuerdo. Consiguió una respuesta "sí" tras otra.

**La Técnica Socrática:**

Sócrates hacía preguntas con las cuales sabía que su oponente estaría de acuerdo. Continuaba ganando una respuesta de afirmación tras otra. Tenía a su oponente diciendo "sí, sí" desde el principio. Esto es la Técnica Socrática.

**Vendiendo en China:**

Un vendedor estadounidense en China quería vender máquinas de coser. No hablaba chino. Su intérprete comenzó: "¿Desea ganar dinero?" "Sí." "¿Quiere ganar dinero sin mucho esfuerzo?" "Sí." "¿Le gustaría tener un negocio respetable?" "Sí."

Para cuando llegaron al producto, el prospecto ya estaba asintiendo. Compró.

**Regla 5: Consiga que la otra persona diga "sí, sí" inmediatamente.**

### Principio 6: Permita que la Otra Persona Hable Mucho

La mayoría de las personas tratando de ganar a otros a su manera de pensar hablan demasiado. Deja que la otra persona hable.

**El Caso del Vendedor Silencioso:**

Un fabricante estaba furioso con un vendedor de una compañía rival. Había decidido no ver más a este vendedor. Pero el vendedor pidió una cita "solo cinco minutos."

Cuando llegó, el fabricante dijo: "No quiero comprar." El vendedor respondió: "No vine a vender. Vine a pedir su consejo."

Luego el fabricante habló por 45 minutos sobre sus problemas. El vendedor apenas dijo nada, solo escuchó. Al final, el fabricante ordenó más de lo que jamás había comprado antes.

**La Confesión de un Vendedor:**

"He vendido por muchos años," dijo un vendedor, "pero solo recientemente descubrí que no es lo que yo digo lo que importa. Es lo que ellos dicen."

**Regla 6: Permita que la otra persona hable mucho.**

### Principio 7: Permita que la Otra Persona Sienta que la Idea es Suya

¿No te gustaría tener una fórmula mágica que detuviera desacuerdos, eliminara malos sentimientos, creara buena voluntad? Aquí está: Deja que la otra persona sienta que la idea es suya.

**La Historia de Adler:**

El Sr. Wesson fue a ver al psicólogo Dr. Adler sobre su hijo. El hijo no quería ir a la escuela.

Adler preguntó: "¿Le gusta a su hijo las fresas con crema?" "Sí." "Bien, mañana por la mañana cuando se despierte, dígale: ''Hoy puedes quedarte en casa y comer fresas con crema.''"

El padre estaba confundido. "¿Solo eso?" "Solo eso," dijo Adler.

Al día siguiente, el hijo dijo: "Papá, creo que iré a la escuela. Las fresas están bien, pero la escuela es más divertida."

Adler dejó que el niño decidiera por sí mismo.

**En Negocios:**

Un ejecutivo tenía una idea para reorganizar su departamento. En lugar de simplemente implementarla, plantó la semilla. En reuniones, hizo preguntas que llevaron a otros a sugerir su idea. Cuando finalmente fue "decidido," todos sintieron que era su idea.

**Regla 7: Permita que la otra persona sienta que la idea es suya.**

### Principio 8: Trate Honestamente de Ver las Cosas desde el Punto de Vista de la Otra Persona

No hay misterio sobre el éxito en las relaciones humanas. Es simplemente la capacidad de ver las cosas desde el punto de vista de la otra persona tanto como del tuyo.

**La Pregunta Mágica:**

Antes de cualquier conversación importante, pregúntate: "¿Cómo vería yo esto si estuviera en su posición?"

**El Caso del Inquilino:**

Un propietario tenía problemas con inquilinos que no pagaban el alquiler a tiempo. Enviaba cartas duras. No funcionó.

Luego pensó desde su perspectiva: Están sin dinero, estresados, avergonzados. Escribió: "Sé que las cosas son difíciles ahora. ¿Hay alguna manera en que pueda ayudar?"

Los inquilinos respondieron. Arreglaron planes de pago. Todos pagaron eventualmente.

**Regla 8: Trate honestamente de ver las cosas desde el punto de vista de la otra persona.**

### Principio 9: Sea Comprensivo con las Ideas y Deseos de los Demás

Hay una oración que detiene argumentos, elimina malos sentimientos, crea buena voluntad: "No te culpo por sentirte como te sientes. Si yo fuera tú, sin duda me sentiría exactamente igual."

**La Frase Mágica:**

"No te culpo por sentirte como te sientes. Si yo estuviera en tu lugar, me sentiría igual."

Esto es verdad del 100% del tiempo. Por supuesto que se sienten así. De lo contrario, no se sentirían así.

**El Cliente Enojado:**

Un cliente llamó, furioso sobre un producto defectuoso. El representante de servicio dijo: "Señora, entiendo completamente. Si yo recibiera un producto defectuoso, estaría igual de molesto. Déjeme ver qué puedo hacer."

La cliente se calmó inmediatamente. El problema se resolvió rápidamente.

**Regla 9: Sea comprensivo con las ideas y deseos de los demás.**

### Principio 10: Apele a los Motivos Más Nobles

Una persona usualmente tiene dos razones para hacer una cosa: una que suena bien y una razón real.

**La Razón Real y la Razón Noble:**

La persona misma pensará sobre la razón real. Pero todos somos idealistas en el corazón y nos gusta pensar en motivos que suenan bien.

Así que, para cambiar a las personas, apela a sus motivos más nobles.

**El Inquilino Desocupante:**

Un propietario quería que los inquilinos desocuparan. Podría haberlos demandado. En su lugar, fue y dijo:

"Sé que han invertido mucho en hacer de este apartamento un hogar. Y sé que la idea de mudarse es desagradable. Pero tengo una situación familiar de emergencia y realmente necesito recuperar este apartamento. ¿Podrían ayudarme?"

Se mudaron voluntariamente en dos semanas.

**Regla 10: Apele a los motivos más nobles.**

### Principio 11: Dramatice Sus Ideas

Esta es la era del espectáculo. Simplemente declarar una verdad no es suficiente. La verdad tiene que ser vivida, dramatizada, hecha interesante.

**La Demostración del Ratón:**

Un vendedor de trampas para ratones no solo decía que su trampa funcionaba. Llevaba ratones vivos a las demostraciones y mostraba cómo atrapaba a cada uno.

Sus ventas se dispararon.

**En Publicidad:**

Las mejores campañas publicitarias no solo dicen algo. Lo muestran dramáticamente.

Ejemplo: En lugar de decir "nuestros refrigeradores son duraderos," una compañía hizo un comercial tirando uno de un avión. Sobrevivió. Las ventas explotaron.

**Regla 11: Dramatice sus ideas.**

### Principio 12: Lance un Reto

Charles Schwab estaba pasando por una de sus fábricas un día. Encontró a un grupo de empleados fumando directamente bajo un letrero de "No Fumar."

En lugar de señalar el letrero, Schwab les entregó puros a cada uno y dijo: "Les agradecería muchachos si fumaran estos afuera."

Nunca más fumaron en ese lugar.

**El Deseo de Sobresalir:**

Todos tenemos un deseo de sobresalir, de ser el mejor. La manera de motivar es lanzar un desafío.

Frederic Herzberg, uno de los grandes psicólogos de negocios: "Si quieres que alguien haga un buen trabajo, dale un buen trabajo que hacer."

**En Ventas:**

Un gerente tenía un equipo de ventas con bajo rendimiento. En lugar de criticar, estableció una competencia amistosa con premios. Las ventas se duplicaron en un mes.

**Regla 12: Lance un reto.**

## Parte IV: Sea un Líder

### Principio 1: Comience con Elogio y Aprecio Honesto

Siempre es más fácil escuchar cosas desagradables después de haber oído algo de elogio de nuestras virtudes.

**La Técnica del Corte de Cabello:**

Un barbero comienza diciendo: "Tienes un cabello muy bueno." Luego procede a decirte todo lo que necesita arreglarse.

**McKinley y el Discurso:**

El presidente McKinley tenía que rechazar un discurso escrito por un ayudante. Comenzó: "Ese es un discurso espléndido. Nadie podría haberlo hecho mejor. Es adecuado para muchas ocasiones. Pero no es exactamente adecuado para esta ocasión."

El ayudante se fue feliz, no ofendido.

**Regla 1: Comience con elogio y aprecio honesto.**

### Principio 2: Llame la Atención sobre los Errores de Otros Indirectamente

Muchas personas comienzan sus críticas con elogios sinceros seguidos de la palabra "pero" y terminando con una declaración crítica.

**El Problema con "Pero":**

"Estás haciendo un buen trabajo, pero..." La persona espera la crítica y se pregunta si el elogio fue sincero.

**Cambia "Pero" por "Y":**

"Estás haciendo un buen trabajo, y si prestas atención a estos detalles, serás aún mejor."

**La Historia de Charles Schwab:**

Schwab caminaba por su fábrica un día al mediodía y se encontró con algunos empleados fumando. Arriba de sus cabezas había un letrero que decía "No Fumar."

¿Señaló Schwab al letrero y dijo: "¿No pueden leer?"? No, no lo hizo. En cambio, caminó hacia ellos, les dio a cada uno un puro y dijo: "Les agradecería muchachos si fumaran estos afuera." Ellos sabían que habían roto una regla, y lo admiraron porque no dijo nada al respecto.

**Regla 2: Llame la atención sobre los errores de otros indirectamente.**

### Principio 3: Hable de Sus Propios Errores Antes de Criticar a Otros

Admitir los propios errores - incluso cuando uno no los ha corregido - puede ayudar a persuadir a otros a cambiar su comportamiento.

**La Confesión Personal:**

"Hace unos años, hice lo mismo y aprendí..." Esta apertura hace que las personas sean receptivas.

**El Caso de Clarence Zerhusen:**

Clarence tenía un hijo pequeño que estaba obteniendo malas calificaciones. En lugar de criticar, Clarence dijo:

"Cuando yo era joven, no estudiaba lo suficiente y mis calificaciones eran terribles. Me arrepiento de eso ahora. Desearía haber estudiado más. Pero tú eres más inteligente que yo. Estoy seguro de que puedes hacerlo mejor."

Las calificaciones del hijo mejoraron dramáticamente.

**Regla 3: Hable de sus propios errores antes de criticar a otros.**

### Principio 4: Haga Preguntas en Lugar de Dar Órdenes

Nadie le gusta recibir órdenes. Hacer preguntas hace que las órdenes parezcan menos dictatoriales y a menudo estimula la creatividad.

**En Lugar de Decir:**
"Haz esto."
"No hagas eso."
"¿Por qué hiciste eso?"

**Pregunta:**
"¿Consideraste hacer esto?"
"¿Crees que funcionaría si...?"
"¿Qué piensas sobre...?"

**La Historia de Owen D. Young:**

Owen D. Young nunca dio una orden directa. Siempre hacía preguntas: "¿Consideraste esto?" "¿Crees que eso funcionaría?"

Esto daba a las personas la oportunidad de corregir sus errores. Les daba un sentido de importancia. Les hacía querer cooperar.

**Regla 4: Haga preguntas en lugar de dar órdenes.**

### Principio 5: Permita que la Otra Persona Salve su Dignidad

Incluso si tenemos razón y la otra persona está definitivamente equivocada, solo causamos daño destruyendo el ego de alguien.

**La Historia del General Electric:**

Un empleado cometió un error que costó a la compañía miles de dólares. Charles Steinmetz, un ingeniero genio, fue llamado. Después de analizar, simplemente dijo al empleado: "Creo que la próxima vez puedes hacerlo de esta manera."

El empleado se sintió motivado, no humillado.

**Antoine de Saint-Exupéry:**

"No tengo derecho a hacer o decir nada que disminuya a un hombre en su propia estimación. Lo que importa no es lo que pienso de él, sino lo que él piensa de sí mismo. Herir a un hombre en su dignidad es un crimen."

**Regla 5: Permita que la otra persona salve su dignidad.**

