CAPITULO 11: EL ARTE DE INNOVAR

INNOVACION NO ES INVENCION

Invencion: Crear algo nuevo
Innovacion: Hacer algo mejor, mas barato, mas accesible

No necesitas inventar rueda. Necesitas hacer mejor rueda.

TIPOS DE INNOVACION

1. PRODUCTO
Mejorar el producto mismo.

2. PROCESO
Mejorar como produces o entregas.

3. MODELO DE NEGOCIO
Cambiar como creas y capturas valor.

4. EXPERIENCIA
Mejorar como clientes interactuan contigo.

FOMENTANDO CULTURA DE INNOVACION

1. PERMITE EXPERIMENTACION
No todo experimento exitoso, pero necesitas intentar.

2. CELEBRA INTENTOS
No solo exitos - intentos honestos tambien.

3. PERMITE TIEMPO PARA EXPLORAR
Google 20% time: Permite a empleados trabajar en proyectos propios.

4. ESCUCHA A TODOS
Buenas ideas vienen de todas partes, no solo de arriba.

5. ACTUA RAPIDO EN IDEAS PROMETEDORAS
No analisis-paralisis. Prueba, aprende, adapta.

BARRERAS A INNOVACION

1. Miedo al fracaso
2. Pensamiento de silo
3. Falta de recursos
4. Resistencia al cambio
5. Enfoque corto plazo

SUPERANDO BARRERAS

1. Haz fracaso seguro
Experimentos pequenos, aprendizaje rapido.

2. Colaboracion cross-functional
Mejores ideas en intersecciones.

3. Asigna recursos especificamente
Innovacion no sucede en tiempo libre.

4. Liderazgo modelando cambio
Lideres deben demostrar apertura a nuevas ideas.

5. Balance corto y largo plazo
Optimiza presente mientras construyes futuro.

