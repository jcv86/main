Visual representation of the steps in a process, showing the sequence of activities and decision points.

Types:
- High-level process map
- Detailed process map
- Value stream map
- Swimlane diagram

**Data Collection Plan**
A structured approach to collecting data that ensures the right data is collected in the right way.

Elements:
- What data to collect
- How to collect it
- When to collect it
- Who will collect it
- Where to collect it

**Measurement System Analysis (MSA)**
Methods for evaluating the quality of measurement systems.

Key Concepts:
- Accuracy: How close measurements are to the true value
- Precision: How consistent measurements are
- Stability: How consistent measurements are over time
- Linearity: How accurate measurements are across the range

**Process Capability**
Statistical measures of how well a process meets customer requirements.

Key Metrics:
- Cp: Process capability (spread)
- Cpk: Process capability (spread and centering)
- Pp: Process performance (spread)
- Ppk: Process performance (spread and centering)

