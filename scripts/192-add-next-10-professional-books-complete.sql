**RED OCEANS VS. BLUE OCEANS**

**Red Oceans**
Red oceans represent all the industries in existence today—the known market space. In red oceans, industry boundaries are defined and accepted, and the competitive rules of the game are known.

Characteristics of Red Oceans:
- Compete in existing market space
- Beat the competition
- Exploit existing demand
- Make the value-cost trade-off
- Align the whole system of activities with strategic choice of differentiation or low cost

**Blue Oceans**
Blue oceans denote all the industries not in existence today—the unknown market space, untainted by competition. In blue oceans, demand is created rather than fought over.

Characteristics of Blue Oceans:
- Create uncontested market space
- Make competition irrelevant
- Create and capture new demand
- Break the value-cost trade-off
- Align the whole system of activities in pursuit of differentiation and low cost

**THE STRATEGY CANVAS**

The strategy canvas is both a diagnostic and an action framework for building a compelling blue ocean strategy. It captures the current state of play in the known market space.

**Components:**
- **Horizontal axis**: Factors that the industry competes on and invests in
- **Vertical axis**: The offering level that buyers receive across all key competing factors
- **Value curve**: The graphic depiction of a company''s relative performance across its industry''s factors of competition

**THE FOUR ACTIONS FRAMEWORK**

To reconstruct buyer value elements in crafting a new value curve, there are four key questions:

**Eliminate**
Which factors that the industry takes for granted should be eliminated?

**Reduce**
Which factors should be reduced well below the industry standard?

**Raise**
Which factors should be raised well above the industry standard?

**Create**
Which factors should be created that the industry has never offered?

**THE ELIMINATE-REDUCE-RAISE-CREATE GRID**

This grid pushes companies to act on all four questions and serves as a diagnostic tool to ensure a compelling blue ocean strategy.

**Benefits:**
- Pushes you to pursue differentiation and low cost simultaneously
- Flags companies that are only focused on raising and creating (leading to over-engineering and complexity)
- Easily understood by managers at any level

**SIX PRINCIPLES OF BLUE OCEAN STRATEGY**

**FORMULATION PRINCIPLES**

**Principle 1: Reconstruct Market Boundaries**
The first principle of blue ocean strategy is to reconstruct market boundaries to break from the competition and create blue oceans.

**Six Paths to Reconstruct Market Boundaries:**

**Path 1: Look Across Alternative Industries**
Companies compete not only with companies in their own industry but also with companies in other industries that produce alternative products or services.

**Path 2: Look Across Strategic Groups Within Industries**
Strategic groups are groups of companies within an industry that pursue similar strategies. Look across strategic groups to discover new opportunities.

**Path 3: Look Across the Chain of Buyers**
In most industries, competitors converge around a common definition of who the target buyer is. Challenge this by looking across the chain of buyers.

**Path 4: Look Across Complementary Product and Service Offerings**
Few products and services are used in isolation. Look at what happens before, during, and after your product is used.

**Path 5: Look Across Functional or Emotional Appeal to Buyers**
Some industries compete principally on price and function based on calculations of utility; their appeal is rational. Other industries compete largely on feelings; their appeal is emotional.

**Path 6: Look Across Time**
All industries are subject to external trends that affect their business over time. Look across time to understand trends and their impact.

**Principle 2: Focus on the Big Picture, Not the Numbers**
The second principle is to focus on the big picture, not the numbers. Don''t get caught up in operational effectiveness; focus on strategy.

**Drawing Your Strategy Canvas:**
1. Visual awakening: Compare your business with competitors by drawing your "as is" strategy canvas
2. Visual exploration: Go into the field to explore the six paths to creating blue oceans
3. Visual strategy fair: Draw your "to be" strategy canvas based on insights from field observations
4. Visual communication: Distribute your before-and-after strategic profiles for easy comparison

**Principle 3: Reach Beyond Existing Demand**
The third principle is to reach beyond existing demand. Instead of focusing on customers, focus on noncustomers.

**Three Tiers of Noncustomers:**

**First Tier: "Soon-to-be" Noncustomers**
These are buyers who minimally purchase an industry''s offering out of necessity but are mentally noncustomers.

**Second Tier: "Refusing" Noncustomers**
These are buyers who consciously refuse to use your industry''s offerings.

**Third Tier: "Unexplored" Noncustomers**
These are buyers who have never been targeted or thought of as potential customers by your industry.

**Principle 4: Get the Strategic Sequence Right**
The fourth principle is to get the strategic sequence right to ensure commercial viability.

**The Right Strategic Sequence:**
1. **Buyer Utility**: Is there exceptional buyer utility in your business idea?
2. **Price**: Is your price easily accessible to the mass of buyers?
3. **Cost**: Can you attain your cost target to profit at your strategic price?
4. **Adoption**: What are the adoption hurdles in actualizing your business idea?

**EXECUTION PRINCIPLES**

**Principle 5: Overcome Key Organizational Hurdles**
Once you have developed a blue ocean strategy with a profitable business model, you then move to execution.

**Four Key Organizational Hurdles:**
1. **Cognitive Hurdle**: Waking employees up to the need for a strategic shift
2. **Resource Hurdle**: Limited resources
3. **Motivational Hurdle**: Discouraging staff
4. **Political Hurdle**: Opposition from powerful vested interests

**Tipping Point Leadership:**
Focus on the extremes: the people, acts, and activities that exercise disproportionate influence on performance.

**Principle 6: Build Execution into Strategy**
The sixth principle is to build execution into strategy from the start.

**Fair Process:**
Fair process builds execution into strategy by creating buy-in and ownership of strategic decisions at all levels.

**Three E Principles of Fair Process:**
1. **Engagement**: Involving individuals in strategic decisions that affect them
2. **Explanation**: Explaining the thinking behind strategic decisions
3. **Expectation Clarity**: Making clear what is expected of everyone after decisions are made

