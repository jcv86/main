- Goal statement
- Scope
- Business case
- Team members
- Timeline

**Voice of the Customer (VOC)**
Methods for capturing customer requirements and expectations.

Tools:
- Customer surveys
- Focus groups
- Interviews
- Observation
- Customer complaints analysis

**SIPOC Diagram**
A high-level process map that identifies Suppliers, Inputs, Process, Outputs, and Customers.

Benefits:
- Provides process overview
- Defines process boundaries
- Identifies key stakeholders
- Helps scope the project

**MEASURE PHASE TOOLS**

