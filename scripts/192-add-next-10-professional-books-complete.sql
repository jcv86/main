Tools:
- Hypothesis testing
- Regression analysis
- Analysis of variance (ANOVA)
- Correlation analysis

**Value Stream Mapping**
A Lean tool for visualizing the flow of materials and information through a process.

Benefits:
- Identifies waste and non-value-added activities
- Shows the current state of the process
- Helps design the future state
- Provides a roadmap for improvement

**IMPROVE PHASE TOOLS**

**Design of Experiments (DOE)**
Statistical method for systematically varying process inputs to understand their effect on outputs.

Benefits:
- Identifies optimal settings
- Understands interactions between factors
- Minimizes the number of experiments needed
- Provides statistical confidence in results

**Kaizen Events**
Focused improvement workshops that bring together cross-functional teams to rapidly improve a specific process.

Characteristics:
- Short duration (3-5 days)
- Cross-functional team
- Focused scope
- Immediate implementation
- Measurable results

**Mistake Proofing (Poka-Yoke)**
Methods for preventing errors from occurring or detecting them when they do occur.

Types:
- Prevention: Makes it impossible to make a mistake
- Detection: Detects mistakes when they occur
- Mitigation: Reduces the impact of mistakes

