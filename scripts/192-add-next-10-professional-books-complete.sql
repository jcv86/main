-- BOOK 19: The Lean Startup
('The Lean Startup: How Today''s Entrepreneurs Use Continuous Innovation to Create Radically Successful Businesses', 'Entrepreneurship',
'Eric Ries presents a scientific approach to creating and managing successful startups in an age when companies need to innovate more than ever. The Lean Startup methodology teaches you how to drive a startup and when to turn, and when to persevere.

**THE LEAN STARTUP METHOD**

The Lean Startup is a new approach to business that''s being adopted around the world. It is changing the way companies are built and new products are launched.

**Core Principles:**
1. Entrepreneurs are everywhere
2. Entrepreneurship is management
3. Validated learning
4. Build-Measure-Learn
5. Innovation accounting

**THE BUILD-MEASURE-LEARN FEEDBACK LOOP**

The fundamental activity of a startup is to turn ideas into products, measure how customers respond, and then learn whether to pivot or persevere.

**BUILD**
The goal of the Build step is to build a minimum viable product (MVP) as quickly as possible to begin the process of learning.

**MEASURE**
The goal of the Measure step is to measure the impact of your product on real customer behavior.

**LEARN**
The goal of the Learn step is to learn whether your fundamental business hypotheses are true and decide whether to pivot or persevere.

**VALIDATED LEARNING**

Validated learning is the process of demonstrating empirically that a team has discovered valuable truths about a startup''s present and future business prospects.

**Key Characteristics:**
- It is more concrete, more accurate, and faster than market forecasting or classical business planning
- It is the principal antidote to the lethal problem of achieving failure: successfully executing a plan that leads nowhere
- It demonstrates progress when we are embedded in the soil of extreme uncertainty

**THE MINIMUM VIABLE PRODUCT (MVP)**

The minimum viable product is that version of a new product which allows a team to collect the maximum amount of validated learning about customers with the least effort.

**Types of MVPs:**

**Video MVP**
Create a video demonstrating your product''s functionality before building it.

**Concierge MVP**
Provide your service manually to a small number of customers to test your assumptions.

**Wizard of Oz MVP**
Create the appearance of a fully functional product while manually performing the work behind the scenes.

**Landing Page MVP**
Create a simple landing page that describes your product and measures interest.

**MVP Principles:**
- Remove any feature, process, or effort that does not contribute directly to the learning you seek
- The goal is to test fundamental business hypotheses, not to answer all questions
- Speed matters: get to market as quickly as possible

**INNOVATION ACCOUNTING**

Innovation accounting is a way of evaluating progress when all the metrics typically used in an established company (revenue, customers, ROI, market share) are effectively zero.

**Three Learning Milestones:**

**1. Establish the Baseline**
Use an MVP to establish real data on where the company is right now.

**2. Tune the Engine**
Every product development, marketing, or other initiative should be targeted at improving one of the drivers of the business model.

**3. Pivot or Persevere**
If the company is not moving the drivers of the business model, it is time to pivot.

**PIVOT OR PERSEVERE**

A pivot is a structured course correction designed to test a new fundamental hypothesis about the product, strategy, and engine of growth.

**Types of Pivots:**

**Zoom-in Pivot**
What previously was considered a single feature in a product becomes the whole product.

**Zoom-out Pivot**
What previously was considered the whole product becomes a single feature of a much larger product.

**Customer Segment Pivot**
The company realizes that the product it is building solves a real problem for real customers but that they are not the type of customers it originally planned to serve.

**Customer Need Pivot**
The company realizes that the problem they are trying to solve for customers is not very important, but through this process discovers a related problem that is important.

**Platform Pivot**
A change from an application to a platform or vice versa.

**Business Architecture Pivot**
Some companies change from high margin, low volume to low margin, high volume or vice versa.

**Value Capture Pivot**
Changes in how the company captures value (monetization or revenue model).

**Engine of Growth Pivot**
Most startups use one of three primary engines of growth: viral, sticky, or paid. A pivot may require changing engines.

**Channel Pivot**
The mechanism by which a company delivers its product to customers is called the sales channel or distribution channel.

**Technology Pivot**
A company discovers a way to achieve the same solution by using a completely different technology.

**THE THREE ENGINES OF GROWTH**

**The Sticky Engine of Growth**
Companies using the sticky engine of growth track their attrition rate or churn rate very carefully. The rules that govern the sticky engine are simple: if the rate of new customer acquisition exceeds the churn rate, the product will grow.

**The Viral Engine of Growth**
Products that exhibit viral growth depend on person-to-person transmission as a necessary consequence of normal product use. Viral growth is powered by a feedback loop called the viral loop, and its speed is determined by the viral coefficient.

**The Paid Engine of Growth**
Each customer pays a certain amount of money for the product over his or her lifetime. From this lifetime value, we subtract the variable costs associated with serving that customer. This yields the customer lifetime value (LTV). This revenue can then be invested in growth by buying advertising.

**LEAN STARTUP PRINCIPLES IN PRACTICE**

**For Established Companies:**

**Innovation Sandbox**
Create a sandbox for innovation that allows teams to experiment with new ideas without affecting the core business.

**Characteristics of Innovation Sandbox:**
- Any team can create a true split-test experiment
- One experiment must affect only the sandboxed parts of the product
- One experiment must be designed to run for a specified time period
- No experiment can affect more than a specified number of customers
- Every experiment has to be evaluated by the same five to ten actionable metrics
- Every team that works inside the sandbox must monitor the metrics and customer reactions while the experiment is in progress

**IMPLEMENTING LEAN STARTUP**

**Getting Started:**
