**INTRODUCTION TO LEAN SIX SIGMA**

Lean Six Sigma combines two powerful improvement methodologies:
- **Lean**: Focuses on speed and efficiency by eliminating waste
- **Six Sigma**: Focuses on quality by reducing variation and defects

**The Goal**: Deliver maximum value to customers in the shortest time with the highest quality and lowest cost.

**THE DMAIC METHODOLOGY**

DMAIC is the core problem-solving methodology of Six Sigma:

**DEFINE**
- Define the problem and project goals
- Identify customer requirements
- Create a project charter
- Form the project team

**MEASURE**
- Measure current performance
- Collect baseline data
- Validate measurement systems
- Calculate process capability

**ANALYZE**
- Analyze data to identify root causes
- Use statistical tools to understand variation
- Identify value-added and non-value-added activities
- Determine critical factors

**IMPROVE**
- Generate and evaluate solutions
- Design and implement improvements
- Pilot test changes
- Validate improvements

**CONTROL**
- Implement control systems
- Monitor ongoing performance
- Standardize improvements
- Transfer ownership to process owners

**LEAN PRINCIPLES**

**The Five Principles of Lean:**

**1. Value**
Define value from the customer''s perspective. Value is what the customer is willing to pay for.

**2. Value Stream**
Map the value stream to identify all activities required to deliver value to the customer.

**3. Flow**
Make value flow smoothly through the process without interruptions, delays, or batches.

**4. Pull**
Let customer demand pull products through the system rather than pushing based on forecasts.

**5. Perfection**
Continuously improve toward perfection by eliminating waste and reducing variation.

**THE EIGHT WASTES (MUDA)**

**1. Transportation**
Unnecessary movement of materials, products, or information.

**2. Inventory**
Excess raw materials, work-in-process, or finished goods.

**3. Motion**
Unnecessary movement of people or equipment.

**4. Waiting**
Idle time when resources are not being used productively.

**5. Overproduction**
Producing more than what is needed or before it is needed.

**6. Over-processing**
Doing more work than what is required by the customer.

**7. Defects**
Products or services that don''t meet customer requirements.

**8. Skills**
Underutilizing people''s talents, skills, and knowledge.

**KEY LEAN SIX SIGMA TOOLS**

