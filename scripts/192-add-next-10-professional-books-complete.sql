**The Three A''s of Metrics:**
- **Actionable**: Must demonstrate clear cause and effect
- **Accessible**: Must be simple to understand
- **Auditable**: Must be credible to employees

**BUILDING A LEARNING ORGANIZATION**

**Five Whys**
When problems arise, use the Five Whys technique to get to the root cause and prevent future occurrences.

**Example:**
1. Why did the machine stop? (There was an overload and the fuse blew)
2. Why was there an overload? (The bearing was not sufficiently lubricated)
3. Why was it not lubricated? (The lubrication pump was not pumping sufficiently)
4. Why was it not pumping sufficiently? (The shaft of the pump was worn and rattling)
5. Why was the shaft worn out? (There was no strainer attached and metal scrap got in)

**Proportional Investment**
Make investments in prevention that are proportional to the severity of the problem.

