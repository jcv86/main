**THE GOLDEN CIRCLE**

The Golden Circle is a naturally occurring pattern, grounded in the biology of human decision making, that explains why we are inspired by some people, leaders, companies and messages over others.

**WHAT**
Every single company and organization on the planet knows WHAT they do. This is true no matter how big or small, no matter what industry. Everyone is easily able to describe the products or services a company sells or the job function they have within that system.

**HOW**
Some companies and people know HOW they do WHAT they do. Whether you call them a "differentiating value proposition," "proprietary process" or "unique selling proposition," HOWs are often given to explain how something is different or better.

**WHY**
Very few people or companies can clearly articulate WHY they do WHAT they do. When I say WHY, I don''t mean to make money—that''s a result. By WHY I mean what is your purpose, cause or belief? WHY does your company exist? WHY do you get out of bed every morning? And WHY should anyone care?

**THE BIOLOGY OF DECISION MAKING**

The Golden Circle corresponds perfectly with how our brain works:
- The neocortex (WHAT) - responsible for rational and analytical thought and language
- The limbic brain (WHY and HOW) - responsible for feelings, trust, loyalty, and decision-making

When we communicate from the outside in (WHAT first), we speak to the part of the brain that controls rational thought but not behavior. When we communicate from the inside out (WHY first), we speak directly to the part of the brain that controls decision-making.

**CLARITY, DISCIPLINE, AND CONSISTENCY**

**Clarity of WHY**
You must know WHY you do WHAT you do. If people don''t buy WHAT you do, they buy WHY you do it, so it follows that if you don''t know WHY you do WHAT you do, how will anyone else?

**Discipline of HOW**
Once you know WHY you do what you do, the question is HOW will you do it? HOWs are your values or principles that guide HOW to bring your cause to life.

**Consistency of WHAT**
Everything you say and everything you do has to prove what you believe. A WHY without the discipline of HOW quickly becomes manipulation.

**THE EMERGENCE OF TRUST**

Trust begins to emerge when we have a sense that another person or organization is driven by things other than their own self-gain. Trust is maintained when the things we believe someone stands for are proven by the things they do.

