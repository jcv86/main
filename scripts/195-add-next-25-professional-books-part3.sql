**PRINCIPLE 1: RECIPROCITY**

**The Rule of Reciprocity**
People feel obligated to return favors, pay back debts, and treat others as they have been treated.

**Why Reciprocity Works:**
- It''s a fundamental social norm across all cultures
- It creates psychological discomfort when violated
- It helped human societies develop and survive
- It operates even with uninvited favors

**How to Use Reciprocity:**
- **Give first**: Provide value before asking for something
- **Be genuine**: Authentic gestures are more powerful
- **Make it personal**: Tailor your approach to the individual
- **Be specific**: Clear about what you''re giving and why

**Examples:**
- Free samples in stores
- Complimentary gifts from charities
- Consultants providing free initial advice
- Restaurants offering free bread or appetizers

**Defense Against Reciprocity:**
- Recognize when someone is trying to create obligation
- Distinguish between genuine gifts and manipulation tactics
- Feel free to reject uninvited favors
- Remember that you don''t owe anything for manipulative attempts

**PRINCIPLE 2: COMMITMENT AND CONSISTENCY**

**The Consistency Principle**
People have a deep desire to be consistent with their previous commitments and self-image.

**Why Consistency Works:**
- It simplifies decision-making
- It''s socially valued
- It reduces cognitive dissonance
- It helps maintain a stable self-concept

**Types of Commitment:**
- **Public commitments**: Stated in front of others
- **Written commitments**: Put down on paper
- **Active commitments**: Require effort to make
- **Voluntary commitments**: Made without coercion

