Por Stephen R. Covey

INTRODUCCIÓN: DE ADENTRO HACIA AFUERA

Durante los primeros 150 años de historia estadounidense la literatura de éxito se centraba en la ética del carácter. Enseñaba principios básicos como integridad humildad fidelidad templanza coraje justicia paciencia diligencia simplicidad y modestia.

Después de la Primera Guerra Mundial la manera básica de ver el éxito cambió de la ética del carácter a la ética de la personalidad. El éxito se convirtió en función de personalidad imagen pública actitudes y conductas.

Sin embargo algunas de estas filosofías de personalidad eran manipuladoras. Alentaban a usar técnicas para conseguir lo que uno quiere de otros.

Los paradigmas son poderosos porque crean los lentes a través de los cuales vemos el mundo. Si queremos cambios significativos debemos trabajar en nuestros paradigmas básicos.

HÁBITO 1: SEA PROACTIVO

Entre estímulo y respuesta el hombre tiene la libertad de elegir. Este es el hábito de la responsabilidad personal.

Viktor Frankl prisionero en un campo nazi descubrió una libertad fundamental: la libertad de elegir la actitud en cualquier conjunto de circunstancias.

Entre lo que nos sucede y nuestra respuesta hay un espacio. En ese espacio reside nuestra libertad y poder de elegir. En nuestra respuesta está nuestro crecimiento.

Las personas reactivas están afectadas por condiciones físicas y ambiente. Las personas proactivas están impulsadas por valores.

El círculo de influencia vs el círculo de preocupación: Las personas proactivas enfocan sus esfuerzos en el círculo de influencia trabajan en cosas que pueden controlar. Su energía es positiva y expande su círculo de influencia.

Lenguaje reactivo vs proactivo:
- Reactivo: No hay nada que pueda hacer Así soy yo
- Proactivo: Veamos nuestras alternativas Puedo elegir un enfoque diferente

HÁBITO 2: EMPIECE CON UN FIN EN MENTE

Este hábito se basa en el principio de que todas las cosas son creadas dos veces. Hay una creación mental primera y una creación física segunda.

Comenzar con el fin en mente significa empezar con una clara comprensión de tu destino. Significa saber a dónde vas para que comprendas mejor dónde estás ahora.

Es fácil quedar atrapado en la trampa de actividad trabajar más duro para subir la escalera del éxito solo para descubrir que está apoyada contra la pared equivocada.

Administración es eficiencia al subir la escalera. Liderazgo determina si la escalera está contra la pared correcta.

Un enunciado de misión personal es como una constitución personal. Te da una medida mediante la cual puedes medir todo en tu vida.

Para escribir un enunciado de misión debes empezar en el centro de tu círculo de influencia ese centro compuesto de tus paradigmas más básicos.

HÁBITO 3: PONGA PRIMERO LO PRIMERO

Este hábito es la realización física la creación segunda. Es el ejercicio de voluntad independiente hacia ser dirigido por principios.

La matriz de administración del tiempo organiza actividades en cuatro cuadrantes:

Cuadrante 1: Urgente e importante (Crisis problemas proyectos con fechas límite)
Cuadrante 2: No urgente e importante (Prevención construcción de relaciones planificación recreación)
Cuadrante 3: Urgente y no importante (Interrupciones algunas llamadas correo)
Cuadrante 4: No urgente y no importante (Trivialidades pérdidas de tiempo)

Las personas efectivas permanecen fuera de los Cuadrantes 3 y 4. También reducen el Cuadrante 1 pasando más tiempo en el Cuadrante 2.

El Cuadrante 2 es el corazón de administración personal efectiva. Trata con cosas no urgentes pero importantes.

La delegación efectiva aumenta tu capacidad y la de otros. Hay dos tipos: delegación de recadero y delegación de administración.

HÁBITO 4: PIENSE GANAR-GANAR

Ganar-ganar busca beneficio mutuo en todas las interacciones humanas. Los acuerdos son mutuamente beneficiosos y satisfactorios.

Los seis paradigmas de interacción:
1. Ganar-Ganar: Ambas partes consiguen lo que quieren
2. Gano-Pierdes: Si gano yo pierdes tú
3. Pierdo-Ganas: Permito que otros se aprovechen
4. Pierdo-Pierdes: Ambos perdemos
5. Gano: Me enfoco solo en conseguir lo que quiero
6. Ganar-Ganar o No Hay Trato: Si no hay beneficio mutuo no hacemos trato

Los cinco elementos de ganar-ganar son: carácter relaciones acuerdos sistemas y procesos.

La mentalidad de abundancia fluye de un profundo sentido de valor y seguridad. Es el paradigma de que hay mucho para todos.

HÁBITO 5: PROCURE PRIMERO COMPRENDER Y DESPUÉS SER COMPRENDIDO

La mayoría no escucha con intención de comprender sino con intención de responder.

Cinco niveles de escucha:
1. Ignorar
2. Fingir escuchar
3. Escuchar selectivamente
4. Escuchar atentamente
5. Escuchar empáticamente

Escuchar empáticamente es entrar en el marco de referencia de la otra persona. Ver el mundo como ellos lo ven comprender su paradigma sentir como se sienten.

Las cuatro respuestas autobiográficas son: evaluamos sondeamos aconsejamos e interpretamos. Tendemos a responder desde nuestro propio marco de referencia.

HÁBITO 6: SINERGICE

Sinergia significa que el todo es más que la suma de sus partes. La relación de las partes es la parte más catalizadora empoderadora unificadora y excitante.

La esencia de sinergia es valorar las diferencias. No solo tolerarlas sino celebrarlas.

Cuando las personas interactúan genuinamente y están abiertas a la influencia mutua ganan nueva perspectiva. El diálogo produce perspectivas que ninguno había visto antes.

La persona verdaderamente efectiva tiene humildad para reconocer sus limitaciones y apreciar los recursos disponibles a través de interacción con otros.

HÁBITO 7: AFILE LA SIERRA

Este hábito preserva y mejora el mayor activo que tienes: tú mismo. Renueva las cuatro dimensiones de tu naturaleza.

Dimensión física: Cuidar efectivamente tu cuerpo. Comer bien descansar suficiente hacer ejercicio regular. Un buen programa trabaja resistencia flexibilidad y fuerza.

Dimensión espiritual: Proporciona liderazgo a tu vida. Está relacionada al Hábito 2. Es tu núcleo tu centro tu compromiso con valores. Es supremamente importante.

Dimensión mental: La mayoría del desarrollo mental viene de educación formal. Pero después de la escuela muchos dejan que sus mentes se atrofien. Leer ampliamente expone tu mente a otros grandes mentes.

Dimensión social-emocional: Se enfoca en Hábitos 4 5 y 6. Se centra en liderazgo de principios comunicación empática y cooperación creativa.

La renovación en todas las dimensiones es lo que te capacita para moverte en una espiral ascendente de crecimiento cambio y mejora continua.

CONCLUSIÓN

Los hábitos son factores poderosos en nuestras vidas. Son patrones consistentes a menudo inconscientes que constantemente expresan nuestro carácter.

Los hábitos pueden ser aprendidos y desaprendidos. Pero no es un proceso rápido. Requiere proceso y tremendo compromiso.

