Por Daniel Kahneman

INTRODUCCION: DOS SISTEMAS

Este libro presenta una vision de como la mente funciona basada en descubrimientos en psicologia cognitiva y social.

SISTEMA 1: Opera automatica y rapidamente, con poco o ningun esfuerzo y sin sentido de control voluntario.

SISTEMA 2: Asigna atencion a las actividades mentales esforzadas que demandan, incluidos calculos complejos.

PARTE I: DOS SISTEMAS

CAPITULO 1: LOS PERSONAJES

El Sistema 1 opera automaticamente y el Sistema 2 esta normalmente en modo de esfuerzo bajo.

Ejemplos del Sistema 1:
- Detectar que un objeto esta mas lejos que otro
- Orientarse hacia la fuente de un sonido repentino
- Completar la frase pan y...
- Hacer una cara de disgusto al ver imagen horrible
- Detectar hostilidad en una voz
- Responder a 2 mas 2

Ejemplos del Sistema 2:
- Prepararte para disparo de inicio en carrera
- Enfocar atencion en payasos en circo
- Monitorear propiedad de tu comportamiento en situacion social
- Contar ocurrencias de letra a en pagina de texto
- Dar a alguien tu numero de telefono
- Calcular 17 por 24

El Sistema 1 genera sugerencias para Sistema 2: impresiones, intuiciones, intenciones y sentimientos.

CAPITULO 2: ATENCION Y ESFUERZO

El Sistema 2 tiene capacidad para cambiar manera en que Sistema 1 funciona, programando funciones automaticas de atencion y memoria.

Experimento: Cuenta cuantas veces jugadores vestidos de blanco pasan baloncesto. Mayoria de observadores no ven gorila caminando a traves de escena. Esto es ceguera de falta de atencion.

Ley del menor esfuerzo: Si hay varias maneras de alcanzar mismo objetivo, personas gravitaran hacia curso de accion menos exigente.

CAPITULO 3: EL CONTROLADOR PEREZOSO

El Sistema 2 es perezoso, y Sistema 1 es rapido para saltar a conclusiones.

Problema del murciélago y pelota:
Un murciélago y pelota cuestan 1.10 en total.
Murciélago cuesta 1.00 mas que pelota.
Cuanto cuesta pelota?

Respuesta intuitiva: 10 centavos (INCORRECTO)
Respuesta correcta: 5 centavos

Mas del 50% de estudiantes en Harvard, MIT y Princeton dieron respuesta intuitiva incorrecta.

CAPITULO 4: LA MAQUINA ASOCIATIVA

Sistema 1 es maquina de asociaciones. Cuando piensas en palabra, muchas otras se activan.

Priming: Palabras evocan ideas, que evocan otras ideas, en cascada de actividad mental.

Experimento: Personas caminaron mas lentamente despues de leer palabras relacionadas con edad avanzada.

Efecto Florida: Estudiantes expuestos a palabras relacionadas con edad avanzada (gris, arruga, calvo) caminaron mas lentamente por pasillo despues.

CAPITULO 5: FACILIDAD COGNITIVA

Cuando estas en estado de facilidad cognitiva, probablemente estas de buen humor, te gustan lo que ves, crees lo que escuchas, confias en intuiciones.

Experiencias repetidas, presentacion clara, idea preparada, buen humor - todos crean facilidad cognitiva.

Efecto de mera exposicion: Personas desarrollan preferencia por cosas meramente porque estan familiarizadas con ellas.

CAPITULO 6: NORMAS, SORPRESAS Y CAUSAS

Sistema 1 mantiene y actualiza modelo de tu mundo personal. Modelo esta compuesto de asociaciones vinculadas por nocion de causalidad.

Cuando algo viola modelo (es sorprendente), Sistema 1 activa Sistema 2 para buscar explicacion causal.

CAPITULO 7: UNA MAQUINA PARA SALTAR A CONCLUSIONES

WYSIATI: What You See Is All There Is (Lo que ves es todo lo que hay)

Sistema 1 es radicalmente insensible tanto a calidad como a cantidad de informacion que da lugar a impresiones y juicios.

Sesgo de confirmacion: Buscamos informacion que confirma creencias y descontamos informacion que contradice.

Efecto halo: Si te gusta (o no gusta) todo sobre persona, incluidas cosas que no has observado.

PARTE II: HEURISTICAS Y SESGOS

CAPITULO 8: COMO SE FORMAN JUICIOS

Sustitucion: Cuando enfrentamos pregunta dificil, a menudo respondemos una mas facil en su lugar, usualmente sin notar sustitucion.

Pregunta objetivo: Que tan feliz estas con tu vida en estos dias?
Pregunta heuristica: Cual es mi estado de animo ahora mismo?

CAPITULO 9: RESPONDIENDO UNA PREGUNTA MAS FACIL

Personas sustituyen pregunta mas facil sin darse cuenta de que estan haciendo esto.

Ejemplo: Que tan popular sera presidente en seis meses?
Se convierte en: Que tan popular es ahora?

Cascada afectiva: Cadena auto-sustentable de reacciones emocionales. Historia desencadena emocion, que desencadena cobertura de medios, que desencadena mas emocion.

CAPITULO 10: LA LEY DE NUMEROS PEQUEÑOS

Ley de numeros grandes: Muestras grandes son mas precisas que pequeñas.

Personas, incluyendo investigadores estadisticos, son insensibles a tamaño de muestra.

Hospitales pequeños tienen tanto mas dias con mas de 60% de nacimientos masculinos como mas dias con menos de 40% de nacimientos masculinos que hospitales grandes - simplemente porque muestras pequeñas varian mas.

CAPITULO 11: ANCLAS

Efecto de anclaje: Cuando consideras valor para cantidad desconocida, ocurre sesgo: tus estimaciones permanecen cercanas a numero que consideraste.

Experimento: Rueda de fortuna se detiene en 10 o 65. Pregunta: Cual es porcentaje de naciones africanas en ONU?
Aquellos que vieron 10 estimaron 25%. Aquellos que vieron 65 estimaron 45%.

Anclas funcionan incluso cuando son obviamente aleatorias.

En negociaciones, quien hace primera oferta establece ancla.

CAPITULO 12: LA CIENCIA DE DISPONIBILIDAD

Heuristica de disponibilidad: Juzgas frecuencia o probabilidad por facilidad con que ejemplos vienen a mente.

Hay mas palabras que comienzan con r o tienen r como tercera letra? Mayoria dice que comienzan con r, pero en realidad hay tres veces mas con r como tercera letra.

Palabras que comienzan con r son mas faciles de recordar (mas disponibles).

CAPITULO 13: DISPONIBILIDAD, EMOCION Y RIESGO

Personas tienden a evaluar riesgo de tecnologia considerando cuan malo se sentirian si ocurriera.

Victimas identificables: Personas responderan mas vigorosamente a una sola victima identificada que a vasta calamidad.

Una sola muerte es tragedia; un millon de muertes es estadistica - Joseph Stalin

CAPITULO 14: ESPECIALIDAD DE TOM W

Linda tiene 31 años, soltera, franca y muy brillante. Se especializo en filosofia. Como estudiante, estaba profundamente preocupada por asuntos de discriminacion y justicia social.

Que es mas probable?
A) Linda es cajera de banco
B) Linda es cajera de banco y activa en movimiento feminista

Mas del 85% elige B. Pero esto viola logica: B no puede ser mas probable que A porque B es subconjunto de A.

Falacia de conjuncion: Juzgar evento de conjuncion (A y B) como mas probable que uno de sus constituyentes (A).

CAPITULO 15: LINDA: MENOS ES MAS

Personas asignan mas probabilidad a eventos que son mas representativos, no mas probables.

Descripciones vividas tienen peso desproporcionado en juicios de probabilidad.

CAPITULO 16: CAUSAS TRUMPAN ESTADISTICAS

Personas no prestan adecuadamente atencion a informacion estadistica de tasas base cuando se les proporciona informacion causal o individual.

Ejemplo: 85% de taxis son verdes, 15% son azules. Testigo dice que taxi en accidente era azul. Testigo tiene 80% de precision.

Cual es probabilidad de que taxi fuera realmente azul? Mayoria dice 80%. Respuesta correcta es 41%.

Personas ignoran tasa base (85% verdes) y se enfocan en evidencia causal especifica (testimonio de testigo).

CAPITULO 17: REGRESION A LA MEDIA

Eventos extremos tienden a ser seguidos por eventos mas modestos.

Si anotas excepcional en primer examen, probablemente te ira menos bien (pero aun bien) en segundo examen.

No es porque fuiste elogiado o castigado - es regresion estadistica.

Instructores de vuelo pensaban que elogio dañaba rendimiento y critica lo mejoraba - en realidad, solo estaban viendo regresion a media.

PARTE III: EXCESO DE CONFIANZA

CAPITULO 19: LA ILUSION DE ENTENDER

Falacia narrativa: Construimos historias coherentes del pasado que nos hacen creer que mundo es mas predecible de lo que realmente es.

Sesgo retrospectivo: Tendencia a creer, despues de que evento ha ocurrido, que uno lo habria predicho.

Una vez que adoptas nueva vision del mundo, pierdes gran parte de capacidad de recordar lo que solias creer antes de que cambiara tu mente.

CAPITULO 20: LA ILUSION DE VALIDEZ

Personas tienen confianza injustificada en sus juicios intuitivos.

Expertos de bolsa no son mejores que lanzar dardos para elegir acciones, pero tienen tremenda confianza en sus habilidades.

Ilusion de habilidad: Cuando resultados son esencialmente aleatorios, confundes suerte con habilidad.

CAPITULO 21: INTUICIONES DE EXPERTOS

Intuiciones genuinas desarrollan a traves de practica prolongada.

Dos condiciones para adquirir habilidad:
1. Entorno suficientemente regular para ser predecible
2. Oportunidad de aprender esas regularidades a traves de practica prolongada

Ajedrez y bomberos: Entornos predecibles donde pericia es real.
Prediccion de stock: Entorno altamente irregular donde pericia es ilusion.

CAPITULO 22: INTUICIONES VERSUS FORMULAS

Formulas simples superan rutinariamente juicio de expertos.

Ejemplo: Puntaje Apgar (simplifica evaluacion neonatal) supero evaluaciones de enfermeras.

Algoritmos simples superan a expertos porque:
1. Expertos intentan ser inteligentes, buscando patrones complejos
2. Muchos factores tienen efectos pequeños e independientes
3. Algoritmos combinan consistentemente informacion; expertos son inconsistentes

PARTE IV: ELECCIONES

CAPITULO 26: TEORIA DE PERSPECTIVA

Tres principios cognitivos:

1. EVALUACION ES RELATIVA A PUNTO DE REFERENCIA NEUTRAL
Personas piensan en terminos de ganancias y perdidas de punto de referencia (generalmente status quo).

2. PRINCIPIO DE SENSIBILIDAD DECRECIENTE
100 importa mucho mas cuando vas de 0 a 100 que cuando vas de 900 a 1000.

3. AVERSION A PERDIDAS
Perdidas duelen mas que ganancias equivalentes se sienten bien. Aproximadamente, perder 100 se siente tan malo como ganar 200 se siente bien.

CAPITULO 27: EL EFECTO DOTACION

Personas demandan mucho mas para renunciar a objeto que lo pagarian para adquirirlo.

Experimento: Mitad de sujetos reciben taza, otra mitad nada. Precio de venta promedio (dueños): 7. Precio de compra promedio (no dueños): 3.

Causa: Aversion a perdida. Vendedores experimentan vender taza como perdida; compradores experimentan comprar como ganancia.

PARTE V: DOS YOES

CAPITULO 35: DOS YOES

Yo que experimenta: Vive en presente
Yo que recuerda: Mantiene registro y toma decisiones

Estos dos yoes tienen intereses diferentes.

CAPITULO 36: LA VIDA COMO HISTORIA

Regla del pico-final: Evaluamos experiencias pasadas por su pico (mejor o peor momento) y su final, no por promedio o total.

Experimento de colonoscopia: Pacientes con procedimiento mas largo pero final menos doloroso lo recordaron como menos doloroso en general.

Negligencia de duracion: Duracion de experiencia tiene poco efecto en evaluaciones retrospectivas.

