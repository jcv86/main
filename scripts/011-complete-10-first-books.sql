## Por Angela Duckworth

LA VERDADERA CLAVE DEL ÉXITO ESTÁ EN LA TENACIDAD, NO EN LA INTELIGENCIA INNATA.

## QUÉ ES GRIT?

Grit = Pasión (Interés Profundo) + Perseverancia (Esfuerzo Sostenido)

No es talento. No es suerte. Es la combinación de amar profundamente lo que haces Y estar dispuesto a trabajar años para lograrlo.

## LOS 4 PILARES DEL GRIT

**1. INTERÉS (Descubrimiento de Pasión)**
- Pasión no es algo que "encuentras" de repente
- Se cultiva mediante exploración y exposición
- Requiere curiosidad activa
- Toma tiempo identificar qué te engaña profundamente

**2. PRÁCTICA (Mejora Deliberada)**
- La práctica ordinaria ≠ mejora
- Practica con INTENCIÓN clara
- Busca retroalimentación constantemente
- Refina basado en lo que aprendes

**3. PROPÓSITO (Significado Mayor)**
- ¿Por qué tu trabajo importa?
- Conecta tu esfuerzo a un propósito que te trasciende
- El dinero motiva a corto plazo; el propósito motiva años

**4. ESPERANZA (Resiliencia Mental)**
- Cuando fallas, ¿abandonas o buscas nuevas estrategias?
- Grit requiere creer que puedes mejorar
- Es optimismo + acción, no negación

## 4 ESTRATEGIAS PARA CONSTRUIR GRIT

1. Identifica tu interés auténtico
2. Practica deliberadamente con retroalimentación
3. Conecta tu trabajo a un propósito mayor
4. Cultiva la mentalidad: "Puedo mejorar con esfuerzo"

## APLICACIÓN PROFESIONAL

Ideal para emprendedores, deportistas, artistas, padres - cualquiera que quiera lograr cosas difíciles.'
