## PRIMERA PARTE: TÉCNICAS FUNDAMENTALES PARA TRATAR CON LAS PERSONAS

### Principio 1: No Critique, No Condene, No Se Queje

#### La Gran Lección que Aprendió Al Capone
Al Capone, uno de los criminales más notorios de América, no se culpaba por nada. Decía: "He pasado los mejores años de mi vida dando a las personas los placeres más ligeros, ayudándolas a pasar un buen rato, y todo lo que obtengo son abusos, la existencia de un hombre perseguido."

**La Lección Fundamental:**
Las críticas son inútiles porque ponen a una persona a la defensiva y por lo común hacen que trate de justificarse. Las críticas son peligrosas, porque lastiman el orgullo tan precioso de una persona, hieren su sentido de la importancia y despiertan su resentimiento.

#### El Instinto Humano Fundamental
Cuando tratamos con personas, recordemos que no estamos tratando con criaturas lógicas. Estamos tratando con criaturas emocionales, criaturas erizadas de prejuicios e impulsadas por el orgullo y la vanidad.

**Historia de Abraham Lincoln:**
Lincoln aprendió esta lección de manera difícil. En su juventud, criticaba abiertamente a otros, incluso escribía cartas sarcásticas que publicaba en el periódico. Una vez casi tuvo un duelo por esto. Después de esa experiencia, nunca más criticó a nadie.

#### Benjamin Franklin y su Fórmula para el Éxito
Benjamin Franklin se convirtió en el americano más querido de su tiempo porque aprendió temprano en la vida que "no hablaré mal de ningún hombre... y de todos hablaré todo el bien que sepa."

**Cualquier Tonto Puede Criticar:**
Cualquier tonto puede criticar, condenar y quejarse, y la mayoría de los tontos lo hacen. Pero se necesita carácter y autocontrol para ser comprensivo y perdonar.

#### Regla Número 1
**No critique, no condene, no se queje.**

### Principio 2: Demuestre Aprecio Honrado y Sincero

#### El Gran Secreto para Tratar con las Personas
Solo hay una forma bajo el cielo de conseguir que alguien haga algo. ¿Se ha detenido alguna vez a meditar en esto? Sí, solo una forma. Y es hacer que la otra persona quiera hacerlo.

**¿Qué Quiere Todo el Mundo?**
Sigmund Freud dijo que todo lo que usted y yo hacemos surge de dos motivos: el impulso sexual y el deseo de ser grande.

John Dewey, uno de los filósofos más profundos de América, formuló esto de manera ligeramente diferente. Dijo que el impulso más profundo en la naturaleza humana es "el deseo de ser importante."

#### La Diferencia entre Aprecio y Adulación
- **Aprecio**: Es sincero. Viene del corazón. Es desinteresado.
- **Adulación**: Es superficial, egoísta y universalmente condenada.

**Historia de Pamela Dunham:**
Una mujer escribió a Carnegie sobre cómo transformó su matrimonio simplemente expresando aprecio genuino por las pequeñas cosas que su esposo hacía, en lugar de criticar lo que no hacía.

#### El Principio que Cambió una Vida
Charles Schwab ganaba un millón de dólares al año (equivalente a más de 15 millones hoy) porque tenía la capacidad de tratar con las personas. Su secreto: "Considero que mi capacidad para despertar entusiasmo entre las personas es el bien más grande que poseo, y la forma de desarrollar lo mejor que hay en una persona es por medio del aprecio y el aliento."

#### Regla Número 2
**Demuestre aprecio honrado y sincero.**

### Principio 3: Despierte en los Demás un Deseo Vehemente

#### Cómo Pescar
Si usted va a pescar, no piensa en lo que le gusta a usted; piensa en lo que les gusta a los peces. No ceba el anzuelo con fresas con crema. Ceba el anzuelo con gusanos o saltamontes.

**¿Por qué no usar la misma psicología cuando pescamos personas?**

#### La Única Forma de Influir en Otras Personas
La única forma en la tierra de influir en otras personas es hablar acerca de lo que ellas quieren y demostrarles cómo conseguirlo.

**Historia de Henry Ford:**
Cuando los hijos de Henry Ford dejaron la escuela y se negaron a trabajar, Ford no los sermoneó sobre responsabilidad. En su lugar, les mostró cómo el trabajo podría darles lo que querían: independencia y respeto.

#### El Secreto del Éxito de Andrew Carnegie
Andrew Carnegie pagó a Charles Schwab un salario de un millón de dólares al año porque Schwab podía manejar personas. ¿Cómo lo hacía? Despertando entusiasmo en las personas, y lo hacía apreciando y alentando.

#### Hablando en Términos de los Intereses de la Otra Persona
Cuando Theodore Roosevelt esperaba un visitante en la Casa Blanca, se quedaba despierto hasta tarde la noche anterior leyendo sobre el tema que más interesaba a su huésped. Roosevelt sabía que el camino real al corazón de una persona es hablar sobre las cosas que él o ella más aprecia.

#### Regla Número 3
**Despierte en los demás un deseo vehemente.**

## SEGUNDA PARTE: SEIS MANERAS DE AGRADAR A LAS PERSONAS

### Principio 1: Interésese Genuinamente en las Otras Personas

#### El Secreto de la Popularidad
Usted puede hacer más amigos en dos meses interesándose genuinamente en otras personas que los que puede hacer en dos años tratando de que otras personas se interesen en usted.

**Historia del Perro:**
¿Por qué cree que los perros tienen tantos amigos? Porque están genuinamente contentos de vernos. Cuando un perro ve a su amo, se emociona tanto que salta y mueve la cola y lame la cara de su amo.

#### La Técnica que Usaba Theodore Roosevelt
Roosevelt recordaba los nombres de todos, desde el portero hasta el presidente de una corporación. Su técnica: interés genuino en las personas.

#### Si Queremos Hacer Amigos
Si queremos hacer amigos, salgamos de nuestro camino para hacer cosas por otras personas, cosas que requieren tiempo, energía, altruismo y consideración.

**Historia de la Señora Charles Northam:**
Una mujer solitaria en Nueva York transformó su vida social simplemente comenzando a interesarse genuinamente en otras personas en lugar de esperar que se interesaran en ella.

#### Regla Número 1
**Interésese genuinamente en las otras personas.**

### Principio 2: Sonría

#### El Valor de una Sonrisa
Una sonrisa no cuesta nada, pero crea mucho. Enriquece a quienes la reciben, sin empobrecer a quienes la dan. Ocurre en un abrir y cerrar de ojos, y su recuerdo dura a veces para siempre.

**Historia del Hombre que No Sonreía:**
Un hombre de Nueva York que nunca sonreía decidió experimentar sonriendo durante una semana. Los resultados fueron tan dramáticos que transformó completamente su vida personal y profesional.

#### Las Acciones Hablan Más Fuerte que las Palabras
Las personas que sonríen tienden a manejar, enseñar y vender más efectivamente, y a criar niños más felices. Hay mucha más información en una sonrisa que en un ceño fruncido.

#### La Sonrisa que Vale un Millón de Dólares
William B. Steinhardt, un corredor de bolsa de Nueva York, admitió que su sonrisa había valido un millón de dólares. Explicó que cuando comenzó a sonreír genuinamente a sus clientes, sus ventas se dispararon.

#### Debe Venir del Interior
Una sonrisa insincera es mecánica y ofende. Estamos hablando de una sonrisa real, que calienta el corazón, que viene del interior, el tipo que vale mucho en el mercado.

#### Regla Número 2
**Sonría.**

### Principio 3: Recuerde que para una Persona, su Nombre es el Sonido más Dulce e Importante en Cualquier Idioma

#### La Importancia de los Nombres
La mayoría de las personas no recuerdan nombres por la simple razón de que no se toman el tiempo y la energía necesarios para concentrarse y repetir y fijar nombres claramente en sus mentes.

**Historia de Andrew Carnegie:**
Cuando Carnegie era un niño pobre en Escocia, atrapó una coneja madre. Pronto tuvo una camada de conejitos, pero no tenía nada para alimentarlos. Entonces tuvo una idea brillante: les dijo a los niños del vecindario que si traían suficiente trébol y diente de león para alimentar a los conejos, él nombraría a los conejos en honor a ellos. El plan funcionó como magia.

#### La Técnica de Carnegie en los Negocios
Años más tarde, Carnegie usó la misma psicología en los negocios. Cuando estaba luchando contra George Pullman por el negocio de los coches cama, Carnegie construyó la planta más grande y la llamó "Pullman Palace Car Company." Pullman se sintió tan halagado que le dio a Carnegie el contrato.

#### Cómo Recordar Nombres
1. **Escuche cuidadosamente** cuando se presente
2. **Repita el nombre** inmediatamente
3. **Haga una asociación mental** con algo familiar
4. **Escriba el nombre** si es posible
5. **Use el nombre** durante la conversación

#### La Política de Jim Farley
Jim Farley, quien ayudó a Franklin D. Roosevelt a llegar a la Casa Blanca, podía llamar por su nombre a 50,000 personas. Su secreto: cuando conocía a alguien, averiguaba su nombre completo, el tamaño de su familia, la naturaleza de su negocio y sus opiniones políticas. Toda esta información la archivaba en su mente como un archivo de computadora.

#### Regla Número 3
**Recuerde que para una persona, su nombre es el sonido más dulce e importante en cualquier idioma.**

### Principio 4: Sea un Buen Oyente. Anime a Otros a Hablar de Sí Mismos

#### El Camino Real al Corazón de una Persona
Para ser interesante, sea interesado. Haga preguntas que a las otras personas les guste responder. Anímelas a hablar de sí mismas y de sus logros.

**Historia del Botánico:**
Un distinguido botánico asistió a una cena donde conoció a Carnegie. Carnegie no sabía nada de botánica, pero estaba genuinamente interesado. Hizo preguntas inteligentes y escuchó atentamente. Al final de la noche, el botánico le dijo al anfitrión que Carnegie era el "conversador más interesante" que había conocido.

#### La Técnica de Escuchar de Lincoln
Incluso cuando Lincoln era presidente, escuchaba durante horas a visitantes que venían a la Casa Blanca. Una vez escuchó a un hombre durante horas sin decir una palabra. Cuando el hombre se fue, le dijo a sus amigos que había tenido una "conversación deliciosa" con el presidente.

#### Por qué Funciona la Escucha
- Las personas están más interesadas en sí mismas que en usted
- Una persona que habla solo de sí misma, solo piensa en sí misma
- La persona que piensa solo en sí misma es desesperadamente ineducada

#### Cómo Ser un Buen Oyente
1. **Dé su atención completa**
2. **Haga preguntas que fomenten más conversación**
3. **No interrumpa**
4. **Muestre interés genuino**
5. **Recuerde los detalles para conversaciones futuras**

#### Regla Número 4
**Sea un buen oyente. Anime a otros a hablar de sí mismos.**

### Principio 5: Hable en Términos de los Intereses de la Otra Persona

#### Encontrando el Interés Dominante
Siempre que Roosevelt esperaba un visitante, se quedaba despierto hasta tarde la noche anterior leyendo sobre el tema que sabía que más interesaba a su huésped.

**Historia del Niño Explorador:**
Un ejecutivo quería que su hijo de 10 años dejara de fumar. En lugar de sermonear sobre los peligros para la salud, habló sobre cómo fumar afectaría su capacidad para hacer senderismo y actividades de explorador. El niño dejó de fumar inmediatamente.

#### En los Negocios
Edward Chalif era presidente de una de las mayores empresas de construcción de apartamentos en Nueva York. Cuando quería rentar apartamentos, no hablaba sobre lo que él quería. Hablaba sobre lo que el inquilino quería: comodidad, conveniencia, prestigio.

#### La Regla de Oro de los Negocios
Todos los clientes exitosos han aprendido que el camino al corazón de las personas es hablar sobre las cosas que ellas más aprecian.

#### Regla Número 5
**Hable en términos de los intereses de la otra persona.**

### Principio 6: Haga que la Otra Persona se Sienta Importante, y Hágalo Sinceramente

#### El Deseo Más Profundo
El deseo de sentirse importante es uno de los principales factores distintivos que separan a la humanidad del reino animal.

**Historia de la Pequeña Anciana:**
Carnegie conoció a una anciana de 76 años en un hogar de ancianos que no había hablado con nadie en años. Cuando Carnegie le preguntó sobre su vida y escuchó con interés genuino, ella se animó completamente y comenzó a hablar. Más tarde, las enfermeras dijeron que fue la primera vez en años que la habían visto tan feliz.

#### Cómo Hacer que las Personas se Sientan Importantes
1. **Use frases como "Lo siento mucho molestarlo"**
2. **Diga "¿Sería tan amable de...?"**
3. **Agradezca a las personas por su tiempo**
4. **Reconozca la experiencia de otros**
5. **Pida consejos y opiniones**

#### La Diferencia entre Aprecio y Adulación
- **Aprecio**: Viene del corazón, es sincero
- **Adulación**: Es superficial, viene de los dientes hacia afuera

#### La Regla de Oro
Haga a otros lo que le gustaría que le hicieran a usted. ¿Cómo le gustaría ser tratado si estuviera en su lugar?

#### Regla Número 6
**Haga que la otra persona se sienta importante, y hágalo sinceramente.**

## TERCERA PARTE: DOCE MANERAS DE GANAR A LAS PERSONAS A SU MANERA DE PENSAR

### Principio 1: La Única Manera de Salir Ganando de una Discusión es Evitándola

#### Por qué las Discusiones son Inútiles
No se puede ganar una discusión. No se puede porque si se pierde, se pierde; y si se gana, se pierde. ¿Por qué? Bueno, suponga que triunfa sobre el otro hombre y demuestra que está equivocado. ¿Y qué? Se sentirá satisfecho. Pero ¿y él? Lo ha hecho sentir inferior. Ha lastimado su orgullo.

**Historia de Patrick J. O''Haire:**
Un vendedor de camiones aprendió esta lección cuando un cliente lo desafió sobre las especificaciones técnicas. En lugar de discutir, O''Haire dijo: "Puede que tenga razón. No lo había pensado de esa manera." El cliente se calmó inmediatamente y terminó comprando el camión.

#### Cómo Evitar Discusiones
1. **Desconfíe de su primera reacción instintiva**
2. **Controle su temperamento**
3. **Escuche primero**
4. **Busque áreas de acuerdo**
5. **Sea honesto**
6. **Piense sobre las ideas de sus oponentes**
7. **Agradezca a sus oponentes sinceramente por su interés**
8. **Posponga la acción para dar tiempo a que ambos lados piensen**

#### La Sabiduría de Benjamin Franklin
"Si discutes y peleas y contradices, puedes lograr a veces una victoria; pero será una victoria vacía porque nunca obtendrás la buena voluntad de tu oponente."

#### Regla Número 1
**La única manera de salir ganando de una discusión es evitándola.**

### Principio 2: Demuestre Respeto por las Opiniones Ajenas. Jamás Diga a una Persona que Está Equivocada

#### Las Palabras que Destruyen
Nunca comience diciendo: "Le voy a demostrar tal y tal cosa." Eso es malo. Equivale a decir: "Soy más inteligente que usted. Voy a decirle una o dos cosas y le haré cambiar de idea."

**Historia de un Vendedor de Seguros:**
Un vendedor perdía clientes constantemente diciéndoles que estaban equivocados sobre sus pólizas actuales. Cuando cambió su enfoque y comenzó a decir: "Pensé de manera diferente, pero puede que me equivoque. Examinemos los hechos," sus ventas se dispararon.

#### El Método Socrático
Sócrates, "el hombre más sabio de Atenas," nunca le decía a nadie que estaba equivocado. Su método era hacer preguntas que llevaban a las personas a descubrir la verdad por sí mismas.

#### Frases que Suavizan el Desacuerdo
- "Puede que me equivoque. Frecuentemente lo estoy. Examinemos los hechos."
- "Pensé de manera diferente, pero puede que esté equivocado."
- "Entiendo perfectamente su punto de vista."
- "Esa es una forma interesante de verlo."

#### La Técnica de Galileo
Cuando Galileo quería probar que la Tierra giraba alrededor del Sol, no atacó directamente las creencias de la Iglesia. En su lugar, presentó sus ideas como "hipótesis interesantes" que merecían consideración.

#### Regla Número 2
**Demuestre respeto por las opiniones ajenas. Jamás diga a una persona que está equivocada.**

### Principio 3: Si Usted Está Equivocado, Admítalo Rápida y Enfáticamente

#### El Poder de la Admisión
Cuando sabemos que vamos a ser regañados, ¿no es mucho mejor adelantarse y regañarnos a nosotros mismos? ¿No es mucho más fácil escuchar la crítica de nuestros propios labios que de labios ajenos?

**Historia Personal de Carnegie:**
Carnegie caminaba con su perro sin correa en un parque donde era requerido. Cuando un policía se acercó, Carnegie inmediatamente admitió que estaba equivocado y se criticó a sí mismo más duramente de lo que el policía podría haberlo hecho. El resultado: el policía se volvió comprensivo y amigable.

#### Por qué Funciona
- Desarma a la otra persona
- Reduce la tensión
- Muestra carácter
- Genera respeto
- Permite enfocarse en soluciones

#### La Técnica de Bruce Harvey
Un supervisor admitió rápidamente un error costoso ante su jefe, tomando completa responsabilidad. En lugar de ser despedido, fue promovido porque demostró integridad y liderazgo.

#### Regla Número 3
**Si usted está equivocado, admítalo rápida y enfáticamente.**

### Principio 4: Empiece en Forma Amigable

#### La Fábula de Esopo
El Sol y el Viento discutían sobre cuál era más fuerte. Decidieron competir para ver quién podía hacer que un hombre se quitara su abrigo. El Viento sopló fuertemente, pero mientras más fuerte soplaba, más se envolvía el hombre en su abrigo. Entonces el Sol brilló suavemente, y el hombre se quitó el abrigo voluntariamente.

**Moraleja:** La amabilidad y la apreciación pueden hacer que las personas cambien de opinión más fácilmente que toda la fuerza del mundo.

#### La Técnica de Lincoln
Lincoln una vez comenzó una carta a un oficial militar obstinado con estas palabras: "Todo el mundo le gusta un cumplido." Luego procedió a elogiar al hombre antes de hacer su petición.

#### Cómo Empezar Amigablemente
1. **Comience con algo en lo que ambos estén de acuerdo**
2. **Enfatice que ambos están trabajando hacia el mismo objetivo**
3. **Mencione algo que aprecie sobre la otra persona**
4. **Use un tono cálido y amigable**

#### Regla Número 4
**Empiece en forma amigable.**

### Principio 5: Consiga que la Otra Persona Diga "Sí, Sí" Inmediatamente

#### La Técnica del "Sí"
Cuando una persona dice "No," todo su organismo - glandular, nervioso, muscular - se reúne en una condición de rechazo. Cuando dice "Sí," ninguno de los sistemas de retiro se pone en acción.

**Historia de Eddie Snow:**
Un vendedor de seguros transformó su técnica de ventas comenzando cada presentación con preguntas que sabía que el prospecto respondería "sí." Para cuando llegaba a su propuesta principal, el cliente estaba en un estado mental positivo.

#### El Método Socrático Moderno
Sócrates hacía preguntas con las que su oponente tenía que convenir. Seguía ganando una admisión tras otra hasta que tenía una armada de "síes" a su favor.

#### Ejemplos de Preguntas "Sí"
- "¿Está de acuerdo en que queremos lo mejor para su familia?"
- "¿Le gustaría ahorrar dinero si fuera posible?"
- "¿Cree que la calidad es importante?"

#### Regla Número 5
**Consiga que la otra persona diga "sí, sí" inmediatamente.**

### Principio 6: Permita que la Otra Persona Hable Mucho

#### El Valor de Escuchar
La mayoría de las personas que tratan de ganar a otros a su manera de pensar hablan demasiado. Deje que la otra persona hable. Ella sabe más sobre su negocio y sus problemas que usted.

**Historia del Vendedor de Camiones:**
Un vendedor estaba perdiendo una venta importante hasta que dejó de hablar y comenzó a escuchar. El cliente reveló exactamente lo que necesitaba, y el vendedor pudo adaptar su presentación perfectamente.

#### Por qué Funciona
- Las personas se convencen más por las razones que ellas mismas descubren
- Hablar les permite desahogarse
- Revela información valiosa
- Hace que se sientan importantes

#### Regla Número 6
**Permita que la otra persona hable mucho.**

### Principio 7: Permita que la Otra Persona Sienta que la Idea es de Ella

#### El Poder de la Propiedad
Las personas tienen mucha más fe en las ideas que ellas mismas descubren que en las ideas que se les sirven en bandeja de plata.

**Historia de Eugene Wesson:**
Un ejecutivo quería que su jefe adoptara una nueva política. En lugar de presentarla directamente, plantó la semilla de la idea y dejó que su jefe llegara a la conclusión por sí mismo. El jefe adoptó la idea entusiasticamente, creyendo que era suya.

#### La Técnica de la Sugerencia
- Haga preguntas que guíen hacia la conclusión deseada
- Presente información que permita a la otra persona "descubrir" la solución
- Dé crédito generosamente cuando adopten "su" idea

#### Regla Número 7
**Permita que la otra persona sienta que la idea es de ella.**

### Principio 8: Trate Honradamente de Ver las Cosas desde el Punto de Vista de la Otra Persona

#### La Importancia de la Empatía
Hay una razón por la que la otra persona piensa y actúa como lo hace. Descubra esa razón oculta y tendrá la clave de sus acciones, quizás de su personalidad.

**Historia del Inquilino Problemático:**
Un propietario tenía un inquilino que se quejaba constantemente. En lugar de discutir, el propietario se puso en el lugar del inquilino y descubrió que sus quejas eran legítimas. Al abordar los problemas reales, convirtió a un inquilino problemático en uno satisfecho.

#### Cómo Desarrollar Empatía
1. **Pregúntese: "¿Cómo me sentiría yo en su lugar?"**
2. **Considere su trasfondo y experiencias**
3. **Escuche no solo las palabras, sino las emociones**
4. **Suspenda el juicio temporalmente**

#### Regla Número 8
**Trate honradamente de ver las cosas desde el punto de vista de la otra persona.**

### Principio 9: Muestre Simpatía por las Ideas y Deseos de la Otra Persona

#### El Poder de la Validación
Todas las personas que usted encuentra tienen un sentimiento de superioridad en algún aspecto. Un camino seguro al corazón de las personas es hacerles saber que usted reconoce su importancia en su pequeño mundo.

**Frases Mágicas:**
- "No lo culpo por sentirse como se siente. Si yo estuviera en su lugar, me sentiría exactamente igual."
- "Esa es una preocupación muy comprensible."
- "Puedo entender perfectamente por qué se siente así."

#### Historia del Cliente Enojado
Un gerente de servicio al cliente transformó una situación hostil simplemente diciendo: "Tiene toda la razón de estar molesto. En su lugar, yo estaría furioso." Esta validación inmediatamente calmó al cliente y permitió una resolución constructiva.

#### Regla Número 9
**Muestre simpatía por las ideas y deseos de la otra persona.**

### Principio 10: Apele a los Motivos Más Nobles

#### La Naturaleza Humana
Una persona generalmente tiene dos razones para hacer algo: una que suena bien y la razón real. La persona misma pensará en la razón real. Usted no necesita enfatizarla. Pero todos, siendo idealistas de corazón, les gusta pensar en motivos que suenan bien.

**Historia del Inquilino Moroso:**
Un propietario tenía un inquilino que no pagaba la renta. En lugar de amenazar con desalojo, apeló al sentido de justicia del inquilino: "Sé que usted es una persona honorable y que quiere hacer lo correcto." El inquilino pagó inmediatamente.

#### Motivos Nobles Comunes
- Justicia y equidad
- Honestidad e integridad
- Servicio a otros
- Hacer lo correcto
- Ser una buena persona

#### Regla Número 10
**Apele a los motivos más nobles.**

### Principio 11: Dramatice sus Ideas

#### El Poder del Drama
La verdad tiene que ser hecha vívida, interesante, dramática. Usted tiene que usar el espectáculo. Las películas lo hacen. La televisión lo hace. Y usted tendrá que hacerlo si quiere atención.

**Historia del Vendedor de Aspiradoras:**
Un vendedor no podía convencer a una ama de casa de que necesitaba una nueva aspiradora hasta que esparció tierra en su alfombra y demostró dramáticamente cuánta suciedad su vieja aspiradora no podía recoger.

#### Técnicas de Dramatización
- Use demostraciones visuales
- Cuente historias impactantes
- Use analogías poderosas
- Cree experiencias memorables

#### Regla Número 11
**Dramatice sus ideas.**

### Principio 12: Lance, con Tacto, un Reto

#### El Poder de la Competencia
La forma de conseguir que se hagan las cosas es estimular la competencia. No hablo del sórdido motivo monetario. Hablo del deseo de sobresalir, del deseo de sentirse importante.

**Historia de Charles Schwab:**
Schwab tenía una planta que no estaba produciendo su cuota. En lugar de criticar, escribió el número de piezas producidas ese día en el piso. El turno de noche vio el número y lo superó. La competencia amistosa continuó hasta que la planta superó todas las expectativas.

#### Elementos de un Reto Efectivo
- Debe ser alcanzable pero desafiante
- Debe apelar al orgullo
- Debe ser justo para todos
- Debe tener reconocimiento para el ganador

#### Regla Número 12
