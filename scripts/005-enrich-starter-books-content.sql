## Los 4 Componentes de CNV

### 1. Observación (sin Juicio)
Describes lo que VES/ESCUCHAS sin interpretación:
- ❌ "Eres irresponsable" (juicio)
- ✅ "He notado que llegas 15 minutos tarde a las reuniones" (observación)

### 2. Sentimiento
Expresas tu emoción genuina:
- ❌ "Me siento como que no te importa" (juicio disfrazado)
- ✅ "Me siento frustrado" (sentimiento real)

### 3. Necesidad
Identifica la necesidad humana universal subyacente:
- Necesidades comunes: respeto, seguridad, autonomía, conexión, crecimiento, contribución
- ❌ "Necesito que hagas las cosas a mi manera"
- ✅ "Necesito sentir que mi contribución es valorada"

### 4. Petición
Haces una solicitud clara y específica, no una demanda:
- ❌ "¡Debes cambiar!"
- ✅ "¿Estarías dispuesto a confirmar conmigo antes de cambios importantes?"

## El Proceso CNV en Conflicto

### En una Discusión Acalorada
1. Haz una observación sin culpa
2. Expresa tu sentimiento real
