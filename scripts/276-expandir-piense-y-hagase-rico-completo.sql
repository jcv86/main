# CAPÍTULO 8: DECISIÓN

**El dominio de la procrastinación**

El análisis de varios cientos de personas que habían acumulado fortunas más allá de la marca de millón de dólares reveló el hecho de que cada una de ellas tenía el hábito de TOMAR DECISIONES CON PRONTITUD, y de cambiar estas decisiones LENTAMENTE, si es que las cambiaban.

Las personas que no logran acumular dinero tienen, sin excepción, el hábito de llegar a decisiones, si es que llegan a ellas, MUY LENTAMENTE, y de cambiar estas decisiones rápida y frecuentemente.

**El valor del análisis propio**

Las opiniones son las mercancías más baratas en la tierra. Todo el mundo tiene una avalancha de opiniones listas para embestir sobre cualquiera que las acepte. Si permites que las opiniones de otros influyan en ti cuando llegues a una decisión, no tendrás éxito en ningún emprendimiento.

