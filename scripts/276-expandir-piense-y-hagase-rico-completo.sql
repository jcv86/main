# CAPÍTULO 6: IMAGINACIÓN

**El taller de la mente**

La IMAGINACIÓN es literalmente el taller donde se moldean todos los planes creados por el hombre. El impulso, el DESEO, se le da forma, forma y ACCIÓN a través de la ayuda de la facultad imaginativa de la mente.

Se ha dicho que el hombre puede crear cualquier cosa que pueda imaginar.

**Las dos formas de imaginación**

La facultad imaginativa funciona de dos formas. Una se conoce como "imaginación sintética" y la otra como "imaginación creativa".

**Imaginación sintética**: A través de esta facultad, uno puede arreglar conceptos, ideas o planes antiguos en nuevas combinaciones. Esta facultad no crea. Simplemente trabaja con el material de la experiencia, educación y observación con el cual se alimenta.

**Imaginación creativa**: A través de esta facultad, la mente finita del hombre tiene comunicación directa con la Inteligencia Infinita. Es la facultad a través de la cual se reciben los "presentimientos" e "inspiraciones".

