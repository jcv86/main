# CAPÍTULO 5: CONOCIMIENTO ESPECIALIZADO

**Experiencia personal u observación**

El conocimiento no es poder. Es solo poder potencial. El conocimiento no atraerá dinero, a menos que sea organizado y dirigido inteligentemente a través de planes prácticos de acción.

**Dónde adquirir conocimiento**

Las fuentes principales de conocimiento son:

1. La propia experiencia y educación
2. Experiencia y educación disponible a través de la cooperación de otros (Mente Maestra)
3. Colegios y universidades
4. Bibliotecas públicas (a través de libros y materiales periódicos)
5. Cursos especializados de capacitación (escuelas nocturnas y cursos de extensión)

El conocimiento especializado es entre las formas más abundantes y las más baratas de servicio disponible.

