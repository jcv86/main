# CAPÍTULO 9: PERSISTENCIA

**El esfuerzo sostenido necesario para inducir la fe**

La PERSISTENCIA es un factor esencial en el procedimiento de transmutar el DESEO en su equivalente monetario. La base de la persistencia es el PODER DE VOLUNTAD.

La persistencia es para el carácter del hombre lo que el carbono es para el acero.

**Los ocho síntomas de la persistencia**

1. Definición de propósito
2. Deseo
3. Confianza en sí mismo
4. Definitividad de planes
5. Conocimiento preciso
6. Cooperación
7. Fuerza de voluntad
8. Hábito

