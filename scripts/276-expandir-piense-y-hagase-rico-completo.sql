# CAPÍTULO 2: DESEO

**El punto de partida de todo logro**

El primer paso hacia la riqueza es el DESEO.

Cuando Henley escribió las líneas proféticas, "Soy el amo de mi destino, soy el capitán de mi alma", debería habernos dicho que somos los amos de nuestro destino, los capitanes de nuestras almas, porque tenemos el poder de controlar nuestros pensamientos.

Debería habernos dicho que el éter en el que el entretejido de nuestro universo flota, es una forma de energía que se mueve a una velocidad inconmensurable, y que el éter está lleno de una forma de energía universal que se adapta a los deseos de la humanidad, tanto constructivos como destructivos.

**Seis pasos para transformar el deseo en oro**

Primero: Fija en tu mente la cantidad exacta de dinero que deseas. No es suficiente decir simplemente "Quiero mucho dinero". Sé definido en cuanto a la cantidad.

Segundo: Determina exactamente qué pretendes dar a cambio del dinero que deseas. (No existe algo como "algo por nada").

Tercero: Establece una fecha definida en la que pretendes poseer el dinero que deseas.

Cuarto: Crea un plan definido para llevar a cabo tu deseo, y comienza de inmediato, estés o no listo, a poner este plan en acción.

Quinto: Escribe una declaración clara y concisa de la cantidad de dinero que pretendes adquirir, nombra el límite de tiempo para su adquisición, establece lo que pretendes dar a cambio del dinero, y describe claramente el plan a través del cual pretendes acumularlo.

Sexto: Lee tu declaración escrita en voz alta, dos veces al día, una vez justo antes de acostarte por la noche y otra después de levantarte por la mañana. A medida que lees, VE y SIENTE y CREE que ya estás en posesión del dinero.

**El hombre que quemó sus naves**

Una de las ilustraciones más comunes de la aplicación de estos principios es la historia del conquistador español, Hernán Cortés.

Cortés quemó sus barcos para que sus hombres no tuvieran la opción de rendirse. Él y sus hombres ganaron porque no tenían otra opción.

Esto es exactamente lo que cada persona debe hacer si quiere tener éxito. Quemar todos los puentes detrás de uno, y seguir adelante con un solo pensamiento: el éxito.

