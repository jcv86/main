# CAPÍTULO 10: PODER DEL GRUPO MENTE MAESTRA

**La fuerza impulsora**

PODER es esencial para el éxito en la acumulación de dinero.

Los PLANES son inertes e inútiles sin suficiente PODER para traducirlos en ACCIÓN.

**Las fuentes del poder**

El poder puede ser definido como "conocimiento organizado e inteligentemente dirigido". El poder se refiere al ESFUERZO ORGANIZADO, suficiente para permitir que un individuo transmute el DESEO en su equivalente monetario.

El ESFUERZO ORGANIZADO se produce a través de la coordinación del esfuerzo de dos o más personas, que trabajan hacia un FIN DEFINIDO, en un espíritu de armonía.

