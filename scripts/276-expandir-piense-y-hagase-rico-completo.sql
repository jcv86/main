# PREFACIO DEL AUTOR

En cada capítulo de este libro, se menciona el secreto del dinero de Andrew Carnegie, un secreto que ha hecho millonarios a más hombres que cualquier otra filosofía.

Este secreto fue traído a mi atención por Andrew Carnegie, hace más de un cuarto de siglo. El astuto, adorable viejo escocés me lo reveló casualmente y con una sonrisa traviesa, cuando yo era apenas un niño. Luego se recostó en su silla, con una expresión satisfecha en su rostro, y me observó cuidadosamente para ver si tenía suficiente sentido común para comprender el significado completo de lo que me acababa de decir.

Cuando vio que había captado la idea, me preguntó si estaría dispuesto a dedicar veinte años o más preparando el mundo para recibirlo. Dije que sí, y con la ayuda del Sr. Carnegie, mantuve esa promesa.

**El secreto**

Este libro contiene el secreto, después de haber sido puesto a prueba práctica por miles de personas, en casi todos los ámbitos de la vida. Fue la sugerencia del Sr. Carnegie que la magia que llevó a su enorme fortuna debería colocarse al alcance de las personas que no tienen tiempo para investigar cómo los hombres ganan dinero.

Espero ansiosamente el momento en que las fortunas del joven hombre de negocios que acaba de comenzar, y del hombre que ha llegado a la mitad de su viaje, que están tan ocupados ganándose la vida que no tienen tiempo para pensar cómo hacerse ricos, cambiarán cuando este libro llegue a sus manos.

