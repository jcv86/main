# CAPÍTULO 4: AUTO-SUGESTIÓN

**El medio para influir en la mente subconsciente**

La AUTO-SUGESTIÓN es un término que se aplica a todas las sugestiones e instrucciones autoadministradas que llegan a la propia mente a través de los cinco sentidos.

Es una agencia de comunicación entre esa parte de la mente donde el pensamiento consciente tiene lugar, y aquella que sirve como la sede de acción de la mente subconsciente.

A través del principio de autosugestión, las personas pueden elevar a grandes alturas de logro si mezclan su deseo con FE.

**Los tres pasos de la autosugestión**

Primero: Ve a un lugar tranquilo donde no serás molestado ni interrumpido, cierra tus ojos y repite en voz alta (para que puedas escucharte a ti mismo) la declaración escrita de la cantidad de dinero que pretendes acumular, el límite de tiempo para su acumulación, y una descripción del servicio o mercancía que pretendes dar a cambio del dinero.

Segundo: Repite este programa noche y mañana hasta que puedas VER (en tu imaginación) el dinero que pretendes acumular.

Tercero: Coloca una copia escrita de tu declaración donde puedas verla noche y mañana, y léela justo antes de retirarte por la noche, y justo después de levantarte hasta que se memorice.

