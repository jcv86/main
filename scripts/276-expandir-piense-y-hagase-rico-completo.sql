# CAPÍTULO 7: PLANIFICACIÓN ORGANIZADA

**La cristalización del deseo en acción**

Has aprendido que todo lo que el hombre crea o adquiere comienza en forma de DESEO, que el DESEO se toma en el primer cruce desde el reino de lo abstracto al reino de lo concreto, en el taller de la IMAGINACIÓN, donde se crean PLANES para su transición.

**Cómo construir planes prácticos**

1. Aliarte con un grupo de personas que sean necesarias para la creación y ejecución de tu plan o planes
2. Antes de formar tu "Mente Maestra", decide qué ventajas y beneficios puedes ofrecer a los miembros individuales del grupo
3. Organiza reuniones con los miembros de tu grupo al menos dos veces por semana
4. Mantén perfecta armonía entre ti y cada miembro de tu grupo

