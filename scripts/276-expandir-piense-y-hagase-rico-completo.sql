# CAPÍTULO 3: FE

**Visualización y creencia en el logro del deseo**

La FE es el "elixir eterno" que da vida, poder y acción al impulso del pensamiento.

La FE es el punto de partida de toda acumulación de riqueza. La FE es la base de todos los "milagros" y de todos los misterios que no pueden ser analizados por las reglas de la ciencia.

La FE es el único antídoto conocido para el fracaso. La FE es el elemento que transforma la vibración ordinaria del pensamiento, creada por la mente finita del hombre, en el equivalente espiritual.

**Cómo desarrollar la fe**

La FE es un estado mental que puede ser inducido, o creado, por afirmación o instrucciones repetidas a la mente subconsciente, a través del principio de autosugestión.

Repetición de afirmación de órdenes a tu mente subconsciente es el único método conocido de desarrollo voluntario de la emoción de la fe.

**La fórmula de la autosugestión**

Primera: Sé que tengo la habilidad de lograr el objeto de mi propósito definitivo en la vida; por lo tanto, EXIJO de mí mismo acción persistente y continua hacia su logro, y aquí y ahora prometo hacer tal acción.

Segunda: Me doy cuenta de que los pensamientos dominantes de mi mente eventualmente se reproducirán en acción física externa, y gradualmente se transformarán en realidad física; por lo tanto, concentraré mis pensamientos durante treinta minutos diarios, en la tarea de pensar en la persona que pretendo convertirme, creando así una imagen mental clara de esa persona.

Tercera: Sé a través del principio de autosugestión, cualquier deseo que sostenga persistentemente en mi mente eventualmente buscará expresión a través de algunos medios prácticos de alcanzar el objeto detrás de él; por lo tanto, dedicaré diez minutos diarios a exigir de mí mismo el desarrollo de CONFIANZA EN MÍ MISMO.

