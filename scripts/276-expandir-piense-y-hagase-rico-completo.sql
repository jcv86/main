# CAPÍTULO 1: PENSAMIENTO

**El hombre que "pensó" su camino hacia la asociación con Thomas A. Edison**

Cuando Edwin C. Barnes bajó del tren de carga en Orange, N.J., podría haber sido confundido con un vagabundo, pero sus pensamientos eran los de un rey.

Mientras avanzaba desde la plataforma de carga del ferrocarril, dirigió sus pasos hacia la oficina de Thomas A. Edison. Su apariencia no era la de alguien que estuviera siendo admitido a ver al inventor más famoso del mundo, pero Barnes logró su propósito.

Cuando apareció por primera vez ante el Sr. Edison, Barnes no se veía impresionante, pero había algo en la expresión de su rostro que transmitía el efecto de que estaba determinado a conseguir lo que había venido a buscar.

Años más tarde, el propio Edison habló de su primera reunión con el joven Barnes:

"Él estuvo parado allí frente a mí, pareciendo una mera vagabundo ordinario, pero había algo en su expresión que transmitía el efecto de que estaba determinado a conseguir lo que había venido a buscar. Yo había aprendido, de años de experiencia con hombres, que cuando un hombre desea realmente algo tan profundamente que está dispuesto a apostar todo su futuro en un solo giro de la rueda para conseguirlo, está seguro de ganar."

**El deseo ardiente**

Barnes no consiguió su asociación con Edison en su primera entrevista. Sin embargo, consiguió una oportunidad de trabajar en las oficinas de Edison, a un salario nominal. Pasaron meses. Aparentemente no sucedió nada que acercara a Barnes al objetivo que codiciaba.

Pero algo importante estaba sucediendo en la mente de Barnes. Estaba constantemente intensificando su DESEO de convertirse en el socio de negocios de Edison.

Los psicólogos han dicho correctamente, "cuando uno está verdaderamente listo para algo, aparecerá".

Barnes estaba listo para convertirse en el socio de negocios de Edison. Además, estaba DETERMINADO a seguir siendo listo hasta que OBTUVIERA aquello por lo que había venido.

No dijo a sí mismo, "Bueno, ¿qué pasa si Edison no me da la oportunidad que busco? ¿Qué puedo perder?"

Por el contrario, dijo: "Vine aquí para entrar en negocios con Edison, y lograré mi objetivo, incluso si me lleva el resto de mi vida."

**Los pensamientos son cosas**

Barnes ganó su objetivo, porque eligió un objetivo definitivo y apostó todo para lograr ese objetivo. Él no se convirtió en el socio de Edison el día que llegó. Pasaron cinco años antes de que la oportunidad que buscaba llegara. Pero llegó.

Cuando apareció, vino de una forma diferente, y de una dirección diferente de la que Barnes esperaba. Esa es una de las cosas raras de los logros. Si uno está listo, llega de manera inesperada.

Esto es lo que quiero decir cuando digo que los pensamientos son cosas, y las cosas poderosas cuando se mezclan con determinación, propósito y deseo ardiente.

