## Concepto 3: Confronta Los Hechos Brutales

### La Paradoja de Stockdale

**Historia de James Stockdale:**
- Prisionero de guerra en Vietnam, 8 años
- Torturado más de 20 veces
- Sin fecha de liberación
- Sobrevivió y se convirtió en héroe

**La Pregunta:** ¿Cómo sobreviviste?

**Respuesta de Stockdale:**
Nunca perdí fe en el final de la historia, que no solo saldría, sino que prevalecería al final.

**Segunda Pregunta:** ¿Quiénes no lo lograron?

**Respuesta:**
Los optimistas. Los que decían, Saldremos para Navidad. Y Navidad pasaba. Eventualmente murieron de un corazón roto.

### La Paradoja Aplicada a Empresas

**Debes:**
