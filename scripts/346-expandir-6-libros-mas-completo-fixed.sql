## Capítulo 3: Margin of Safety

### El Principio Más Importante

**Definición:**
Margin of safety es la diferencia entre el valor intrínseco de una acción y su precio de mercado.

**Ejemplo:**
- Valor intrínseco: 100 dólares
- Precio de mercado: 60 dólares
- Margin of safety: 40 por ciento

### Funciones del Margin of Safety

**1. Protección contra Error:**
Tus cálculos pueden estar equivocados.

**2. Protección contra Mala Suerte:**
Desarrollos adversos ocurren.

**3. Rendimientos Satisfactorios:**
Comprar con margin casi garantiza resultado satisfactorio.

