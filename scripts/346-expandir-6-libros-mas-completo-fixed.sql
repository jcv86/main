## Capítulo 1: Inversión vs. Especulación

### Definición de Inversión

**Inversión (según Graham):**
Una operación de inversión es aquella que, tras un análisis exhaustivo, promete seguridad del principal y un rendimiento adecuado.

**Tres Componentes Clave:**
1. Análisis exhaustivo
2. Seguridad del principal
3. Rendimiento adecuado

### El Inversor Defensivo vs. El Inversor Emprendedor

**Inversor Defensivo:**
- Prioridad: Evitar errores graves
- Enfoque: Diversificación amplia
- Esfuerzo: Mínimo
- Objetivo: Resultados promedio

**Inversor Emprendedor:**
- Prioridad: Resultados superiores
- Enfoque: Investigación continua
- Esfuerzo: Considerable
- Objetivo: Rendimientos superiores

