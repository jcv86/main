# VICTORIA PÚBLICA

## El paradigma de interdependencia

Los tres primeros hábitos tratan del autodominio. Se mueven de la dependencia a la independencia. Son las "Victorias Privadas".

Los Hábitos 4, 5 y 6 tratan de las relaciones con otros, trabajo en equipo, cooperación y comunicación. Son las "Victorias Públicas".

Para lograr victorias públicas, primero debemos lograr victorias privadas.

