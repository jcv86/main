# CONCLUSIÓN: DE ADENTRO HACIA AFUERA OTRA VEZ

El carácter privado precede al carácter público. La autodominio viene primero. Como dijo Dag Hammarskjöld: "Es más noble conquistarse a uno mismo que conquistar a otros."

La victoria sobre uno mismo es el triunfo más duradero. Para mantener los 7 Hábitos en tu vida requiere visión, disciplina y pasión: un compromiso constante de afilar la sierra.

**El ciclo ascendente**

El ciclo ascendente del crecimiento está en espiral. Nunca terminamos. Cada vez que aprendemos y nos comprometemos a los 7 Hábitos en un nivel más profundo, trabajamos en cada dimensión nuevamente, en una espiral ascendente de crecimiento.

Los 7 Hábitos no son un conjunto de prácticas de fórmula separadas. Son altamente integrales y sinérgicos. Sus relaciones compuestas resultan en una efectividad mucho mayor.

Al trabajar en tu carácter y vivir los principios incorporados en los 7 Hábitos, literalmente te conviertes en un agente de cambio.

**Crecimiento personal**

A medida que eres proactivo, comienzas con el fin en mente, pones primero lo primero, piensas Ganar-Ganar, buscas primero entender, sinergizas y afilas la sierra, te conviertes en una persona de transición.

Rompes con patrones limitantes familiares y culturales. Modelas el cambio que quieres ver en otros y en tu entorno.

Los 7 Hábitos no son un conjunto de trucos o técnicas para manipular a otros. Son principios fundamentales de efectividad que, cuando se practican consistentemente, transforman vidas.'
