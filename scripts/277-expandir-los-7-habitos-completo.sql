# INTRODUCCIÓN

En más de 25 años de trabajar con personas en negocios, universidades y relaciones matrimoniales y familiares, he llegado en contacto con muchas personas que han logrado un increíble grado de éxito exterior, pero que han luchado con una necesidad interna de desarrollar eficacia personal y relaciones saludables con otras personas.

He descubierto que muchas de estas personas creen que su situación sería diferente si solo otras personas cambiaran, si sus cónyuges fueran más sensibles, si sus hijos fueran más obedientes, o si su jefe fuera más comprensivo. Pero el problema está en sus percepciones, no en la realidad externa.

**De adentro hacia afuera**

Los 7 Hábitos de la Gente Altamente Efectiva representan un enfoque de "adentro hacia afuera" del desarrollo personal. Estos hábitos comienzan en el interior con paradigmas, carácter y motivos.

El enfoque de adentro hacia afuera dice que las victorias privadas preceden a las victorias públicas, que hacerse promesas a uno mismo y cumplirlas precede a hacer promesas a otros y cumplirlas.

