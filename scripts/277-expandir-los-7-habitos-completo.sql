# HÁBITO 4: PENSAR GANAR-GANAR

**Principios del liderazgo interpersonal**

Ganar-Ganar es una creencia en la Tercera Alternativa. No es tu manera ni mi manera; es una mejor manera, una manera más alta.

**Los seis paradigmas de la interacción humana**

1. **Ganar-Ganar**: Ambas partes obtienen lo que quieren
2. **Ganar-Perder**: "Si gano, tú pierdes"
3. **Perder-Ganar**: "Haré lo que sea que me pidas"
4. **Perder-Perder**: "Si voy hacia abajo, te llevaré conmigo"
5. **Ganar**: Las personas solo se preocupan por obtener lo que quieren
6. **Ganar-Ganar o No hay trato**: Si no podemos encontrar un acuerdo, estamos de acuerdo en no estar de acuerdo

**Los cinco elementos de Ganar-Ganar**

1. **Carácter**: Integridad, madurez, mentalidad de abundancia
2. **Relaciones**: Cuenta bancaria emocional
3. **Acuerdos**: Acuerdos de desempeño ganar-ganar
4. **Sistemas**: Los sistemas deben apoyar Ganar-Ganar
5. **Procesos**: Cuatro pasos para lograr Ganar-Ganar

