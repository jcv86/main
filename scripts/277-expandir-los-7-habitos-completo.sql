# PARADIGMAS Y PRINCIPIOS

## El poder de un cambio de paradigma

Cada uno de nosotros tiene muchos mapas en nuestra cabeza que pueden clasificarse en dos categorías principales: mapas de la forma en que las cosas son, o realidades, y mapas de la forma en que las cosas deberían ser, o valores.

Interpretamos todo lo que experimentamos a través de estos mapas mentales. Rara vez cuestionamos su precisión; usualmente ni siquiera somos conscientes de que los tenemos. Simplemente asumimos que la forma en que vemos las cosas es la forma en que realmente son o la forma en que deberían ser.

**Un ejemplo personal**

Recuerdo una experiencia que tuve en el metro de Nueva York un domingo por la mañana. La gente estaba sentada tranquilamente, algunos leyendo periódicos, algunos descansando con los ojos cerrados, algunos mirando por la ventana.

Entonces un hombre y sus hijos entraron al vagón. Los niños eran tan ruidosos y revoltosos que instantáneamente toda la atmósfera cambió. El hombre se sentó junto a mí y cerró sus ojos, aparentemente ajeno a la situación. Los niños gritaban, arrojaban cosas, incluso agarraron los periódicos de la gente.

Era muy molesto. No podía creer que el hombre pudiera ser tan insensible como para dejar que sus hijos corrieran salvajemente así y no hacer nada al respecto.

Así que, con lo que sentí que era control y restricción inusuales, me dirigí a él: "Señor, sus hijos están realmente molestando a muchas personas. Me pregunto si podría controlarlos un poco más."

El hombre levantó la vista como si estuviera consciente de la situación por primera vez y dijo suavemente: "Oh, tiene razón. Supongo que debería hacer algo al respecto. Acabamos de venir del hospital donde su madre murió hace aproximadamente una hora. No sé qué pensar, y supongo que ellos tampoco saben cómo manejarlo."

¿Puedes imaginar lo que sentí en ese momento? Mi paradigma cambió. De repente vi las cosas de manera diferente, y porque vi de manera diferente, pensé de manera diferente, sentí de manera diferente, me comporté de manera diferente.

