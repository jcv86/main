# HÁBITO 7: AFILAR LA SIERRA

**Principios de la renovación equilibrada**

El Hábito 7 es tomar tiempo para afilar la sierra. Rodea los otros hábitos porque es el que los hace todos posibles.

**Las cuatro dimensiones de la renovación**

El Hábito 7 es la renovación personal. Preserva y mejora el activo más grande que tienes: tú.

Tiene cuatro dimensiones de renovación:

**Física**: Ejercicio, nutrición, gestión del estrés
- Ejercitar regularmente de manera que construya resistencia, flexibilidad y fuerza
- Comer alimentos saludables y equilibrados
- Manejar el estrés de manera que aumente tu capacidad

**Espiritual**: Clarificación de valores y compromiso, estudio y meditación
- Clarificar y comprometerte con tus valores
- Estudiar literatura inspiradora
- Meditar para renovar tu espíritu

**Mental**: Leer, visualizar, planificar, escribir
- Leer buena literatura
- Limitar ver televisión
- Mantener un diario personal
- Planificar con anticipación

**Social/Emocional**: Servicio, empatía, sinergia, seguridad intrínseca
- Desarrollar tu seguridad intrínseca
- Trabajar en tu Círculo de Influencia
- Hacer depósitos en Cuentas Bancarias Emocionales de otros
- Practicar los Hábitos 4, 5 y 6 en interacciones diarias

**Renovación equilibrada**

Es importante trabajar en las cuatro dimensiones. Descuidar cualquier área afecta negativamente al resto.

