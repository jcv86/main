# HÁBITO 2: COMENZAR CON EL FIN EN MENTE

**Principios del liderazgo personal**

Comenzar con el fin en mente se basa en el principio de que todas las cosas se crean dos veces. Hay una creación mental (primera) y una creación física (segunda).

**Liderazgo y gestión**

La gestión es eficiencia en subir la escalera del éxito; el liderazgo determina si la escalera está apoyada contra la pared correcta.

Puedes ser muy ocupado, muy eficiente, muy eficaz, subiendo la escalera del éxito, solo para descubrir que está apoyada contra la pared equivocada.

**Una declaración de misión personal**

Una de las mejores maneras de incorporar el Hábito 2 en tu vida es desarrollar una Declaración de Misión Personal. Se enfoca en lo que quieres SER (carácter) y HACER (contribuciones y logros) y en los valores o principios sobre los cuales se basa el ser y el hacer.

Ejemplo de declaración de misión:
"Tener éxito en casa primero. Nunca comprometeré mi integridad personal. Escucharé a ambos lados antes de tomar una decisión. Aconsejaré con los demás. Defenderé ausentes. Seré sincero pero efectivo. Gastaré dentro de mi presupuesto. Seré humilde. Desarrollaré un nuevo talento al año."

