# HÁBITO 5: BUSCAR PRIMERO ENTENDER, LUEGO SER ENTENDIDO

**Principios de la comunicación empática**

Supón que has estado teniendo problemas con tus ojos y decides ver un optometrista para ayuda. Después de escuchar brevemente tu queja, él se quita los anteojos, te los entrega y dice: "Póntelos. Los he estado usando durante diez años, y realmente me han ayudado. Espero que te ayuden a ti."

Eso es absurdo, ¿verdad? Pero, ¿con qué frecuencia hacemos el equivalente con problemas de comunicación?

**Escucha empática**

Buscar Primero Entender involucra un cambio de paradigma muy profundo. Típicamente buscamos primero ser entendidos. La mayoría de la gente no escucha con la intención de entender; escuchan con la intención de responder.

La escucha empática entra en el marco de referencia de la otra persona. Miras a través de él, ves el mundo como esa persona lo ve, entiendes su paradigma, entiendes cómo se siente.

**Los cinco niveles de escucha**

1. **Ignorar**: No escuchar realmente en absoluto
2. **Fingir**: "Sí. Uh-huh. Correcto"
3. **Escucha selectiva**: Escuchar solo ciertas partes
4. **Escucha atenta**: Prestar atención y enfocar energía
5. **Escucha empática**: Escuchar con la intención de entender

