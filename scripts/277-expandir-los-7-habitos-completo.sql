# HÁBITO 6: SINERGIZAR

**Principios de la cooperación creativa**

La sinergia significa que el todo es más que la suma de sus partes. Significa que la relación que las partes tienen entre sí es una parte en y por sí misma.

La esencia de la sinergia es valorar las diferencias: las diferencias mentales, emocionales y psicológicas entre las personas.

**Comunicación sinérgica**

Cuando te comunicas sinérgicamente, simplemente abres tu mente y corazón y expresión a nuevas posibilidades, nuevas alternativas, nuevas opciones.

En una situación interdependiente, la sinergia es especialmente poderosa en tratar con fuerzas negativas que trabajan contra el crecimiento y el cambio.

**La tercera alternativa**

En una situación de interdependencia, la sinergia es particularmente poderosa al tratar con fuerzas negativas que trabajan contra el crecimiento y el cambio.

La sinergia dice que 1 + 1 puede igual 8, 16 o incluso 1,600. La relación sinérgica es la que la mayoría de las personas experimenta solo unas pocas veces en sus vidas, donde cada persona aporta sus fortalezas para compensar las debilidades del otro.

