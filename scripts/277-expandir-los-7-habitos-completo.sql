# HÁBITO 1: SER PROACTIVO

**Principios de la visión personal**

Entre el estímulo y la respuesta, el hombre tiene la libertad de elegir.

Las personas reactivas son impulsadas por sentimientos, circunstancias, condiciones y su entorno. Las personas proactivas son impulsadas por valores, valores seleccionados cuidadosamente, pensados y internalizados.

**Tomando la iniciativa**

Ser proactivo significa algo más que tomar la iniciativa. Significa que como seres humanos, somos responsables de nuestras propias vidas. Nuestro comportamiento es una función de nuestras decisiones, no de nuestras condiciones.

Tenemos la iniciativa y la responsabilidad de hacer que las cosas sucedan.

**El círculo de influencia y el círculo de preocupación**

Las personas proactivas enfocan sus esfuerzos en el Círculo de Influencia. Trabajan en las cosas que pueden hacer algo al respecto: salud, hijos, problemas en el trabajo.

Las personas reactivas enfocan sus esfuerzos en el Círculo de Preocupación. Su enfoque resulta en acusar y actitudes reactivas, lenguaje de víctima aumentado y sentimientos de impotencia.

**Lenguaje reactivo vs. proactivo**

Reactivo:
- "No hay nada que pueda hacer"
- "Así soy yo"
- "Me vuelve loco"
- "No lo permitirán"

Proactivo:
- "Veamos nuestras alternativas"
- "Puedo elegir un enfoque diferente"
- "Controlo mis propios sentimientos"
- "Puedo crear una presentación efectiva"

