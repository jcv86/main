# HÁBITO 3: PONER PRIMERO LO PRIMERO

**Principios de la gestión personal**

El Hábito 3 es la segunda creación, la creación física. Es la realización, la actualización, la aparición natural de los Hábitos 1 y 2.

El Hábito 3 es donde los Hábitos 1 y 2 se juntan. Sucede día a día, momento a momento. Trata con muchas de las preguntas abordadas en el campo de la gestión de la vida y el tiempo.

**La matriz de gestión del tiempo**

Hay cuatro generaciones de gestión del tiempo:

**Primera generación**: Notas y listas de verificación
**Segunda generación**: Calendarios y citas
**Tercera generación**: Priorización, establecimiento de metas
**Cuarta generación**: Paradigma de gestión personal

La matriz de gestión del tiempo se organiza en cuatro cuadrantes:

**Cuadrante I**: Urgente e Importante (Crisis, problemas apremiantes)
**Cuadrante II**: No urgente pero Importante (Prevención, construcción de relaciones, planificación)
**Cuadrante III**: Urgente pero No importante (Interrupciones, algunas llamadas, correos)
**Cuadrante IV**: No urgente y No importante (Trivialidades, pérdida de tiempo)

**El cuadrante II**

Las personas efectivas permanecen fuera de los Cuadrantes III y IV porque, urgentes o no, no son importantes. También reducen el Cuadrante I pasando más tiempo en el Cuadrante II.

El Cuadrante II es el corazón de la gestión personal efectiva. Trata con cosas que no son urgentes, pero sí importantes. Trata con cosas como construir relaciones, escribir una declaración de misión personal, ejercicio, preparación preventiva: todas esas cosas que sabemos que necesitan hacerse, pero de alguna manera rara vez llegamos a hacer, porque no son urgentes.

