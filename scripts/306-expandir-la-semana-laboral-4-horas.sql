Por Tim Ferriss

INTRODUCCION: PRIMER PASO - SISTEMA DE VALORES ALTERNATIVOS

Este libro no es sobre retiro diferido. Es sobre distribuir mini-retiros y aventuras a lo largo de vida.

Pregunta no es cuando puedes retirarte, sino como puedes disenar vida que quieres AHORA.

NUEVO RICO vs DIFERIDORES

DIFERIDORES (Traditional)
- Trabajan por dinero
- Esperan hasta 65 para vivir
- Compran cosas que no necesitan
- Trabajan mas horas para mas dinero

NUEVO RICO (New Rich)
- Dinero es medio, no fin
- Viven bien ahora mientras construyen negocios
- Valoran tiempo y movilidad sobre posesiones
- Trabajan inteligentemente, no duramente

DEFINICION DE RIQUEZA

Riqueza = Que haces + Cuando lo haces + Donde lo haces + Con quien lo haces

No solo cuanto tienes en banco.

PASOS DEL SISTEMA DEAL

