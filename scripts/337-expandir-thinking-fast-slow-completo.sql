**CAPÍTULO 4: LA MÁQUINA DE SALTAR A CONCLUSIONES**

**Sistema 1 Busca Coherencia:**

**Ejemplo:**

"John está corriendo."

Tu mente automáticamente añade:
- Está haciendo ejercicio (tal vez)
- Está apurado (posiblemente)
- Está escapando (quizás)

**Creaste una historia coherente con información mínima.**

**El Efecto Halo:**

Tu impresión general de una persona influye tu evaluación de sus características específicas.

**Experimento:**

**Descripción A:**
"Alan es inteligente, trabajador, impulsivo, crítico, terco, envidioso"

**Descripción B:**
"Ben es envidioso, terco, crítico, impulsivo, trabajador, inteligente"

**Las mismas características, orden inverso.**

**Resultado:** Alan es visto mucho más favorablemente que Ben.

**Por qué:** Las primeras impresiones colorean todo lo demás.

**WYSIATI: What You See Is All There Is**

**Principio:** Sistema 1 construye la mejor historia posible con la información disponible, ignorando la información que falta.

**Ejemplo:**

**Escenario:** "Laura tiene un doctorado en física."

**Tu mente automáticamente asume:**
- Es inteligente
- Trabaja en universidad o investigación
- Es introvertida
- Le gustan las matemáticas

**Pero no sabes:**
- Si le gusta su trabajo
- Su personalidad real
- Sus otros intereses
- Su vida fuera del trabajo

**Sin embargo, tu mente crea una historia completa y coherente.**

**El Peligro:** Confiamos en narrativas incompletas.

**PARTE 2: HEURÍSTICAS Y SESGOS**

**CAPÍTULO 5: HEURÍSTICA DE DISPONIBILIDAD**

**Definición:** Juzgamos la frecuencia o probabilidad de eventos por la facilidad con que ejemplos vienen a la mente.

**Pregunta:**

"¿Qué mata más personas?"
A) Ataques de tiburón
B) Piezas de avión cayendo

**Respuesta de la mayoría:** Tiburones
**Realidad:** Piezas de avión (30x más frecuente)

**Por qué:** Los ataques de tiburón son dramáticos, están en películas, son fáciles de recordar.

**Aplicaciones del Sesgo:**

**En Salud:**
- Sobreestimamos riesgos dramáticos (ataques terroristas)
- Subestimamos riesgos comunes (enfermedad cardíaca)

**En Negocios:**
- Recordamos éxitos recientes más que patrones de largo plazo
- Eventos recientes pesan más en decisiones

**En Vida Personal:**
- Evaluamos relaciones basándonos en eventos recientes
- Olvidamos el panorama general

**CAPÍTULO 6: AFECTO Y HEURÍSTICA**

**El Afecto Influye el Pensamiento:**

**Experimento:**

**Grupo A:** Leyó sobre beneficios de la energía nuclear
**Grupo B:** Leyó sobre riesgos de la energía nuclear

**Luego ambos evaluaron:**
1. Beneficios de energía nuclear
2. Riesgos de energía nuclear

**Resultado:**
- Grupo A: Altos beneficios, bajos riesgos
- Grupo B: Bajos beneficios, altos riesgos

**Lógicamente no tiene sentido:** Los beneficios no cambian porque los riesgos aumentan.

**Pero emocionalmente sí:** Si algo se siente mal, tanto beneficios como riesgos se ajustan a la narrativa.

**El Afecto Sustituye al Análisis:**

**Pregunta difícil:** "¿Esta inversión tiene buen rendimiento ajustado al riesgo?"

**Sustituida por pregunta fácil:** "¿Me gusta esta inversión?"

**Sistema 1 responde la pregunta fácil y Sistema 2 acepta la respuesta.**

**CAPÍTULO 7: ANCLAS**

**El Efecto de Anclaje:**

**Experimento:**

**Paso 1:** Gira una rueda de ruleta (manipulada para caer en 10 o 65)

**Paso 2:** Pregunta: "¿Qué porcentaje de países africanos están en la ONU?"

**Resultado:**
- Rueda mostró 10: Estimación promedio 25%
- Rueda mostró 65: Estimación promedio 45%

**El ancla (número aleatorio) influyó la estimación.**

**Anclas en la Vida Real:**

**En Negociaciones:**
- Primera oferta establece el ancla
- Todas las ofertas subsecuentes se ajustan a ella
- Quien hace la primera oferta tiene ventaja

**En Ventas:**
- Precio original tachado: $199 $99
- El ancla ($199) hace que $99 parezca gran oferta

**En Evaluaciones:**
- Pregunta de salario esperado
- Tu primera estimación ancla la negociación

**Cómo Defenderte:**

**No puedes evitar ser influenciado por anclas.**

Pero puedes:
1. Ser consciente del efecto
2. Cuestionar activamente la relevancia del ancla
3. Generar tu propia estimación independiente primero

