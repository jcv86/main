**Respuesta:** "7-10 años, y 40% nunca terminan."

**Resultado real:** 8 años.

**Lección:** Ignoramos evidencia estadística a favor de nuestras esperanzas optimistas.

**PARTE 3: EXCESO DE CONFIANZA**

**CAPÍTULO 9: REGRESIÓN A LA MEDIA**

**Concepto:**

Después de un evento extremo, el siguiente evento tiende a ser más cercano al promedio.

**Ejemplo del Golf:**

Tiger Woods tiene ronda excepcional (62).
Su siguiente ronda: 71 (buena pero no excepcional).

**No es porque "perdió su toque".**
Es regresión a la media.

**En Negocios:**

**Revista de Negocios:**

Artículo: "Las 10 Mejores Empresas de 2010"

**Seguimiento en 2015:**
La mayoría tuvieron rendimiento promedio o inferior.

**No porque se volvieron malas.**
Regresión a la media.

**El Peligro:**

Creamos narrativas causales para regresión simple.

**Ejemplo:**
- Empresa tiene año excepcional
- Contratan CEO caro
- Siguiente año es promedio
- "El CEO es malo, despídanlo"

**Realidad:** Probablemente habría sido promedio de todos modos.

