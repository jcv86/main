- Escribir el guion critico: no pienses en grande, piensa en comportamientos especificos
- Senalar el destino: el cambio es mas facil cuando sabes hacia donde vas

MOTIVAR AL ELEFANTE (el lado emocional):
- Encontrar el sentimiento: el conocimiento no cambia el comportamiento, el sentimiento si
- Encoger el cambio: divide el cambio en pasos pequenos y manejables
- Cultivar identidad: comportate de acuerdo a quien quieres ser

ALLANAR EL CAMINO (moldear la situacion):
- Ajustar el entorno: cuando la situacion cambia, el comportamiento cambia
- Construir habitos: cuando el comportamiento es habitual, es gratis
- Reunir la manada: el comportamiento es contagioso, ayuda a que se propague

EJEMPLOS REALES DE CAMBIO EXITOSO:

1. Cambio en Industria: Una fabrica redujo errores al hacer que los trabajadores usaran guantes de diferentes colores segun la etapa del proceso.

