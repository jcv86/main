INTRODUCCION: Cambiando cuando el cambio es dificil

El cambio es dificil. Cualquiera que haya intentado cambiar un habito personal o implementar un cambio en una organizacion sabe que el cambio es extraordinariamente dificil. Pero no tiene que serlo.

Los autores presentan un marco basado en una metafora simple: nuestras mentes estan divididas, como un Jinete sobre un Elefante. El Jinete representa nuestro lado racional y analítico. El Elefante es nuestro lado emocional e instintivo. Y hay un tercer factor: el Camino, que es el entorno y la situacion.

Para que el cambio ocurra, necesitas dirigir al Jinete, motivar al Elefante y allanar el Camino.

PARTE 1: DIRIGIR AL JINETE

Capitulo 1: Seguir el camino brillante

El problema con el cambio es que el Jinete parece ser el que tiene el control, pero ese control es precario y puede agotarse. Cuando esto sucede, el Elefante toma el control y puede sabotear el cambio.

Para dirigir al Jinete exitosamente, necesitas proporcionarle direccion clara. La ambiguedad agota al Jinete. Lo que parece resistencia a menudo es falta de claridad.

Script de los puntos brillantes: en lugar de enfocarte en lo que esta mal, busca lo que esta funcionando y clonalo. Encuentra los puntos brillantes en tu organizacion o vida y analiza que los hace funcionar.

Capitulo 2: Escribir el guion critico

El Jinete ama analizar y contemplar opciones. Pero el analisis excesivo puede paralizar. Para dirigir al Jinete, necesitas escribir un guion muy claro que especifique comportamientos.

No pienses en grandes cosas, piensa en comportamientos especificos. En lugar de decir "se mas saludable", di "compra leche descremada". La claridad disuelve la resistencia.

Capitulo 3: Senalar el destino

Para que el cambio suceda, necesitas senalar un destino atractivo. El Jinete necesita direccion. La pregunta es: hacia donde estamos yendo?

Una buena meta de destino tiene dos propiedades: es especifica y es emocional. Piensa en una postal del futuro que muestra como se veran las cosas cuando llegues alli.

PARTE 2: MOTIVAR AL ELEFANTE

Capitulo 4: Encontrar el sentimiento

El conocimiento no cambia el comportamiento. Puedes conocer todos los hechos sobre por que deberias cambiar, pero eso no te movera a la accion. El cambio tiene que sentirse bien.

El elefante necesita motivacion emocional. Los datos rara vez cambian corazones. Pero las historias si. Muestra a las personas, no solo les digas con numeros.

Cuando quieras crear cambio, busca formas de tocar el corazon de las personas. El sentimiento impulsa el cambio mas que el pensamiento.

Capitulo 5: Encoger el cambio

Cuando el cambio se siente abrumador, el Elefante se resiste. Una forma de motivar al Elefante es hacer que el cambio parezca mas pequeno y mas alcanzable.

La tarjeta de lavado de autos: cuando das a las personas una tarjeta de lealtad que ya tiene algunos sellos, se sienten mas cerca del objetivo y es mas probable que la completen.

Divide el cambio en pequenos pasos manejables. Celebra los pequenos exitos. El progreso crea momentum y hace que el cambio se sienta posible.

Capitulo 6: Cultivar un sentido de identidad

El comportamiento es contagioso. Cuando cambias tu identidad, el comportamiento cambia con ella. No te ves como alguien que esta tratando de perder peso; te ves como un atleta.

La identidad es poderosa porque es autosostenible. Una vez que decides que eres cierto tipo de persona, te comportaras consistentemente con esa identidad.

PARTE 3: ALLANAR EL CAMINO

Capitulo 7: Ajustar el entorno

Lo que parece un problema de persona es frecuentemente un problema de situacion. El entorno puede hacer que los comportamientos deseados sean mas faciles o mas dificiles.

Si quieres cambiar el comportamiento, cambia el entorno. Haz que el comportamiento correcto sea el comportamiento mas facil.

Ejemplos: colocar la fruta a la altura de los ojos en la cafeteria escolar aumenta su consumo. Reducir el tamano de los platos reduce el consumo de comida. El entorno importa enormemente.

Capitulo 8: Construir habitos

Cuando creas habitos, liberas al Jinete de tener que tomar decisiones constantemente. Los habitos son comportamientos en piloto automatico.

El mejor momento para crear un habito es cuando hay un "disparador" de accion. Cuando X sucede, hago Y. Este formato if-then es increiblemente poderoso para crear habitos.

Los listas de verificacion son otra forma de construir habitos institucionales. Los pilotos y cirujanos usan listas de verificacion no porque sean tontos, sino porque incluso los expertos pueden olvidar pasos bajo presion.

Capitulo 9: Reunir a la manada

El comportamiento es contagioso. Tendemos a seguir a la manada. Si quieres que las personas cambien, muestrales que otros ya estan cambiando.

La prueba social es poderosa: "Todos tus vecinos ya estan haciendo esto." Es mas efectivo que cualquier argumento racional.

Crea una cultura donde el comportamiento deseado sea la norma. Haz que las personas sientan que son parte de algo mas grande que ellas mismas.

Capitulo 10: Mantener el cambio vivo

El cambio no es un evento; es un proceso. Para mantener el cambio vivo, necesitas:

1. Reconocer y celebrar los primeros exitos (aunque sean pequenos)
2. Reforzar nuevos comportamientos con feedback positivo
3. Cultivar un sentido de identidad en torno al cambio
4. Ajustar continuamente el entorno para apoyar el cambio

El cambio es dificil porque las personas usan la misma palabra para referirse a cosas muy diferentes. Trata de cambiar y el cambio puede ser dificil. Dirigir al Jinete, motivar al Elefante y allanar el Camino, y el cambio puede venir mucho mas facilmente.

MARCO COMPLETO PARA EL CAMBIO:

DIRIGIR AL JINETE (el lado racional):
