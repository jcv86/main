## SEGUNDA LEY: HACERLO ATRACTIVO

### Capítulo 8: Cómo hacer un hábito irresistible

Agrupamiento de tentaciones: Agrupa una acción que quieres hacer con una que necesitas hacer.

Fórmula: Después de este hábito necesario, haré este hábito deseado.

Ejemplos:
- Después de sacar mi teléfono, haré 10 flexiones
- Después de recibir mi café, diré algo por lo que estoy agradecido

### Capítulo 9: El papel de la familia y amigos

Somos animales de manada. Queremos encajar y obtener respeto de nuestros pares.

Únete a una cultura donde tu comportamiento deseado es normal:
- Quieres leer: únete a un club de lectura
- Quieres emprender: rodéate de emprendedores

Nada sostiene un comportamiento mejor que pertenecer a una tribu.

