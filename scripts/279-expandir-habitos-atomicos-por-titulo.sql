## CUARTA LEY: HACERLO SATISFACTORIO

### Capítulo 15: La regla cardinal del cambio de comportamiento

Regla cardinal: Lo que se recompensa inmediatamente se repite. Lo que se castiga inmediatamente se evita.

El problema con buenos hábitos es que la recompensa viene después de mucho tiempo. Esto hace difícil mantenerlos sin satisfacción inmediata.

### Cómo mantener buenos hábitos todos los días

Usa un rastreador de hábitos visual:

- Marca una X en un calendario cada día que haces ejercicio
- Mueve un clip de papel por cada llamada de ventas
- Pon una moneda en un frasco cada vez que meditas

Los rastreadores son obvios porque registrar crea disparador para el próximo. Son atractivos porque el progreso motiva. Son satisfactorios porque marcar progreso se siente bien.

### Capítulo 16: Cómo adherirse a los buenos hábitos

Nunca falles dos veces. La primera falla nunca te arruina. Es la espiral de errores repetidos que sigue.

Perder un entrenamiento no causa sobrepeso. Perder entrenamientos durante cinco meses sí.

Clave: Nunca fallar dos veces seguido. Si te pierdes un día vuelve lo más rápido posible.

