## TERCERA LEY: HACERLO FÁCIL

### Capítulo 11: Camina lentamente pero nunca retrocedas

Diferencia entre estar en movimiento y tomar acción:

- Movimiento: planificar, estrategizar, aprender
- Acción: comportamiento que produce resultados

A veces el movimiento es útil pero nunca produce resultados por sí solo.

### La ley del menor esfuerzo

Humanos gravitamos hacia la opción que requiere menos trabajo. Haz tus hábitos lo más fáciles posible.

Reduce la fricción:
- Quieres ejercicio: pon ropa de gimnasio la noche anterior
- Quieres comer saludable: corta frutas y verduras con anticipación
- Quieres practicar guitarra: deja tu guitarra en medio de la sala

### Capítulo 12: La regla de los dos minutos

Casi cualquier hábito puede reducirse a una versión de dos minutos:

- Leer antes de dormir se convierte en leer una página
- Hacer 30 minutos de yoga se convierte en sacar mi estera de yoga
- Estudiar para clase se convierte en abrir mis notas
- Correr 5 kilómetros se convierte en atarme mis zapatos para correr

Haz que tus hábitos sean lo más fáciles de comenzar posible. Una vez que comienzas es más fácil continuar.

