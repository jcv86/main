## TÁCTICAS AVANZADAS

### Capítulo 18: La verdad sobre el talento

Regla de Goldilocks: Experimentamos motivación máxima cuando trabajamos en tareas justo en el borde de nuestras habilidades actuales.

- Demasiado fácil resulta en aburrimiento
- Demasiado difícil resulta en frustración
- Justo correcto resulta en flujo

La zona de flujo necesita tareas aproximadamente 4% más allá de tu habilidad actual. Esto te mantiene comprometido y motivado.

### Capítulo 19: La desventaja de crear buenos hábitos

El poder de la reflexión: Establece tiempo para reflexión y revisión. Por ejemplo cada diciembre pregúntate qué salió bien este año, qué no salió bien y qué aprendiste.

La revisión anual te permite reflexionar sobre tus hábitos y hacer decisiones conscientes sobre cómo mejorarlos.

