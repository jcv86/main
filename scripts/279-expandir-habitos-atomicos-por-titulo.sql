## CAPÍTULO 2: CÓMO TUS HÁBITOS MOLDEAN TU IDENTIDAD

Hay tres capas de cambio de comportamiento:

1. Resultados: Cambiar tus resultados como perder peso o publicar un libro
2. Procesos: Cambiar tus hábitos y sistemas como nueva rutina en el gimnasio
3. Identidad: Cambiar tus creencias, visión del mundo y autoimagen

La mayoría comienza enfocándose en lo que quiere lograr. Esto lleva a cambios basados en resultados.

### El enfoque alternativo

Construir hábitos basados en identidad. Comenzamos enfocándonos en quién deseamos ser.

Ejemplos de cambio de mentalidad:
- No digo quiero leer más, sino soy un lector
- No digo quiero correr un maratón, sino soy un corredor
- No digo quiero aprender guitarra, sino soy un músico

### Cómo cambiar tu identidad

Tu identidad emerge de tus hábitos. Cada acción es un voto por el tipo de persona que deseas ser. Ninguna instancia única transforma tus creencias, pero a medida que los votos se acumulan, también lo hace la evidencia de tu nueva identidad.

El ciclo de retroalimentación:
1. Decide el tipo de persona que quieres ser
2. Pruébatelo con pequeñas victorias

La formación de hábitos no se trata de mantener un hábito durante 30 días. Se trata de adoptar una nueva identidad y demostrarla con pequeños cambios consistentes.

