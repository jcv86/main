## CAPÍTULO 3: CÓMO CONSTRUIR MEJORES HÁBITOS EN 4 PASOS

En 1898, Edward Thorndike realizó un experimento con gatos en cajas negras. Al principio tardaban mucho en escapar. Con cada repetición aprendían. Eventualmente escapaban en segundos.

### El ciclo del hábito

Cuatro pasos simples:

1. Señal: Desencadena tu cerebro para iniciar un comportamiento
2. Anhelo: Fuerza motivacional detrás de cada hábito
3. Respuesta: El hábito real que realizas
4. Recompensa: El objetivo final de cada hábito

Si falta alguna etapa, el comportamiento no se convierte en hábito.

### Las cuatro leyes del cambio de comportamiento

Para crear un buen hábito:
1. Señal: Hacerlo obvio
2. Anhelo: Hacerlo atractivo
3. Respuesta: Hacerlo fácil
4. Recompensa: Hacerlo satisfactorio

Para romper un mal hábito:
1. Hacerlo invisible
2. Hacerlo poco atractivo
3. Hacerlo difícil
4. Hacerlo insatisfactorio

