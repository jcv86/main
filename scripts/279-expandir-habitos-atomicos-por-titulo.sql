## PRIMERA LEY: HACERLO OBVIO

### Capítulo 4: El hombre que no se veía bien

El cambio de comportamiento comienza con la conciencia. Necesitas ser consciente de tus hábitos antes de poder cambiarlos.

El Cuadro de Mando de Hábitos:

Haz una lista de tus hábitos diarios como despertar, apagar alarma, revisar teléfono, ir al baño, pesarte, ducharte y cepillar dientes.

Para cada comportamiento pregunta si es bueno, malo o neutral. Marca con más si es bueno, menos si es malo e igual si es neutral.

### Capítulo 5: La mejor manera de comenzar un hábito

En 2001, investigadores trabajaron con 248 personas para construir hábitos de ejercicio. El grupo control tuvo 38% de éxito, el grupo con motivación 35%, pero el grupo con plan específico logró 91% de éxito.

La fórmula de intención de implementación:

Haré este comportamiento a esta hora en esta ubicación.

Ejemplos:
- Meditaré 5 minutos a las 7 am en mi cocina
- Estudiaré español 20 minutos a las 6 pm en mi dormitorio

Muchas personas piensan que carecen de motivación cuando lo que les falta es claridad.

### Acumulación de hábitos

Identifica un hábito actual y apila tu nuevo comportamiento encima.

Fórmula: Después de este hábito actual, haré este nuevo hábito.

Ejemplos:
- Después de servirme café, meditaré 60 segundos
- Después de quitarme los zapatos, me cambiaré a ropa de entrenamiento

