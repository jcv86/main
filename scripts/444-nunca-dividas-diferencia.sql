## TÁCTICA 8: ENCUENTRA EL CISNE NEGRO

### Cisnes Negros

**Qué son:** Información desconocida que cambia todo.

**Ejemplos:**
- Tienen otro comprador
- Su jefe odia a tu empresa
- Están por cerrar
- Tienen presupuesto oculto

**Cómo encontrarlos:**

1. **Escucha lo que NO dicen**
2. **Observa comportamiento inconsistente**
3. **Pregunta sobre el proceso de decisión**
4. **Habla con múltiples personas en la organización**

**Pregunta poderosa:** "¿Qué más debería saber que no te he preguntado?"

