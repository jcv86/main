## TÁCTICA 1: ESCUCHA ACTIVA

### Espejeo (Mirroring)

**Qué es:** Repetir las últimas 1-3 palabras que dijo la otra persona.

**Cómo:**
1. Escucha
2. Repite últimas palabras con tono interrogativo
3. Silencio (deja que hablen)

**Ejemplo:**
- Ellos: "No puedo pagar ese precio"
- Tú: "¿No puedes pagar ese precio?"
- Ellos: "Bueno, es que nuestro presupuesto es limitado este trimestre..."

**Por qué funciona:** Las personas quieren ser escuchadas. El espejeo les da permiso para elaborar.

### Etiquetado (Labeling)

**Qué es:** Identificar y verbalizar las emociones de la otra persona.

**Fórmula:** "Parece que..." o "Suena como..."

**Ejemplos:**
- "Parece que esto es realmente importante para ti"
- "Suena como que has tenido una mala experiencia antes"
- "Parece que estás frustrado con el proceso"

**Regla:** Después de etiquetar, CÁLLATE. Deja que respondan.

**Por qué funciona:** Etiquetar emociones las difunde. Las personas se sienten comprendidas.

---

## TÁCTICA 2: EL PODER DEL "NO"

### "No" es Protección

**Verdad:** Las personas tienen miedo de decir "Sí" porque sienten que pierden control.

**Estrategia:** Haz que digan "No" primero.

**En lugar de:** "¿Tienes unos minutos para hablar?"
**Di:** "¿Es mal momento para hablar?"

**En lugar de:** "¿Estás de acuerdo con esto?"
**Di:** "¿Esto te parece ridículo?"

**Por qué funciona:** "No" hace que las personas se sientan seguras y en control. Paradójicamente, abre la conversación.

### Tres Tipos de "Sí"

1. **Compromiso:** Verdadero acuerdo
2. **Confirmación:** "Sí, te escucho"
3. **Falsificación:** "Sí" para terminar la conversación

**Problema:** No sabes cuál es cuál.

**Solución:** Busca "Así es" en lugar de "Sí".

---

## TÁCTICA 3: "ASÍ ES"

### El Resumen Acusatorio

**Qué es:** Resumir la posición de la otra persona tan bien que dicen "Así es".

**Cómo:**
1. Escucha activamente
2. Parafrasea su posición
3. Etiqueta sus emociones
4. Resume todo

**Ejemplo:**

"Entonces, si entiendo correctamente, estás preocupado por el costo porque el presupuesto ya está ajustado este trimestre. Parece que también te preocupa que el equipo no vea el valor inmediato. ¿Así es?"

**Respuesta ideal:** "¡Así es!"

**Por qué funciona:** Cuando las personas sienten que las entiendes completamente, bajan la guardia.

**Advertencia:** "Tienes razón" es diferente de "Así es". "Tienes razón" es apaciguamiento. "Así es" es acuerdo genuino.

---

## TÁCTICA 4: DOBLA SU REALIDAD

### Anclaje

**Principio:** El primer número en una negociación ancla la conversación.

**Estrategia:** Deja que ellos anclen primero (si es posible), o ancla extremo.

**Ejemplo:**
Si quieres $100k de salario, no digas $100k. Di $120k. Ahora $100k parece razonable.

### Pérdida Aversión

**Verdad:** Las personas odian perder más de lo que aman ganar.

**Aplicación:** Enmarca tu oferta en términos de lo que perderán si no aceptan.

**En lugar de:** "Ganarás X con este trato"
**Di:** "Sin este trato, perderás X"

### El Rango

**Táctica:** Cuando des un número, usa un rango.

**Ejemplo:**
"En mi investigación, personas con mi experiencia en esta ciudad ganan entre $110k y $130k"

**Por qué funciona:** 
1. Parece que hiciste investigación
2. El número alto ancla
3. Parece más razonable que un número único

---

## TÁCTICA 5: CREA LA ILUSIÓN DE CONTROL

### Preguntas Calibradas

**Qué son:** Preguntas abiertas que empiezan con "Cómo" o "Qué".

**Poder:** Dan a la otra persona ilusión de control mientras tú diriges la conversación.

**Preguntas Mágicas:**

1. **"¿Cómo se supone que haga eso?"**
   - Úsala cuando piden algo imposible
   - Los hace pensar en tu perspectiva

2. **"¿Qué es lo que te preocupa de esto?"**
   - Descubre objeciones reales

3. **"¿Cómo podemos resolver esto?"**
   - Los hace parte de la solución

4. **"¿Qué te trajo a esta posición?"**
   - Descubre motivaciones reales

5. **"¿Cómo sabremos que tenemos éxito?"**
   - Alinea expectativas

**Evita:** Preguntas que empiezan con "Por qué" (suenan acusatorias)

### El Poder del Silencio

**Después de una pregunta calibrada:** CÁLLATE.

**Regla:** El primero en hablar pierde.

**Por qué funciona:** El silencio es incómodo. Las personas lo llenan con información valiosa.

---

## TÁCTICA 6: GARANTIZA LA EJECUCIÓN

### El "Sí" No es Suficiente

**Problema:** Conseguir "sí" no garantiza que cumplan.

**Solución:** Usa la Regla de Tres.

### La Regla de Tres

**Qué es:** Consigue que la otra persona esté de acuerdo con lo mismo tres veces en la conversación.

**Cómo:**
1. Primera vez: Acuerdo inicial
2. Segunda vez: Resume y confirma ("Entonces estamos de acuerdo en...")
3. Tercera vez: Pregunta calibrada ("¿Cómo aseguramos que esto suceda?")

**Por qué funciona:** Tres acuerdos = compromiso real, no solo apaciguamiento.

### Detecta Mentiras

**Señales de que no cumplirán:**

1. **Uso de pronombres:** "Yo" vs "Nosotros"
   - "Yo creo que es buena idea" = Solo ellos
   - "Nosotros creemos que es buena idea" = Tienen apoyo

2. **Lenguaje corporal incongruente**

3. **Respuestas vagas a preguntas específicas**

**Pregunta de prueba:** "¿Cómo afecta esto a los demás en tu equipo?"

