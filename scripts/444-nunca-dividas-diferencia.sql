## APLICACIONES PRÁCTICAS

### Negociar Salario

**Preparación:**
1. Investiga rangos de mercado
2. Identifica tu número objetivo
3. Prepara tu valor (logros específicos)

**En la conversación:**
1. Deja que ellos anclen primero si es posible
2. Usa espejeo y etiquetado
3. Presenta tu rango basado en investigación
4. Usa preguntas calibradas: "¿Cómo podemos hacer que esto funcione?"
5. Aplica sistema Ackerman

### Negociar con Proveedor

**Objetivo:** Mejor precio o términos

**Táctica:**
1. Construye rapport primero
2. Etiqueta sus preocupaciones: "Parece que el precio es firme"
3. Pregunta calibrada: "¿Cómo puedo pagar eso con mi presupuesto actual?"
4. Deja que ellos propongan soluciones
5. Busca valor no monetario (términos de pago, servicios adicionales)

### Negociar con Cliente

**Objetivo:** Cerrar venta sin descuento excesivo

**Táctica:**
1. Descubre objeciones reales: "¿Qué te preocupa de esto?"
2. Resume su posición hasta "Así es"
3. Enmarca en pérdida: "Sin esto, seguirás teniendo [problema]"
4. Pregunta calibrada: "¿Qué necesitarías ver para seguir adelante?"
5. Ofrece opciones (no descuentos)

