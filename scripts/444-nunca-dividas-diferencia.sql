## TÁCTICA 7: NEGOCIA DURO

### El Acuerdo Ackerman

**Sistema de 6 pasos para negociar precio:**

1. **Establece tu precio objetivo**
2. **Ofrece 65% de tu objetivo**
3. **Calcula tres incrementos:** 85%, 95%, 100%
4. **Usa empatía y diferentes formas de decir "No"**
5. **En incrementos finales, usa números precisos** ($37,893 no $38,000)
6. **En la oferta final, añade un ítem no monetario** (para mostrar que llegaste al límite)

**Ejemplo:**

Objetivo: $100,000 salario

1. Ellos ofrecen: $80,000
2. Tú: "Aprecio la oferta, pero investigué y el rango para esta posición es $110k-$130k. ¿Cómo podemos acercarnos a eso?"
3. Ellos: $90,000
4. Tú: "Entiendo las limitaciones presupuestarias. ¿Qué tal $95,000?"
5. Ellos: $92,000
6. Tú: "Estoy realmente emocionado por esta oportunidad. ¿Podrían hacer $97,843 con revisión de salario en 6 meses?"

### Tipos de Negociadores

**1. Analista**
- Valora: Tiempo y preparación
- Táctica: Da espacio, presenta datos

**2. Acomodador**
- Valora: Relación
- Táctica: Construye rapport, socializa

**3. Asertivo**
- Valora: Tiempo y respeto
- Táctica: Sé directo, escucha activamente

**Identifica el tipo y adapta tu enfoque.**

