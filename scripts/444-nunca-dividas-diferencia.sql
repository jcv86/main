## INTRODUCCIÓN

Chris Voss fue el principal negociador de rehenes del FBI durante 24 años. Este libro comparte las tácticas que usó para salvar vidas y cómo aplicarlas en negociaciones cotidianas.

**Verdad Central:** La negociación no es sobre lógica y razón. Es sobre emoción y conexión.

**Mito:** Dividir la diferencia es justo
**Realidad:** Dividir la diferencia es perder

