## PRINCIPIO 1: LA NUEVA REGLA

### La Negociación es Descubrimiento

**Vieja escuela:** Negociación es batalla racional
**Nueva escuela:** Negociación es descubrimiento emocional

**Tu trabajo:** Descubrir qué quiere realmente la otra persona y por qué.

### El Cerebro Emocional Manda

**Verdad:** Las decisiones son emocionales, luego justificadas con lógica.

**Implicación:** Conecta emocionalmente primero, luego presenta lógica.

