## PARTE 12: CNV con Uno Mismo

### Auto-Conexión y Auto-Compasión

La CNV más importante es la que tenemos con nosotros mismos.

#### Transformar Diálogo Interno

**Crítico interno violento:**
"Soy un fracaso"
"Siempre arruino todo"
"Qué estúpido fui"

**Auto-empatía CNV:**
"Me siento decepcionado conmigo mismo porque valoro la competencia y cometí un error. ¿Qué puedo aprender? ¿Qué necesito para crecer?"

#### Duelo en CNV

Cuando cometemos errores o actuamos en formas que no honran nuestros valores:

**1. Auto-empatía**
Conectar con sentimientos y necesidades que motivaron la acción.
"Actué así porque necesitaba protección/aceptación/autonomía"

**2. Duelo**
Lamentar que la estrategia no sirvió a nuestras necesidades genuinas o dañó a otros.

**3. Auto-perdón**
Reconocer nuestra humanidad y compromiso de aprender.

**4. Transformación**
"La próxima vez que necesite [necesidad], ¿qué estrategia diferente podría usar?"

