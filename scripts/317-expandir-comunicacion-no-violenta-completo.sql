**Situación: Pareja que no ayuda en casa**

**Enfoque tradicional:**
"Nunca ayudas. Soy la única que hace algo aquí."

**Enfoque CNV:**
"Cuando veo que esta semana yo preparé las cenas y lavé los platos todas las noches mientras tú miraste TV [observación], me siento exhausta y resentida [sentimientos] porque necesito apoyo y equidad en nuestra relación [necesidades]. ¿Estarías dispuesto a que creemos un plan juntos donde ambos contribuyamos a las tareas del hogar? [petición]"

