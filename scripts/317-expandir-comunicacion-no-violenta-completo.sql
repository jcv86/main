## PARTE 1: Observar sin Evaluar

### El Poder de la Observación Clara

Cuando combinamos observación con evaluación, las personas tienden a recibir crítica y resistir lo que decimos. La CNV nos invita a distinguir entre observación y evaluación.

#### Observación vs. Evaluación

**Evaluación mezclada con observación:**
- "Eres perezoso" (evaluación de carácter)
- "Siempre llegas tarde" (generalización temporal)
- "Mi jefe es manipulador" (interpretación de intenciones)

**Observación pura:**
- "No has completado las tres tareas que acordamos para esta semana"
- "Has llegado después de las 9am los últimos tres días"
- "Mi jefe solicitó el informe sin mencionar la carga de trabajo que ya tengo"

#### El Lenguaje de la Observación

**Palabras que señalan evaluación:**
- Siempre, nunca, frecuentemente, rara vez
- Bueno, malo, correcto, incorrecto
- Debería, debe, tiene que
- Todos, nadie, algunos

**Lenguaje de observación específica:**
- "En las últimas cuatro reuniones..."
- "Cuando escuché que dijiste..."
- "Observé que en el documento..."
- "Durante la presentación de ayer..."

#### Práctica de Observación

**Ejercicio:** Transforma estas evaluaciones en observaciones:

| Evaluación | Observación |
|-----------|-------------|
| "Eres desconsiderado" | "Cuando cambiaste el horario sin avisarme..." |
| "El equipo es disfuncional" | "En la última reunión, tres personas hablaron simultáneamente y no llegamos a conclusiones" |
| "Tu presentación fue confusa" | "Tu presentación tenía 50 diapositivas en 20 minutos y no pude seguir la idea principal" |

