## PARTE 10: Liberarse del Viejo Condicionamiento

### Desaprender Patrones Violentos

Muchos hemos sido condicionados a comunicarnos de maneras que:
- Niegan responsabilidad por nuestras acciones
- Demandan en lugar de pedir
- Juzgamos y etiquetamos
- Comparamos para determinar quién es "mejor"

#### Lenguaje que Oscurece Responsabilidad

**Lenguaje que niega elección:**
- "Tengo que..."
- "No tuve opción..."
- "Me hiciste..."
- "Es política de la compañía..."

**Transformación CNV:**
- "Elijo... porque valoro..."
- "Decido... porque necesito..."
- "Cuando tú..., yo elegí... porque..."

#### El Costo de Recompensas y Castigos

**Sistema tradicional:**
"Si haces esto, recibirás recompensa"
"Si no lo haces, habrá consecuencias"

**Problema:** Motiva cumplimiento externo, no compromiso interno. Las personas actúan por miedo o por premio, no por conexión genuina con el valor de la acción.

**Alternativa CNV:**
Conectar acciones con necesidades humanas. Ayudar a las personas a ver cómo sus acciones contribuyen al bienestar propio y colectivo.

