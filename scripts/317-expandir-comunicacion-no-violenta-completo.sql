## PARTE 7: Expresar Enojo Completamente

### Transformar el Enojo en Conexión

El enojo es una emoción que muchos han aprendido a temer o suprimir. La CNV nos enseña que el enojo es una señal de alarma que nos indica que estamos pensando de manera que no sirve a nuestras necesidades.

#### La Anatomía del Enojo

**La superficie:** "Estoy enojado porque tú..."
**La profundidad:** "Estoy enojado porque yo necesito... y mi necesidad no está siendo satisfecha"

**Ejemplo:**
**Superficie:** "Estoy furioso porque llegaste tarde otra vez"
**Profundidad:** "Me siento frustrado porque valoro la puntualidad y la confiabilidad en nuestros compromisos"

#### Cuatro Pasos para Expresar Enojo

**1. Detenerse y respirar**
No actuar desde el enojo reactivo. Crear espacio entre estímulo y respuesta.

**2. Identificar pensamientos de juicio**
"Es un irresponsable"
"Esto es inaceptable"
"Siempre hace esto"

**3. Conectar con necesidades**
¿Qué necesidad importante no está siendo satisfecha?
- Respeto, consideración, confiabilidad, colaboración

**4. Expresar sentimientos y necesidades**
"Cuando llegaste 30 minutos tarde a nuestra reunión, me sentí frustrado y decepcionado porque necesito confiabilidad en nuestros compromisos. ¿Estarías dispuesto a discutir cómo podemos asegurar puntualidad en futuras reuniones?"

