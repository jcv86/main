## PARTE 11: La CNV en Acción: Mediación de Conflictos

### Facilitando Conexión entre Partes en Conflicto

Como mediador CNV, el rol es facilitar empatía mutua, no imponer soluciones.

#### Proceso de Mediación CNV

**1. Establecer intención**
"Mi rol es ayudarles a escucharse mutuamente y encontrar soluciones que satisfagan las necesidades de ambos."

**2. Acuerdos básicos**
- Una persona habla a la vez
- Enfoque en expresar sentimientos y necesidades, no atacar
- Disposición a escuchar perspectiva del otro

**3. Escuchar a la primera parte**
Facilitar expresión de observaciones, sentimientos, necesidades, peticiones.

**4. Reflejar empatía a la segunda parte**
"¿Puedes decirle a [primera parte] qué escuchaste de sus sentimientos y necesidades?"

**5. Escuchar a la segunda parte**
Misma estructura: observaciones, sentimientos, necesidades, peticiones.

**6. Identificar necesidades compartidas**
"Ambos valoran respeto y claridad en la comunicación. ¿Es correcto?"

**7. Co-crear soluciones**
"¿Qué estrategias podrían satisfacer las necesidades de ambos?"

