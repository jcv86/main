## PARTE 8: Expresar Aprecio en CNV

### Más Allá del Elogio Superficial

El aprecio en CNV no es elogio que evalúa o juzga ("¡Buen trabajo!"). Es expresar gratitud por acciones específicas que enriquecieron nuestras vidas.

#### Los Tres Componentes del Aprecio CNV

**1. Acción específica que contribuyó a nuestro bienestar**
"Cuando preparaste ese análisis detallado..."

**2. Necesidad particular que fue satisfecha**
"...satisfizo mi necesidad de claridad y me ayudó a tomar una decisión informada..."

**3. Sentimientos placenteros generados**
"...y me siento agradecido y aliviado."

**Ejemplo completo:**
"Cuando tomaste tiempo para explicarme el nuevo sistema paso a paso, satisficiste mi necesidad de aprendizaje y comprensión, y me siento agradecido y más confiado para usar el sistema."

