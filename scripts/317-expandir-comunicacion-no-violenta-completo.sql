## PARTE 2: Identificar y Expresar Sentimientos

### Más Allá de "Bien" y "Mal"

Muchos de nosotros hemos sido educados para negar, ignorar o suprimir nuestros sentimientos. La CNV nos invita a desarrollar un vocabulario emocional que nos permita expresar claramente nuestra experiencia interior.

#### Sentimientos vs. Pseudo-Sentimientos

**Pseudo-sentimientos** (pensamientos disfrazados de sentimientos):
- "Me siento ignorado" (interpretación de acción de otros)
- "Me siento manipulado" (interpretación de intención)
- "Me siento como si no me valoraran" (interpretación)

**Sentimientos genuinos:**
- "Me siento triste y solo"
- "Me siento confundido y frustrado"
- "Me siento desanimado y ansioso"

#### Vocabulario Emocional Expandido

**Sentimientos cuando necesidades están satisfechas:**

**Alegría/Satisfacción:**
Alegre, contento, entusiasmado, feliz, jubiloso, optimista

**Paz/Tranquilidad:**
Calmado, centrado, despejado, cómodo, relajado, sereno

**Energía/Vitalidad:**
Animado, enérgico, estimulado, renovado, vigoroso

**Gratitud/Aprecio:**
Agradecido, conmovido, reconfortado, tocado

**Sentimientos cuando necesidades NO están satisfechas:**

**Enojo/Frustración:**
Molesto, enojado, exasperado, frustrado, impaciente, irritado

**Miedo/Ansiedad:**
Alarmado, ansioso, asustado, nervioso, preocupado, temeroso

**Tristeza/Desánimo:**
Abatido, deprimido, desalentado, desanimado, melancólico, triste

**Confusión/Duda:**
Ambivalente, confundido, desorientado, inseguro, perplejo

#### Expresar Sentimientos Responsablemente

**Lenguaje que asume responsabilidad:**
- "Me siento frustrado cuando..."
- "Experimento tristeza porque..."
- "Noto que me siento ansioso..."

**Lenguaje que culpa:**
- "Me haces sentir frustrado"
- "Tu actitud me deprime"
- "Me obligas a sentir ansiedad"

**Principio clave:** Otros pueden ser estímulo de nuestros sentimientos, pero no la causa. La causa son nuestras necesidades satisfechas o insatisfechas.

