## PARTE 3: Asumir Responsabilidad de Nuestros Sentimientos

### Conectar Sentimientos con Necesidades

Nuestros sentimientos resultan de cómo elegimos recibir lo que otros dicen y hacen, así como de nuestras necesidades y expectativas particulares en ese momento.

#### Las Cuatro Opciones ante Mensajes Negativos

Cuando recibimos un mensaje negativo, tenemos cuatro opciones:

**1. Culparnos (autoculpa)**
"Cometí un error. Soy incompetente."
**Consecuencia:** Culpa, vergüenza, depresión

**2. Culpar a otros**
"Esto es tu culpa. Eres irresponsable."
**Consecuencia:** Ira, resentimiento, violencia

**3. Sentir nuestros sentimientos y necesidades**
"Me siento preocupado porque necesito confiabilidad"
**Consecuencia:** Consciencia, responsabilidad

**4. Sentir necesidades de otros**
"¿Te sientes abrumado porque necesitas apoyo?"
**Consecuencia:** Empatía, conexión

**CNV nos invita a opciones 3 y 4.**

#### Necesidades Humanas Universales

Todos los seres humanos comparten las mismas necesidades fundamentales. Nuestras estrategias para satisfacer esas necesidades varían, pero las necesidades son universales.

**Categorías de Necesidades:**

**Sustento físico:**
Aire, agua, alimento, descanso, movimiento, seguridad física, abrigo

**Interdependencia:**
Aceptación, afecto, aprecio, cercanía, comunidad, consideración, contribución, empatía, honestidad, intimidad, amor, respeto, apoyo, confianza

**Autonomía:**
Elección, libertad, independencia, espacio, espontaneidad

**Sentido:**
Aprendizaje, celebración, crecimiento, creatividad, desafío, duelo, esperanza, inspiración, integridad, luto, propósito, realización

**Juego y disfrute:**
Alegría, diversión, humor, risa, placer, relajación

#### Distinguir Necesidades de Estrategias

**Necesidad (universal, abstracta):**
- Reconocimiento, comprensión, colaboración

**Estrategia (específica, concreta):**
- "Necesito que mi jefe me elogie en la reunión de mañana"
- "Necesito que Juan responda mi email en 24 horas"

**Transformación CNV:**
"Necesito reconocimiento" (necesidad) → "¿Estarías dispuesto a compartir qué impacto tuvo mi trabajo en el proyecto?" (petición específica que podría satisfacer la necesidad)

