## PARTE 5: Recibir con Empatía

### Escuchar los Sentimientos y Necesidades de Otros

La empatía es presencia respetuosa y comprensiva a lo que otros están viviendo. No es:
- Aconsejar
- Consolar
- Educar
- Explicar
- Corregir
- Contar nuestra propia historia similar

La empatía es simplemente estar presente con la experiencia de otro.

#### Los Obstáculos a la Empatía

**Consejo:** "Deberías..."
**Consuelo:** "No fue tu culpa..."
**Historia propia:** "Eso no es nada, una vez yo..."
**Minimización:** "No es tan malo..."
**Interrogatorio:** "¿Por qué hiciste...?"
**Explicación:** "Lo que pasó fue..."
**Corrección:** "En realidad no fue así..."

#### El Proceso de Escucha Empática

**1. Presencia total**
- Dejar de lado agenda propia
- Suspender juicios
- Enfocarse completamente en la otra persona

**2. Escuchar sentimientos**
"¿Te sientes frustrado?"
"Escucho tristeza en tu voz..."
"Pareces ansioso..."

**3. Escuchar necesidades**
"¿Necesitas ser escuchado?"
"¿Es importante para ti tener claridad?"
"¿Valoras el respeto en las interacciones?"

**4. Parafrasear**
Reflejar lo escuchado sin repetir mecánicamente:

**Persona:** "¡No puedo creer que hicieron eso sin consultarme!"

**Empatía:**
"¿Te sientes molesto porque valoras ser incluido en decisiones que te afectan?"

#### Mantener la Empatía Cuando Es Difícil

**Cuando alguien nos ataca verbalmente:**

**Ataque:** "¡Eres el peor jefe que he tenido! Nunca escuchas."

**Respuestas no empáticas:**
- Contraataque: "Y tú eres el peor empleado..."
- Defensa: "Eso no es cierto, siempre escucho..."
- Desconexión: "Si vas a ser así, no puedo hablar contigo..."

**Respuesta empática:**
"¿Te sientes frustrado porque necesitas ser escuchado y valorado en el equipo?"

O simplemente hacer una pausa, respirar, y mantener presencia sin responder verbalmente de inmediato.

