LA HISTORIA

Esta es historia simple de cuatro personajes que viven en Laberinto y buscan Queso para nutrirse y ser felices.

DOS RATONCITOS: Fisgon y Escurridizo
DOS PERSONAS PEQUENAS: Hem y Haw

El Queso es metafora de lo que quieres en vida - trabajo, relacion, dinero, salud, paz mental.

El Laberinto es donde buscas lo que quieres - organizacion, familia, comunidad.

LA BUSQUEDA

Cada manana, cuatro personajes corrian por Laberinto buscando Queso.

Eventualmente, todos encontraron Estacion de Queso C, repleta de Queso delicioso.

RATONCITOS mantuvieron rutina simple:
- Llegaban temprano cada dia
- Revisaban si habia cambios
- Estaban preparados para seguir adelante

PERSONAS PEQUENAS se volvieron complacientes:
- Llegaban mas tarde
- Asumian Queso siempre estaria ahi
- Se acomodaron
- El Queso se convirtio en su identidad

UN DIA, EL QUESO DESAPARECIO

REACCIONES:

FISGON Y ESCURRIDIZO (ratones):
- No se sorprendieron (habian notado Queso disminuyendo)
- Inmediatamente se pusieron zapatos
- Salieron a Laberinto para buscar Nuevo Queso
- No analizaron en exceso

HEM Y HAW (personas):
- Entraron en shock
- No podian creerlo
- Se enojaron
- Gritaron: No es justo!
- Esperaron en Estacion C cada dia, esperando que Queso volviera

LECCION 1: EL CAMBIO SUCEDE

Anticipar cambio: Olfatea constantemente Queso para saber cuando esta envejeciendo.

Los ratones habian notado que provisiones de Queso disminuian gradualmente.

Las personas ignoraron senales porque estaban comodos.

DIAS EN ESTACION C VACIA

Hem y Haw seguian viniendo a Estacion C vacia.

Hem: Quien movio mi Queso?
Haw eventualmente se cansó de esperar.

Haw sugirio: Quizas deberiamos salir y buscar Nuevo Queso.
Hem: No! El Queso esta aqui en algun lugar. Solo necesitamos mirar mas duro.

LECCION 2: ADAPTATE RAPIDAMENTE AL CAMBIO

Cuanto mas rapido dejes ir Queso Viejo, mas rapido puedes disfrutar Nuevo Queso.

MIEDO DE HAW

Haw tenia miedo de adentrarse en Laberinto:
- Que pasa si no hay Queso afuera?
- El Laberinto es grande y confuso
- Podria perderse
- Podria encontrar algo peor

Pero finalmente se dio cuenta: Estar atrapado en situacion sin Queso era peor que enfrentar miedo.

LECCION 3: EL CAMBIO PUEDE LLEVARTE A ALGO MEJOR

Imagina disfrutando Nuevo Queso antes de encontrarlo, y te ayudara a alcanzarlo.

HAW SALE AL LABERINTO

Al principio, Haw estaba asustado. Pero tambien emocionado.

Encontro pequenas piezas de Queso aqui y alla. No mucho, pero suficiente para seguir adelante.

PENSAMIENTOS DE HAW:

Cuando dejas tus miedos atras, te sientes libre.

Oler Queso frecuentemente te ayuda a saber cuando esta envejeciendo.

Movimiento en nueva direccion te ayuda a encontrar Nuevo Queso.

LECCION 4: SUPERA TUS MIEDOS

Cuanto antes puedas reir de ti mismo y dejar ir Queso Viejo, mas rapido encontraras Nuevo Queso.

