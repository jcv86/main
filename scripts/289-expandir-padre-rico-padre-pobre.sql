Por Robert Kiyosaki

INTRODUCCIÓN

Tuve dos padres: uno rico y uno pobre. Uno era altamente educado e inteligente, el otro nunca terminó el octavo grado. Ambos hombres fueron exitosos en sus carreras trabajando duro toda su vida. Ambos ganaron ingresos substanciales. Sin embargo, uno siempre luchó financieramente mientras que el otro se convirtió en uno de los hombres más ricos de Hawaii.

Uno murió dejando decenas de millones de dólares a su familia, instituciones de caridad y su iglesia. El otro dejó cuentas por pagar.

LECCIÓN 1: LOS RICOS NO TRABAJAN POR DINERO

Los pobres y la clase media trabajan por dinero. Los ricos hacen que el dinero trabaje para ellos.

La mayoría de las personas quieren que haya seguridad cuando se trata de dinero. El miedo los mantiene en el trabajo, trabajando para alguien más, pagando impuestos excesivos.

"Despierta y huele las rosas" mi padre rico me decía. "El dinero es una ilusión."

Las personas permiten que dos emociones controlen sus vidas: miedo y avaricia. Ofréceles más dinero y continuarán el ciclo incrementando también sus gastos.

Mi padre rico me enseñó: "Trabaja para aprender, no trabajes por dinero."

El patrón de levantarse, ir a trabajar, pagar cuentas, levantarse, ir a trabajar, pagar cuentas... sus vidas están controladas por el miedo y la avaricia.

La principal causa de pobreza es el miedo y la ignorancia, no la economía, el gobierno o los ricos. Son los miedos y la ignorancia autoimpuestos los que mantienen atrapadas a las personas.

LECCIÓN 2: ¿POR QUÉ ENSEÑAR ESPECIALIZACIÓN FINANCIERA?

La inteligencia financiera resuelve muchos problemas de la vida. La inteligencia financiera es simplemente tener más opciones.

La contabilidad es posiblemente la materia más aburrida del mundo. También es la más confusa. Pero si quieres ser rico a largo plazo, podría ser la más importante.

Activo: algo que pone dinero en tu bolsillo.
Pasivo: algo que saca dinero de tu bolsillo.

Esta es realmente toda la definición que necesitas. Si quieres ser rico, simplemente pasa tu vida comprando activos. Si quieres ser pobre o clase media, pasa tu vida comprando pasivos.

La casa propia es el mayor gasto, no activo. Las personas trabajan toda su vida pagando una casa que nunca poseen completamente.

Patrón de flujo de dinero del pobre: Ingreso → Gasto
Patrón de flujo de dinero de la clase media: Ingreso → Gasto → Pasivo (hipoteca)
Patrón de flujo de dinero del rico: Ingreso → Activo → Ingreso adicional

LECCIÓN 3: OCÚPATE DE TU PROPIO NEGOCIO

Los ricos se enfocan en su columna de activos mientras todos los demás se enfocan en sus estados de ingresos.

La profesión de una persona es de lo que pagan sus cuentas. Su negocio es lo que los hace ricos.

Mantén tu trabajo diario, sé un gran empleado de tiempo completo, pero construye tu columna de activos.

Los activos reales caen en las siguientes categorías:
1. Negocios que no requieren mi presencia
2. Acciones
3. Bonos
4. Fondos de inversión
5. Bienes raíces que generan ingresos
6. Pagarés (IOUs)
7. Regalías de propiedad intelectual
8. Cualquier cosa que tenga valor, produzca ingreso o se aprecie

Comienza a ocuparte de tu propio negocio. Mantén tus gastos bajos, reduce tus pasivos y diligentemente construye una base de activos sólidos.

LECCIÓN 4: LA HISTORIA DE LOS IMPUESTOS Y EL PODER DE LAS CORPORACIONES

Mi padre rico jugaba el juego inteligentemente. Él lo hacía a través de corporaciones: el mayor secreto de los ricos.

El conocimiento es poder. Los ricos con corporaciones:
1. Ganan
2. Gastan
3. Pagan impuestos

Los empleados que trabajan para corporaciones:
1. Ganan
2. Pagan impuestos
3. Gastan

Una corporación es simplemente un archivo de documentos legales sentado en la oficina de algún abogado y registrado con una agencia estatal.

El IQ financiero está compuesto de conocimiento de cuatro áreas amplias:
1. Contabilidad: capacidad de leer números
2. Inversión: estrategias y fórmulas
3. Entendimiento de mercados: oferta y demanda
4. La ley: ventajas fiscales y protección contra demandas

LECCIÓN 5: LOS RICOS INVENTAN EL DINERO

La inteligencia financiera es simplemente tener más opciones. Si las oportunidades no te están viniendo a ti, ¿qué más puedes hacer para mejorar tu situación financiera?

Hay dos tipos de inversionistas:
1. El primer tipo compra un paquete de inversión
2. El segundo tipo crea inversiones

Si quieres ser el segundo tipo de inversionista, necesitas desarrollar tres habilidades principales:
1. Cómo encontrar oportunidades que otros pasaron por alto
2. Cómo recaudar dinero
3. Cómo organizar personas inteligentes

El mercado siempre está proporcionando oportunidades de una clase u otra. El cambio crea oportunidades.

La razón por la que tantas personas tienen problemas financieros es porque actuaron sobre emoción en lugar de sus cabezas.

Trabajo para aprender algo nuevo. Les doy a mis estudiantes también el mismo consejo. Muchos estudian específicamente para conseguir un trabajo, no para aprender habilidades.

LECCIÓN 6: TRABAJE PARA APRENDER, NO TRABAJE POR DINERO

"Eres solo una habilidad fuera de la gran riqueza." La mayoría de las personas necesitan solo aprender y dominar una habilidad más y su ingreso aumentaría exponencialmente.

Cuando se trata de dinero, la única habilidad que la mayoría de las personas conoce es trabajar duro.

Las habilidades más importantes son ventas y marketing. La capacidad de vender es la habilidad número uno en negocios.

Cuanto más especializado te vuelves, más atrapado quedas en esa especialización. Las corporaciones hacen exactamente lo opuesto. Buscan empleados que conozcan un poco sobre mucho.

Trabajé para aprender habilidades. No trabajé por dinero. Recomiendo a los jóvenes que busquen trabajo por lo que aprenderán más que por lo que ganarán.

La educación es más valiosa que el dinero a largo plazo.

SUPERANDO OBSTÁCULOS

Las cinco razones principales por las que las personas financieramente alfabetizadas todavía no desarrollan columnas de activos:

1. MIEDO: El miedo a perder dinero es real. Todos lo tienen. El problema no es el miedo en sí, sino cómo lo manejas. La diferencia entre una persona rica y pobre es cómo manejan ese miedo.

Los ganadores no tienen miedo de perder. Los perdedores sí. El fracaso es parte del proceso de éxito. Las personas que evitan el fracaso también evitan el éxito.

2. CINISMO: El cielo se está cayendo. Los pesimistas nunca ganarán. Las personas cínicas son gallinas pequeñas. Los pesimistas críticos nunca ganarán.

Los cínicos nunca ganan. El mundo siempre te está dando oportunidades de una clase u otra. Sin embargo, las dudas a menudo nos paralizan.

3. PEREZA: Las personas ocupadas son a menudo las más perezas. Si se les pregunta por qué no cuidan su salud o su riqueza, la respuesta es siempre "Estoy ocupado."

La cura para la pereza: un poco de codicia. Sin ese poco de codicia, el deseo de tener algo mejor, no hay progreso.

4. MALOS HÁBITOS: Primero págate a ti mismo. Cuando me quedo corto de dinero, dejo que la presión me motive a crear otras formas de ingreso.

5. ARROGANCIA: Arrogancia es ego más ignorancia. Hay muchas personas en el mundo del dinero que no tienen idea de lo que están hablando. La mayoría son vendedores, no maestros.

