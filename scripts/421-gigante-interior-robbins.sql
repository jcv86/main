## PARTE V: PREGUNTAS SON LA RESPUESTA

### Capítulo 5: El Poder de las Preguntas

**Verdad:**
"La calidad de tu vida es determinada por la calidad de las preguntas que te haces."

**Preguntas Destructivas vs Empoderadoras:**

**Destructivas:**
- "¿Por qué siempre me pasa esto a mí?"
- "¿Por qué soy tan estúpido?"
- "¿Por qué no puedo hacer nada bien?"

**Resultado:** Te sientes peor, sin soluciones.

**Empoderadoras:**
- "¿Qué puedo aprender de esto?"
- "¿Cómo puedo usar esto?"
- "¿Qué es genial de esto que aún no veo?"

**Resultado:** Te sientes mejor, encuentras soluciones.

### Las Preguntas de la Mañana

**Ritual Diario:**
Cada mañana, hazte estas preguntas:

**1. ¿Qué me hace feliz en mi vida ahora?**
