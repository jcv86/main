## TERCER ACUERDO: NO HAGAS SUPOSICIONES

### El Problema de las Suposiciones

Hacemos suposiciones constantemente. Suponemos que otros saben lo que pensamos, sentimos y necesitamos. Suponemos que sabemos lo que otros piensan, sienten y necesitan.

**Resultado:**
Malentendidos, conflictos, sufrimiento innecesario.

### Por Qué Hacemos Suposiciones

**Necesidad de Explicación:**
El cerebro humano necesita explicar todo. Cuando no tenemos información, la inventamos.

**Miedo a Preguntar:**
- Miedo a parecer ignorante
- Miedo al rechazo
- Miedo a la verdad

**Resultado:**
Preferimos suponer que preguntar.

### El Costo de las Suposiciones

**En Relaciones:**

**Ejemplo 1:**
Tu pareja llega tarde. Supones que no le importas. Te enojas. Pelean.

**Realidad:**
Hubo tráfico. Intentó llamar pero su teléfono murió.

**Ejemplo 2:**
Tu amigo no te invita a una fiesta. Supones que está enojado contigo. Dejas de hablarle.

**Realidad:**
Pensó que estabas ocupado ese día.

**En el Trabajo:**

**Ejemplo:**
Tu jefe no responde tu email. Supones que está molesto contigo. Te preocupas todo el día.

**Realidad:**
Está en reuniones todo el día y no ha revisado emails.

### La Solución: Preguntar

**Principio Simple:**
Cuando no sepas, pregunta. No supongas.

**Beneficios:**
- Claridad
- Menos conflictos
- Mejor comunicación
- Menos sufrimiento

**Cómo Preguntar:**

**1. Directamente:**
"¿Estás molesto conmigo?" en lugar de suponer que lo está.

**2. Sin Acusar:**
"Noté que no respondiste mi mensaje. ¿Todo bien?" en lugar de "¿Por qué me ignoras?"

**3. Con Apertura:**
"Quiero entender tu perspectiva" en lugar de "Sé lo que estás pensando."

### Comunicación Clara

**Expresa Claramente:**

**No Supongas que Otros Saben:**
- Lo que piensas
- Lo que sientes
- Lo que necesitas
- Lo que quieres

**Di Claramente:**
- "Necesito..."
- "Siento..."
- "Pienso..."
- "Quiero..."

**Ejemplo:**

**Suposición:**
"Si me amara, sabría que necesito espacio."

**Comunicación Clara:**
"Te amo, pero necesito un poco de tiempo a solas para recargar energías."

### Verificar Entendimiento

**No Supongas que Entendiste:**

Después de escuchar, verifica:
- "¿Entendí correctamente que...?"
- "¿Quieres decir que...?"
- "¿Puedes explicar más sobre...?"

**No Supongas que te Entendieron:**

Después de explicar, pregunta:
- "¿Tiene sentido?"
- "¿Hay algo que no esté claro?"
- "¿Cómo entendiste lo que dije?"

### Cómo Practicar el Tercer Acuerdo

**1. Conciencia:**
Nota cuando estás suponiendo. Pregúntate: "¿Sé esto con certeza o estoy suponiendo?"

**2. Coraje para Preguntar:**
Supera el miedo. Pregunta directamente.

**3. Comunicación Clara:**
Expresa tus pensamientos, sentimientos y necesidades claramente.

**4. Verificación:**
Verifica que entendiste y que te entendieron.

**5. Apertura:**
Mantén la mente abierta. La realidad puede ser diferente de tu suposición.

**Ejercicio:**

**Cuando Notes una Suposición:**
1. Pausa
2. Pregunta: "¿Sé esto con certeza?"
3. Si no, pregunta o investiga
4. No actúes basado en la suposición

**Práctica Diaria:**
- Identifica 3 suposiciones que hiciste hoy
- ¿Cuáles fueron las consecuencias?
- ¿Cómo podrías haber preguntado en su lugar?

