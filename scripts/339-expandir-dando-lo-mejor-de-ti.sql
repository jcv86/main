- Lidera con preguntas, no respuestas
- Conduce autopsias sin culpar
- Construye mecanismos de alerta temprana

**4. EL CONCEPTO DEL ERIZO**

**Tres círculos:**

**Círculo 1: En qué puedes ser el mejor del mundo**
- No tu competencia central
- No lo que quieres ser mejor
- Sino en qué puedes ser el mejor

**Círculo 2: Qué impulsa tu motor económico**
- Cuál es tu única métrica clave
- Qué hace la mayor diferencia a tus resultados

**Círculo 3: Por qué te apasionas profundamente**
- Qué enciende tu entusiasmo
- Qué nunca dejarías de hacer

**Tu Concepto del Erizo = La intersección de los tres círculos**

**Ejemplos:**

**Wells Fargo:**
- Mejor en: Ejecutar banca como negocio
- Motor económico: Ganancia por empleado
- Pasión: Mostrar que pueden ganar

**Walgreens:**
- Mejor en: Conveniencia de farmacia comunitaria
- Motor económico: Ganancia por visita de cliente
- Pasión: Ayudar a las personas

**5. CULTURA DE DISCIPLINA**

**Disciplina no es igual a tiranía:**

**En empresas disciplinadas:**
- Las personas disciplinadas no necesitan jerarquía
- El pensamiento disciplinado no necesita burocracia
- La acción disciplinada no necesita controles excesivos

**La Fórmula:**
Personas disciplinadas + Pensamiento disciplinado + Acción disciplinada = Grandeza

**Lista de NO hacer:**

Las grandes empresas tienen listas de qué NO hacer:
- Tan importantes como listas de qué hacer
- Mantienen el foco
- Eliminan distracciones

**6. TECNOLOGÍA COMO ACELERADOR**

**Principio clave:** La tecnología es acelerador, no creador de momentum.

**Las grandes empresas:**
- Usan tecnología para acelerar momentum
- NO esperan que tecnología cree momentum
- Primero tienen Concepto del Erizo claro
- Luego buscan tecnología que lo acelere

**Errores comunes:**
- Usar tecnología porque otros la usan
- Saltar a nueva tecnología sin estrategia
- Esperar que tecnología resuelva problemas fundamentales

**7. EL VOLANTE Y EL BUCLE DE CONDENA**

**El Volante:**

El éxito sostenible viene de:
- Empujar consistentemente en la misma dirección
- No un evento dramático
- Sino acumulación de esfuerzo

**Fases del volante:**
1. Empiezas a empujar
2. El volante apenas se mueve
3. Sigues empujando consistentemente
4. Gana un poco de momentum
5. Sigues empujando en la misma dirección
6. Más momentum
7. Eventualmente alcanza breakthrough
8. Pero no fue un solo empujón - fue la acumulación

**El Bucle de Condena:**

Lo opuesto del volante:
- Reaccionar sin comprensión
- Nueva dirección, programa, líder
- Sin acumular momentum
- Resultados decepcionantes
- Otra reacción, nueva dirección
- Ciclo se repite
- Espiral descendente

