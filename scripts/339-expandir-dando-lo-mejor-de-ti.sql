'**DANDO LO MEJOR DE TI**
*Por Jim Collins*

**INTRODUCCIÓN**

Jim Collins investigó qué hace que las buenas empresas se conviertan en grandes empresas. Estudió durante 5 años más de 1,400 compañías para encontrar los patrones del éxito sostenible.

**La pregunta central:** Cómo puede una buena compañía convertirse en una gran compañía y mantener ese estatus.

**CONCEPTOS FUNDAMENTALES**

**1. LIDERAZGO NIVEL 5**

Los líderes excepcionales combinan:
- Humildad personal
- Voluntad profesional férrea

**Características del Líder Nivel 5:**
- Construye éxito duradero
- Piensa en el siguiente líder
- Atribuye éxito a otros
- Asume responsabilidad personal por fracasos
- Ambicioso para la empresa, no para sí mismo

**Ejemplo: Darwin Smith (Kimberly-Clark)**
- Tímido y modesto
- Transformó Kimberly-Clark de buena a excelente
- Tomó la audaz decisión de salir de molinos de papel
- Entró en productos de consumo
- Superó a Procter and Gamble

**2. PRIMERO QUIÉN, LUEGO QUÉ**

**El orden correcto:**
1. Consigue las personas correctas en el bus
2. Consigue las personas incorrectas fuera del bus
3. Consigue las personas correctas en los asientos correctos
4. Decide a dónde conducir el bus

**Por qué este orden:**
- Las personas correctas se auto-motivan
- Si la estrategia cambia, las personas correctas se adaptan
- Las personas incorrectas nunca funcionarán

**Tres principios:**

**A. Disciplinado con la gente:**
- Cuando tengas dudas, no contrates
- Actúa cuando sabes que debes cambiar personas
- Pon a tus mejores personas en tus mejores oportunidades

**B. Riguroso, no despiadado:**
- Las grandes empresas son rigurosas
- No son despiadadas con la gente

**C. Las compensaciones siguen el desempeño:**
- No intentes motivar con incentivos
- Contrata personas motivadas

**3. ENFRENTA LOS HECHOS BRUTALES**

**El Concepto del Almirante Stockdale:**

James Stockdale fue prisionero de guerra en Vietnam por 8 años.

**La Paradoja de Stockdale:**
- Mantén fe inquebrantable en que triunfarás al final
- Y al mismo tiempo
- Enfrenta los hechos más brutales de tu realidad actual

**Quién NO sobrevivió:**
Los optimistas ingenuos:
- Esto terminará para Navidad
- Esto terminará para Pascua
- Esto terminará para Acción de Gracias
- Eventualmente murieron de corazón roto

**Aplicación en negocios:**
