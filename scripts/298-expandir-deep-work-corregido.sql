Realidad: La mayoria de lo que sucede en linea no importa para tu trabajo o vida.

CAPITULO 3: DEEP WORK ES SIGNIFICATIVO

El trabajo profundo no es solo economicamente valioso - es profundamente satisfactorio.

PERSPECTIVA NEUROLOGICA
Tu cerebro construye tu realidad basandose en lo que enfocas. Si enfocas en lo trivial, tu vida se sentira trivial.

"Quien eres, lo que piensas, sientes, y haces, lo que amas - es la suma de en que enfocas tu atencion."

PERSPECTIVA PSICOLOGICA
Mihaly Csikszentmihalyi descubrio que las mejores experiencias en nuestras vidas ocurren en "flow" - un estado de concentracion intensa en una tarea desafiante.

El trabajo profundo es una fuente fiable de flow.

PERSPECTIVA FILOSOFICA
Trabajo artesanal produce significado. El programador, escritor, o artista que se sumerge profundamente en su oficio experimenta una satisfaccion que el trabajo superficial nunca puede proporcionar.

PARTE 2: LAS REGLAS

REGLA 1: TRABAJA PROFUNDAMENTE

La fuerza de voluntad es limitada. No puedes simplemente decidir "trabajare profundamente" y esperar que suceda consistentemente.

Necesitas rutinas y rituales para minimizar la cantidad de fuerza de voluntad necesaria.

CUATRO FILOSOFIAS DE PROGRAMACION DE DEEP WORK:

1. FILOSOFIA MONASTICA
Eliminar o minimizar radicalmente obligaciones superficiales.
Ejemplo: Donald Knuth (cientifico computacional) - no tiene email.
Funciona para: Personas con objetivo profesional singular y claro.

2. FILOSOFIA BIMODAL
Dividir tu tiempo, dedicando algunos periodos claramente definidos a busquedas profundas y dejando el resto abierto a todo lo demas.
Ejemplo: Carl Jung - se retiraba a su torre en Bollingen para pensar profundamente, pero mantenia practica activa en Zurich.
Funciona para: Personas que pueden controlar su horario.

3. FILOSOFIA RITMICA
Convertir el trabajo profundo en un habito simple y regular.
Ejemplo: Escritor que escribe de 5:30 AM a 7:30 AM cada dia.
Funciona para: La mayoria de las personas con trabajos tradicionales.

4. FILOSOFIA PERIODISTICA
Encajar trabajo profundo donde puedas en tu horario.
Ejemplo: Periodista que puede cambiar instantaneamente a modo de escritura profunda.
Funciona para: Expertos que han entrenado su capacidad de cambiar rapidamente a profundidad.

RITUALES PARA DEEP WORK

Tu ritual debe abordar:

1. DONDE trabajaras y por CUANTO TIEMPO
Ejemplo: Biblioteca desde 9 AM hasta 12 PM.

2. COMO trabajaras una vez que comiences
Ejemplo: No internet, puerta cerrada, telefono en otra habitacion.

3. COMO apoyaras tu trabajo
Ejemplo: Cafe listo, bocadillos saludables, musica de fondo.

EL GRAN GESTO

A veces, un cambio radical en tu ambiente normal puede proporcionar el impulso psicologico para profundidad.

Ejemplo: 
- J.K. Rowling se registro en un hotel de lujo para terminar Harry Potter
- Bill Gates toma "semanas de pensamiento" dos veces al ano, retirándose a una cabana

NO TRABAJES SOLO

Colaboracion puede profundizar el trabajo, no siempre diluirlo.

El efecto whiteboard: Trabajar junto a alguien en un problema puede generar insights mas profundos que trabajar solo.

Pero necesitas tiempo solo para absorber e implementar lo que aprendiste.

