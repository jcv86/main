Por Cal Newport

INTRODUCCION

Deep Work: Actividades profesionales realizadas en un estado de concentracion libre de distracciones que empujan tus capacidades cognitivas a su limite. Estos esfuerzos crean nuevo valor, mejoran tu habilidad, y son dificiles de replicar.

Shallow Work: Tareas no cognitivamente demandantes, estilo logistico, a menudo realizadas mientras se esta distraido. Estos esfuerzos tienden a no crear mucho valor nuevo en el mundo y son faciles de replicar.

LA HIPOTESIS DEL DEEP WORK

La capacidad de realizar trabajo profundo se esta volviendo cada vez mas rara y al mismo tiempo se esta volviendo cada vez mas valiosa en nuestra economia. Como consecuencia, los pocos que cultivan esta habilidad y luego la hacen el nucleo de su vida laboral prosperaran.

PARTE 1: LA IDEA

CAPITULO 1: DEEP WORK ES VALIOSO

En la nueva economia, tres grupos tienen una ventaja particular:

1. TRABAJADORES DE ALTA HABILIDAD
Aquellos que pueden trabajar bien y creativamente con maquinas inteligentes.
Ejemplo: Nate Silver, estadistico que domina analisis de datos complejos.

2. LOS SUPER ESTRELLAS
Los mejores en lo que hacen.
Ejemplo: David Heinemeier Hansson, programador excepcional.

3. LOS DUENOS
Aquellos con capital para invertir en las nuevas tecnologias.

Para unirte a los primeros dos grupos necesitas dos habilidades nucleares:

HABILIDAD 1: La capacidad de dominar rapidamente cosas dificiles
Las tecnologias cambian rapidamente. Debes ser capaz de aprender cosas complejas rapidamente, una y otra vez.

HABILIDAD 2: La capacidad de producir a un nivel elite, en terminos de calidad y velocidad
No es suficiente solo saber hacer algo - debes ser capaz de producir resultados que la gente valore.

Ambas habilidades dependen de tu capacidad para realizar trabajo profundo.

LA FORMULA DEL TRABAJO DE ALTA CALIDAD

Trabajo de Alta Calidad Producido = (Tiempo Gastado) x (Intensidad de Enfoque)

Si constantemente cambias tu atencion de tarea A a tarea B y de vuelta, pagas un costo de cambio cada vez. Tu atencion residual de la tarea previa reduce tu rendimiento en la nueva tarea.

CAPITULO 2: DEEP WORK ES RARO

Tendencias actuales del lugar de trabajo:

- Oficinas abiertas
- Mensajeria instantanea
- Presencia en redes sociales
- Reuniones frecuentes
- Multitarea constante

Todas estas tendencias reducen la capacidad de concentracion profunda.

EL PRINCIPIO DEL MENOR ESFUERZO

En ausencia de indicadores claros de productividad, muchos trabajadores usan "estar ocupado" como proxy para productividad real.

Responder correos rapidamente se siente productivo. Pero no produce valor real.

EL CULTO A INTERNET

