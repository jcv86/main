Por Cal Newport

INTRODUCCION

Deep Work es la capacidad de enfocarse sin distraccion en una tarea cognitivamente demandante. Es una habilidad que te permite dominar rapidamente informacion complicada y producir mejores resultados en menos tiempo.

Deep Work te hara mejor en lo que haces y proporcionara el sentido de verdadero cumplimiento que viene de la artesania. En resumen, el trabajo profundo es como un superpoder en nuestra economia cada vez mas competitiva.

El trabajo profundo se esta volviendo cada vez mas raro exactamente al mismo tiempo que se esta volviendo cada vez mas valioso en nuestra economia. Como consecuencia, los pocos que cultivan esta habilidad, y luego la hacen el nucleo de su vida laboral, prosperaran.

LA HIPOTESIS DEL TRABAJO PROFUNDO:
La capacidad de realizar trabajo profundo se esta volviendo cada vez mas rara al mismo tiempo que se esta volviendo cada vez mas valiosa en nuestra economia. Como consecuencia, los pocos que cultivan esta habilidad, y luego la hacen el nucleo de su vida laboral, prosperaran.

SHALLOW WORK (TRABAJO SUPERFICIAL):
Tareas de estilo logistico no cognitivamente demandantes, a menudo realizadas mientras se esta distraido. Estos esfuerzos tienden a no crear mucho valor nuevo en el mundo y son faciles de replicar.

PARTE UNO: LA IDEA

CAPITULO 1: EL TRABAJO PROFUNDO ES VALIOSO

En la nueva economia, tres grupos tendran una ventaja particular:

1. AQUELLOS QUE PUEDEN TRABAJAR BIEN Y CREATIVAMENTE CON MAQUINAS INTELIGENTES
2. AQUELLOS QUE SON LOS MEJORES EN LO QUE HACEN
3. AQUELLOS CON ACCESO A CAPITAL

Para unirte a los primeros dos grupos (los unicos realistas para la mayoria), necesitas las siguientes dos habilidades centrales:

HABILIDAD 1: La capacidad de dominar rapidamente cosas dificiles
HABILIDAD 2: La capacidad de producir a nivel elite, en terminos de calidad y velocidad

Estas dos habilidades centrales dependen de tu capacidad para realizar trabajo profundo.

APRENDIENDO COSAS DIFICILES RAPIDAMENTE

Para aprender requiere intensa concentracion. Anders Ericsson, el experto en el estudio de expertos, senala que los individuos de elite en campos intelectualmente exigentes son diferenciados por cuanto practican deliberadamente.

La practica deliberada requiere:
1. Tu atencion esta enfocada estrechamente en una habilidad especifica que estas tratando de mejorar
2. Recibes retroalimentacion para que puedas corregir tu enfoque
3. Te mantienes enfocado - las distracciones son el enemigo

La practica deliberada = trabajo profundo

PRODUCIENDO A NIVEL ELITE

Adam Grant, el profesor de gestion mas joven en recibir permanencia en Wharton, es conocido por su ritmo increible de produccion de alta calidad.

Su secreto: Agrupa su ensenanza en el semestre de otono, liberando su primavera y verano para trabajo profundo sin interrupcion. En estos periodos, puede lograr en dias lo que tomaria semanas con constantes interrupciones.

Ley de Productividad de Alto Nivel:
Trabajo de Alta Calidad Producido = (Tiempo Gastado) x (Intensidad de Enfoque)

Para producir a tu nivel pico necesitas trabajar por periodos extendidos con total concentracion en una sola tarea libre de distraccion. En otras palabras, trabajo profundo.

CAPITULO 2: EL TRABAJO PROFUNDO ES RARO

A pesar de su valor, el trabajo profundo esta en camino de extincion en la economia actual.

CULTURA DE CONECTIVIDAD
Expectativa de responder rapida y constantemente a emails y mensajes. Esta cultura persiste porque es mas facil para todos estar conectados que definir comunicacion mas estructurada.

OPEN OFFICES
Los espacios de oficina abiertos pueden aumentar la colaboracion, pero destruyen el trabajo profundo. Un estudio de Harvard encontro que las interacciones cara a cara realmente disminuyeron en un 70 por ciento despues de mudarse a oficinas abiertas.

REUNIONES REGULARES
Reuniones de actualizacion de estado, reuniones permanentes, check-ins - todos interrumpen bloques de tiempo profundo.

PRESENCIA EN REDES SOCIALES
La expectativa de presencia continua en multiples plataformas de redes sociales fragmenta la atencion.

POR QUE PERSISTEN ESTAS TENDENCIAS

PRINCIPIO DE MINIMA RESISTENCIA:
En un entorno de negocios sin retroalimentacion clara sobre el impacto de varios comportamientos al valor de la firma, tenderemos hacia comportamientos que son mas faciles en el momento.

Es mas facil:
- Responder emails que disenar un sistema de comunicacion mas estructurado
- Asistir a reuniones que proteger bloques de tiempo de enfoque
- Revisar Twitter que pensar profundamente sobre un problema

BUSYNESS AS PROXY FOR PRODUCTIVITY:
En ausencia de indicadores claros de lo que significa ser productivo y valioso, muchos trabajadores del conocimiento recurren a un indicador industrial: hacer muchas cosas de manera visible.

CAPITULO 3: EL TRABAJO PROFUNDO ES SIGNIFICATIVO

El trabajo profundo no es solo economicamente valioso - es profundamente significativo.

ARGUMENTO NEUROLOGICO

Estudios de Mihaly Csikszentmihalyi muestran que el flow - inmersion profunda en una actividad desafiante - es el estado donde las personas reportan mayor satisfaccion.

Las mejores momentos usualmente ocurren cuando el cuerpo o mente de una persona esta estirado hasta sus limites en un esfuerzo voluntario por lograr algo dificil y que vale la pena.

El trabajo profundo es actividad disenada para empujarte hacia estos estados de flow.

ARGUMENTO PSICOLOGICO

Winifred Gallagher argumenta que quien eres, lo que piensas, sientes y haces, en lo que crees, es la suma de aquello en lo que enfocas.

Al trabajar profundamente, diriges tu atencion hacia actividades significativas en lugar de hacia las trivialidades y molestias de la vida moderna.

ARGUMENTO FILOSOFICO

Dreyfus y Kelly argumentan que la artesania proporciona una clave para encontrar significado en un mundo post-religioso.

El artesano habil esta absorto en el esfuerzo de hacer algo bien - no para hacer algo perfecto, sino para hacer algo mejor que antes.

El trabajo profundo es artesania moderna. Es la habilidad de nuestro tiempo.

PARTE DOS: LAS REGLAS

REGLA 1: TRABAJA PROFUNDAMENTE

Esforzarse por concentracion profunda no es algo natural. Requiere estructuras y rutinas para superar resistencias.

DECIDE TU FILOSOFIA DE PROFUNDIDAD

FILOSOFIA MONASTICA:
Maximiza esfuerzos profundos eliminando o minimizando radicalmente obligaciones superficiales.
Ejemplo: Donald Knuth (no tiene email)

FILOSOFIA BIMODAL:
Divide tu tiempo, dedicando algunos periodos claramente definidos a busquedas profundas y dejando el resto abierto a todo lo demas.
Ejemplo: Carl Jung (retiros largos en Bollingen)

FILOSOFIA RITMICA:
Convierte el trabajo profundo en un habito simple y regular.
Ejemplo: Jerry Seinfeld y su no romper la cadena

FILOSOFIA PERIODISTICA:
Encaja trabajo profundo donde puedes en tu horario.
Ejemplo: Walter Isaacson (escribia biografias entre trabajos de periodismo)

RITUALIZA

Las grandes mentes como las grandes rutinas. Construye rituales de las mismas severidad como pensadores serios.

Tu ritual debe abordar:
1. DONDE trabajaras y por cuanto tiempo
2. COMO trabajaras una vez que comiences
3. COMO apoyaras tu trabajo (cafe, comida, ejercicio ligero)

HAZ GRANDES GESTOS

Al aumentar radicalmente la inversion normal en tu busqueda de profundidad - dedicando un lugar especial, tomando un viaje largo, poniendo un desafio o apuesta grande en la mesa - aumentas la importancia percibida de la tarea.

J.K. Rowling escribio los ultimos libros de Harry Potter en un suite de hotel de cinco estrellas de 1000 dolares por dia.

Bill Gates toma Think Weeks - retiros en solitario en una cabana remota con nada mas que libros y papers.

NO TRABAJES SOLO

El hub-and-spoke modelo de arquitectura puede funcionar bien:
- Hub: espacio compartido para interaccion serendipica
- Spokes: oficinas privadas para trabajo profundo

Ejemplo: Building 20 en MIT - mezcla de espacios colaborativos y privados genero avances.

EJECUTA COMO UN NEGOCIO

Estrategia de Ejecucion 4DX (4 Disciplines of Execution):

DISCIPLINA 1: Enfocate en lo Tremendamente Importante
Identifica un pequeno numero de metas ambiciosas. Si intentas hacer demasiado, no lograras hacer nada bien.

DISCIPLINA 2: Actua sobre Medidas de Liderazgo
Para trabajo profundo, el tiempo gastado en estado de trabajo profundo dedicado a tu objetivo tremendamente importante.

DISCIPLINA 3: Manten un Marcador Convincente
Coloca una hoja de papel en la pared. Registra cada hora de trabajo profundo con una marca de conteo.

DISCIPLINA 4: Crea una Cadencia de Accountability
Revision semanal: Tuviste un buen semana? Que obstaculizo las horas profundas? Que haras diferente?

SE PEREZOSO

Shutdown completo ayuda a recargar energia para trabajo profundo.

Razon 1: El tiempo de inactividad ayuda a insights
La teoria de pensamiento inconsciente sugiere que algun pensamiento inconsciente prolongado sobre un problema produce mejores decisiones.

Razon 2: El tiempo de inactividad ayuda a recargar energia
La teoria de restauracion de atencion sugiere que pasar tiempo en naturaleza puede mejorar tu capacidad de concentrarte.

Razon 3: El trabajo que el tiempo de inactividad reemplaza usualmente no es tan importante
Tu capacidad para trabajo profundo en un dia dado es limitada. Una vez que has alcanzado tu limite diario, no tiene sentido luchar mas.

RITUAL DE SHUTDOWN:
1. Revisa tu lista de tareas
2. Revisa tu calendario
3. Haz un plan aproximado para manana
4. Di shutdown completo en voz alta

REGLA 2: ABRAZA EL ABURRIMIENTO

La capacidad de concentrarse intensamente es una habilidad que debe ser entrenada.

EL ESFUERZO PARA PROFUNDIZAR NO ES SUFICIENTE SI CONSTANTEMENTE CEDES A DISTRACCIONES

Si todas las instancias de menor estimulo te encuentran alcanzando tu telefono, tu cerebro ha sido efectivamente reentrenado a un punto donde no es capaz de sostener concentracion profunda.

NO TOMES DESCANSOS DE DISTRACCION. EN SU LUGAR, TOMA DESCANSOS DE ENFOQUE.

En lugar de programar descansos ocasionales de distraccion, programa descansos ocasionales de enfoque.

Programa cuando usaras internet, y evitalo completamente fuera de esos tiempos.

Ejemplo de Horario:
- Internet: 9:00-9:15, 10:30-10:45, 2:00-2:30
- Todo lo demas: Sin internet

Esto aplica en casa tambien. No mires tu telefono mientras esperas en linea o durante comerciales.

TRABAJA COMO TEDDY ROOSEVELT

Teddy Roosevelt en Harvard: Usaba bloques breves de tiempo intenso para trabajo academico, dejando tiempo libre para actividades extracurriculares.

Identifica una tarea de alta prioridad. Estima cuanto tiempo tomaria normalmente. Dale una fecha limite dramaticamente reducida. Trabaja con gran intensidad - sin email, sin internet, sin distraccion.

Estas sesiones de Roosevelt entrenan tu capacidad para concentrarte y demuestran que puedes hacer mucho mas en menos tiempo.

MEDITA PRODUCTIVAMENTE

Toma un periodo en el que estas ocupado fisicamente pero no mentalmente - caminando, corriendo, conduciendo - y enfoca tu atencion en un solo problema profesional bien definido.

Sugerencia 1: Ten cuidado con distracciones y bucles
Tu mente querra evitar el pensamiento profundo. Cuando notes esto, redirige suavemente tu atencion.

Sugerencia 2: Estructura tu pensamiento profundo
1. Identifica las variables relevantes
2. Define la pregunta especifica de siguiente nivel que necesitas responder
3. Consolida tus ganancias revisando claramente la respuesta identificada

MEMORIZA UNA BARAJA DE CARTAS

Los atletas de memoria usan una estrategia llamada el palacio de memoria. Almacenan numeros asociandolos con imagenes en locaciones de un palacio mental imaginado.

Practicar esto entrena tu capacidad de concentrarte - aunque nunca uses la habilidad.

REGLA 3: DEJA LAS REDES SOCIALES

Las redes sociales son particularmente seductoras porque son disenadas para gatillar un sentido de conexion sin la demanda de verdadera relacion.

APLICA LA LEY DE LOS POCOS VITALES A TUS HABITOS DE INTERNET

Identifica las metas principales en tu vida profesional y personal. Luego lista las dos o tres actividades mas importantes que te ayudan a satisfacer la meta.

Adopta una herramienta de red solo si sus impactos positivos en estos factores sustancialmente superan los impactos negativos.

NO USES INTERNET PARA ENTRETENERTE

Pon mas pensamiento en tu tiempo de ocio. Darle a tu mente un descanso de demandas no significa que necesites darle cualquier entretenimiento suave que cruza tu camino.

