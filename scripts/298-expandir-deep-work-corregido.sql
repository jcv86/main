CUANTIFICA LA PROFUNDIDAD DE CADA ACTIVIDAD

Pregunta: Cuanto tiempo llevaria entrenar a un graduado universitario recien graduado sin entrenamiento especializado para completar esta tarea?

Actividades que requieren muchos meses = profundas
Actividades que requieren poco entrenamiento = superficiales

Objetivo: Maximiza lo primero, minimiza lo segundo.

PREGUNTA A TU JEFE POR UN PRESUPUESTO DE TRABAJO SUPERFICIAL

Que porcentaje de mi tiempo debe ser dedicado a deberes superficiales?

Una vez que tienes este numero, presupuesta tu tiempo de acuerdo. Rechaza (educadamente) obligaciones que te empujarian sobre el limite.

TERMINA TU TRABAJO A LAS 5:30

Fija un final duro para tu dia de trabajo. Trabaja hacia atras para encontrar estrategias de productividad que te permitan satisfacer este horario.

Esto crea escasez - si sabes que tienes solo hasta 5:30, eliminaras despiadadamente lo superficial.

VUELVETE DIFICIL DE CONTACTAR

PUNTA 1: Haz que la gente que te envie email haga mas trabajo
Usa una direccion de correo de proposito especifico: una direccion diferente para diferentes propositos con instrucciones claras sobre que tipo de emails son apropiados.

PUNTA 2: Haz mas trabajo cuando envies o respondas emails
Cual es el proyecto representado por este mensaje, y cual es la manera mas eficiente de llevarlo a una conclusion exitosa?

En lugar de: Te gustaria tomar cafe?
Intenta: Quieres tomar cafe? Estoy libre los martes y jueves despues de las 4. Si te interesa, enviame tres momentos que funcionen para ti y mi asistente establecera una cita.

PUNTA 3: No respondas
Es perfecto no responder a emails que:
- Son ambiguos o dificiles de generar una respuesta razonable
- No son una pregunta o propuesta de interes
- Nada bueno pasaria si respondieras y nada malo si no respondieras

