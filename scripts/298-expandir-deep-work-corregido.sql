EL ENFOQUE DE CUALQUIER BENEFICIO (EVITAR ESTO)

Justificacion: "Esta herramienta tiene algun beneficio, por lo tanto deberia usarla."

Problema: Casi cualquier cosa tiene algun beneficio. Pero tambien tiene costos.

EL ENFOQUE ARTESANAL PARA SELECCION DE HERRAMIENTAS

Identificar los principales factores que determinan exito y felicidad en tu vida profesional y personal.

Solo usar una herramienta de red si sus impactos positivos en estos factores superan sustancialmente los impactos negativos.

APLICA LA LEY DE LOS POCOS VITALES A TUS HABITOS DE INTERNET

Ley de Pareto: 80% de un efecto dado se debe a solo 20% de las posibles causas.

Para cada meta clave, identifica 2-3 actividades mas importantes que te ayudan a alcanzarla.

Ejemplo:
Meta: Mantener relaciones cercanas con un grupo de amigos.
Actividades clave:
1. Regularmente tomar tiempo para reuniones en profundidad
2. Dar apoyo significativo en momentos importantes

Facebook podria apoyar esto debilmente. Pero el costo (tiempo, atencion) probablemente supera el beneficio.

ABANDONA LAS REDES SOCIALES

Desafio de 30 dias: Deja de usar todas las redes sociales por 30 dias. No anuncies. Solo detente.

Despues de 30 dias pregunta:
1. Habrian sido los ultimos 30 dias significativamente mejores si hubiera podido usar este servicio?
2. La gente se preocupo porque no estaba usando este servicio?

Si respondes "no" a ambas, abandona el servicio permanentemente.

NO USES INTERNET PARA ENTRETENERTE

Las compañias tecnologicas han invertido miles de millones para hacer internet entretenido durante cada momento libre.

Resultado: Has perdido tu capacidad de aburrirte.

Solucion: Pon mas pensamiento en tu tiempo libre.

Planea tu tarde y fin de semana antes de que lleguen. Dale a tu cerebro algo de calidad para hacer.

REGLA 4: DRENA LO SUPERFICIAL

La mayor parte del trabajo de conocimiento moderno es trabajo superficial disfrazado de profundo.

PROGRAMA CADA MINUTO DE TU DIA

Al comienzo del dia laboral, divide tu dia en bloques y asigna actividades.

No sobre-programa. Deja espacio para flexibilidad.

El proposito no es seguir el horario perfectamente - es ser consciente de como usas tu tiempo.

CUANTIFICA LA PROFUNDIDAD DE CADA ACTIVIDAD

Pregunta: Cuantos meses tomaria entrenar a un graduado universitario inteligente sin entrenamiento especializado para completar esta tarea?

Si la respuesta es "no mucho tiempo," la tarea es superficial.

PREGUNTA A TU JEFE POR UN PRESUPUESTO DE TRABAJO SUPERFICIAL

Confrontacion hipotetica: "Que porcentaje de mi tiempo deberia ser gastado en trabajo superficial?"

Esto fuerza una conversacion productiva sobre prioridades.

Para la mayoria de trabajadores de conocimiento no ejecutivos, 30-50% es razonable. Mas alla de eso y estas desperdiciando tu potencial.

TERMINA TU TRABAJO A LAS 5:30 PM

Productividad fija de horario: Establece un horario de trabajo firme, luego trabaja hacia atras para encontrar estrategias de productividad.

Esta restriccion fuerza cuidadosa priorización y eliminacion implacable de lo superficial.

