EL SHUTDOWN RITUAL

Al final del dia laboral:
1. Revisa tu lista de pendientes
2. Revisa tu calendario para los proximos dias
3. Haz un plan rapido para el dia siguiente
4. Di "shutdown completo" en voz alta

Esto cierra el loop abierto y permite a tu mente relajarse.

REGLA 2: ABRAZA EL ABURRIMIENTO

No puedes simplemente decidir trabajar profundamente - tu cerebro debe estar entrenado para concentracion intensa.

NO TOMES DESCANSOS DE DISTRACCION. TOMA DESCANSOS DE ENFOQUE.

Metodo tradicional (NO FUNCIONA): Trabajo enfocado con descansos ocasionales para distraccion.

Metodo correcto: Bloques programados para distraccion, con trabajo enfocado como default.

Ejemplo:
- 9:00 AM: Puede usar internet
- 9:30 AM: No internet hasta 11:00 AM
- 11:00 AM: Puede usar internet
- 11:20 AM: No internet hasta 2:00 PM

Entrena tu cerebro para resistir distracciones.

TRABAJA COMO TEDDY ROOSEVELT

Roosevelt en Harvard: Dejaba estudiar hasta 8:30 PM cada noche para actividades sociales y atleticas. Pero durante el tiempo de estudio, trabajaba con intensidad feroz.

Tecnica: Estimar cuanto tiempo una tarea deberia tomar, luego darte un deadline mucho mas ajustado. Trabaja con gran intensidad para cumplirlo.

Esto entrena tu capacidad de concentracion.

