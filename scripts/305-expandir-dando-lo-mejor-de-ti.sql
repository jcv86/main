2. VISUALIZA VIVIDAMENTE
Ve, escucha, siente como si ya lo lograste.

3. LEE SOBRE PERSONAS QUE LO LOGRARON
Inspiracion alimenta deseo.

4. DECLARA PUBLICAMENTE
Compromiso publico fortalece compromiso personal.

5. ACTUA INMEDIATAMENTE
Accion genera mas deseo. Deseo genera mas accion.

