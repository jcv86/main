Por Zig Ziglar

INTRODUCCION: PUEDES TENERLO TODO

Zig Ziglar filosofia central: Puedes tener todo en vida que quieras si ayudas suficiente otras personas conseguir lo que quieren.

Este no es libro de trucos rapidos o atajos. Es sobre construir exito duradero basado en caracter, integridad, y servicio a otros.

PARTE 1: PASOS HACIA CIMA

CAPITULO 1: TU IMAGEN DE TI MISMO

Tu imagen de ti mismo - como te ves a ti mismo - determina rendimiento en todas areas.

TRES COMPONENTES DE IMAGEN PERSONAL

1. COMO TE VES A TI MISMO
Tu evaluacion interna de tus capacidades.

2. COMO OTROS TE VEN
Percepcion externa basada en tu comportamiento.

3. COMO QUISIERAS QUE OTROS TE VIERAN
Tu aspiracion de como quieres ser percibido.

Brecha entre estos tres crea tension. Trabajo es alinearlos.

MEJORANDO TU IMAGEN PERSONAL

1. CAMBIA TU CONVERSACION INTERNA
Deja de decir no puedo.
Empieza decir estoy aprendiendo a.

2. CELEBRA PEQUENAS VICTORIAS
Exito construye sobre exito.

3. ASOCIATE CON GENTE POSITIVA
Te conviertes en promedio de 5 personas con quien pasas mas tiempo.

4. LEE Y ESTUDIA
Alimenta tu mente con input positivo y educativo.

5. ESTABLECE METAS
Personas con metas tienen direccion. Sin metas, vagas.

CAPITULO 2: TU RELACION CON OTROS

Nadie tiene exito solo. Todos necesitamos ayuda de otros.

PRINCIPIOS DE RELACIONES EFECTIVAS

1. INTERES GENUINO
Dale Carnegie: Puedes hacer mas amigos en dos meses interesandote en otros que en dos anos tratando de interesarlos en ti.

2. ESCUCHA ACTIVAMENTE
Mayoria de personas esperan su turno para hablar. Verdaderamente escucha.

3. RECUERDA NOMBRES
Nombre de persona es sonido mas dulce en cualquier idioma para esa persona.

4. HAZ PREGUNTAS
Muestra curiosidad genuina sobre vida de otros.

5. BUSCA DAR, NO RECIBIR
Que puedo hacer por ti? es pregunta mas poderosa que que puedes hacer por mi?

CONSTRUYENDO RELACIONES DURADERAS

1. SE CONFIABLE
Haz lo que dices. Siempre.

2. SE HONESTO
Verdad corto plazo es mejor que engano largo plazo.

3. SE CONSISTENTE
Personas necesitan saber que esperar de ti.

4. MUESTRA APRECIO
Agradece verbalmente y especificamente.

5. PERDONA RAPIDAMENTE
Guardar rencor te lastima mas a ti que a ellos.

CAPITULO 3: TUS METAS

Metas son suenos con fecha limite.

POR QUE NECESITAS METAS

Sin metas:
- Vagas sin direccion
- Te distraes facilmente
- No mides progreso
- Vives reactivamente

Con metas:
- Tienes claridad de proposito
- Enfocas energia
- Mides avance
- Vives proactivamente

TIPOS DE METAS

1. METAS CORTO PLAZO (0-3 meses)
Pasos inmediatos hacia vision mayor.

2. METAS MEDIANO PLAZO (3-12 meses)
Hitos significativos en camino.

3. METAS LARGO PLAZO (1-5+ anos)
Vision grande de quien quieres ser.

ESTABLECIENDO METAS EFECTIVAS

Sistema SMART:

S - Especifica
No quiero estar saludable
Si quiero perder 20 libras

M - Medible
Cuantifica para poder rastrear.

A - Alcanzable
Desafiante pero posible.

R - Relevante
Alinea con valores y prioridades.

T - Con tiempo definido
Fecha limite especifica.

ESCRIBIENDO METAS

1. Escribe en presente
No voy a, sino estoy logrando

2. Hazlas positivas
No dejaré de fumar
Si vivire estilo de vida saludable sin tabaco

3. Incluye por que
Meta sin razon es deseo sin poder.

4. Visualiza logro
Ve, siente, experimenta mentalmente exito.

CAPITULO 4: TU ACTITUD

Actitud determina altitud. Como piensas determina cuan alto vuelas.

ACTITUD ES ELECCION

No controlas todas circunstancias.
Pero siempre controlas tu respuesta.

Entre estimulo y respuesta hay espacio.
En ese espacio esta tu poder de elegir.

COMPONENTES DE ACTITUD POSITIVA

1. GRATITUD
Enfocate en lo que tienes, no en lo que falta.

2. OPTIMISMO
Ve posibilidades, no solo problemas.

3. RESPONSABILIDAD
Tomas cargo de tu vida, no culpas a otros.

4. PERSEVERANCIA
No te rindes ante primeros obstaculos.

5. CRECIMIENTO
Ves desafios como oportunidades para aprender.

CAMBIANDO TU ACTITUD

1. MONITOREA TU DIALOGO INTERNO
Nota cuando pensamientos son negativos.

2. DESAFIA PENSAMIENTOS NEGATIVOS
Es esto realmente cierto? Hay otra forma de verlo?

3. PRACTICA GRATITUD DIARIAMENTE
Escribe 3 cosas por las que estas agradecido.

4. RODÉATE DE POSITIVIDAD
Personas, libros, musica, contenido positivo.

5. ACTUA COMO SI
Incluso si no sientes, actua con actitud que quieres tener.

