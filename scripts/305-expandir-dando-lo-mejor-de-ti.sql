CAPITULO 6: TU DESEO

Deseo intenso es combustible que impulsa logro.

Sin deseo fuerte, renuncias ante primera dificultad.
Con deseo ardiente, superas cualquier obstaculo.

DIFERENCIA ENTRE DESEO Y FANTASIA

Fantasia: Me gustaria ser rico
Deseo: Estoy comprometido a construir riqueza y dispuesto a hacer lo necesario

Fantasia es pasiva. Deseo es activo.

INTENSIFICANDO DESEO

1. CONECTA CON TU POR QUE
