CAPITULO 9: CARACTER

Caracter es quien eres cuando nadie mira.
Reputacion es quien otros piensan que eres.

Enfocate en caracter. Reputacion seguira.

ELEMENTOS DE CARACTER FUERTE

1. RESPONSABILIDAD
Tomas cargo de tus acciones y resultados.

2. DISCIPLINA
Haces lo que debe hacerse, no solo lo que quieres.

3. VALOR
Haces lo correcto a pesar de miedo.

4. COMPASION
Importas genuinamente sobre bienestar de otros.

5. HUMILDAD
Reconoces que no lo sabes todo y estas dispuesto a aprender.

CONSTRUYENDO CARACTER

Caracter no se construye en crisis. Se revela.
Construyes caracter en decisiones diarias pequenas.

Cada vez que:
- Cumples promesa cuando es inconveniente
- Dices verdad cuando mentira seria mas facil
- Ayudas alguien sin beneficio personal
- Te disciplinas cuando nadie mira

Construyes caracter.

CAPITULO 10: FE Y ESPERANZA

Fe es creer que puedes lograr algo antes de ver evidencia.
Esperanza es mantener esa creencia incluso ante contratiempos.

FE EN TI MISMO

No arrogancia - eso es falsa confianza.
Es creencia solida que con esfuerzo y aprendizaje, puedes mejorar.

FE EN OTROS

Ve potencial en personas, no solo estado actual.
Tu fe en ellos puede ayudarlos ver potencial en si mismos.

FE EN PROCESO

Exito no es accidente. Es resultado de seguir principios correctos consistentemente.

ESPERANZA COMO COMBUSTIBLE

Cuando situaciones son dificiles, esperanza te sostiene.

Esperanza no es pensar positivo ignorando realidad.
Es creer que a pesar de realidad actual, futuro puede ser mejor.

CULTIVANDO FE Y ESPERANZA

