## Capítulo 10: Bonos y la Cartera Balanceada

### Rol de Bonos en Cartera

**Función 1: Estabilidad de Capital**
- Menor volatilidad que acciones
- Preservación de principal en mercados bajistas de acciones
- Ancla psicológica en pandemias

**Función 2: Ingreso Predecible**
- Cupones fijos proveen flujo de caja regular
- Independiente de fluctuaciones de mercado
- Útil para retiro o reinversión

**Función 3: Balanceo de Riesgo**
- Correlación históricamente baja o negativa con acciones
- Protección de cartera en crisis de acciones
- Permite rebalanceo estratégico

### La Recomendación de Balanceo de Graham

**Principio Fundamental:**
Mantener mínimo 25 por ciento en bonos y mínimo 25 por ciento en acciones en todo momento.

**Rango Estándar:**
- **Conservador:** 75 por ciento bonos, 25 por ciento acciones
- **Moderado:** 50 por ciento bonos, 50 por ciento acciones
- **Agresivo:** 25 por ciento bonos, 75 por ciento acciones

**Ajuste por Valoración:**
Cuando acciones parecen muy caras, mover hacia bonos. Cuando acciones parecen baratas, mover hacia acciones. Pero nunca exceder 75/25 en ninguna dirección.

### Tipos de Bonos para Inversor Defensivo

**Bonos del Gobierno de EE.UU.:**
- Más seguros disponibles
- Rendimientos más bajos
- Liquidez alta
- Apropiados para porción core de cartera de bonos

**Bonos Corporativos Grado Inversión:**
- Rendimientos moderadamente más altos que gobierno
- Riesgo moderado de default (históricamente bajo para grado inversión)
- Diversificar entre muchos emisores

**Bonos Municipales (Exentos de Impuestos):**
- Apropiados para inversores en brackets altos de impuestos
- Comparar rendimiento después de impuestos vs. bonos gravables
- Preferir general obligation sobre revenue bonds

**QUÉ EVITAR:**
- Bonos basura (alto riesgo de default)
- Bonos de mercados emergentes sin expertise
- Instrumentos estructurados complejos que no entiendes
- Bonos individuales de empresa en problemas

