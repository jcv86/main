## Capítulo 7: Análisis de Ganancias - Separando Realidad de Ficción

### Calidad de Ganancias - Ajustes Necesarios

**Ajuste 1: Items No Recurrentes**
- Ganancias o pérdidas extraordinarias
- Ventas de activos a precios excepcionales
- Acuerdos legales one-time
- **Acción:** Eliminar completamente para ver poder de ganancia normal

**Ajuste 2: Capitalización vs. Gasto de Costos**
- R&D: ¿Capitalizado o gastado?
- Marketing y desarrollo de marca
- Exploración (petróleo, minería)
- **Acción:** Ajustar para consistencia entre empresas comparables

**Ajuste 3: Dilución por Stock Options**
- Options otorgadas a management y empleados
- Diluyen ganancias por acción futuras
- A menudo ignoradas en reportes
- **Acción:** Ajustar EPS por dilución completa asumiendo ejercicio

**Ajuste 4: Activos y Pasivos de Pensiones**
- Asunciones sobre returns futuros
- Sobrepensiones o subpensiones
- Impacto en costo anual
- **Acción:** Ajustar por realidad actuarial conservadora

**Ajuste 5: Calidad de Ganancias Operativas**
- ¿Ganancias vienen de operaciones core?
- ¿O de actividades financieras, inversiones, one-timers?
- **Preferencia:** Ganancias de operaciones recurrentes

### El Enfoque Conservador de Graham

**Principio Fundamental:**
Usar ganancias promedio de 7 a 10 años, no solo las del último año.

**Razones:**
- Elimina anomalías de un solo año
- Refleja poder de ganancia sostenible a través de ciclos
- Conservador en naturaleza
- Protege contra pagar demasiado por año excepcionalmente bueno

**Cálculo:**
Tomar ganancias totales de últimos 7 años, dividir entre 7, ajustar por inflación y cambios en capitalización.

### Ratio Precio-Ganancias (P/E) - Interpretación

**Rangos de P/E:**
- **P/E menor a 10:** Potencialmente infravalorado, investigar por qué
- **P/E 10 a 15:** Rango normal para empresa madura estable
- **P/E 15 a 25:** Premium moderado, debe justificarse con crecimiento
- **P/E mayor a 25:** Alto, requiere crecimiento excepcional sostenido

**La Advertencia Crucial de Graham:**
Nunca pagues más de 20 veces las ganancias promedio de últimos 3 años, o 25 veces las ganancias del último año.

**Razón:**
P/E alto incorpora expectativas muy optimistas. Riesgo de desilusión es extremo.

