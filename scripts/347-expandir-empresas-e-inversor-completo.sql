## Capítulo 5: La Estrategia del Inversor Emprendedor

### Operaciones que Debe EVITAR

**Operación Negativa 1: Trading Basado en Predicciones de Mercado**
- Intentar predecir dirección general del mercado a corto o mediano plazo
- **Por qué falla:** Nadie puede predecir consistentemente
- **Evidencia:** Profesionales fallan regularmente

**Operación Negativa 2: Trading de Corto Plazo**
- Comprar con intención de vender en semanas o meses basado en movimientos de precio
- **Por qué falla:** Costos de transacción y impuestos consumen ganancias
- **Realidad:** Enriquece a brokers, no a inversores

**Operación Negativa 3: Comprar IPOs de Empresas de Moda**
- Empresas nuevas sin historial probado
- **Por qué falla:** Casi siempre sobrepreciadas por entusiasmo
- **Historia:** Repetidamente termina en desilusión (dot-com, etc.)

### Operaciones Positivas que Pueden Funcionar

**Operación Positiva 1: Valores Altamente Subvalorados**

**Características:**
- Precio significativamente por debajo de valor intrínseco calculado
- Margin of safety de 40 a 50 por ciento
- Situación financiera sólida (no en peligro de bancarrota)
- Ganancias estables o historial de recuperación

**Fuentes de Subvaluación:**
- Pesimismo temporal injustificado
- Desatención del mercado (empresa pequeña o aburrida)
- Situaciones complejas que requieren análisis profundo
- Industria temporalmente fuera de favor

**Ejemplo Clásico:**
Empresa con 30 dólares en efectivo por acción, sin deuda, ganancias históricas de 3 dólares por acción, negociando a 20 dólares por acción.

**Operación Positiva 2: Situaciones Especiales**

**Tipos:**
- Arbitraje de fusiones anunciadas
- Liquidaciones de empresas
- Reorganizaciones de bancarrota
- Spin-offs ignorados

**Requisitos:**
- Análisis cuidadoso de situación específica
- Entendimiento de procesos legales y corporativos
- Paciencia para esperar resolución
- Diversificación entre múltiples situaciones

**Operación Positiva 3: Empresas Bargain (Ganga)**

**Definición:**
Empresas con fundamentos sólidos, temporalmente fuera de favor, negociando a múltiplos muy bajos.

**Criterios:**
- P/E menor a 10 veces ganancias normales
- P/B menor a 1.0 veces
- Yield de dividendo mayor a bonos de calidad
- Situación financiera fuerte

**Catalista:**
Típicamente, reversión a la media cuando el mercado reconoce valor.

