## Capítulo 9: Dollar-Cost Averaging - La Disciplina Automática

### El Concepto

Invertir una cantidad fija de dinero a intervalos regulares (mensual, trimestral), completamente independiente del nivel de precios del mercado.

**Ejemplo Clásico:**
500 dólares cada mes en un fondo indexado S&P 500, sin importar si el mercado está en máximos o mínimos.

### Los Cuatro Beneficios Poderosos

**Beneficio 1: Elimina la Decisión de Timing**
- No necesitas predecir tops o bottoms del mercado
- Nadie puede hacerlo consistentemente de todos modos
- Automático elimina parálisis de análisis

**Beneficio 2: Compras Más Acciones Cuando Precios Son Bajos**
- Con cantidad fija de dólares, compras más acciones cuando precio es bajo
- Compras menos acciones cuando precio es alto
- Matemática automática trabaja a tu favor

**Beneficio 3: Tu Costo Promedio Tiende a Ser Favorable**
- A lo largo de décadas, tiendes a comprar a precio promedio por debajo de media de mercado
- Especialmente cierto en mercados volátiles
- Tiempo y volatilidad son tus amigos

**Beneficio 4: Disciplina Automática de Ahorro**
- Fuerza ahorro regular independiente de emociones
- Construye cartera sistemáticamente
- Elimina tentación de gastar en lugar de invertir

### Implementación Práctica

**Para Inversor Defensivo:**
- Configurar transferencia automática mensual de cuenta de banco
- 500 a 1,000 dólares por mes (según capacidad)
- 60 por ciento a fondo indexado total de acciones
- 40 por ciento a fondo indexado de bonos
- Nunca detener, incluso en crashes de mercado (especialmente entonces)

