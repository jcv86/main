## Capítulo 12: Inflación - El Enemigo Silencioso

### La Realidad Histórica de la Inflación

**Promedio Histórico de EE.UU.:**
Aproximadamente 3 por ciento anual durante el siglo 20.

**Impacto en Poder Adquisitivo:**
- 3 por ciento anual duplica precios cada 24 años
- En 50 años, precios se multiplican por 4.4 veces
- Tu dinero compra 77 por ciento menos después de 50 años

**Implicación para Inversores:**
Necesitas rendimiento solo para mantener poder adquisitivo, antes de ganar realmente.

### Acciones como Protección Contra Inflación

**La Tesis:**
Empresas pueden traspasar aumentos de costos a clientes vía precios más altos, protegiendo así valor real de sus ganancias.

**La Realidad Más Compleja:**
Esto solo funciona para empresas con características específicas.

**Características de Empresas que Protegen Contra Inflación:**

**1. Pricing Power:**
- Capacidad de subir precios sin perder clientes
- Marca fuerte o productos diferenciados
- Poca competencia o switching costs altos

**2. Baja Intensidad de Capital:**
- No requieren reinversión constante grande
- Free cash flow alto relativo a ganancias
- Returns on capital superiores a costo de capital

**3. Turnover de Inventario Rápido:**
- Venden inventario antes de que suba su costo de reposición
- No quedan atrapados con inventario costoso

**Ejemplos de Buena Protección:**
- Marcas de consumo fuertes (Coca-Cola, etc.)
- Plataformas tecnológicas con network effects
- Negocios de servicios con contratos recurrentes

**Ejemplos de Mala Protección:**
- Commodities intensivos en capital
- Retailers con márgenes bajos
- Negocios cíclicos con competencia intensa

### Estrategia Anti-Inflación para Inversor Defensivo

**Cartera Sugerida:**
- 50 a 70 por ciento en acciones de calidad (protección largo plazo)
- 30 a 50 por ciento en bonos (estabilidad corto plazo)
- Incluir TIPS (Treasury Inflation-Protected Securities)
- Rebalancear anualmente

**TIPS (Bonos Protegidos Contra Inflación):**
- Principal ajusta automáticamente por inflación
- Interés se paga sobre principal ajustado
- Protección directa contra inflación
- 10 a 20 por ciento de porción de bonos puede estar en TIPS

