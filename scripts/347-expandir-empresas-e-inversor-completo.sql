## Capítulo 6: Análisis de Balance - Qué Realmente Importa

### Evaluación de Activos

**Activos de Calidad Alta:**
- **Cash y equivalentes:** Valor completo, 100 por ciento
- **Valores negociables:** Valor de mercado actual
- **Cuentas por cobrar:** 90 a 95 por ciento de valor de libro (después de allowances)

**Activos de Calidad Media:**
- **Inventarios (FIFO):** 50 a 75 por ciento de valor de libro
- **Inventarios (LIFO):** Puede estar muy subvalorado, ajustar
- **Propiedad, planta y equipo:** Depende de industria, depreciación, utilidad

**Activos de Calidad Dudosa:**
- **Goodwill:** Generalmente ignorar o descontar severamente
- **Intangibles (patentes, marcas):** Conservadoramente, ignorar
- **Inversiones en subsidiarias no consolidadas:** Requiere análisis especial

### Evaluación de Pasivos

**Pasivos Corrientes:**
- Deben ser cubiertos cómodamente por activos corrientes
- Current ratio de 2.0 es standard mínimo
- Menor que 1.5 es señal de alarma

**Deuda a Largo Plazo:**
- Debe ser modesta en relación al capital total
- Para industrial: No más del 50 por ciento de equity
- Para utility: Puede ser más alto, hasta 100 por ciento de equity

**Obligaciones Fuera de Balance:**
- Pensiones no fondeadas
- Arrendamientos operativos
- Garantías y contingencias
- Ajustar para obtener cuadro verdadero

### Ratios Clave de Solidez Financiera

**Current Ratio:**
- Fórmula: Activos corrientes / Pasivos corrientes
- **Mínimo aceptable:** 2.0 para empresas industriales
- **Ideal:** 2.5 o más
- **Advertencia:** Menos de 1.5 indica posible dificultad

**Quick Ratio (Acid Test):**
- Fórmula: (Cash + Cuentas por Cobrar + Valores) / Pasivos Corrientes
- **Mínimo:** 1.0
- **Propósito:** Mide liquidez sin depender de inventarios

**Debt-to-Equity Ratio:**
- Fórmula: Deuda total / Equity total
- **Máximo para industrial:** 0.5 (deuda no más de 50 por ciento del equity)
- **Máximo para utility:** 1.0 (deuda igual al equity)
- **Ideal:** Menor a 0.3

**Interest Coverage:**
- Fórmula: EBIT / Gastos de interés anuales
- **Mínimo para industrial:** 5 veces
- **Mínimo para utility:** 3 veces
- **Ideal:** 7 veces o más

