## Capítulo 4: La Cartera del Inversor Defensivo

### Los 7 Criterios de Graham para Selección Defensiva

**Criterio 1: Tamaño Adecuado de la Empresa**
- Ventas anuales: No menos de 100 millones de dólares para industrial
- No menos de 50 millones para utility
- **Razón:** Empresas grandes tienen recursos y estabilidad para sobrevivir adversidades

**Ajuste Moderno (2024):** Multiplicar por 10 debido a inflación. Buscar empresas con ventas superiores a 1 billón de dólares.

**Criterio 2: Condición Financiera Suficientemente Fuerte**
- Current ratio mayor a 2.0
- Deuda a largo plazo no debe exceder working capital
- **Razón:** Protección contra dificultades financieras

**Criterio 3: Estabilidad de Ganancias**
- Ganancias positivas en cada uno de los últimos 10 años
- Sin años de pérdida
- **Razón:** Demuestra capacidad de superar ciclos económicos

**Criterio 4: Registro de Dividendos**
- Pagos de dividendos ininterrumpidos por al menos 20 años
- **Razón:** Indica management conservador y ganancias genuinas

**Criterio 5: Crecimiento de Ganancias**
- Incremento de al menos un tercio (33 por ciento) en ganancias por acción en últimos 10 años
- Usando promedios de 3 años al inicio y al final
- **Razón:** Protección contra inflación y deterioro competitivo

**Criterio 6: P/E Moderado**
- Precio actual no debe ser más de 15 veces ganancias promedio de últimos 3 años
- **Razón:** Protección contra pagar demasiado

**Criterio 7: P/B Moderado**
- Precio no debe ser más de 1.5 veces valor de libro
- **Regla alternativa:** P/E multiplicado por P/B no debe exceder 22.5
- (Ejemplo: P/E de 15 x P/B de 1.5 = 22.5)
- **Razón:** Combinación razonable de ganancias y activos

### Aplicación Práctica del Proceso de Screening

**Paso 1:** Comenzar con universo completo de acciones
**Paso 2:** Aplicar criterios 1, 2, y 3 (eliminatorios)
**Paso 3:** De las sobrevivientes, aplicar criterios 4, 5, 6, y 7 (preferibles)
**Paso 4:** Diversificar entre al menos 10, preferiblemente 20 a 30 de las finalistas

**Resultado Esperado:**
Cartera de empresas de calidad compradas a precios razonables, con alta probabilidad de resultados satisfactorios.

