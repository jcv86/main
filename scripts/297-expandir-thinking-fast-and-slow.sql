Por Daniel Kahneman

INTRODUCCIÓN

Este libro presenta una visión de cómo la mente funciona basada en descubrimientos recientes en psicología cognitiva y social. El enfoque de la historia es una conversación dramática entre dos personajes en tu mente.

Los dos sistemas que dirigen cómo pensamos:

SISTEMA 1: Opera automática y rápidamente, con poco o ningún esfuerzo y sin sentido de control voluntario.

SISTEMA 2: Asigna atención a las actividades mentales esforzadas que demandan, incluidos cálculos complejos. Las operaciones del Sistema 2 están a menudo asociadas con la experiencia subjetiva de agencia, elección y concentración.

PARTE I: DOS SISTEMAS

CAPÍTULO 1: LOS PERSONAJES DE LA HISTORIA

El Sistema 1 opera automáticamente y el Sistema 2 está normalmente en un modo confortable de esfuerzo bajo.

Ejemplos del Sistema 1:
- Detectar que un objeto está más lejos que otro
- Orientarse hacia la fuente de un sonido repentino
- Completar la frase "pan y..."
- Hacer una "cara de disgusto" al ver una imagen horrible
- Detectar hostilidad en una voz
- Responder a 2+2=?

Ejemplos del Sistema 2:
- Prepararte para el disparo de inicio en una carrera
- Enfocar atención en los payasos en un circo
- Monitorear la propiedad de tu comportamiento en una situación social
- Contar las ocurrencias de la letra "a" en una página de texto
- Dar a alguien tu número de teléfono
- Calcular 17 x 24

El Sistema 1 genera sugerencias para el Sistema 2: impresiones, intuiciones, intenciones y sentimientos. Cuando son respaldadas por el Sistema 2, las impresiones se convierten en creencias, y los impulsos se convierten en acciones voluntarias.

CAPÍTULO 2: ATENCIÓN Y ESFUERZO

El Sistema 2 tiene cierta capacidad para cambiar la manera en que el Sistema 1 funciona, programando las funciones automáticas de atención y memoria.

Experimento: Cuenta cuántas veces los jugadores vestidos de blanco pasan el baloncesto. La mayoría de los observadores no ven el gorila caminando a través de la escena. Esto es ceguera de falta de atención.

Cuando estás enfocado en una tarea, te vuelves efectivamente ciego a estímulos que normalmente atraerían atención.

La ley del menor esfuerzo: Si hay varias maneras de alcanzar el mismo objetivo, las personas eventualmente gravitarán hacia el curso de acción menos exigente.

CAPÍTULO 3: EL CONTROLADOR PEREZOSO

El Sistema 2 es perezoso, y el Sistema 1 es rápido para saltar a conclusiones.

Problema del murciélago y la pelota:
Un murciélago y una pelota cuestan $1.10 en total.
El murciélago cuesta $1.00 más que la pelota.
¿Cuánto cuesta la pelota?

La respuesta intuitiva: 10 centavos (INCORRECTO)
La respuesta correcta: 5 centavos

Más del 50% de estudiantes en Harvard, MIT y Princeton dieron la respuesta intuitiva incorrecta.

Las personas que son más vigilantes y mentalmente activas son significativamente menos propensas a caer en estas trampas.

CAPÍTULO 4: LA MÁQUINA ASOCIATIVA

El Sistema 1 es una máquina de asociaciones. Cuando piensas en una palabra, muchas otras se activan.

Priming: Las palabras evocan ideas, que evocan otras ideas, en una cascada de actividad mental.

Experimento: Las personas caminaron más lentamente después de leer palabras relacionadas con la edad avanzada.

El efecto Florida: Estudiantes expuestos a palabras relacionadas con la edad avanzada (gris, arruga, calvo) caminaron más lentamente por el pasillo después.

Priming ideomotor: Ideas pueden evocar acciones, y acciones pueden evocar ideas.

Experimento: Las personas que fueron preparadas para sonreír encontraron caricaturas más divertidas.

CAPÍTULO 5: FACILIDAD COGNITIVA

Cuando estás en un estado de facilidad cognitiva, probablemente estás de buen humor, te gustan lo que ves, crees lo que escuchas, confías en tus intuiciones, y sientes que la situación actual es cómoda y familiar.

Experiencias repetidas, presentación clara, idea preparada, buen humor - todos crean facilidad cognitiva.

Cuando experimentas tensión cognitiva, es más probable que estés vigilante, desconfiado, inviertas más esfuerzo, te sientas menos cómodo, cometas menos errores.

Efecto de mera exposición: Las personas desarrollan una preferencia por cosas meramente porque están familiarizadas con ellas.

CAPÍTULO 6: NORMAS, SORPRESAS Y CAUSAS

El Sistema 1 mantiene y actualiza un modelo de tu mundo personal. El modelo está compuesto de asociaciones vinculadas por noción de causalidad.

Cuando algo viola el modelo (es sorprendente), el Sistema 1 activa el Sistema 2 para buscar una explicación causal.

Ilusiones de causalidad: El Sistema 1 es excelente en construir la mejor historia posible que incorpora las ideas actualmente activadas, pero no (no puede) permitir información que no tiene.

CAPÍTULO 7: UNA MÁQUINA PARA SALTAR A CONCLUSIONES

WYSIATI: What You See Is All There Is (Lo que ves es todo lo que hay)

El Sistema 1 es radialmente insensible tanto a la calidad como a la cantidad de la información que da lugar a impresiones y juicios.

Sesgo de confirmación: Buscamos información que confirma nuestras creencias y descontamos información que las contradice.

Efecto halo: Si te gusta (o no te gusta) todo sobre una persona, incluidas cosas que no has observado.

PARTE II: HEURÍSTICAS Y SESGOS

CAPÍTULO 8: CÓMO SE FORMAN LOS JUICIOS

Sustitución: Cuando enfrentamos una pregunta difícil, a menudo respondemos una más fácil en su lugar, usualmente sin notar la sustitución.

Pregunta objetivo: "¿Qué tan feliz estás con tu vida en estos días?"
Pregunta heurística: "¿Cuál es mi estado de ánimo ahora mismo?"

3D heurística: Si la pregunta es cuánto donarías para salvar delfines en peligro, tu cerebro podría sustituir: ¿Cuánta emoción siento cuando pienso en delfines moribundos?

CAPÍTULO 9: RESPONDIENDO UNA PREGUNTA MÁS FÁCIL

Las personas sustituyen una pregunta más fácil sin darse cuenta de que están haciendo esto.

Ejemplo: "¿Qué tan popular será el presidente en seis meses?"
Se convierte en: "¿Qué tan popular es ahora?"

Cascada afectiva: Una cadena auto-sustentable de reacciones emocionales. Una historia desencadena emoción, que desencadena cobertura de medios, que desencadena más emoción.

CAPÍTULO 10: LA LEY DE NÚMEROS PEQUEÑOS

Ley de números grandes: Muestras grandes son más precisas que pequeñas.

Las personas, incluyendo investigadores estadísticos, son insensibles al tamaño de muestra.

Los hospitales pequeños tienen tanto más días con >60% de nacimientos masculinos como más días con <40% de nacimientos masculinos que hospitales grandes - simplemente porque las muestras pequeñas varían más.

CAPÍTULO 11: ANCLAS

Efecto de anclaje: Cuando consideras un valor para una cantidad desconocida, ocurre un sesgo: tus estimaciones permanecen cercanas al número que consideraste.

Experimento: La rueda de fortuna se detiene en 10 o 65. Pregunta: "¿Cuál es el porcentaje de naciones africanas en la ONU?"
Aquellos que vieron 10 estimaron 25%. Aquellos que vieron 65 estimaron 45%.

Las anclas funcionan incluso cuando son obviamente aleatorias.

En negociaciones, quien hace la primera oferta establece el ancla.

CAPÍTULO 12: LA CIENCIA DE DISPONIBILIDAD

Heurística de disponibilidad: Juzgas la frecuencia o probabilidad por la facilidad con la que los ejemplos vienen a la mente.

¿Hay más palabras que comienzan con "r" o tienen "r" como tercera letra? La mayoría dice que comienzan con "r", pero en realidad hay tres veces más con "r" como tercera letra.

Las palabras que comienzan con "r" son más fáciles de recordar (más disponibles).

Cascada de disponibilidad: Proceso auto-sustentable donde lo frecuentemente mencionado se vuelve disponible, y lo disponible se vuelve frecuentemente mencionado.

CAPÍTULO 13: DISPONIBILIDAD, EMOCIÓN Y RIESGO

Las personas tienden a evaluar el riesgo de una tecnología considerando cuán malo se sentirían si ocurriera.

Las víctimas identificables: Las personas responderán más vigorosamente a una sola víctima identificada que a una vasta calamidad.

"Un solo muerte es una tragedia; un millón de muertes es una estadística." - Joseph Stalin

CAPÍTULO 14: ESPECIALIDAD DE TOM W

Linda tiene 31 años, soltera, franca y muy brillante. Se especializó en filosofía. Como estudiante, estaba profundamente preocupada por asuntos de discriminación y justicia social.

¿Qué es más probable?
A) Linda es cajera de banco
B) Linda es cajera de banco y activa en el movimiento feminista

Más del 85% elige B. Pero esto viola la lógica: B no puede ser más probable que A porque B es un subconjunto de A.

Falacia de conjunción: Juzgar un evento de conjunción (A y B) como más probable que uno de sus constituyentes (A).

Representatividad: Juzgamos probabilidad por cuán bien coincide algo con nuestros estereotipos.

CAPÍTULO 15: LINDA: MENOS ES MÁS

Las personas asignan más probabilidad a eventos que son más representativos, no más probables.

Las descripciones vívidas tienen peso desproporcionado en juicios de probabilidad.

CAPÍTULO 16: CAUSAS TRUMPAN ESTADÍSTICAS

Las personas no prestan adecuadamente atención a información estadística de tasas base cuando se les proporciona información causal o individual.

Ejemplo: El 85% de los taxis son verdes, 15% son azules. Un testigo dice que el taxi en un accidente era azul. El testigo tiene un 80% de precisión.

¿Cuál es la probabilidad de que el taxi fuera realmente azul? La mayoría dice 80%. La respuesta correcta es 41%.

Las personas ignoran la tasa base (85% verdes) y se enfocan en la evidencia causal específica (el testimonio del testigo).

CAPÍTULO 17: REGRESIÓN A LA MEDIA

Los eventos extremos tienden a ser seguidos por eventos más modestos.

Si anotas excepcional en un primer examen, probablemente te irá menos bien (pero aún bien) en un segundo examen.

No es porque fuiste elogiado o castigado - es regresión estadística.

Los instructores de vuelo pensaban que el elogio dañaba el rendimiento y la crítica lo mejoraba - en realidad, solo estaban viendo regresión a la media.

CAPÍTULO 18: DOMESTICANDO PREDICCIONES INTUITIVAS

Correlación y regresión están estrechamente relacionados. Alta correlación (como altura del padre y altura del hijo) significa menos regresión a la media.

Para hacer mejores predicciones:
1. Comienza con una estimación de tasa base
2. Determina la correlación
3. Ajusta tu estimación de la tasa base en la dirección de tu impresión

PARTE III: EXCESO DE CONFIANZA

CAPÍTULO 19: LA ILUSIÓN DE ENTENDER

Falacia narrativa: Construimos historias coherentes del pasado que nos hacen creer que el mundo es más predecible de lo que realmente es.

Sesgo retrospectivo: La tendencia a creer, después de que un evento ha ocurrido, que uno lo habría predicho.

Una vez que adoptas una nueva visión del mundo, pierdes gran parte de tu capacidad de recordar lo que solías creer antes de que cambiara tu mente.

CAPÍTULO 20: LA ILUSIÓN DE VALIDEZ

Las personas tienen confianza injustificada en sus juicios intuitivos.

Los expertos de bolsa no son mejores que lanzar dardos para elegir acciones, pero tienen tremenda confianza en sus habilidades.

Ilusión de habilidad: Cuando los resultados son esencialmente aleatorios, confundes suerte con habilidad.

CAPÍTULO 21: INTUICIONES DE EXPERTOS: CUÁNDO PODEMOS CONFIAR EN ELLAS

Las intuiciones genuinas desarrollan a través de práctica prolongada.

Dos condiciones para adquirir habilidad:
1. Un entorno suficientemente regular para ser predecible
2. Una oportunidad de aprender esas regularidades a través de práctica prolongada

Ajedrez y bomberos: Entornos predecibles donde la pericia es real.
Predicción de stock: Entorno altamente irregular donde la pericia es ilusión.

CAPÍTULO 22: INTUICIONES VERSUS FÓRMULAS

Las fórmulas simples superan rutinariamente el juicio de expertos.

Ejemplo: El puntaje Apgar (simplifica evaluación neonatal) superó las evaluaciones de enfermeras.

Los algoritmos simples superan a expertos porque:
1. Los expertos intentan ser inteligentes, buscando patrones complejos
2. Muchos factores tienen efectos pequeños e independientes
3. Los algoritmos combinan consistentemente información; los expertos son inconsistentes

CAPÍTULO 23: LA VISTA DESDE AFUERA

Vista desde adentro: Hacer predicciones basadas en tu comprensión de los detalles de un caso.

Vista desde afuera: Ignorar los detalles del caso y preguntarse cuánto tiempo proyectos similares generalmente toman.

La planificación fallacy: Planes y pronósticos que son irracionalmente cercanos a mejores escenarios de caso.

Mortem previa: Antes de comenzar un proyecto, imagina que ha fallado completamente. Escribir una breve historia de ese desastre.

CAPÍTULO 24: EL MOTOR DEL CAPITALISMO

Optimismo enterprise: Los emprendedores tienden a ser más optimistas que realistas.

¿Por qué las personas comienzan negocios a pesar de bajas probabilidades de éxito?
- Ilusión de control
- Sesgo de optimismo
- Énfasis en habilidad, ignorando suerte

La competición negligente: Cuando la entrada a una profesión es desregulada, demasiadas personas entran.

El capitalismo necesita optimismo - un motor de la economía. Los pesimistas, sin importar cuán perspicaces, pierden oportunidades.

PARTE IV: ELECCIONES

CAPÍTULO 25: LOS ERRORES DE BERNOULLI

La teoría de utilidad esperada de Bernoulli dice que las personas toman decisiones basadas en valores esperados de resultados, ponderados por sus probabilidades.

Pero esto no explica el comportamiento real.

Riqueza versus cambios en riqueza: Las personas piensan en términos de ganancias y pérdidas, no en términos de riqueza total.

CAPÍTULO 26: TEORÍA DE PERSPECTIVA

Tres principios cognitivos en el corazón de la teoría de perspectiva:

1. EVALUACIÓN ES RELATIVA A UN PUNTO DE REFERENCIA NEUTRAL
Las personas piensan en términos de ganancias y pérdidas de un punto de referencia (generalmente el status quo).

2. PRINCIPIO DE SENSIBILIDAD DECRECIENTE
$100 importa mucho más cuando vas de $0 a $100 que cuando vas de $900 a $1000.

3. AVERSIÓN A PÉRDIDAS
Las pérdidas duelen más que las ganancias equivalentes se sienten bien. Aproximadamente, perder $100 se siente aproximadamente tan malo como ganar $200 se siente bien.

CAPÍTULO 27: EL EFECTO DOTACIÓN

Las personas demandan mucho más para renunciar a un objeto que lo pagarían para adquirirlo.

Experimento: La mitad de los sujetos reciben una taza, la otra mitad nada. Precio de venta promedio (dueños): $7. Precio de compra promedio (no dueños): $3.

Esto viola teoría económica que sugiere que estos precios deberían ser aproximadamente iguales.

Causa: Aversión a pérdida. Los vendedores experimentan vender la taza como una pérdida; los compradores experimentan comprar como una ganancia. Las pérdidas pesan aproximadamente dos veces más que las ganancias.

CAPÍTULO 28: EVENTOS MALOS

La asimetría entre pérdidas y ganancias es evolutivamente sensata. Los organismos que tratan las amenazas como más urgentes que las oportunidades tenían mejores posibilidades de sobrevivir.

Las personas responden más vigorosamente a pérdidas que a ganancias. Este es el fundamento de la aversión al riesgo.

Para superar la aversión a pérdidas:
- Ampliar marcos (evaluar series de eventos, no eventos únicos)
- Establecer políticas que bloqueen aversión a pérdidas miope

CAPÍTULO 29: EL PATRÓN DE CUATRO VECES

Resultados ciertos son sobreponderados en relación con resultados meramente probables.

PROBABILIDADES ALTAS - EFECTO DE CERTEZA:
- 95% de ganar $10,000 → Personas aceptan $9,000 seguro (aversión al riesgo)
- 95% de perder $10,000 → Personas rechazan perder $9,000 seguro (búsqueda de riesgo)

PROBABILIDADES BAJAS - EFECTO DE POSIBILIDAD:
- 5% de ganar $10,000 → Personas pagan mucho por ticket de lotería (búsqueda de riesgo)
- 5% de perder $10,000 → Personas pagan mucho por seguro (aversión al riesgo)

CAPÍTULO 30: EVENTOS RAROS

Sobreponderamos eventos raros en nuestras decisiones.

Cuando raramente tiene probabilidad exacta, las personas sobreponderan. Cuando raro es vívido o emocional, las personas sobreponderan aún más.

Esto explica:
- Miedo desproporcionado al terrorismo
- Popularidad de loteías
- Demanda de seguro contra riesgos improbables

CAPÍTULO 31: POLÍTICAS DE RIESGO

Decisiones amplias, estrechas y raras:

Estrecha encuadre: Trata cada decisión en aislamiento
Amplia encuadre: Considera portfolio completo de decisiones

Personas exitosas piensan en términos amplios. Aceptan pequeños riesgos porque el portfolio completo los beneficiará.

CAPÍTULO 32: MANTENIMIENTO DE CUENTAS

Las personas mantienen cuentas mentales - categorizando gastos y ingresos en categorías específicas.

Esto lleva a comportamiento ilógico:
- Personas que no usarían una tarjeta de crédito con alta tasa de interés pero mantienen ahorros con baja tasa
- Personas que tratan "dinero de bonificación" diferente de salario regular

CAPÍTULO 33: REVERSIONES

Preferencias no son estables - dependen de cómo se formula la pregunta.

Evaluación conjunta versus evaluación separada:
- Separada: Evalúas cada opción en aislamiento
- Conjunta: Evalúas opciones lado a lado

Las preferencias a menudo se revierten entre estos contextos.

CAPÍTULO 34: MARCOS Y REALIDAD

La formulación de un problema a menudo controla la respuesta final.

Problema de la enfermedad asiática:
Formulación 1: "Salvar 200 vidas" versus "1/3 probabilidad de salvar 600"
Formulación 2: "400 personas morirán" versus "1/3 probabilidad de que nadie morirá"

La mayoría es aversa al riesgo en formulación 1, busca riesgo en formulación 2 - a pesar de que los resultados son idénticos.

PARTE V: DOS YOES

CAPÍTULO 35: DOS YOES

El yo que experimenta: Vive en el presente
El yo que recuerda: Mantiene el registro y toma decisiones

Estos dos yoes tienen intereses diferentes.

CAPÍTULO 36: LA VIDA COMO HISTORIA

Regla del pico-final: Evaluamos experiencias pasadas por su pico (mejor o peor momento) y su final, no por el promedio o total.

Experimento de colonoscopia: Pacientes con procedimiento más largo pero final menos doloroso lo recordaron como menos doloroso en general.

Negligencia de duración: La duración de una experiencia tiene poco efecto en evaluaciones retrospectivas.

CAPÍTULO 37: BIENESTAR EXPERIMENTADO

Felicidad puede ser medida momento a momento (yo que experimenta) o en retrospectiva (yo que recuerda).

U-index: Porcentaje de tiempo que pasas en estado desagradable.

Diferencias individuales en bienestar son sorprendentemente estables a través de tiempo y situación.

Factores que mejoran experiencias momento a momento:
- Tiempo social
- Ejercicio
- Dormir bien
- Tiempo en naturaleza

CAPÍTULO 38: PENSANDO SOBRE LA VIDA

El yo que recuerda está a cargo. Tomamos decisiones basadas en memorias, no en experiencia.

Ilusión de enfoque: Nada en la vida es tan importante como piensas que es cuando estás pensando en ello.

Las circunstancias de vida (riqueza, estado civil) importan menos para felicidad de lo que las personas piensan.

