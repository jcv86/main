## Capítulo 3: Historial del Mercado de Valores

### Patrones de Mercado (1871-1970)

**Ciclos Observados:**
1. **Bull markets:** Optimismo excesivo, precios inflados, especulación rampante
2. **Bear markets:** Pesimismo excesivo, precios deprimidos, oportunidades abundantes
3. **Recuperación:** Retorno a valores razonables

**Lección Crítica:**
"El mercado de valores tiene dos funciones primarias:
1. Mecanismo de valuación (a menudo muy equivocado)
2. Mecanismo de transferencia de riqueza (de los impacientes a los pacientes)"

### El Ratio P/E Histórico

**P/E Normal:** Históricamente 15-17x ganancias promedio

**P/E en Extremos:**
- Bull market extremo: 25-40x ganancias
- Bear market extremo: 5-10x ganancias

**Advertencia de Graham (1970s):**
Cuando mercado general cotiza a P/E de 20+, el inversor inteligente debe ser cauteloso.

