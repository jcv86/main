## Capítulo 8: El Inversor y Fluctuaciones de Mercado

### Mr. Market: La Parábola Fundamental

**La Parábola:**
Imagina que eres dueño de 50% de un negocio privado por $1,000. Tu socio, Mr. Market, es maníaco-depresivo:

**Días Buenos de Mr. Market:**
- Viene y ofrece comprarte o venderte acciones a $1,500
- Todo se ve maravilloso
- Futuro es brillante

**Días Malos de Mr. Market:**
- Viene y ofrece $500 por las mismas acciones
- Todo es terrible
- Futuro es sombrío

**Tu Respuesta Inteligente:**
- En días buenos: No le vendas (él sobrevaloaa)
- En días malos: Cómprale si valor intrínseco justifica (él infravaloora)
- La mayoría de días: Ignóralo completamente

**Lección:**
"El mercado está ahí para servirte, no para instruirte. Su función es proveer precios, no instrucción. Si él quiere venderte barato, aprovecha; si quiere comprarte caro, aprovecha. Pero si quieres entrar en histeria junto con él, ese es tu problema."

### Fluctuaciones de Mercado: Oportunidad, No Peligro

**Para el Inversor Especulador:**
Fluctuaciones = Riesgo y fuente de ansiedad

**Para el Inversor Inteligente:**
Fluctuaciones = Oportunidad de:
1. Comprar barato cuando mercado es pesimista
2. Vender caro cuando mercado es optimista
3. Ignorar cuando precios son razonables

**Principio Contrario:**
"Mientras más fluctúa el mercado, más oportunidades para el inversor inteligente."

### Timing de Mercado vs. Pricing de Mercado

**Timing (Predecir Dirección):**
- Intentar predecir si mercado subirá o bajará
- Graham: "Hemos revisado 60 años de intentos de timing. Conclusión: No funciona."
- Incluso "expertos" fallan consistentemente

**Pricing (Evaluar Valor):**
- Evaluar si precios actuales son altos, bajos o razonables
- Mucho más posible y productivo
- Requiere análisis, no predicción

**Fórmula de Graham:**
- Cuando mercado general tiene P/E promedio < 12 y dividend yield > 4%: Condiciones atractivas (sobreponderar acciones a 75%)
- Cuando mercado general tiene P/E > 20 y dividend yield < 3%: Condiciones no atractivas (subponderar acciones a 25%)

