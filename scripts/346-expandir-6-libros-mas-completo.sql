## Capítulo 7: Política de Cartera para Inversor Emprendedor

### Tres Líneas de Ataque Recomendadas

**Línea 1: Bonos Corporativos Suba­calificados y Acciones Preferentes**

**Concepto:**
Bonos de empresas sólidas que han caído temporalmente de gracia.

**Criterios:**
- Historial de ganancias anteriormente sólido
- Problema temporal, no terminal
- Cotizando a descuento significativo
- Rendimiento atractivo + apreciación de capital potencial

**Ejemplo Histórico:**
Durante recesión, bonos de empresas industriales sólidas a veces venden a 60-70 centavos por dólar, con rendimientos de 7-9%.

**Línea 2: Empresas de Crecimiento No Populares**

**Concepto:**
Empresas con crecimiento real pero que mercado ignora.

**Criterios:**
- Crecimiento real de ganancias (10%+ anual)
- P/E bajo relativo a tasa de crecimiento (PEG < 1.0)
- Razón de ser no popular: industria percibida como "aburrida" o en declive

**Línea 3: Casos Especiales o "Workout"**

**Tipos:**
- Arbitraje de fusiones
- Spin-offs
- Liquidaciones
- Reorganizaciones de bancarrota

**Requisito:**
Conocimiento especializado considerable, no recomendado sin experiencia.

### Encontrando Valores Subvalorados

**Screening Cuantitativo:**

**Criterios de Graham para "Bargains":**
1. P/E menor que mercado general
2. P/B menor que 1.2x (idealmente < 1.0x)
3. Deuda-equity ratio razonable (< 0.5)
4. Activos corrientes > 1.5x deuda total
5. Historial de ganancias positivas en últimos 5 años

**Análisis Cualitativo:**
- ¿Por qué está barata la acción?
- ¿Es problema temporal o estructural?
- ¿Tiene management capacidad de resolver?
- ¿Qué catalyst podría desbloquear valor?

