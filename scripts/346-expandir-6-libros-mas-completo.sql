## Concepto 2: Primero Quién... Luego Qué

### El Orden Correcto

**Empresas Buenas a Excelentes:**
1. Primero pusieron a las personas correctas en el bus
2. A las personas incorrectas fuera del bus
3. A las personas correctas en los asientos correctos
4. LUEGO decidieron a dónde conducir el bus

**Empresas de Comparación:**
1. Primero decidieron a dónde conducir
2. Luego intentaron convencer a personas de ir ahí
3. Gastaron energía gestionando y motivando
4. Resultados mediocres

### Tres Verdades Fundamentales

**Verdad 1: Si Comienzas con "Quién", Adaptas Más Fácilmente**
- El mundo cambia, estrategias se vuelven obsoletas
- Personas correctas se adaptan
- Si tienes personas correctas, no necesitas motivar
- Si tienes personas incorrectas, no importa cuánto motives

**Verdad 2: Si Tienes a las Personas Correctas, el Problema de Motivación Desaparece**
- Personas correctas tienen auto-disciplina
- Personas correctas tienen motivación interna
- Personas correctas producen mejores resultados

**Verdad 3: Si Tienes a las Personas Incorrectas, No Importa si Descubres la Dirección Correcta**
- No puedes hacer grande una empresa con personas incorrectas
- Personas incorrectas drenan energía
- Tiempo gestionándolas es tiempo perdido

### Ser Riguroso, No Despiadado

**Riguroso:**
- Estándares altos consistentes
- Personas correctas prosperan
- Sistema atrae mejores personas
- Cultura de disciplina

**Despiadado:**
- Despide personas frecuentemente
- Crea cultura de miedo
- Personas gastan energía en política
- Rotación alta, momentum bajo

### Las Tres Disciplinas para Ser Riguroso

**Disciplina 1: Cuando Tengas Dudas, No Contrates - Sigue Buscando**
- Error: Necesito llenar puesto urgentemente
- Correcto: Mejor sin nadie que con persona incorrecta
- Una contratación equivocada cuesta años

**Disciplina 2: Cuando Sabes Que Necesitas Hacer Cambio de Persona, Actúa**
- Error: Esperar, dar más oportunidades indefinidamente
- Correcto: Una vez que sabes con certeza, muévete rápido
- Dos preguntas clave:
  1. Si fuera decisión de contratación nuevamente, ¿la contratarías?
  2. Si la persona viniera y dijera que está renunciando, ¿sentirías alivio o decepción?

**Disciplina 3: Pon a Tus Mejores Personas en Tus Mayores Oportunidades, No en Tus Mayores Problemas**
- Error: Asignar A-players a arreglar problemas
- Correcto: Asignar A-players a explotar oportunidades
- Problemas se gestionan para no drenar recursos
- Oportunidades se aprovechan con los mejores

