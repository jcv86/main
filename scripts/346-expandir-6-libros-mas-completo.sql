## Concepto 1: Liderazgo de Nivel 5

### La Jerarquía de Liderazgo

**Nivel 1: Individuo Altamente Capaz**
- Contribuye con talento, conocimiento, habilidades
- Hábitos de trabajo productivos

**Nivel 2: Miembro Contribuyente del Equipo**
- Aporta capacidades individuales al logro de objetivos grupales
- Trabaja efectivamente con otros

**Nivel 3: Gerente Competente**
- Organiza personas y recursos hacia persecución efectiva y eficiente de objetivos predeterminados

**Nivel 4: Líder Efectivo**
- Cataliza compromiso y persecución vigorosa de una visión clara y convincente
- Estimula altos estándares de desempeño

**Nivel 5: Ejecutivo de Nivel 5**
- Construye grandeza duradera mediante una paradójica mezcla de humildad personal y voluntad profesional

### Las Características del Líder de Nivel 5

**Humildad Personal:**
- Modesto, evita publicidad
- Calmo, determinado, sereno
- Se apoya en estándares inspiradores, no carisma inspirador
- Canaliza ambición a la empresa, no a sí mismo
- Mira al espejo para asumir responsabilidad por malos resultados
- Mira por la ventana para atribuir éxito a factores externos

**Voluntad Profesional:**
- Crea resultados superiores, claro estándar de excelencia
- Demuestra determinación inquebrantable para hacer lo que sea necesario para producir los mejores resultados a largo plazo
- Pone la empresa primero, su propio ego y riqueza segundo
- Busca sucesores que sean aún más exitosos en la próxima generación
- Atribuye éxito a factores externos; nunca atribuye a mala suerte

### Ejemplos de Líderes Nivel 5

**Darwin Smith (Kimberly-Clark):**
- Tímido, incómodo, modesto
- En su primer día como CEO, Wall Street se preguntó quién era
- Transformó empresa de molino de papel a empresa de consumo líder
- 4.1 veces mejor que el mercado durante 20 años
- Rechazó invitaciones a la Casa Blanca
- Pasaba vacaciones en su granja de Wisconsin
- "No me consideraría un líder. Solo hice mi trabajo."

**Comparación con Nivel 4: Lee Iacocca (Chrysler):**
- Carismático, celebridad
- Salvó Chrysler inicialmente (Nivel 4)
- Pero después: ego creció, publicidad aumentó, resultados disminuyeron
- Gastó tiempo escribiendo autobiografías, apareciendo en TV
- Chrysler perdió momentum mientras él celebraba su fama

**Lección:**
La grandeza duradera requiere Nivel 5. El carisma sin humildad lleva a declive eventual.

