## Capítulo 9: Invertir en Fondos de Inversión

### El Registro de Fondos Mutuos

**Hallazgos de Graham:**
- Mayoría de fondos activamente gestionados NO superan índices de mercado a largo plazo
- Después de fees, performance es aún peor
- Solo pequeña minoría supera consistentemente

**Razones:**
1. Costos de gestión (expense ratios 1-2%)
2. Costos de trading (turnover)
3. Dificultad de superar mercado sistemáticamente
4. "Tax drag" en cuentas taxables

### Selección de Fondos

**Para Inversor Defensivo:**

**Opción Preferida: Fondos Indexados**
- S&P 500 Index Fund
- Total Stock Market Index Fund
- Criterio: Expense ratio < 0.20%

**Si Insiste en Fondos Activos:**
- Historial de al menos 10 años
- Expense ratio < 1.0%
- Low turnover (< 50% anual)
- Manager estable (mismo manager por 5+ años)

### Advertencias sobre Fondos

**1. Performance Pasado:**
"Performance pasado no garantiza resultados futuros" - no es solo disclaimer legal, es verdad fundamental.

**2. "Hot Funds":**
Fondos con mejor performance reciente atraen más capital, lo cual típicamente hace más difícil mantener performance.

**3. Fondos de Sector:**
Muy arriesgados; esencialmente apuestas en una industria o tema.

