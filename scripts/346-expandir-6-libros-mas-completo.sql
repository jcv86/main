## Capítulo 12: Margin of Safety: Concepto Central

### El Principio Más Importante

**Definición:**
"Margin of safety es la diferencia entre el valor intrínseco de una acción y su precio de mercado."

**Ejemplo:**
- Valor intrínseco estimado: $100/acción
- Precio de mercado: $60/acción
- Margin of safety: 40%

**Funciones del Margin of Safety:**

**1. Protección contra Error de Análisis:**
Tus cálculos de valor intrínseco pueden estar equivocados. Un margin amplio perdona errores.

**2. Protección contra Mala Suerte:**
Desarrollos adversos imprevistos. Margin absorbe shocks negativos.

**3. Rendimientos Satisfactorios:**
Comprar con margin sustancial casi garantiza resultado satisfactorio eventualmente.

### Cuánto Margin es Suficiente

**Recomendaciones de Graham:**

**Para Bonos:**
- Ganancias deben ser al menos 2x cargos de interés
- Assets deben cubrir deuda con cushion substantial

**Para Acciones Comunes:**

**Método 1: Precio vs. Valor de Activos Netos:**
Comprar a no más de 2/3 de valor de activos netos tangibles.

**Ejemplo:**
- Activos corrientes: $15M
- Pasivos totales: $5M
- Activos netos tangibles: $10M
- 2/3 de valor: $6.67M
- Si capitalización de mercado < $6.67M, hay margin

**Método 2: Precio vs. Valor de Ganancias:**
Comprar a P/E no mayor que 15x promedio de 7 años, idealmente 10x o menos.

**Ejemplo:**
- Ganancias promedio 7 años: $1.00/acción
- Comprar a máximo $15, idealmente $10 o menos
- A $10: Margin de 33% vs. límite superior

**Preferencia de Graham:**
Combinar ambos métodos. Margen adecuado en AMBOS activos y ganancias.

### Margin of Safety en Diversificación

**Principio:**
Diversificación apropiada es componente del margin of safety.

**Razón:**
- Una inversión individual puede fallar impredeciblemente
- Cartera de 10-30 inversiones con margin reduce riesgo dramáticamente
- Probabilidad de que TODAS fallen simultáneamente es muy baja

**Fórmula:**
Margin of Safety Individual + Diversificación = Seguridad de Cartera

### No Confundir Margin of Safety con:

**NO es lo mismo que:**
1. **"Acciones seguras":** No existen acciones inherentemente seguras; solo precios que proveen margin
2. **Empresa de alta calidad:** Empresa excelente a precio excesivo NO tiene margin
3. **Evitar volatilidad:** Volatilidad no es riesgo; riesgo es pérdida permanente de capital

**Graham:**
"Confrontado con un desafío de distinguir entre solidez y precio, la mayoría de inversionistas naturalmente enfatizan solidez. Esto es error fundamental. Un precio suficientemente bajo puede convertir una value de segunda clase en una oportunidad de primera."

