## Concepto 4: El Concepto del Erizo

### La Parábola del Erizo y el Zorro

**Fábula Griega:**
- El zorro sabe muchas cosas
- El erizo sabe una gran cosa
- El zorro ataca con múltiples estrategias
- El erizo simplemente se hace bola de espinas
- El erizo siempre gana

**En Negocios:**

**Empresas Zorro (Comparación):**
- Múltiples iniciativas
- Diversificación no enfocada
- Reaccionan a cada tendencia
- Complejidad

**Empresas Erizo (Buenas a Excelentes):**
- Un concepto simple y cristalino
- Todo se unifica bajo ese concepto
- Disciplina para decir no a oportunidades que no encajan
- Simplicidad

### Los Tres Círculos del Concepto del Erizo

**Para encontrar tu Concepto del Erizo, debes identificar la intersección de:**

**Círculo 1: En Qué Puedes Ser el Mejor del Mundo**
- No "qué quieres ser" sino "en qué PUEDES ser"
- Igualmente importante: en qué NO puedes ser el mejor
- Requiere honestidad brutal

**Pregunta clave:**
"Si no puedes ser el mejor del mundo en tu negocio principal, ¿qué negocio puede ser?"

**Ejemplo: Walgreens**
- No podían ser mejores del mundo en conveniencia general
- PODÍAN ser mejores en farmacias convenientes en cada esquina
- Concepto: "La mejor cadena de farmacias de conveniencia con alta densidad de profit por visita"

**Círculo 2: Qué Impulsa Tu Motor Económico**
- Una métrica económica profunda
- Tiene mayor impacto en tu economía
- Foco en numerador/denominador específico

**Ejemplos:**
- Walgreens: Profit por visita al cliente
- Wells Fargo: Profit por empleado
- Nucor: Profit por tonelada de acero terminado

**Círculo 3: Por Qué Eres Profundamente Apasionado**
- No qué te hace dinero
- Qué te apasiona genuinamente
- Qué te da energía

**La Intersección:**
Tu Concepto del Erizo está donde se cruzan los tres círculos.

### Ejemplos de Conceptos del Erizo

**Wells Fargo:**
- Mejor en: Llevar banca sofisticada a mercados desa­tendidos del oeste de USA
- Motor económico: Profit por empleado
- Pasión: "Queremos ser EL banco del oeste"

**Fannie Mae:**
- Mejor en: Proveer financiamiento hipotecario accesible a mercados subservidos
- Motor económico: Spread de profit por riesgo de crédito
- Pasión: Democratizar la propiedad de vivienda en América

**Abbott Laboratories:**
- Mejor en: Crear producto de nicho en mercado con alto profit margin
- Motor económico: Profit por línea de producto seleccionada
- Pasión: Avance de healthcare mediante productos diferenciados

