## Capítulo 11: Análisis de Seguridad: Las Ganancias

### Calidad de Ganancias

**Ganancias Reportadas vs. Ganancias Reales:**

**Ajustes Necesarios:**
1. **Items no recurrentes:** Eliminar ganancias/pérdidas one-time
2. **Capitalización vs. Gasto:** Corregir accounting agresivo
3. **Stock options:** Incorporar costo de dilución
4. **Pensiones:** Ajustar assumptions no realistas

**Conservadurismo de Graham:**
Usar ganancias promedio de 7-10 años, no solo último año, para eliminar volatilidad cíclica.

### Ratios de Ganancias

**P/E Ratio (Price-to-Earnings):**

**Interpretación:**
- P/E < 10: Potencialmente infravalorado (o problemas serios)
- P/E 10-20: Rango normal/razonable
- P/E > 25: Sobrevaloado o expectativas de alto crecimiento

**Advertencia de Graham:**
"Nunca pagues más de 20x ganancias promedio de últimos 3 años, y preferiblemente no más de 15x."

**Earnings Yield (Inverso de P/E):**
- Ganancias / Precio
- Permite comparación directa con rendimientos de bonos

**Ejemplo:**
- Acción a P/E de 10 = Earnings yield de 10%
- Si bonos rinden 5%, acción ofrece "spread" de 5%

### Crecimiento de Ganancias

**Tasa de Crecimiento Sostenible:**
ROE x (1 - Payout Ratio)

**Evaluación:**
- Crecimiento histórico de 7-10 años
- Consistencia de crecimiento (no errático)
- Probabilidad de continuación

**Relación Precio-Crecimiento:**

**PEG Ratio:**
P/E / Tasa de crecimiento

- PEG < 1.0: Potencialmente atractivo
- PEG 1.0-2.0: Razonablemente valuado
- PEG > 2.0: Caro relativo a crecimiento

**Nota de Graham:**
Escéptico de proyecciones de crecimiento de largo plazo; prefiere comprar crecimiento probado a precio razonable.

