- Rebalancear una vez al año con bonos según fórmula 50/50 o ajuste

**Opción 2: Selección Directa con Criterios Estrictos**

**Graham's Defensive Stock Criteria (Revisitado):**

1. **Tamaño:** Ventas > $100M (ajustado por inflación: ~$1B hoy)
2. **Financial Strength:** Current ratio > 2, LT debt < working capital
3. **Earnings Stability:** Ganancias positivas últimos 10 años
