## Capítulo 5: Inversor Defensivo y Acciones Comunes

### Enfoque en Fondos Indexados (Concepto Moderno)

**Graham No Conoció Fondos Indexados, Pero:**
Su filosofía para inversor defensivo es perfectamente compatible.

**Ventajas de Indexación:**
- Diversificación instantánea
- Costos bajos
- Rendimientos de mercado garantizados
- No requiere selección individual
- Elimina error de selección de gerentes activos

**Fondos Apropiados:**
- Fondos indexados de mercado total
- Fondos indexados S&P 500
- Fondos indexados de bajo costo (<0.20% ratio de gastos)

### Dollar-Cost Averaging

**Concepto:**
Invertir misma cantidad a intervalos regulares, independiente de precio de mercado.

**Ejemplo:**
$500/mes en fondo indexado, cada mes, sin falta.

**Beneficios:**
- Elimina decisión de timing
- Compras más acciones cuando precios son bajos
- Compras menos acciones cuando precios son altos
- Promedio de costo por acción favorable a largo plazo

**Disciplina Clave:**
Continuar invirtiendo ESPECIALMENTE cuando mercado ha caído. Ahí es donde el valor real se captura.

