## Capítulo 17: Cuatro Casos Históricos Instructivos

### Caso 1: Situación de Bargain Extremo

**Penn Central Railroad (1970):**
- Acción cayó de $86 a $5 después de bancarrota
- Assets liquidables excedían claramente precio de mercado
- Análisis mostró: Aún en liquidación, valor > $10/acción
- Margin of safety: 100%+
- Eventualmente, acción recuperó a $20+ en reorganización

**Lección:**
Mercado ocasionalmente ofrece oportunidades extremas donde margin of safety es enorme. Requiere:
1. Coraje para comprar en pesimismo extremo
2. Análisis cuidadoso de valor de liquidación
3. Paciencia para realización de valor

### Caso 2: "Growth Stock" Sobrevaloado

**Polaroid (1972):**
- P/E de 90x en peak
- Empresa excelente, pero precio insano
- Asumiendo crecimiento de 15% anual por 10 años, aún sobrevaloado
- Acción cayó 90% en años siguientes

**Lección:**
Incluso empresas excelentes son malas inversiones a precios suficientemente altos. No hay margin of safety a 90x earnings, sin importar calidad de empresa.

### Caso 3: Inversión en Value que Funcionó

**Chrysler (1982):**
- Cerca de bancarrota, rescate gobierno
- Acción a $5, P/B de 0.3x
- Skepticismo extremo en mercado
- Análisis mostró: Si sobrevivía, valía $20-30
- Margin of safety: Assets claramente excedían precio
- Resultado: Acción llegó a $48 en 1983

**Lección:**
Situaciones de "cigar butt" (último puff gratis) pueden ser extremadamente rentables. Requiere estómago fuerte y análisis disciplinado.

### Caso 4: Inversión en Growth que Funcionó

**Walmart (1972-1992):**
- Creció de empresa regional a líder nacional
- Nunca "barato" en términos de P/E
- Pero crecimiento de ganancias justificó valuación
