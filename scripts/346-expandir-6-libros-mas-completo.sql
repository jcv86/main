## Capítulo 2: El Inversionista y la Inflación

### La Realidad de la Inflación

**Hecho Histórico:**
Desde que Graham escribió (1949-1972), inflación promedio fue aproximadamente 2.5% anual.

**Impacto:**
- $1,000 en 1949 valían $500 en poder adquisitivo en 1972
- Necesitas rendimiento solo para mantener poder adquisitivo

### Estrategias Contra Inflación

**Acciones Comunes como Protección:**
- Históricamente, rendimientos de acciones superaron inflación
- Pero NO garantía automática
- Depende de:
  1. Precio pagado por acciones
  2. Capacidad de empresas de traspasar costos

**Bonos como Componente:**
- No protegen contra inflación
- Pero proveen estabilidad
- Componente necesario para cartera balanceada

**Recomendación de Graham:**
Cartera equilibrada entre acciones y bonos, ajustada según condiciones de mercado (mínimo 25% en cada categoría).

