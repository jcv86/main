## Capítulo 16: Valores Convertibles

### Bonos Convertibles y Preferentes Convertibles

**Definición:**
Valores que pagan interés/dividendo fijo Y permiten conversión a acciones comunes.

**Ventaja Teórica:**
- Downside protection de bono/preferente
- Upside potential de conversión a acciones

**Evaluación de Graham:**

**Positivo:**
Puede ser atractivo si:
1. Yield de bono es razonable (comparable a bonos no convertibles)
2. Precio de conversión no muy por encima de precio actual de acción
3. Credit quality es sólida

**Negativo:**
Típicamente:
1. Yield es menor que bonos no convertibles (pagas por conversión feature)
2. Precio de conversión es sustancialmente sobre mercado (conversión improbable)
3. Obtienes "peor de ambos mundos"

**Conclusión de Graham:**
Para inversor defensivo, típicamente mejor comprar bonos directos O acciones directas. Convertibles son compromiso mediocre.

