## Capítulo 14: Comparación de Ocho Pares de Empresas

**Método de Graham:**
Comparar empresas directamente para ilustrar principios.

### Par 1: Empresa de Crecimiento Real vs. Promocionada

**Empresa A (Crecimiento Real):**
- Crecimiento de ganancias consistente 10+ años
- Financieramente sólida
- Management estable y capaz
- P/E razonable (10-15x)

**Empresa B (Promocionada):**
- Crecimiento errático
- Deuda alta
- Management cambia frecuentemente
- P/E alto (30-50x) basado en "historia" y hype

**Lección:**
Crecimiento promovido rara vez iguala crecimiento real. Paga por sustancia, no historia.

### Par 2: Empresa Grande vs. Empresa Pequeña

**Empresa Grande:**
- Recursos para capear tormentas
- Acceso a capital
- Marcas establecidas
- Pero: Más difícil crecer rápidamente

**Empresa Pequeña:**
- Potencial de crecimiento rápido
- Más ágil
- Pero: Más vulnerable a problemas
- Menos recursos

**Lección Graham:**
Para inversor defensivo, enfócate en empresas grandes. Para emprendedor, pequeñas pueden ofrecer oportunidades pero con análisis riguroso.

### Par 3: Industria en Crecimiento vs. Industria Madura

**Industria en Crecimiento:**
- Alta competencia atrae capital
- Típicamente sobrevaloadas
- Muchas empresas fracasan eventualmente

**Industria Madura:**
- Competencia estable
- Típicamente infravaloradas
- Líderes tienen ventajas sostenibles

**Paradoja de Graham:**
"Las mejores inversiones a menudo están en industrias que nadie quiere."

