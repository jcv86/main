## Capítulo 4: Política de Cartera: Inversor Defensivo

### Principios Fundamentales

**Regla Básica:**
Nunca menos de 25% ni más de 75% en acciones comunes, con mínimo de 25% en bonos de alta calidad.

**Fórmula Simple:**
- **50-50:** Default baseline para la mayoría
- **Ajustar:** Según condiciones de mercado
- **75-25 acciones:** Cuando mercado parece atractivamente valuado
- **25-75 acciones:** Cuando mercado parece sobrevaloado

### Diversificación

**Número de Tenencias:**
- **Mínimo:** 10 diferentes empresas
- **Máximo:** Aproximadamente 30 empresas
- **Óptimo:** 20-25 para inversionista defensivo

**Diversificación por Industria:**
- No más de 10% de cartera en cualquier industria única
- Spread entre múltiples sectores

### Criterios de Selección para Inversor Defensivo

**Graham estableció 7 criterios para acciones defensivas:**

**1. Tamaño Adecuado:**
- **Industrial:** No menos de $100 millones en ventas anuales
- **Utilities:** No menos de $50 millones en activos totales
- Razón: Empresas grandes tienen recursos para capear tormentas

**2. Condición Financiera Suficientemente Fuerte:**
- **Industrials:** Activos corrientes al menos 2x pasivos corrientes, y deuda a largo plazo no más que capital de trabajo neto
- **Utilities:** Deuda no más de 2x equity

**3. Estabilidad de Ganancias:**
- Alguna ganancia para acciones comunes en cada uno de los últimos 10 años

**4. Registro de Dividendos:**
- Pagos de dividendos ininterrumpidos por al menos 20 años

**5. Crecimiento de Ganancias:**
- Incremento en EPS de al menos un tercio en últimos 10 años usando promedios de 3 años

**6. Ratio Precio-Ganancias Moderado:**
- Precio actual no más de 15x ganancias promedio de últimos 3 años

**7. Ratio Precio-Activos Moderado:**
- Precio actual no más de 1.5x book value más reciente
- Alternativamente, P/E x P/B no debe exceder 22.5

**Advertencia:**
Estos son estándares mínimos. Valores que cumplen estos criterios PUEDEN ser comprados; los que no, DEBEN ser evitados.

