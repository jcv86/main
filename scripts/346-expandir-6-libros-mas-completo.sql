## Capítulo 10: Análisis de Seguridad: El Balance

### Activos: Qué Realmente Importa

**Activos Tangibles:**
- Cash y equivalentes
- Cuentas por cobrar
- Inventarios (con cautela: valoración puede ser cuestionable)
- Propiedad, planta y equipo

**Activos Intangibles:**
- Goodwill (con escepticismo: generalmente sobrevalorado)
- Patentes y marcas (valiosas pero difíciles de valorar)
- "Brand value" (real pero no en balance tradicional)

**Análisis de Graham:**
Enfócate en activos tangibles; descuenta o ignora intangibles a menos que claramente valiosos y verificables.

### Pasivos: Deuda y Obligaciones

**Tipos de Deuda:**
- Deuda de corto plazo (< 1 año)
- Deuda de largo plazo
- Obligaciones off-balance sheet (leases, pensiones, etc.)

**Ratios Clave:**

**1. Current Ratio:**
Activos corrientes / Pasivos corrientes
- Mínimo aceptable: 2.0 para industrial
- Preferible: 2.5+

**2. Debt-to-Equity:**
Deuda total / Equity
- Máximo aceptable: 0.5 para industrial
- Utilities pueden ser más altas (hasta 1.0)

**3. Interest Coverage:**
EBIT / Gastos de interés
- Mínimo: 5x para industrial
- Preferible: 7x+

### Book Value y Valor Intrínseco

**Book Value (Valor en Libros):**
Activos totales - Pasivos totales = Equity de accionistas

**Limitaciones:**
- Assets pueden estar sobre o subvalorados
- No refleja valor de marca o posición competitiva
- Accounting puede distorsionar

**Precio-to-Book (P/B):**
- P/B < 1.0: Potencialmente infravalorado (o empresa en problemas)
- P/B 1.0-2.0: Razonable para empresa promedio
- P/B > 3.0: Requiere justificación de alto ROE o ventajas competitivas

