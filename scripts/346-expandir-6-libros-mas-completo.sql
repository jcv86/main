## Capítulo 6: Inversor Emprendedor

### Operaciones Negativas (Qué NO Hacer)

**1. Trading Basado en Movimientos de Mercado:**
- Intentar predecir dirección de mercado
- Trading frecuente basado en "momentum"
- Resultado: Costos de transacción erosionan ganancias

**2. Trading de Corto Plazo:**
- Intentar aprovechar fluctuaciones de corto plazo
- Requiere timing perfecto (imposible consistentemente)
- Evidencia muestra que traders promedio pierden

**3. Comprar IPOs "Calientes":**
- Empresas nuevas sin historial
- Típicamente sobrevaloradas
- Probabilidad alta de decepción

### Operaciones Positivas

**1. Compra de Valores Subvalorados:**
- Precio significativamente por debajo de valor intrínseco
- Requiere análisis exhaustivo
- Paciencia para que mercado reconozca valor

**2. Situaciones Especiales:**
- Arbitraje de fusiones
- Liquidaciones
- Reorganizaciones
- Requiere conocimiento especializado

**3. "Empresas Bargain" - Oportunidades Secundarias:**
- Empresas con fundamentos sólidos, temporalmente fuera de favor
- Cotizando a P/E bajos por razones corregibles
- Margin of safety substancial

