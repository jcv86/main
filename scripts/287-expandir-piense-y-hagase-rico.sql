INTRODUCCIÓN

Este libro contiene el secreto del dinero de Andrew Carnegie que ha creado más millonarios que cualquier otra filosofía de éxito.

El secreto fue dado a mí por Andrew Carnegie hace más de un cuarto de siglo. El astuto escocés me desafió con malicia a descubrir el secreto por mí mismo.

LECCIÓN 1: EL DESEO

El punto de partida de todo logro es el deseo. Los deseos débiles traen resultados débiles así como una pequeña cantidad de fuego hace una pequeña cantidad de calor.

Seis pasos para convertir deseos en oro:
1. Fija en tu mente la cantidad exacta de dinero que deseas
2. Determina exactamente qué darás a cambio del dinero
3. Establece una fecha definida cuando tendrás el dinero
4. Crea un plan definido para llevar a cabo tu deseo
5. Escribe una declaración clara de todo lo anterior
6. Lee tu declaración dos veces al día visualizando el éxito

LECCIÓN 2: LA FE

La fe es el elemento químico principal de la mente. Cuando la fe se mezcla con la vibración del pensamiento el subconsciente la capta instantáneamente.

La fe puede ser inducida por afirmaciones o instrucciones repetidas al subconsciente a través del principio de autosugestión.

Toda mente humana capaz de creer puede hacer que una idea mental se materialice en su equivalente físico.

LECCIÓN 3: AUTOSUGESTIÓN

La autosugestión es el medio de comunicación entre la mente consciente y la mente subconsciente.

A través de los sentidos dominantes del pensamiento uno puede voluntariamente alimentar su subconsciente con pensamientos de naturaleza creativa.

Tu habilidad para usar autosugestión depende en gran medida de tu concentración en un deseo dado hasta que ese deseo se convierta en una obsesión ardiente.

