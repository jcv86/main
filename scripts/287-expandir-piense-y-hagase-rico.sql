La transmutación del sexo significa cambiar de la mente pensamientos de expresión física a pensamientos de otra naturaleza.

Los hombres de mayor logro son aquellos que han desarrollado naturalezas sexuales altamente desarrolladas y que han aprendido el arte de transmutación sexual.

