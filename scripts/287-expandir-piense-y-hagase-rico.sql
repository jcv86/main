Henry Ford no tenía mucha educación pero sabía cómo rodearse de hombres que poseían el conocimiento que él necesitaba.

LECCIÓN 5: IMAGINACIÓN

La imaginación es el taller donde se dan forma a todos los planes creados por el hombre. El impulso del deseo toma forma y acción a través de la imaginación.

Hay dos formas de imaginación:
- Imaginación sintética: reorganiza ideas existentes en nuevas combinaciones
- Imaginación creativa: crea algo de la nada a través de la inspiración

Las ideas son el punto de partida de todas las fortunas. Las ideas son productos de la imaginación.

LECCIÓN 6: PLANIFICACIÓN ORGANIZADA

El deseo es llevado a la forma práctica a través de la planificación organizada.

Alíate con un grupo de cerebro maestro de tantas personas como necesites para crear y ejecutar tu plan.

Antes de formar tu grupo decide qué ventajas puedes ofrecer a cada miembro a cambio de su cooperación.

Reúnete con tu grupo al menos dos veces por semana hasta que hayas perfeccionado el plan necesario.

LECCIÓN 7: DECISIÓN

El análisis de varios cientos de personas que acumularon fortunas reveló que cada una tenía el hábito de llegar a decisiones con prontitud.

Las personas que no acumulan dinero tienen el hábito de llegar a decisiones muy lentamente y de cambiar estas decisiones rápida y frecuentemente.

El valor de las decisiones depende del coraje requerido para tomarlas. Las grandes decisiones requieren gran coraje.

LECCIÓN 8: PERSISTENCIA

La persistencia es un factor esencial en el procedimiento de transmutar deseo en su equivalente monetario.

La base de la persistencia es el poder de voluntad. La mayoría de las personas están listas para tirar sus metas al primer signo de mala fortuna.

Cuatro pasos simples para desarrollar persistencia:
1. Un propósito definido respaldado por deseo ardiente
2. Un plan definido expresado en acción continua
3. Una mente cerrada contra influencias negativas
4. Una alianza amigable con personas que te animan

LECCIÓN 9: EL PODER DEL CEREBRO MAESTRO

El cerebro maestro se define como coordinación de conocimiento y esfuerzo en espíritu de armonía entre dos o más personas para el logro de un propósito definido.

Ningún individuo puede tener gran poder sin avalar el principio del cerebro maestro.

Andrew Carnegie atribuyó toda su fortuna al poder que acumuló a través de su grupo de cerebro maestro.

