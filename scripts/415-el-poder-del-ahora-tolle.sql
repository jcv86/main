## CAPÍTULO 2: CONCIENCIA: LA SALIDA DEL DOLOR

### El Cuerpo del Dolor

Acumulación de dolor emocional del pasado que vive en tu cuerpo.

**Características:**
- Se alimenta de drama y negatividad
- Se activa por situaciones similares al pasado
- Busca más dolor para sobrevivir
- Puede ser individual o colectivo

**Ejemplo:**
Alguien dice algo levemente crítico → Tu cuerpo del dolor se activa → Reaccionas desproporcionadamente → Creas más drama → El cuerpo del dolor se alimenta

**Disolverlo:**

1. **Reconócelo** - "Ah, mi cuerpo del dolor está activo"
2. **Observa sin juzgar** - Siente la emoción en tu cuerpo
3. **Presencia** - Mantente presente con la sensación
4. **No lo alimentes** - No crees más drama
5. **Se disuelve** - La luz de la conciencia lo transmuta

### Presencia vs Pensamiento

**Vivir en la Mente:**
- Ansiedad (futuro)
- Depresión (pasado)
- Insatisfacción (comparación)
- Resistencia (lo que es)

**Vivir en Presencia:**
- Paz (aceptación)
- Alegría (ser)
- Amor (conexión)
- Creatividad (flujo)

