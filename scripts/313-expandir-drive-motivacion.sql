Por Daniel H. Pink

INTRODUCCION: EL DESCUBRIMIENTO

Durante demasiado tiempo, hemos pensado en la motivacion de manera incorrecta. El modelo tradicional de zanahoria y palo funciona en algunas situaciones, pero falla en muchas otras, especialmente en tareas que requieren creatividad y pensamiento conceptual.

Este libro presenta una nueva vision de la motivacion humana basada en tres elementos esenciales: autonomia, maestria y proposito. Estas son las verdaderas fuentes de motivacion intrinseca que impulsan el alto rendimiento y la satisfaccion en el trabajo y la vida.

PARTE 1: EL ASCENSO Y CAIDA DE LA MOTIVACION 2.0

CAPITULO 1: LA HISTORIA DE LA MOTIVACION

La Motivacion 1.0 era puramente biologica: sobrevivir, reproducirse, obtener comida. Funcionaba bien para nuestros ancestros en la sabana africana.

La Motivacion 2.0 surgio con la revolucion industrial: recompensas y castigos externos. El modelo de zanahoria y palo. Si haces esto, obtendras aquello. Si no lo haces, recibiras este castigo.

Este sistema funciono magnificamente durante decadas. Las fabricas necesitaban trabajadores que realizaran tareas repetitivas y mecanicas. Las recompensas extrinsecas eran perfectas para este tipo de trabajo.

Pero el mundo cambio. El trabajo cambio. Ya no se trata solo de apretar tuercas en una linea de ensamblaje. Ahora necesitamos creatividad, innovacion, resolucion de problemas complejos.

CAPITULO 2: LOS SIETE DEFECTOS DE LA MOTIVACION 2.0

La ciencia moderna ha descubierto que las recompensas extrinsecas:

1. Pueden extinguir la motivacion intrinseca
Cuando pagas a alguien por hacer algo que le gusta, puede dejar de gustarle. Los estudios muestran que los ninos que reciben recompensas por dibujar, dibujan menos cuando no hay recompensa.

2. Pueden disminuir el rendimiento
Las recompensas funcionan bien para tareas mecanicas y simples. Pero para tareas que requieren pensamiento creativo, las recompensas pueden reducir el rendimiento. Dan Ariely y otros investigadores han demostrado esto repetidamente.

3. Pueden aplastar la creatividad
Cuando te enfocas en la recompensa, te enfocas en el camino mas rapido y directo hacia ella. No exploras. No experimentas. No innov as. La creatividad requiere libertad mental, no presion por recompensas.

4. Pueden desplazar el buen comportamiento
Las personas hacen lo que se recompensa, incluso si va contra sus valores o el bien comun. Los incentivos pueden crear comportamientos no eticos.

5. Pueden fomentar trampas y atajos
Cuando solo importa el resultado medible, las personas buscan atajos. Manipulan numeros. Hacen trampa. Mienten en sus informes.

6. Pueden crear adiccion
Las recompensas extrinsecas son como drogas. Necesitas dosis cada vez mayores para obtener el mismo efecto. Los bonos de este ano se convierten en expectativas del proximo.

7. Pueden fomentar pensamiento a corto plazo
Las recompensas enfocadas en resultados inmediatos desalientan la vision a largo plazo. Las empresas sacrifican investigacion e innovacion por resultados trimestrales.

CAPITULO 3: EL TIPO I Y EL TIPO X

Pink distingue entre dos tipos de comportamiento:

Tipo X: Motivado extrinsecamente
- Busca recompensas externas
- Evita castigos externos
- Necesita supervision constante
- Pierde interes sin incentivos
- Rendimiento limitado a largo plazo

Tipo I: Motivado intrinsecamente
- Encuentra satisfaccion en el trabajo mismo
- Autonomo y autodirigido
- Busca maestria continua
- Impulsado por proposito
- Alto rendimiento sostenible

La buena noticia: todos podemos desarrollar comportamiento Tipo I. No es genetico. Es una decision y una practica.

PARTE 2: LOS TRES ELEMENTOS DE LA MOTIVACION 3.0

CAPITULO 4: AUTONOMIA - EL DESEO DE DIRIGIR NUESTRAS PROPIAS VIDAS

La autonomia es nuestra necesidad de ser autodirigidos. Es esencial para la motivacion intrinseca y el alto rendimiento.

La autonomia no es lo mismo que independencia. No significa hacer todo solo. Significa tener control sobre tu trabajo: que haces, cuando lo haces, como lo haces, con quien lo haces.

CUATRO DIMENSIONES DE LA AUTONOMIA:

1. Autonomia sobre la TAREA
Google permite a sus ingenieros dedicar 20% de su tiempo a proyectos propios. Gmail, Google News y AdSense nacieron del tiempo del 20%. Esta autonomia sobre las tareas genera innovacion extraordinaria.

Atlassian, empresa de software australiana, tiene FedEx Days: 24 horas donde los empleados trabajan en cualquier proyecto que quieran, con quien quieran, como quieran. La unica regla: deben entregar algo al dia siguiente. Estos dias han producido docenas de mejoras de software.

2. Autonomia sobre el TIEMPO
Best Buy implemento ROWE: Results Only Work Environment. Los empleados no tienen horarios fijos. No hay reuniones obligatorias. Solo importan los resultados.

Resultado: productividad aumento 35%. Rotacion disminuyo dramaticamente. Satisfaccion de empleados aumento significativamente.

La autonomia sobre el tiempo reconoce que diferentes personas trabajan mejor en diferentes momentos. Algunos son mas productivos por la manana. Otros por la noche. Algunos necesitan bloques largos e ininterrumpidos. Otros prefieren sesiones cortas.

3. Autonomia sobre el EQUIPO
Whole Foods permite a los equipos de tienda decidir quien se une al equipo. Los nuevos empleados tienen periodo de prueba de 30 dias. Luego el equipo vota si se queda.

Este nivel de autonomia crea equipos mas cohesivos y comprometidos. Las personas no trabajan con colegas impuestos, sino con companeros elegidos.

Zappos ofrece $3,000 a nuevos empleados despues de la primera semana si quieren renunciar. Solo quieren personas verdaderamente comprometidas. La autonomia de elegir quedarse o irse fortalece el compromiso.

4. Autonomia sobre la TECNICA
Southwest Airlines da autonomia a sus empleados sobre como hacer su trabajo. Las azafatas pueden ser creativas en sus anuncios de seguridad. Los agentes de puerta pueden resolver problemas sin autorizacion gerencial.

Resultado: Southwest es consistentemente la aerolinea mas rentable y con mejor servicio al cliente en Estados Unidos.

CAPITULO 5: MAESTRIA - EL IMPULSO DE MEJORAR EN ALGO QUE IMPORTA

La maestria es nuestro deseo de mejorar continuamente en algo significativo. Es el impulso de ser mejor hoy que ayer.

La maestria comienza con FLUJO. Mihaly Csikszentmihalyi descubrio que las personas son mas felices cuando estan en estado de flujo: completamente absortas en una actividad desafiante que requiere habilidad.

TRES REGLAS DE LA MAESTRIA:

1. La maestria es una MENTALIDAD
Carol Dweck distingue entre mentalidad fija y mentalidad de crecimiento.

Mentalidad fija: La inteligencia y habilidad son innatas y limitadas. O eres bueno en algo o no lo eres. El fracaso es permanente.

Mentalidad de crecimiento: La inteligencia y habilidad pueden desarrollarse. Con esfuerzo y practica, puedes mejorar en cualquier cosa. El fracaso es informacion para mejorar.

Las personas con mentalidad de crecimiento logran mas porque:
- Ven desafios como oportunidades
- Persisten ante obstaculos
- Aprenden de criticas
- Se inspiran en el exito de otros

2. La maestria es un PROCESO DOLOROSO
La maestria requiere esfuerzo, no solo durante horas sino durante anos. Anders Ericsson descubrio que los expertos en cualquier campo han dedicado aproximadamente 10,000 horas de practica deliberada.

Practica deliberada significa:
- Trabajo enfocado en mejorar aspectos especificos
- Retroalimentacion inmediata
- Repeticion mental y fisica
- No es divertido, es trabajo duro

Los violinistas elite practican mas de 10,000 horas antes de los 20 anos. Los maestros de ajedrez estudian posiciones durante decadas. Los grandes escritores escriben millones de palabras malas antes de escribir obras maestras.

3. La maestria es una ASINTOTA
Una asintota es una linea que constantemente se acerca pero nunca toca. La maestria es inalcanzable pero la busqueda es gratificante.

Nunca llegaras a la maestria perfecta. Siempre habra espacio para mejorar. Y eso es hermoso. La busqueda continua da significado y satisfaccion.

Los mejores atletas, musicos, escritores, cientificos nunca dejan de aprender y mejorar. Roger Federer a los 35 anos seguia perfeccionando su reves. Picasso a los 90 seguia experimentando con nuevos estilos.

CAPITULO 6: PROPOSITO - EL ANHELO DE HACER LO QUE HACEMOS AL SERVICIO DE ALGO MAS GRANDE

El proposito proporciona energia y activacion. Es la diferencia entre simplemente hacer un trabajo y contribuir a algo significativo.

Las empresas impulsadas por proposito superan a las empresas enfocadas solo en ganancias. James Collins y Jerry Porras en Built to Last mostraron que las empresas visionarias con propositos claros superaron al mercado por un factor de 15 durante 50 anos.

TRES DIMENSIONES DEL PROPOSITO:

1. METAS QUE USAN PALABRAS DE BENEFICIO SOBRE PALABRAS DE GANANCIA
Compara estas declaraciones de mision:

Empresa A: Maximizar el valor para los accionistas
Empresa B: Democratizar el acceso a la informacion mundial

La segunda inspira. La primera no. Las palabras importan. Las metas expresadas en terminos de beneficio humano motivan mas que metas expresadas en terminos financieros.

2. PALABRAS QUE ENFATIZAN MAS QUE EL INTERES PROPIO
TOMS Shoes: Por cada par de zapatos vendido, donamos un par a un nino necesitado. Este modelo one-for-one ha inspirado docenas de empresas similares.

Patagonia: Construimos el mejor producto, no causamos dano innecesario, usamos negocios para inspirar e implementar soluciones a la crisis ambiental.

Estas empresas no solo buscan ganancias. Buscan impacto positivo. Y sus empleados estan mas comprometidos y motivados.

3. POLITICAS QUE PERMITEN A LAS PERSONAS BUSCAR PROPOSITO POR SU CUENTA
Medtronic, fabricante de dispositivos medicos, regularmente invita pacientes a hablar con empleados. Los pacientes cuentan como los marcapasos y otros dispositivos salvaron sus vidas.

Ver el impacto directo de su trabajo motiva profundamente a los empleados. No solo ensamblan componentes electronicos. Salvan vidas.

PARTE 3: EL KIT DE HERRAMIENTAS TIPO I

HERRAMIENTAS PARA INDIVIDUOS

1. DESPERTADOR DE FLUJO
Cada 90 minutos durante una semana, preguntate:
- Que estoy haciendo?
- Como me siento?
- Estoy en flujo?

Identifica patrones. Que actividades te ponen en flujo? Reorganiza tu dia para maximizar esas actividades.

2. PRIMER INFORME DE MOTIVACION INTRINSECA
Al final de cada mes, reflexiona:
- Que te dio mas energia este mes?
- Que te dreno energia?
- Que aprendiste?
- Que quieres mejorar el proximo mes?

3. ASK A GREAT QUESTION
En lugar de: Que debo hacer?
Pregunta: Que problema quiero resolver?

En lugar de: Como puedo terminar esto?
Pregunta: Como puedo hacer esto excelente?

HERRAMIENTAS PARA ORGANIZACIONES

1. 20% DE TIEMPO PARA TODOS
Permite a los empleados dedicar 20% de su tiempo a proyectos propios. Google, 3M y Atlassian han generado innovaciones extraordinarias con esta politica.

2. DIY REPORT CARD
Permite a los empleados evaluar su propio desempeno primero. Luego comparalo con la evaluacion del gerente. La autoevaluacion promueve autonomia y responsabilidad.

3. OFERTAS DE COMPENSACION AJUSTADA
En lugar de: Tu bono es X% de tu salario base
Ofrece: Tu compensacion refleja tu contribucion, maestria y proposito

Involucra a los empleados en determinar compensacion justa.

HERRAMIENTAS PARA PADRES Y EDUCADORES

1. DIY REPORT CARD PARA NINOS
Permite a los ninos evaluar su propio progreso. Que aprendieron? Donde mejoraron? Que quieren aprender despues?

2. ELOGIO DE ESFUERZO, NO HABILIDAD
En lugar de: Eres muy inteligente
Di: Trabajaste muy duro en esto

El primer elogio crea mentalidad fija. El segundo crea mentalidad de crecimiento.

3. MESADA 2.0
No ates mesada a tareas del hogar. Las tareas son contribuciones esperadas a la familia. La mesada ensena administracion de dinero.

Ofrece oportunidades de ganar dinero extra por trabajos especiales que van mas alla de contribuciones basicas.

CONCLUSION: EL FUTURO DE LA MOTIVACION

Estamos en un punto de inflexion. El viejo sistema operativo de motivacion - Motivacion 2.0 - ya no es suficiente para el trabajo del siglo XXI.

Necesitamos una actualizacion: Motivacion 3.0, construida sobre autonomia, maestria y proposito.

Las empresas que adopten este nuevo enfoque:
- Tendran empleados mas comprometidos
- Generaran mas innovacion
- Retendr an mejor talento
- Superaran a la competencia

Los individuos que adopten este enfoque:
- Seran mas productivos
- Estaran mas satisfechos
- Lograran mayor exito sostenible
- Viviran vidas mas plenas

La transicion no es facil. Requiere cambiar creencias profundamente arraigadas sobre que motiva a las personas. Pero la ciencia es clara y los resultados son convincentes.

El futuro pertenece a los Tipo I: personas autonomas que buscan maestria y estan impulsadas por proposito.

