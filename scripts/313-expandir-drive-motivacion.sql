2. La autonomia sobre tarea, tiempo, tecnica y equipo genera mayor compromiso y rendimiento

3. La maestria requiere mentalidad de crecimiento, practica deliberada y paciencia con el proceso

4. El proposito proporciona energia duradera y significado profundo

