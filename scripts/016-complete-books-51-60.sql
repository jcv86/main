- Proximity Principle: Physical or emotional nearness increases familiarity, which increases likability
- Frequency Principle: Repeated interactions strengthen bonds; regular contact builds relationships more effectively than sporadic contact
- Intensity Principle: Shared emotional experiences create deeper connections than casual interactions

THE FBI FRIENDSHIP FORMULA:
Proximity + Frequency + Intensity + Duration = Genuine Friendship
Each element must develop proportionally; intensity without time-building creates superficial connections, while extended low-intensity contact builds weaker bonds.

PROFESSIONAL APPLICATION:
