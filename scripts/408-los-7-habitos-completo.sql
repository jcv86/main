## HÁBITO 4: PENSAR EN GANAR-GANAR

### El Principio del Beneficio Mutuo

Ganar-Ganar es un marco mental que busca constantemente el beneficio mutuo en todas las interacciones humanas.

**Los Seis Paradigmas:**
1. Ganar-Ganar: Ambos ganan
2. Gano-Pierdes: Yo gano, tú pierdes
3. Pierdo-Ganas: Yo pierdo, tú ganas
4. Pierdo-Pierdes: Ambos perdemos
5. Gano: Solo me importa ganar yo
6. Ganar-Ganar o No Hay Trato: Si no hay beneficio mutuo, no hay acuerdo

---

## HÁBITO 5: BUSCAR PRIMERO ENTENDER, LUEGO SER ENTENDIDO

### El Principio de la Comunicación Empática

La mayoría de las personas no escuchan con la intención de entender; escuchan con la intención de responder.

**Los Cinco Niveles de Escucha:**
1. Ignorar
2. Fingir
3. Escucha Selectiva
4. Escucha Atenta
5. Escucha Empática

**La escucha empática es entrar en el marco de referencia de otra persona, ver el mundo como ella lo ve, entender su paradigma, sentir cómo se siente.**

---

## HÁBITO 6: SINERGIZAR

### El Principio de la Cooperación Creativa

Sinergia significa que el todo es más que la suma de sus partes. 1 + 1 = 3 o más.

**Valorar las Diferencias:**
- Respeto (Ganar-Ganar)
- Comunicación Empática (Hábito 5)
- Cooperación Creativa (Sinergia)

Cuando valoras las diferencias, creas una tercera alternativa mejor que cualquiera de las propuestas originales.

---

## HÁBITO 7: AFILAR LA SIERRA

### El Principio de la Renovación Equilibrada

Afilar la sierra significa preservar y realzar el mayor bien que tienes: tú mismo.

**Las Cuatro Dimensiones:**

1. **Física:** Ejercicio, nutrición, manejo del estrés
2. **Espiritual:** Clarificación de valores, compromiso, estudio
3. **Mental:** Lectura, escritura, planificación
4. **Social/Emocional:** Servicio, empatía, sinergia

**El balance es la clave. Descuidar cualquier área afecta negativamente al resto.**

