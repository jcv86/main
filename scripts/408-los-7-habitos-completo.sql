## HÁBITO 3: PONER PRIMERO LO PRIMERO

### El Principio de la Administración Personal

Poner primero lo primero es la segunda creación, la creación física. Es la realización, la actualización, la aparición natural del Hábito 1 y 2.

### La Matriz de Administración del Tiempo

Todas las actividades se pueden clasificar en cuatro cuadrantes:

**Cuadrante I: Urgente e Importante**
- Crisis, problemas apremiantes, proyectos con fechas límite

**Cuadrante II: No Urgente pero Importante**
- Prevención, construcción de relaciones, planificación, recreación

**Cuadrante III: Urgente pero No Importante**
- Interrupciones, algunas llamadas, algunos correos

**Cuadrante IV: No Urgente y No Importante**
- Trivialidades, pérdidas de tiempo

**La clave del éxito: Vivir en el Cuadrante II**

