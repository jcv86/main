## HÁBITO 2: EMPEZAR CON UN FIN EN MENTE

### El Principio del Liderazgo Personal

Empezar con un fin en mente significa comenzar con una clara comprensión de tu destino. Significa saber a dónde vas, para que comprendas mejor dónde estás ahora y los pasos que debes dar siempre en la dirección correcta.

### El Ejercicio del Funeral

Imagina que estás asistiendo a un funeral. Ves a los amigos, la familia. Sientes el dolor compartido de la pérdida. Mientras caminas y miras dentro del ataúd, de repente te enfrentas a ti mismo. Este es tu funeral, tres años desde hoy.

Cuatro personas van a hablar:
1. Un miembro de tu familia
2. Un amigo
3. Un colega de trabajo
4. Un miembro de tu comunidad

**¿Qué te gustaría que cada uno dijera sobre ti y tu vida?**
**¿Qué tipo de esposo, esposa, padre, madre, amigo querías ser?**
**¿Qué contribuciones, qué logros querías que se recordaran?**

### Tu Enunciado de Misión Personal

Un enunciado de misión personal es tu constitución, la expresión sólida de tu visión y valores. Se convierte en el criterio mediante el cual mides todo lo demás en tu vida.

**Elementos de una Misión Personal:**

1. **Roles:** ¿Qué roles desempeñas? (padre, profesional, amigo, etc.)
2. **Metas:** ¿Qué quieres lograr en cada rol?
3. **Valores:** ¿Qué principios guían tus decisiones?

**Ejemplo de Enunciado de Misión:**

"Tener éxito en casa primero. Buscar y merecer la ayuda divina. Nunca comprometer la honestidad e integridad. Recordar a las personas involucradas. Escuchar ambos lados antes de juzgar. Aconsejar con mis hijos. Defender a los ausentes. Ser sincero pero decidido. Desarrollar un nuevo talento cada año. Planificar el presente para el futuro. Mantener una perspectiva positiva."

