## HÁBITO 1: SER PROACTIVO

### El Principio de la Visión Personal

Entre el estímulo y la respuesta, el ser humano tiene la libertad de elegir.

**Personas Reactivas:**
- Culpan a las circunstancias
- Culpan a otras personas
- Culpan a su pasado
- Se sienten víctimas

**Personas Proactivas:**
- Toman responsabilidad
- Eligen su respuesta
- Actúan basados en valores
- Crean su propio clima

### El Círculo de Influencia vs Círculo de Preocupación

**Círculo de Preocupación:**
Todo lo que te preocupa: el clima, la economía, las guerras, lo que otros piensan, el pasado, etc.

**Círculo de Influencia:**
Las cosas sobre las que puedes hacer algo: tus acciones, tus actitudes, tus decisiones, tu respuesta.

**Personas Reactivas:**
- Enfocan energía en el Círculo de Preocupación
- Su Círculo de Influencia se reduce
- Se sienten impotentes

**Personas Proactivas:**
- Enfocan energía en el Círculo de Influencia
- Su Círculo de Influencia crece
- Ganan más control

### Lenguaje Reactivo vs Proactivo

**Lenguaje Reactivo:**
- "No puedo hacer nada"
- "Yo soy así"
- "Me vuelve loco"
- "No lo permitirán"
- "Tengo que hacer eso"
- "No puedo"
- "Debo"
- "Si tan solo..."

**Lenguaje Proactivo:**
- "Veamos nuestras alternativas"
- "Puedo elegir un enfoque diferente"
- "Controlo mis sentimientos"
- "Puedo crear una presentación efectiva"
- "Elegiré una respuesta apropiada"
- "Elijo"
- "Prefiero"
- "Haré"

