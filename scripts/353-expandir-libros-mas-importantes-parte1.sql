Solo vende lo que realmente ayuda al cliente

3. **Sé Transparente:**
Okay decir "esto es una oferta limitada porque..."

4. **Respeta el "No":**
No presiones excesivamente

5. **Enfoca en Beneficio Mutuo:**
Win-win, no win-lose

**Aplicación Ética de los 6 Principios:**

**Reciprocidad:** Da valor real antes de pedir
**Compromiso:** Ayuda a las personas a comprometerse con sus propias metas
**Prueba Social:** Usa testimoniales genuinos
**Agrado:** Sé auténtico, no manipules
**Autoridad:** Construye expertise real
**Escasez:** Usa escasez real, no artificial

