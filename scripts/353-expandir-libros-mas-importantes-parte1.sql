## Métricas y Medición Avanzada

### Embudo de Piratas (AARRR)

Framework creado por Dave McClure para métricas de startups:

**1. Adquisición (Acquisition):**
- ¿Cómo encuentran los usuarios tu producto?
- Canales: SEO, SEM, social media, referidos
- Métrica: Costo por adquisición (CPA)

**2. Activación (Activation):**
- ¿Los usuarios tienen una buena primera experiencia?
- Momento "aha" cuando ven el valor
- Métrica: % de usuarios que completan acción clave

**3. Retención (Retention):**
- ¿Los usuarios regresan?
- Uso repetido del producto
- Métrica: Tasa de retención por cohorte

**4. Referencia (Referral):**
- ¿Los usuarios refieren a otros?
- Crecimiento orgánico
- Métrica: Coeficiente viral

**5. Ingresos (Revenue):**
- ¿Puedes monetizar el comportamiento?
- Sostenibilidad del negocio
- Métrica: LTV / CAC

### Análisis de Cohortes Avanzado

**Segmentación de Cohortes:**
- Por canal de adquisición
- Por característica usada primero
- Por demografía de usuario
- Por comportamiento inicial

**Patrones a Buscar:**
- Mejora constante entre cohortes = producto está mejorando
- Empeoramiento entre cohortes = problema creciente
- Plateau entre cohortes = has encontrado product-market fit
- Alta variación = necesitas entender por qué

### Tests A/B y Experimentación

**Diseño de Experimentos Efectivos:**
1. Una hipótesis clara y específica
2. Una métrica primaria de éxito
3. Significancia estadística adecuada
4. Duración suficiente del experimento
5. Segmentación apropiada de usuarios

**Errores Comunes en A/B Testing:**
- Terminar pruebas demasiado temprano
- Probar demasiadas variables a la vez
- No considerar efectos de novedad
- Ignorar significancia estadística
- Hacer cambios basados en datos insuficientes

