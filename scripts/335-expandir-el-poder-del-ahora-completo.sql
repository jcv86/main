**CAPÍTULO 4: ESTRATEGIAS DE LA MENTE PARA EVITAR EL AHORA**

**La Mente es Adicta al Tiempo:**

La mente opera en tres modos temporales disfuncionales:

**1. Vivir en el Pasado:**

**Formas Comunes:**
- Arrepentimiento: "Debí haber..."
- Resentimiento: "No puedo perdonar que..."
- Culpa: "Soy malo por..."
- Nostalgia excesiva: "Los viejos tiempos eran mejores"

**Función:**
La mente usa el pasado para fortalecer tu sentido de identidad (ego).

**2. Vivir en el Futuro:**

**Formas Comunes:**
- Ansiedad: "¿Y si...?"
- Preocupación: "Esto podría salir mal"
- Espera: "Seré feliz cuando..."
- Fantasía: "Algún día todo será perfecto"

**Función:**
La mente promete que la salvación está en el futuro, manteniéndote siempre insatisfecho con el presente.

**3. El Tiempo Psicológico:**

Distinción importante:

**Tiempo de Reloj** (funcional):
- "Mi cita es a las 3pm"
- "El proyecto se entrega el viernes"
- Necesario para funcionar en el mundo

**Tiempo Psicológico** (disfuncional):
- "Necesito más tiempo para ser feliz"
- "Cuando logre X, entonces..."
- "Si solo hubiera tenido más tiempo..."

**El Problema:**

El tiempo psicológico crea la ilusión de que:
- No eres suficiente AHORA
- La vida real está en otro momento
- El presente es solo un medio para un fin futuro

**La Espera:**

Una de las estrategias favoritas de la mente:
- "Esperando el fin de semana"
- "Esperando las vacaciones"
- "Esperando el retiro"

**La Trampa:**

Cuando llega lo que esperabas, la mente inmediatamente empieza a esperar la siguiente cosa.

**La Alternativa:**

Vive este momento plenamente, mientras trabajas hacia objetivos futuros.

