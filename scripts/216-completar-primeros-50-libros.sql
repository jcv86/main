**Estrategias de Crecimiento:**
- **Surfear olas:** Aprovechar tendencias existentes
- **Crear demanda:** Generar nuevas necesidades
- **Expandir mercado:** Hacer productos accesibles a más personas
- **Capturar valor:** De crecimiento que otros crean

**Ejemplo:** Google aprovechó el crecimiento de internet y creó nuevas formas de capturar valor de la información.

**Diseñando Estrategia:**

**Paso 1: Análisis de Situación**
- **¿Cuál es la situación actual?** Posición competitiva
- **¿Qué está cambiando?** Tendencias y fuerzas
- **¿Dónde están las oportunidades?** Espacios no contestados
- **¿Cuáles son nuestras fortalezas?** Recursos y capacidades únicos

**Paso 2: Identificación de Desafíos**
- **¿Cuál es el obstáculo principal?** Que impide el éxito
- **¿Por qué existe este obstáculo?** Causas raíz
- **¿Qué lo hace difícil de superar?** Complejidades específicas
- **¿Cómo otros han fallado?** Lecciones de intentos anteriores

**Paso 3: Desarrollo de Política**
- **¿Cuál es nuestro enfoque único?** Para superar el obstáculo
- **¿Cómo es diferente?** De lo que otros están haciendo
- **¿Por qué funcionará?** Lógica detrás del enfoque
- **¿Qué sacrificaremos?** Trade-offs necesarios

**Paso 4: Coordinación de Acciones**
- **¿Qué acciones específicas?** Son necesarias
- **¿Cómo se refuerzan mutuamente?** Sinergia entre acciones
- **¿Cuál es la secuencia?** Orden de implementación
- **¿Cómo mediremos progreso?** Métricas de éxito

**Implementando Estrategia:**

**Comunicación Clara:**
- **Explica el diagnóstico:** Por qué este desafío es crítico
- **Articula la política:** Cómo abordaremos el desafío
- **Detalla las acciones:** Qué hará cada persona/área
- **Conecta los puntos:** Cómo todo trabaja junto

**Alineación Organizacional:**
- **Estructura:** Organización que soporte la estrategia
- **Sistemas:** Procesos que refuercen la estrategia
- **Incentivos:** Recompensas alineadas con estrategia
- **Cultura:** Valores que apoyen la estrategia

**Monitoreo y Ajuste:**
- **Métricas clave:** Indicadores de progreso estratégico
- **Revisiones regulares:** Evaluación de efectividad
- **Flexibilidad:** Capacidad de ajustar cuando sea necesario
- **Aprendizaje:** Incorporar lecciones en refinamientos

**Errores Comunes en Implementación:**

**Falta de Compromiso:**
- **Liderazgo dividido:** No todos los líderes apoyan la estrategia
- **Recursos insuficientes:** No se asignan recursos necesarios
- **Competencia interna:** Diferentes áreas persiguen objetivos conflictivos

**Comunicación Pobre:**
- **Mensaje confuso:** La estrategia no se entiende claramente
- **Falta de contexto:** Las personas no entienden el "por qué"
- **Comunicación unidireccional:** No hay feedback o diálogo

**Falta de Disciplina:**
- **Distracciones:** Perseguir oportunidades que no apoyan la estrategia
- **Impaciencia:** Cambiar estrategia antes de darle tiempo de funcionar
- **Falta de seguimiento:** No monitorear progreso consistentemente

