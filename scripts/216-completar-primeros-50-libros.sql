**Necesidades Implícitas vs. Explícitas**

**Necesidades Implícitas:**
- **Problemas reconocidos:** Pero sin urgencia para resolver
- **Insatisfacciones menores:** Que no motivan acción
- **Quejas generales:** Sin compromiso de cambio
- **Ejemplo:** "Nuestro sistema es un poco lento"

**Necesidades Explícitas:**
- **Deseo claro:** De solución o mejora
- **Urgencia:** Para resolver el problema
- **Compromiso:** Para tomar acción
- **Ejemplo:** "Necesitamos un sistema más rápido para mejorar la productividad"

**Cómo Convertir Necesidades Implícitas en Explícitas:**
1. **Usa preguntas de problema:** Para revelar insatisfacciones
2. **Aplica preguntas de implicación:** Para amplificar el dolor
