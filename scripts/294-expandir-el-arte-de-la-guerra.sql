Por Sun Tzu

INTRODUCCIÓN

El Arte de la Guerra es un antiguo tratado militar chino escrito durante el período de los Estados Combatientes. Su autor, Sun Tzu, fue un estratega militar, general y filósofo que vivió en el antiguo Reino de Wu.

Aunque tiene más de 2,500 años de antigüedad, sus enseñanzas permanecen tan relevantes hoy como lo fueron entonces. Los principios se aplican no solo a la guerra sino a los negocios, el deporte, las relaciones y la vida diaria.

CAPÍTULO 1: HACER PLANES

Sun Tzu dijo: El arte de la guerra es de vital importancia para el Estado. Es una cuestión de vida o muerte, un camino hacia la seguridad o la ruina. Por lo tanto, es un tema de investigación que de ninguna manera puede ser descuidado.

El arte de la guerra, por lo tanto, está gobernado por cinco factores constantes, que deben ser tomados en cuenta:

1. EL CAMINO MORAL: Hace que el pueblo esté en completa armonía con su gobernante, de modo que le seguirán sin importar sus vidas, sin desconfiar de ningún peligro.

2. EL CIELO: Significa noche y día, frío y calor, tiempos y estaciones.

3. LA TIERRA: Comprende distancias, grandes y pequeñas; peligro y seguridad; campo abierto y paso estrecho; las posibilidades de vida y muerte.

4. EL COMANDANTE: Representa las virtudes de sabiduría, sinceridad, benevolencia, coraje y estrictez.

5. MÉTODO Y DISCIPLINA: La organización correcta de rangos, las regulaciones adecuadas, el control de gastos militares.

Estos cinco encabezados deben ser familiares para cada general. Quien los conoce será victorioso; quien no los conoce fracasará.

CÁLCULOS

Por lo tanto, al hacer tus planes, compara los siguientes elementos:
- ¿Qué gobernante posee el Camino Moral?
- ¿Qué comandante es el más capaz?
- ¿Con quién están las ventajas del Cielo y la Tierra?
- ¿De qué lado está la disciplina más rigurosamente aplicada?
- ¿Qué ejército es más fuerte?
- ¿Qué lado tiene oficiales y hombres mejor entrenados?
- ¿En qué ejército hay mayor constancia en recompensa y castigo?

Por estos siete elementos, puedo pronosticar victoria o derrota.

EL ENGAÑO EN LA GUERRA

Todo arte de guerra se basa en el engaño. Por lo tanto, cuando seas capaz de atacar, debes parecer incapaz; cuando estés usando tus fuerzas, debes parecer inactivo; cuando estés cerca, debes hacer que el enemigo crea que estás lejos; cuando estés lejos, debes hacerle creer que estás cerca.

Ofrece al enemigo un cebo para atraerlo; finge desorden y aplástalo. Si es seguro, prepárate para él; si es fuerte, evítalo. Si está iracundo, irrita; finge debilidad, que se vuelva arrogante.

Si está descansando, no le des descanso. Si sus fuerzas están unidas, sepáralas. Ataca donde no esté preparado, aparece donde no te esperes.

Estas maniobras militares, que llevan a la victoria, no deben ser divulgadas de antemano.

CAPÍTULO 2: LIBRAR LA GUERRA

Sun Tzu dijo: En las operaciones de guerra, donde hay en el campo mil carros veloces, mil carros pesados y cien mil soldados con armadura, con provisiones suficientes para llevarlos mil millas, los gastos en casa y en el frente serán enormes.

Cuando involucres al enemigo en batalla prolongada, tus armas se embotan y tu ardor se enfría. Cuando saqueas tus fuerzas y energías, tus provisiones se agotan. Entonces los jefes aprovechadores de los estados vecinos aprovechan tu adversidad para atacar.

No hay instancia de un país que se haya beneficiado de una guerra prolongada. Por lo tanto, aquellos que no están completamente familiarizados con el mal de la guerra no pueden estar completamente familiarizados con su ventaja.

El general hábil no requiere un segundo reclutamiento, ni un tercero transporte de provisiones. Él lleva su equipo desde casa, pero confiscaba forraje del enemigo. Así el ejército tiene comida suficiente para sus necesidades.

CAPÍTULO 3: ATAQUE POR ESTRATAGEMA

Sun Tzu dijo: En el arte práctico de la guerra, la mejor cosa de todas es tomar el país del enemigo entero e intacto; destrozarlo y destruirlo no es tan bueno.

Capturar su ejército es mejor que destruirlo; tomar intacta una brigada, regimiento o compañía es mejor que destruirlos.

Por lo tanto, cien victorias en cien batallas no es el colmo de la habilidad. Someter al enemigo sin luchar es el colmo de la habilidad.

La regla es, no atacar directamente fortalezas amuralladas. El ataque de ciudades es solo un asunto de necesidad. Prepara tus máquinas de asedio meses. El general, incapaz de controlar su irritación, ordenará a sus hombres trepar como hormigas, con el resultado de que un tercio será sacrificado sin tomar la ciudad. Tales son los efectos desastrosos de un asedio.

Por lo tanto, el hábil líder somete las tropas enemigas sin luchar; captura sus ciudades sin asediarlas; derroca su reino sin operaciones de campo prolongadas.

Así, la regla para el uso de las fuerzas es la siguiente:
- Si nuestras fuerzas son diez al lado del enemigo, rodéalo
- Si cinco a uno, atácalo
- Si doble, divídelo
- Si igualmente emparejado, puedes comprometerte con él
- Si más débil numéricamente, sé capaz de retirarte
- Si superado en cada sentido, sé capaz de evadir

EL GENERAL

Hay tres maneras en las que un gobernante puede traer desgracia sobre su ejército:

1. Al ordenar un avance cuando es imposible avanzar
2. Al ordenar una retirada cuando es imposible retirarse
3. Al manejar el ejército con ignorancia de los asuntos militares

Hay cinco cualidades peligrosas que pueden afectar a un general:
- Imprudencia, que lleva a la destrucción
- Cobardía, que lleva a la captura
- Temperamento precipitado, que puede ser provocado por insultos
- Delicadeza de honor, sensible a la vergüenza
- Excesiva solicitud por sus hombres, que lo expone a la preocupación

CAPÍTULO 4: DISPOSICIONES TÁCTICAS

Sun Tzu dijo: Los buenos luchadores de antaño primero se ponían más allá de la posibilidad de derrota, y luego esperaban una oportunidad de derrotar al enemigo.

Asegurarse contra la derrota radica en nuestras propias manos, pero la oportunidad de derrotar al enemigo es proporcionada por el enemigo mismo.

Por lo tanto, el buen luchador es capaz de asegurarse contra la derrota, pero no puede asegurarse de derrotar al enemigo.

Por lo tanto, se ha dicho, uno puede CONOCER cómo conquistar sin ser necesariamente capaz de hacerlo.

Seguridad contra la derrota implica tácticas defensivas; capacidad de derrotar al enemigo significa tomar la ofensiva.

Pararse a la defensiva indica fuerza insuficiente; atacar, una superabundancia de fuerza.

El general experto en defensa se esconde en los lugares más secretos de la tierra; el experto en ataque parpadea desde las alturas más elevadas del cielo. Así, por un lado, tenemos capacidad de protegernos; por el otro, una victoria que es completa.

VICTORIA

Ver la victoria solo cuando está al alcance del sentido común no es el colmo de la excelencia. Ni es el colmo de la excelencia si luchas y conquistas y toda la Tierra dice: "¡Bien hecho!"

Levantar una pluma de otoño no es signo de gran fuerza; ver el sol y la luna no es signo de vista aguda; escuchar el ruido del trueno no es signo de oído rápido.

Lo que los antiguos llamaban un luchador inteligente es uno que no solo gana, sino que sobresale en ganar con facilidad. Sus victorias no traen fama por sabiduría ni crédito por coraje.

Gana sus batallas sin cometer errores. Sin cometer errores es lo que establece la certeza de victoria, porque significa conquistar a un enemigo que ya está derrotado.

CAPÍTULO 5: ENERGÍA

Sun Tzu dijo: El control de una fuerza grande es el mismo en principio que el control de unos pocos hombres: es meramente una cuestión de dividir sus números.

Luchar con un ejército grande bajo tu mando no es diferente de luchar con uno pequeño: es meramente una cuestión de instituir signos y señales.

La energía puede ser comparada con el doblado de una ballesta; la decisión, con la soltada del gatillo.

En medio de la confusión de la batalla, puede haber desorden aparente pero sin desorden real; en medio del caos, tu formación puede estar sin cabeza o cola, pero será prueba contra la derrota.

El desorden simulado postula disciplina perfecta; el miedo simulado postula coraje; la debilidad simulada postula fuerza.

La calidad de decisión es como el ataque bien cronometrado de un halcón que le permite golpear y destruir a su víctima.

El general inteligente busca el efecto a partir de energía combinada, y no requiere demasiado de individuos. Por lo tanto, su capacidad es seleccionar a los hombres correctos y utilizar energía combinada.

CAPÍTULO 6: PUNTOS DÉBILES Y FUERTES

Sun Tzu dijo: Quien primero está en el campo de batalla y aguarda la llegada del enemigo, estará fresco para la lucha; quien es el segundo en el campo y tiene que apresurarse a la batalla llegará exhausto.

Por lo tanto, el luchador inteligente impone su voluntad sobre el enemigo, pero no permite que la voluntad del enemigo le sea impuesta.

Puedes prevenir que el enemigo llegue fácilmente al campo de batalla, ofreciéndole dificultades u ofreciéndole señuelos.

Por lo tanto, el general experto ataca al enemigo como el agua moldea su curso según la naturaleza del suelo. De la misma manera, en guerra, la forma nunca es fija; el que puede modificar sus tácticas en relación con su oponente y así tener éxito en ganar, puede ser llamado un capitán enviado por el cielo.

Los cinco elementos (agua, fuego, madera, metal, tierra) no son siempre igualmente predominantes; las cuatro estaciones hacen camino el uno para el otro. Hay días cortos y largos; la luna tiene sus períodos de mengua y crecimiento.

CAPÍTULO 7: MANIOBRA

Sun Tzu dijo: En la guerra, el general recibe sus órdenes del soberano. Habiendo reunido un ejército y concentrado sus fuerzas, debe mezclar y armonizar los diferentes elementos antes de lanzar su campamento.

Después de eso, viene maniobra táctica, que no tiene nada más difícil. La dificultad de la maniobra táctica consiste en convertir lo tortuoso en directo, y la desgracia en ganancia.

Por lo tanto, recorre una ruta indirecta, y distrae al enemigo cebándolo. El resultado es que aunque empiezas después de él, llegas antes que él.

Maniobrar con un ejército es ventajoso; con una multitud indisciplinada, más peligroso. Si estableces un ejército totalmente equipado para marchar para ganar una ventaja, las posibilidades son que llegarás demasiado tarde.

CAPÍTULO 8: VARIACIÓN EN TÁCTICA

Sun Tzu dijo: En la guerra, el general recibe sus órdenes del soberano, reúne su ejército y concentra sus fuerzas.

Cuando en terreno difícil, no acampes. En el país donde las carreteras altas se intersecan, únete con tus aliados. No te quedes en terreno peligrosamente aislado.

En posiciones cerradas, debes recurrir a la estratagema. En posiciones desesperadas, debes luchar.

Hay caminos que no deben ser seguidos, ejércitos que no deben ser atacados, ciudades que no deben ser sitiadas, posiciones que no deben ser disputadas, órdenes del soberano que no deben ser obedecidas.

El general que comprende completamente las ventajas que acompañan la variación de táctica sabe cómo manejar sus tropas.

CAPÍTULO 9: EL EJÉRCITO EN MARCHA

Sun Tzu dijo: Establecimos nuestro campamento, observemos al enemigo. Pasa rápidamente las montañas, y mantente cerca de valles. Acampa en terreno alto, enfrentando el sol.

Cuando cruzas un río, debes alejarte de él. No te encuentres con un enemigo que avanza corriente arriba. Déjalo cruzar a mitad de camino y luego ataca con ventaja.

Si deseas luchar, no vayas a encontrar al enemigo cerca de un río. Establécete en terreno alto, enfrentando el sol. No te muevas corriente arriba para encontrar al enemigo.

Después de cruzar terreno pantanoso, tu único pensamiento debe ser alejarte de él lo más rápido posible. Si obligado a luchar en un pantano, debes mantenerte cerca de pastos de agua y tener árboles a tus espaldas.

En terreno seco plano, toma una posición con terreno elevado a tu derecha y en tu retaguardia, para que el peligro esté al frente y la seguridad detrás.

Estas son las cuatro situaciones útiles en guerra: terreno montañoso, terreno de ríos, pantanos y terreno plano.

Cuando el enemigo está cerca pero permanece quieto, está dependiendo de la fuerza natural de su posición.

Cuando mantiene distancia pero trata de provocar una batalla, está ansioso de que el otro lado avance.

Si su lugar de campamento es fácilmente accesible, está tentándote con una ventaja.

CAPÍTULO 10: TERRENO

Sun Tzu dijo: Podemos distinguir seis tipos de terreno:
1. Terreno accesible
2. Terreno enredado
3. Terreno temporalizador
4. Pasos estrechos
5. Alturas precipitadas
6. Posiciones a gran distancia del enemigo

Terreno que puede ser libremente atravesado por ambos lados se llama accesible. Con respecto al terreno de este tipo, sé el primero en ocupar los lugares altos soleados.

Terreno que puede ser abandonado pero es difícil de reocupar se llama enredado. Desde una posición de este tipo, si el enemigo está desprevenido, puedes salir y derrotarlo; pero si el enemigo está en guardia, tu salida será infructuosa.

Con respecto al terreno temporalizador: si el enemigo es el primero en ocuparlo, no lo sigas; llévatelo alejándote.

El pasaje estrecho es aquel donde solo puedes proceder en archivo simple. Si primero ocupas tal pasaje, debes guarnecerlo fuertemente y esperar al enemigo.

Si el enemigo lo ocupa antes que tú, no lo sigas si está fuertemente guarnecido, pero solo si está débilmente guarnecido.

Con respecto a alturas precipitadas, si estás de antemano en tu oponente, debes ocupar los lugares elevados y soleados, y allí esperar que él suba.

Si el enemigo te ha precedido, no lo sigas; en su lugar, aléjate y trata de atraerlo.

Si estás situado a gran distancia del enemigo, y la fuerza de los dos ejércitos es igual, no es fácil provocar una batalla, y luchar no será a tu ventaja.

Estas son las seis clases de terreno. El general que ha llegado al poder no puede permitirse ignorarlas.

CAPÍTULO 11: LAS NUEVE SITUACIONES

Sun Tzu dijo: El arte de la guerra reconoce nueve variedades de terreno:
1. Terreno dispersivo
2. Terreno ligero
3. Terreno contencioso
4. Terreno abierto
5. Terreno de carreteras que se cruzan
6. Terreno serio
7. Terreno difícil
8. Terreno cerrado
9. Terreno desesperado

Cuando un jefe lucha en su propio territorio, es terreno dispersivo. Cuando ha penetrado en territorio hostil, pero a no gran distancia, es terreno ligero.

Terreno cuya posesión importa grandemente a ambos lados es terreno contencioso.

Terreno sobre el cual cada lado tiene libertad de movimiento es terreno abierto.

Terreno que forma la clave de tres Estados contiguos es terreno de carreteras que se cruzan.

Cuando un ejército ha penetrado en el corazón de un país hostil, dejando un número de ciudades fortificadas en su retaguardia, es terreno serio.

Bosques montañosos, senderos accidentados, pantanos y diques: todas las formaciones de terreno difícil de atravesar, esto es terreno difícil.

Terreno que es alcanzado a través de pasos defiles estrechos, y del que solo podemos retirarnos por caminos tortuosos, de modo que un pequeño número del enemigo bastaría para aplastarnos: esto es terreno cerrado.

Terreno sobre el cual solo podemos salvarnos de la destrucción luchando sin demora, es terreno desesperado.

Por lo tanto, no luches en terreno dispersivo; no pares en terreno ligero; no ataques en terreno contencioso; no permitas que tus fuerzas de comunicación sean bloqueadas en terreno abierto; forma alianzas con tus vecinos en terreno de carreteras que se cruzan; saquea el país en terreno serio; apúrate en terreno difícil; recurre a la estratagema en terreno cerrado; lucha en terreno desesperado.

CAPÍTULO 12: EL ATAQUE POR FUEGO

Sun Tzu dijo: Hay cinco maneras de atacar con fuego:
1. Quemar soldados en su campamento
2. Quemar provisiones
3. Quemar convoyes
4. Quemar arsenales y revistas
5. Hurling dropping fire entre las filas enemigas

Para llevar a cabo un ataque, debemos tener medios disponibles. El material para levantar fuego siempre debe estar a mano.

Hay una temporada apropiada para hacer ataques con fuego, y días especiales para comenzar una conflagración.

La temporada apropiada es cuando el clima está muy seco; los días especiales son aquellos cuando la luna está en las constelaciones de la Canasta, la Pared, el Ala o la Cruz-barra; estos cuatro son todos días de viento creciente.

En atacar con fuego, uno debe estar preparado para hacer frente a cinco posibles desarrollos:

Cuando el fuego estalla dentro del campamento enemigo, responde de inmediato con un ataque desde afuera.

Si hay un estallido de fuego, pero los soldados enemigos permanecen tranquilos, espera y no ataques.

Cuando la fuerza de las llamas ha alcanzado su altura, sigue con un ataque, si es practicable; si no, permanece donde estás.

Si es posible hacer un asalto con fuego desde afuera, no esperes un estallido de fuego dentro, sino lánzate en el momento propicio.

Cuando enciendes fuego, sé a sotavento de él. No ataques desde el lado de sotavento.

Un viento que se levanta de día dura largo, pero uno nocturno pronto cae.

En toda lucha, los diferentes medios de hacer daño al enemigo deben ser conocidos. Un comandante debe actuar prudentemente.

El uso iluminado de un ejército se basa en una estimación de las ventajas a obtener. Un gobernante sabio no debe levantar un ejército porque está enfadado; un comandante prudente no debe provocar una guerra porque está resentido.

Muévete solo si ves una ventaja; usa tus tropas solo si hay algo que ganar. Si no es a tu ventaja, no actúes; si no puedes tener éxito, no uses tropas; si no estás en peligro, no luches.

Un reino que una vez ha sido destruido nunca puede volver a existir; ni pueden los muertos ser traídos de vuelta a la vida.

Por lo tanto, el general iluminado es heedful, y el buen general cauteloso. Esta es la manera de mantener un país en paz y un ejército intacto.

CAPÍTULO 13: EL USO DE ESPÍAS

Sun Tzu dijo: Levantar una hueste de cien mil hombres y marcharlos gran distancia conlleva gastos pesados al pueblo y un drenaje en los recursos del Estado.

Hostilidades prolongadas conducen al agotamiento de recursos y el empobrecimiento del pueblo. La sabiduría del general preparado está en no confiar en lo que es posible que el enemigo no venga, sino en su propia preparación para recibirlo; no en la posibilidad de que no ataque, sino más bien en el hecho de que él ha hecho su posición inexpugnable.

Hay cinco clases de espías a emplear:
1. Espías locales
2. Espías internos
3. Espías convertidos
4. Espías condenados
5. Espías supervivientes

Espías locales son habitantes del distrito, empleados en tu servicio. Espías internos son funcionarios enemigos que son sobornados. Espías convertidos son espías enemigos que hemos subvertido. Espías condenados son nuestros espías que deliberadamente han hecho comunicaciones falsas al enemigo. Espías supervivientes son aquellos que traen noticias del campamento enemigo.

Por lo tanto, tu ejército entero no debe ser nadie más íntimamente conectado que los espías. Deben ser recompensados liberalmente. En ningún otro asunto mayor secreto debe ser preservado.

La inteligencia divina es la facultad de aprovechar información secreta. El soberano debe tener conocimiento completo de las actividades de los cinco tipos de espías.

Y este conocimiento debe venir a través del espía doble. Por lo tanto, es esencial que el espía doble sea tratado con la máxima liberalidad.

