**1. El Sentido es Posible Siempre:**
Incluso en las peores circunstancias, podemos encontrar sentido.

**2. La Libertad Interior es Inviolable:**
Nadie puede quitarte la libertad de elegir tu actitud.

**3. El Sufrimiento Puede Transformarse:**
El sufrimiento inevitable puede convertirse en logro humano.

