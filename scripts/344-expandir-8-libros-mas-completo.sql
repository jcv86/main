## Capítulo 4: Política de Cartera General

**La Regla 50-50:**

Para el inversor defensivo, mantén aproximadamente 50 por ciento en acciones y 50 por ciento en bonos.

**Variaciones Aceptables:**

Puedes variar de 25-75 por ciento basándote en:
- Valoraciones del mercado
- Oportunidades disponibles
- Tu edad y situación

**Cuando el Mercado Está Alto:**

Muévete hacia 25 por ciento acciones, 75 por ciento bonos.

**Cuando el Mercado Está Bajo:**

Muévete hacia 75 por ciento acciones, 25 por ciento bonos.

**Nunca:**

- Nunca 100 por ciento acciones
- Nunca 100 por ciento bonos
- Nunca uses margen (dinero prestado)
- Nunca intentes cronometrar el mercado perfecto

## Capítulo 5: El Inversor Defensivo y las Acciones Comunes

**Reglas para Seleccionar Acciones:**

### 1. Diversificación Adecuada

Mínimo 10 acciones, máximo 30. Muy pocas es arriesgado, demasiadas es inmanejable.

### 2. Empresas Grandes y Prominentes

Elige empresas establecidas con historial largo.

### 3. Historial de Dividendos Largo

Al menos 20 años de pagos de dividendos continuos.

### 4. Límite en el Precio-Ganancias

No pagues más de 25 veces las ganancias promedio de los últimos 7 años.

### 5. Finanzas Sólidas

Activos corrientes al menos el doble de pasivos corrientes. Deuda a largo plazo no mayor que el capital de trabajo neto.

### 6. Crecimiento de Ganancias

Algún crecimiento en las ganancias por acción en los últimos 10 años.

### 7. Precio Razonable en Relación al Valor en Libros

No pagar más de 1.5 veces el valor en libros.

**Por Qué Estas Reglas:**

Estas reglas filtran:
- Empresas especulativas
- Empresas con finanzas débiles
- Acciones sobrevaloradas
- Empresas sin historial

## Capítulo 6: El Inversor Empresarial

**Quién es el Inversor Empresarial:**

Alguien que:
- Tiene tiempo para dedicar al análisis
- Tiene conocimiento equivalente a un profesional
- Busca activamente oportunidades
- Puede actuar con independencia

**Operaciones para el Inversor Empresarial:**

### 1. Compra en Mercados Bajistas

Cuando el pesimismo es extremo, los precios son atractivos.

**Señales de Mercado Bajista:**
- Noticias consistentemente negativas
- Inversionistas huyendo de acciones
- Valoraciones muy por debajo de promedios históricos

### 2. Crecimiento Cuidadosamente Seleccionado

Identificar empresas con:
- Ventajas competitivas duraderas
- Gestión excelente
- Finanzas sólidas
- Precios razonables

**Advertencia:** La mayoría de las acciones de crecimiento están sobrevaloradas.

### 3. Situaciones Especiales

- Reorganizaciones
- Fusiones y adquisiciones
- Liquidaciones
- Acciones infravaloradas por razones técnicas

### 4. Compras por Debajo del Valor Neto de Activos

Empresas que cotizan por debajo de su valor liquidativo. Estas son raras pero ofrecen excelente margen de seguridad.

## Capítulo 7: Política de Cartera para el Inversor Empresarial

**Principio de Margen de Seguridad:**

Compra solo cuando el precio está significativamente por debajo del valor intrínseco.

**Cálculo del Valor Intrínseco:**

1. **Valor de Ganancias:** Ganancias x múltiplo apropiado
2. **Valor de Activos:** Activos menos pasivos
3. **Valor de Dividendos:** Dividendos capitalizados a tasa conservadora

Usa el más bajo de estos tres como tu valor base.

**Margen de Seguridad:**

Compra solo a 33 por ciento o más de descuento del valor intrínseco.

**Ejemplo:**

Valor intrínseco: 100 dólares por acción
Precio máximo de compra: 67 dólares por acción

Este margen protege contra:
- Errores en tu análisis
- Mala suerte
- Deterioro del negocio

## Capítulo 8: El Inversor y las Fluctuaciones del Mercado

**El Sr. Mercado:**

Imagina que eres socio en un negocio privado con el Sr. Mercado.

Cada día, el Sr. Mercado te dice a qué precio compraría tu participación o te vendería más.

**Características del Sr. Mercado:**
- Extremadamente emocional
- A veces eufórico (precios altos)
- A veces deprimido (precios bajos)
- No tiene memoria de precios previos

**Tu Ventaja:**

Puedes:
- Ignorar al Sr. Mercado completamente
- Comprarle cuando está deprimido
- Venderle cuando está eufórico
- O simplemente mantener tu inversión

**Lo que NO Debes Hacer:**

Nunca dejes que el Sr. Mercado te diga el valor de tu inversión. Analiza el negocio subyacente.

**Volatilidad vs Riesgo:**

**Wall Street dice:** La volatilidad es riesgo.

**Graham dice:** El riesgo real es la pérdida permanente de capital.

Una acción puede ser volátil pero no arriesgada si:
- El negocio es sólido
- Compras a precio bajo
- Puedes mantener a largo plazo

