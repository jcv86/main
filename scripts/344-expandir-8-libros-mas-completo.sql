## Capítulo 19: Accionistas y Gestión

**Relaciones entre Accionistas y Gestión:**

**Problema:**
La gestión controla la empresa pero los accionistas son los propietarios.

**Conflictos Comunes:**

1. **Compensación Excesiva:** Paquetes de pago desalineados con el rendimiento.

2. **Opciones sobre Acciones:** Diluyen a los accionistas existentes.

3. **Fusiones y Adquisiciones:** A menudo benefician a la gestión más que a los accionistas.

4. **Dividendos:** Gestión prefiere retener efectivo; accionistas a menudo prefieren dividendos.

**Qué Pueden Hacer los Accionistas:**

1. Votar en juntas
2. Presentar propuestas de accionistas
3. Comunicarse con otros accionistas
4. En casos extremos, luchar por cambio de control

## Capítulo 20: Margen de Seguridad

**El Concepto Central:**

El margen de seguridad es la diferencia entre el precio pagado y el valor intrínseco estimado.

**Por Qué Es Esencial:**

1. **Protege contra errores:** Tu análisis puede estar equivocado.

2. **Protege contra mala suerte:** Eventos impredecibles ocurren.

3. **Permite beneficiarse de sorpresas positivas:** Si el negocio mejora, ganas más.

**Tamaño del Margen:**

- **Mínimo:** 33 por ciento de descuento
- **Preferible:** 50 por ciento o más de descuento

**Ejemplos:**

**Insuficiente Margen:**
Valor intrínseco: 100 dólares
Precio: 95 dólares
Margen: Solo 5 por ciento - demasiado pequeño

**Margen Adecuado:**
Valor intrínseco: 100 dólares
Precio: 66 dólares
Margen: 34 por ciento - aceptable

**Excelente Margen:**
Valor intrínseco: 100 dólares
Precio: 50 dólares
Margen: 50 por ciento - ideal

