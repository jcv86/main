## Introducción: La Pregunta

Puede una buena empresa convertirse en una gran empresa y, de ser así, cómo.

Durante cinco años, Jim Collins y su equipo de investigación estudiaron empresas que hicieron el salto de buenas a grandiosas, sosteniendo ese rendimiento durante al menos 15 años.

