## Capítulo 11: Análisis de Valores para el Inversor Lego

**Análisis Fundamental Básico:**

### 1. Rentabilidad

**ROE (Return on Equity):**
Ganancias netas dividido por patrimonio.

Busca: Consistentemente por encima de 15 por ciento.

**Margen de Ganancia:**
Ganancias netas dividido por ventas.

Busca: Estable o creciente, competitivo en la industria.

### 2. Estabilidad

**Coeficiente de Ganancias:**
Varianza en las ganancias año a año.

Busca: Baja variación, crecimiento constante.

### 3. Crecimiento

**Crecimiento de Ganancias por Acción:**
Tasa de crecimiento en los últimos 7-10 años.

Busca: Crecimiento moderado y sostenible (7-10 por ciento anual).

**Advertencia:** Crecimiento muy rápido raramente es sostenible.

### 4. Finanzas

**Ratio Corriente:**
Activos corrientes dividido por pasivos corrientes.

Busca: Al menos 2:1.

**Deuda a Patrimonio:**
Deuda total dividido por patrimonio.

Busca: Menos de 1:1 para empresas industriales.

### 5. Dividendos

**Historial de Dividendos:**
Años consecutivos de pagos.

Busca: Al menos 20 años.

**Ratio de Pago:**
Dividendos dividido por ganancias.

Busca: Entre 40-60 por ciento.

## Capítulo 12: Consideraciones sobre las Ganancias por Acción

**Calidad de las Ganancias:**

No todas las ganancias son iguales.

**Banderas Rojas:**

### 1. Ganancias No Recurrentes

Ventas de activos, ganancias de una sola vez. Excluye estos del análisis.

### 2. Cambios en Métodos Contables

Si una empresa cambia frecuentemente cómo reporta, desconfía.

### 3. Opciones sobre Acciones Excesivas

Diluyen a los accionistas existentes.

### 4. Gastos Capitalizados vs Gastos Operativos

Algunas empresas capitalizan costos que deberían ser gastos, inflando ganancias.

**Ganancias Ajustadas:**

Siempre mira las ganancias GAAP reales, no las ganancias pro forma o ajustadas que excluyen gastos reales.

