Opciones para comprar acciones a precio fijo.

**Advertencia:**
Altamente especulativos. La mayoría expiran sin valor.

**Recomendación de Graham:**
El inversor defensivo debe evitar ambos. El inversor empresarial debe ser extremadamente selectivo.

