Adoptaron tecnología sin comprensión de cómo encaja.

**Ejemplo:**

Muchas empresas de comparación saltaron a internet sin entender cómo aceleraba su concepto del erizo (porque no tenían uno claro).

**Principio:**

Cuando se usa correctamente, la tecnología se convierte en un acelerador de momentum, no un creador de momentum.

