## Capítulo 1: Bueno es Enemigo de lo Grandioso

**Por Qué Pocas Empresas Son Grandes:**

La mayoría de las organizaciones no se vuelven grandiosas porque es más fácil ser simplemente buenas. Y eso es un problema, porque pocas personas tienen vidas grandiosas en gran parte porque es muy fácil conformarse con una buena vida.

**El Estudio:**

- 1,435 empresas examinadas inicialmente
- 11 empresas que hicieron el salto
- 6 empresas de comparación directa
- Análisis de más de 6,000 artículos
- Entrevistas con ejecutivos clave

**Hallazgos Sorprendentes:**

### 1. Los Grandes Líderes No Eran Carismáticos

Esperábamos encontrar CEOs carismáticos y de alto perfil. Encontramos líderes humildes que canalizaban la ambición hacia la empresa, no hacia ellos mismos.

### 2. No Comenzaron con Estrategia

No comenzaron con una estrategia brillante. Primero consiguieron a las personas correctas en el autobús.

### 3. No Estaban en Industrias Glamurosas

Gillette (navajas), Walgreens (farmacias), Pitney Bowes (máquinas de correo). Industrias aburridas pueden generar resultados extraordinarios.

### 4. La Tecnología No Era el Motor

La tecnología acelera el impulso, pero nunca lo crea. Las empresas que sobresalen primero se enfocaron en lo que podían ser mejores, luego aplicaron tecnología.

