## CAPÍTULO 2: LA ANATOMÍA DE LA CONCIENCIA

### Cómo Funciona la Atención

La conciencia es información que podemos usar para decidir cómo actuar. La atención es la energía psíquica que procesa esa información.

**Límites de la Atención:**
- Solo podemos procesar aproximadamente 126 bits de información por segundo
- Una conversación requiere aproximadamente 60 bits por segundo
- Por eso no puedes entender a dos personas hablando simultáneamente

**Implicación:** Lo que decides atender literalmente crea tu realidad.

### El Yo y la Entropía Psíquica

**Entropía Psíquica:** Estado de desorden interno cuando la información que entra en la conciencia está en conflicto con metas existentes.

**Ejemplos:**
- Quieres trabajar pero estás preocupado por problemas personales
- Intentas concentrarte pero estás ansioso por el futuro
- Quieres disfrutar el momento pero estás pensando en el pasado

**Flow es lo opuesto:** Orden en la conciencia. Toda tu energía psíquica está enfocada en una meta.

