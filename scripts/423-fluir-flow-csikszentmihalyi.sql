## CAPÍTULO 1: LA FELICIDAD REVISADA

### El Problema de la Felicidad

La mayoría de las personas creen que la felicidad viene de circunstancias externas: dinero, fama, placer. Pero la investigación muestra que la felicidad depende más de cómo interpretamos los eventos que de los eventos mismos.

**Paradoja del Progreso:**
- Tenemos más comodidades que nunca
- Pero no somos más felices
- La depresión y ansiedad aumentan

### La Solución: Experiencia Óptima

La felicidad no es algo que sucede. No es el resultado de la buena fortuna o el azar. No es algo que el dinero pueda comprar o el poder comandar. La felicidad es una condición que debe ser preparada, cultivada y defendida por cada persona.

**Flow es la clave:** Cuando estamos en flow, no hay espacio para preocupaciones o aburrimiento.

