## INTRODUCCIÓN

**Flow** es el estado mental en el que una persona está completamente inmersa en una actividad. Es la experiencia óptima donde el tiempo parece detenerse y todo fluye naturalmente.

**Características del Flow:**
- Concentración intensa en el presente
- Fusión entre acción y conciencia
- Pérdida de autoconciencia reflexiva
- Sensación de control sobre la actividad
- Distorsión de la experiencia temporal
- La actividad se vuelve autotélica (vale por sí misma)

