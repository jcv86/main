INTRODUCCION

El Elemento es el punto de encuentro entre las aptitudes naturales y las inclinaciones personales.

Cuando estas en tu Elemento:
- El tiempo pasa diferente
- Estas mas vivo, mas centrado, mas ti mismo que en cualquier otro momento
- Conectas con algo fundamental para tu sentido de identidad y proposito

Este libro trata sobre descubrir tu Elemento y ayudar a otros a encontrar el suyo.

CAPITULO 1: EL ELEMENTO

Gillian Lynne es una de las coreografas mas exitosas del mundo. Creo Cats y El Fantasma de la Opera.

De nina, la escuela penso que tenia trastorno de aprendizaje. No podia quedarse quieta, se distraia constantemente.

Un especialista observo: Esta nina no esta enferma, es bailarina.

Su madre la llevo a escuela de danza. Gillian dice: Entre en habitacion llena de gente como yo. Gente que no podia quedarse quieta. Gente que tenia que moverse para pensar.

Encontro su Elemento.

QUE ES EL ELEMENTO?

El Elemento tiene dos caracteristicas principales:

1. APTITUD
Las cosas que naturalmente haces bien. Algunos tienen aptitud para matematicas, otros para musica, otros para trabajar con gente.

2. PASION
Las cosas que amas hacer, donde el tiempo vuela.

Cuando estas en tu Elemento, estas haciendo algo para lo que tienes aptitud natural Y que amas hacer.

Dos condiciones adicionales:

3. ACTITUD
Tu percepcion de ti mismo y tus circunstancias.
Las personas que encuentran su Elemento tienen actitud de apertura y voluntad.

4. OPORTUNIDAD
Incluso con aptitud, pasion y actitud correctas, necesitas oportunidad para desarrollar tu Elemento.

CAPITULO 2: PENSAR DE MODO DIFERENTE

La mayoria de sistemas educativos fueron disenados para era industrial. Priorizan:
- Conformidad
- Respuestas correctas unicas
- Pensamiento lineal
- Habilidades academicas especificas

Esto deja fuera a muchas personas brillantes.

PENSAMIENTO DIVERGENTE

Prueba de pensamiento divergente: Cuantos usos puedes pensar para clip?

La mayoria de adultos piensa en 10-15.
Ninos pequenos pueden pensar en cientos.

A medida que avanzamos en sistema educativo, nuestra capacidad de pensamiento divergente disminuye.

No porque seamos menos inteligentes - porque hemos sido entrenados a pensar en terminos de una respuesta correcta.

INTELIGENCIAS MULTIPLES

Howard Gardner identifico ocho tipos de inteligencia:
1. Linguistica
2. Logico-matematica
3. Musical
4. Corporal-cinetica
5. Espacial-visual
6. Interpersonal
7. Intrapersonal
8. Naturalista

Sistema educativo tradicional valora principalmente primeras dos. Esto marginaliza a personas cuyas fortalezas estan en otras areas.

CAPITULO 3: MAS ALLA DE LA IMAGINACION

La imaginacion es fuente de todo logro humano.

IMAGINACION VS CREATIVIDAD

Imaginacion: Capacidad de traer a mente cosas que no estan presentes a nuestros sentidos.

Creatividad: Proceso de tener ideas originales que tienen valor.

Creatividad es imaginacion aplicada.

MITOS SOBRE CREATIVIDAD

Mito 1: Solo ciertas personas son creativas
Realidad: Todos tienen capacidad creativa, pero se manifiesta diferentemente.

Mito 2: Creatividad es solo sobre artes
Realidad: Hay creatividad en ciencia, negocios, matematicas, cocina - todo campo humano.

Mito 3: No puedes ensenar creatividad
Realidad: Puedes crear condiciones donde creatividad florece.

CAPITULO 4: EN LA ZONA

Flow es estado de concentracion intensa donde estas completamente absorto en actividad.

Mihaly Csikszentmihalyi estudio flow por decadas. Caracteristicas:

1. Desafio y habilidad estan en balance
Demasiado facil = aburrimiento
Demasiado dificil = ansiedad
Balance perfecto = flow

2. Metas claras
Sabes exactamente que estas tratando de lograr

3. Retroalimentacion inmediata
Ves resultados de tus acciones directamente

4. Concentracion total
No hay espacio mental para preocupaciones o distracciones

5. Sentido de control
Sientes dominio de situacion

6. Perdida de autoconciencia
No estas pensando sobre ti mismo

7. Distorsion del tiempo
Horas pasan como minutos

8. Experiencia autotélica
Actividad es recompensante en si misma

CAPITULO 5: ENCONTRAR TU TRIBU

Las personas encuentran su Elemento a menudo cuando encuentran su tribu - otras personas que comparten misma pasion.

COMUNIDAD IMPORTA

Meg Ryan descubrio actuacion en escuela secundaria. No solo porque era buena, sino porque encontro comunidad de personas que amaban lo mismo.

George Lucas encontro su tribu en escuela de cine. Antes, se sentia fuera de lugar. En escuela de cine, encontro personas que hablaban su lenguaje.

MENTORES

Los mentores son cruciales para encontrar tu Elemento.

Mick Fleetwood fue descubierto por baterista que lo vio tocando en pub. Le dijo: Tienes algo especial. Sigue con esto.

VALIDACION

A veces solo necesitas que alguien diga: Si, eres bueno en esto. Esto vale la pena.

CAPITULO 6: QUE PENSARAN LOS DEMAS?

El miedo al juicio de otros previene a muchas personas de perseguir su Elemento.

PRESION SOCIAL

Familia, amigos, sociedad tienen expectativas. Estas presiones pueden ser aplastantes.

Paulo Coelho queria ser escritor. Sus padres querian que fuera ingeniero. Lo hospitalizaron en institucion psiquiatrica tres veces porque no conformaba.

Eventualmente persiguio escritura. El Alquimista vendio mas de 65 millones de copias.

MIEDOS COMUNES

1. Miedo al fracaso
Que pasa si no soy suficientemente bueno?

2. Miedo al éxito
Que pasa si mi vida cambia de maneras que no puedo controlar?

3. Miedo al ridiculo
Que diran otros?

4. Miedo al rechazo
Que pasa si mi tribu me rechaza?

SUPERANDO MIEDOS

