CAPITULO 7: TE SIENTES AFORTUNADO?

La suerte juega papel, pero puedes crear condiciones para mas suerte.

TRES TIPOS DE OPORTUNIDAD

1. OPORTUNIDAD ESPERADA
Estructura social, familia, geografia proveen ciertas oportunidades automaticamente.

2. OPORTUNIDAD BUSCADA
Activamente buscas y creas oportunidades.

3. OPORTUNIDAD ACCIDENTAL
Eventos inesperados que cambian trayectoria.

CREANDO SUERTE

Richard Wiseman estudio suerte. Descubrio que personas afortunadas:
- Son mas relajadas y abiertas a oportunidades
- Escuchan su intuicion
- Crean y mantienen redes sociales fuertes
- Adoptan actitud resiliente ante mala suerte

PERSISTENCIA

Muchas personas exitosas enfrentaron rechazo repetido antes de triunfar.

The Beatles fueron rechazados por Decca Records: Grupos de guitarra estan pasando de moda.

J.K. Rowling fue rechazada por 12 editores antes de que Harry Potter fuera aceptado.

CAPITULO 8: QUE TE HARA FELIZ?

Encontrar tu Elemento no es sobre dinero o fama - es sobre cumplimiento personal.

EXITO VS CUMPLIMIENTO

Puedes ser exitoso segun estandares sociales (dinero, estatus) pero infeliz.
Puedes tener menos exito material pero estar profundamente satisfecho.

El Elemento es sobre cumplimiento, no necesariamente exito convencional.

RIESGO DE NO PERSEGUIR TU ELEMENTO

1. VIDA DE TRANQUILA DESESPERACION
Thoreau: La mayoria de hombres vive vidas de tranquila desesperacion.
Hacen trabajo que odian, esperando jubilacion.

2. ARREPENTIMIENTOS
Bronnie Ware, enfermera de cuidados paliativos, documento arrepentimientos mas comunes de moribundos:

Numero 1: Desearía haber tenido coraje de vivir vida verdadera a mi mismo, no vida que otros esperaban de mi.

3. IMPACTO EN SALUD
Trabajo que odias afecta salud mental y fisica.
Estar en tu Elemento contribuye a bienestar general.

