**LA INVESTIGACIÓN:**

Jim Collins y su equipo analizaron 1,435 empresas Fortune 500 entre 1965 y 1995, identificando solo 11 que cumplieron con criterios estrictos:
- Rendimiento igual o inferior al mercado durante 15 años
- Punto de transición
- Rendimiento 3 veces superior al mercado durante los siguientes 15 años

