**LOS 7 CONCEPTOS CLAVE:**

**1. LIDERAZGO DE NIVEL 5**

El líder de Nivel 5 combina:
- **Humildad Personal**: Modesto, reservado, tímido incluso
- **Voluntad Profesional**: Ferozmente decidido, implacable en la búsqueda de resultados

Características del Líder Nivel 5:
- Atribuye el éxito a otros y circunstancias externas
- Asume responsabilidad por los fracasos
- Mira por la ventana para el éxito, al espejo para los problemas
- Construye grandeza duradera mediante una mezcla paradójica de humildad y voluntad férrea
- Selecciona sucesores para aún mayor éxito

**Diferencia con Líderes Nivel 4:**
Los líderes carismáticos (Nivel 4) a menudo destruyen lo que construyeron porque su ego necesita ser el centro.

**2. PRIMERO QUIÉN, LUEGO QUÉ**

Antes de decidir HACIA DÓNDE ir, decide QUIÉN debe estar en el autobús:

**Principios:**
- Primero consigue las personas correctas en el autobús
- Saca a las personas incorrectas del autobús
- Pon a las personas correctas en los asientos correctos
- LUEGO decide hacia dónde conducir

**¿Por qué primero quién?**
1. Si comienzas con quién, te adaptas más fácilmente a un mundo cambiante
2. Las personas correctas no necesitan ser motivadas o gestionadas
3. Si tienes las personas incorrectas, no importa la dirección correcta

**Cómo saber quién es la persona correcta:**
- ¿Contrataría a esta persona de nuevo?
- Si la persona viniera a renunciar, ¿te sentirías aliviado o intentarías retenerla?
- Es más sobre carácter que habilidades específicas

**3. CONFRONTA LOS HECHOS BRUTALES (pero mantén la fe)**

La Paradoja de Stockdale:
