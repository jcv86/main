**Tipos de Contratos:**

**Contrato Indefinido:**
- Sin plazo de término establecido
- Relación laboral permanente
- Indemnización por años de servicio al término
- Mayor protección para el trabajador

**Contrato a Plazo Fijo:**
- Máximo 1 año (profesionales y técnicos: 2 años)
- Debe tener fecha de término específica
- Renovable una sola vez por igual período
- Tercera renovación se transforma en indefinido

**Contrato por Obra o Faena:**
- Específico para un proyecto determinado
- Termina con la conclusión de la obra
