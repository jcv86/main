- No genera indemnización por término de contrato

**CAPÍTULO 2: JORNADA LABORAL Y DESCANSOS**

**Jornada Ordinaria:**

**Límites Legales:**
- Máximo 45 horas semanales
- Máximo 10 horas diarias
- Distribución en 5 o 6 días
- Registro obligatorio de asistencia

**Jornada Parcial:**
- Máximo 30 horas semanales
- No puede trabajar horas extraordinarias
- Proporcionalidad en beneficios
- Ideal para trabajos part-time

**Horas Extraordinarias:**
- Máximo 2 horas diarias
- Recargo mínimo 50% sobre sueldo base
- Debe ser pactado por escrito
- No obligatorias para el trabajador

**Descansos Obligatorios:**

**Descanso Semanal:**
- Mínimo 1 día completo a la semana
- Preferentemente domingo
- Puede ser compensado en ciertos casos
- Acumulable hasta 2 domingos al mes

**Colación:**
- Mínimo 30 minutos
- No se considera trabajo efectivo
- Puede ser en el lugar de trabajo
- Obligatorio en jornadas sobre 5 horas continuas

**CAPÍTULO 3: REMUNERACIONES**

**Tipos de Remuneración:**

**Sueldo Base:**
- Monto fijo mensual
- No incluye beneficios variables
- Base para cálculo de beneficios
- Sujeto a impuestos y cotizaciones

