### Capítulo 36: La Vida como una Historia

**La Regla del Pico-Final:**

Evaluamos experiencias en gran parte por cómo se sintieron en su pico y en su final.

**Experimento de Colonoscopia:**

Los pacientes fueron sometidos a colonoscopias. Algunos tuvieron el procedimiento estándar. Otros tuvieron el colonoscopio dejado dentro por más tiempo al final, causando molestia leve pero no dolor severo.

Los que tuvieron el procedimiento más largo lo recordaron como menos doloroso porque terminó en molestia menor en lugar de dolor agudo.

**Negligencia de Duración:**

La duración de una experiencia tiene poco efecto en las evaluaciones retrospectivas.

