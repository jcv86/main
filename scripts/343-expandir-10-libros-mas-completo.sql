**Ejemplo:**

Opción A: Un diccionario con 20,000 entradas, como nuevo
Opción B: Un diccionario con 10,000 entradas, como nuevo, con la cubierta rota

Evaluados juntos: La mayoría prefiere A
Evaluados separadamente: La mayoría paga más por B (porque ignoran el número de entradas y solo ven la cubierta rota)

