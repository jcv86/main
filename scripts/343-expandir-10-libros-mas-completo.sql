- Programa A: 200 personas se salvarán (72% elige esto)
- Programa B: 1/3 de probabilidad de salvar 600, 2/3 de probabilidad de salvar 0

**Enmarcado B (Pérdidas):**
- Programa C: 400 personas morirán
- Programa D: 1/3 de probabilidad de que nadie muera, 2/3 de probabilidad de que 600 mueran (78% elige esto)

Los programas A y C son idénticos, al igual que B y D. Pero el enmarcado cambia dramáticamente las preferencias.

