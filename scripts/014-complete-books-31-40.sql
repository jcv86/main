- Professional application: Build genuine relationships with colleagues

6. SCARCITY
- Limited availability increases perceived value
- Deadlines and limited quantities motivate action
- Professional application: Create realistic urgency in proposals and offers

ETHICAL PERSUASION:
These principles can be used manipulatively or ethically. Ethical persuasion provides genuine value and respects the other person''s autonomy.

WORKPLACE APPLICATIONS:
- Presentations and pitches
- Salary negotiations
- Team motivation
- Stakeholder buy-in
- Change management initiatives

PRACTICE ASSIGNMENTS:
