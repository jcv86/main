**La Ciencia de los Hábitos:**

**El Bucle del Hábito:**
Todo hábito consta de tres componentes que forman un bucle neurológico:

**1. La Señal (Cue):**
- Disparador que inicia el comportamiento automático
- Puede ser ubicación, tiempo, estado emocional, otras personas, o acción inmediatamente anterior
- El cerebro busca constantemente señales que predigan recompensas

**2. La Rutina (Routine):**
- El comportamiento físico, mental o emocional que sigue a la señal
- Puede ser simple (lavarse los dientes) o complejo (hacer ejercicio)
- Se vuelve automático con la repetición

**3. La Recompensa (Reward):**
- El beneficio que obtienes del comportamiento
- Ayuda al cerebro a recordar este bucle para el futuro
- Puede ser física, emocional, o psicológica

**Cómo Cambiar Hábitos:**

**La Regla de Oro del Cambio de Hábitos:**
No puedes eliminar un mal hábito, solo puedes cambiarlo. Mantén la misma señal y recompensa, pero cambia la rutina.

**Pasos para Cambiar un Hábito:**

**1. Identifica la Rutina:**
- ¿Cuál es el comportamiento que quieres cambiar?
- Sé específico sobre qué haces exactamente

**2. Experimenta con Recompensas:**
- ¿Qué anhelo está satisfaciendo este hábito?
- Prueba diferentes recompensas para identificar el verdadero anhelo
- Pregúntate: ¿Qué siento después de hacer esto?

**3. Aísla la Señal:**
- ¿Qué dispara este comportamiento?
- Anota: ubicación, tiempo, estado emocional, otras personas, acción anterior
- Busca patrones en tus registros

**4. Ten un Plan:**
- Cuando vea la SEÑAL, haré la RUTINA para obtener la RECOMPENSA
- Escribe tu plan específicamente
- Practica la nueva rutina conscientemente

