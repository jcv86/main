## CAPÍTULO 2: EL DESEO

El punto de partida de todo logro es el deseo. Mantén esto constantemente en mente. El deseo débil trae resultados débiles, así como una pequeña cantidad de fuego hace una pequeña cantidad de calor.

### Los seis pasos para convertir el deseo en oro

1. Fija en tu mente la cantidad exacta de dinero que deseas. No es suficiente decir quiero mucho dinero. Sé definido en cuanto a la cantidad.

2. Determina exactamente qué intentas dar a cambio del dinero que deseas. No hay realidad como algo por nada.

3. Establece una fecha definida cuando intentas poseer el dinero que deseas.

4. Crea un plan definido para llevar a cabo tu deseo y comienza de una vez, ya sea que estés listo o no, a poner este plan en acción.

5. Escribe una declaración clara y concisa de la cantidad de dinero que intentas adquirir, nombra el límite de tiempo para su adquisición, establece lo que intentas dar a cambio del dinero, y describe claramente el plan a través del cual intentas acumularlo.

6. Lee tu declaración escrita en voz alta, dos veces al día, una vez justo antes de dormir por la noche y una vez después de levantarte por la mañana. Mientras lees, visualízate, siéntete y créete ya en posesión del dinero.

### La historia de un deseo ardiente

Durante la Gran Depresión, un joven vendedor de seguros decidió que ganaría un millón de dólares. Las personas se rieron de él. Pero el joven era diferente. Escribió su meta en un pedazo de papel y la llevó consigo a todas partes.

Todos los días visualizaba su meta. La veía tan claramente que podía casi tocarla. Cuatro años después, había ganado su millón de dólares. No fue suerte. Fue el poder de un deseo ardiente combinado con fe absoluta.

