## CAPÍTULO 9: LA PERSISTENCIA

La persistencia es un factor esencial en el procedimiento de transmutar el deseo en su equivalente monetario. La base de la persistencia es el poder de la voluntad.

### Los síntomas de falta de persistencia

1. Fracaso al reconocer y definir claramente exactamente qué uno quiere
2. Procrastinación, con o sin causa
3. Falta de interés en adquirir conocimiento especializado
4. Indecisión, el hábito de pasar la responsabilidad
5. El hábito de confiar en excusas
6. Autocomplacencia
7. Indiferencia
8. El hábito de culpar a otros

### Cómo desarrollar persistencia

1. Un propósito definido respaldado por un deseo ardiente
2. Un plan definido, expresado en acción continua
3. Una mente cerrada a toda influencia negativa y desalentadora
4. Una alianza amigable con uno o más personas

