## CAPÍTULO 7: PLANIFICACIÓN ORGANIZADA

Has aprendido que todo lo que el hombre crea o adquiere, comienza en forma de deseo. El deseo es llevado al primer plano hacia la forma práctica a través de la acción.

### Los pasos esenciales

1. Alíate con un grupo de tantas personas como puedas necesitar para la creación y ejecución de tu plan.

2. Antes de formar tu grupo de cerebro maestro, decide qué ventajas y beneficios puedes ofrecer a los miembros individuales del grupo a cambio de su cooperación.

3. Organiza reuniones con los miembros de tu grupo de cerebro maestro al menos dos veces por semana, y más a menudo si es posible.

4. Mantén perfecta armonía entre ti y cada miembro de tu grupo de cerebro maestro.

