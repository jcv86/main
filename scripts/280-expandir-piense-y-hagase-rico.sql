## CAPÍTULO 3: LA FE

La fe es la cabeza de química de la mente. Cuando la fe se mezcla con el pensamiento, el subconsciente instantáneamente capta la vibración, la traduce en su equivalente espiritual y la transmite a la Inteligencia Infinita.

### Cómo desarrollar fe

La fe es un estado mental que puede ser inducido o creado por afirmación o instrucciones repetidas al subconsciente, a través del principio de autosugestión.

La repetición de afirmaciones de órdenes a tu subconsciente es el único método conocido de desarrollo voluntario de la emoción de la fe.

### Las características de la fe

Todas las personas que han acumulado grandes fortunas, primero hicieron una cierta cantidad de soñar, esperar, desear y planificar antes de que acumularan dinero.

Si uno no posee persistencia, no logra resultados dignos de notar en ningún empeño. La persistencia es un factor esencial en el procedimiento de transmutar el deseo en su equivalente monetario.

