## CAPÍTULO 8: LA DECISIÓN

El análisis de varios cientos de personas que habían acumulado fortunas reveló el hecho de que cada una de ellas tenía el hábito de tomar decisiones con prontitud.

### El poder de la decisión

Las personas que no logran acumular dinero tienen el hábito de llegar a decisiones, si es que llegan a ellas, muy lentamente, y de cambiar estas decisiones rápida y frecuentemente.

El valor de las decisiones depende del coraje requerido para renderizarlas. Las grandes decisiones, que sirvieron como fundaciones de la civilización, fueron alcanzadas asumiendo grandes riesgos.

### Cómo tomar decisiones efectivas

1. Toma decisiones basadas en hechos, no opiniones
2. Consulta solo con tu grupo de cerebro maestro
3. Una vez que tomes una decisión, mantente firme
4. No permitas que otros influencien tus decisiones
5. Evita hablar demasiado sobre tus planes

Los cincuenta y seis hombres que firmaron la Declaración de Independencia arriesgaron sus vidas al tomar esa decisión. Esa fue una decisión que requirió fe y coraje.

