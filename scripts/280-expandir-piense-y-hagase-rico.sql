## CAPÍTULO 4: LA AUTOSUGESTIÓN

La autosugestión es el medio de comunicación entre la parte de la mente donde el pensamiento consciente tiene lugar, y aquella que sirve como el asiento de acción para el subconsciente.

### El principio de la autosugestión

A través de los sentidos dominantes del pensamiento, uno puede voluntariamente alimentar su mente subconsciente con pensamientos de naturaleza creativa, o por negligencia, permitir pensamientos de naturaleza destructiva.

El subconsciente actúa primero en los dominantes de nuestros pensamientos que han sido mezclados con emoción o sentimiento. El subconsciente actúa en los más dominantes de los pensamientos.

### Técnicas prácticas

Lee en voz alta dos veces diariamente la declaración escrita de tu deseo de dinero. Visualízate ya en posesión del dinero. Siéntelo en tus manos. Esta es la forma de enviar instrucciones claras a tu subconsciente.

Tu habilidad para usar el principio de autosugestión dependerá en gran medida de tu capacidad para concentrarte en un deseo dado hasta que ese deseo se convierta en una obsesión ardiente.

