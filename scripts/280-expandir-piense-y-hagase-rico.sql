1. Ventaja económica: Si estás comprometido en cualquier forma de negocio, debes tener aliados.

2. Ventaja psíquica: Dos mentes juntas producen una tercera fuerza invisible, un tercer cerebro maestro, superior a cualquiera de los dos cerebros individuales.

