## CAPÍTULO 6: LA IMAGINACIÓN

La imaginación es el taller donde se forman todos los planes creados por el hombre. El impulso, el deseo, es dado forma, forma y acción a través de la ayuda de la facultad imaginativa de la mente.

### Los dos tipos de imaginación

1. Imaginación sintética: A través de esta facultad, uno puede arreglar viejos conceptos, ideas o planes en nuevas combinaciones.

2. Imaginación creativa: A través de esta facultad, la mente finita del hombre tiene comunicación directa con Inteligencia Infinita. Es la facultad a través de la cual se reciben las presentimientos e inspiraciones.

### Cómo usar la imaginación

Las ideas son el punto de partida de todas las fortunas. Las ideas son productos de la imaginación. Desarrolla tu imaginación mediante el uso constante.

En tu imaginación, visualiza el dinero que deseas ver en tu cuenta bancaria. Visualízate viviendo el estilo de vida que el dinero te proporcionará. Haz esta visualización tan clara y real que tu subconsciente acepte tu imagen mental como realidad.

