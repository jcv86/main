## CAPÍTULO 5: CONOCIMIENTO ESPECIALIZADO

Hay dos tipos de conocimiento. Uno es general, el otro es especializado. El conocimiento general, sin importar cuán grande en cantidad o variedad pueda ser, es de poco uso en la acumulación de dinero.

### El conocimiento que paga

Henry Ford no tenía mucha educación formal, pero sabía cómo rodearse de hombres que tenían el conocimiento que él no poseía. Esto es inteligencia práctica.

El conocimiento es solo poder potencial. Se convierte en poder solo cuando y si está organizado en planes de acción definidos y dirigido hacia un fin definido.

### Dónde adquirir conocimiento

El conocimiento especializado puede adquirirse de:
1. Experiencia y educación propias
2. Experiencia y educación de otros, disponible a través de cooperación
3. Colegios y universidades
4. Bibliotecas públicas
5. Cursos de capacitación especiales

