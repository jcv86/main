**Strategy Is Not:**
- A goal or objective
- A vision or mission statement
- A list of desired outcomes
- Financial projections
- A motivational speech

**Strategy Is:**
A coherent response to an important challenge that involves:
1. **Diagnosis**: Understanding the nature of the challenge
2. **Guiding Policy**: An overall approach to dealing with the challenge
3. **Coherent Action**: Steps that work together to carry out the guiding policy

**THE KERNEL OF GOOD STRATEGY**

**1. DIAGNOSIS**
Simplifies the complexity of reality by identifying certain aspects of the situation as critical.

**Characteristics of Good Diagnosis:**
- Cuts through complexity to identify key issues
- Names or classifies the situation
- Creates a common understanding
- Points toward solutions

**Example: Apple in 1997**
**Diagnosis**: Apple was a niche computer company with too many products, unclear positioning, and declining market share in a commoditizing industry.

**2. GUIDING POLICY**
Specifies the approach to dealing with the obstacles identified in the diagnosis.

**Characteristics of Good Guiding Policy:**
- Provides direction without being overly specific
- Rules out certain actions
- Channels efforts in a particular direction
- Creates advantage through focus

**Example: Apple in 1997**
**Guiding Policy**: Focus on a few high-quality products that integrate hardware and software to deliver superior user experience.

**3. COHERENT ACTION**
Steps that are coordinated with one another to work together in accomplishing the guiding policy.

**Characteristics of Coherent Action:**
- Actions reinforce each other
- Resources are concentrated
- Efforts are coordinated
- Policies are aligned

**Example: Apple in 1997**
