- Culture deteriorates

**THE ACCOUNTABILITY DILEMMA**

**Two Concerns:**
1. **Content**: Getting the results you want
2. **Relationship**: Maintaining a good relationship

**Common Mistakes:**
- **Avoid**: Say nothing and hope the problem goes away
- **Attack**: Confront aggressively and damage the relationship
- **Hint**: Drop subtle hints that don''t address the real issue

**The Goal:**
Address the content while strengthening the relationship.

**CHOOSE WHAT AND IF**

**Step 1: Work on Me First**
Before holding others accountable, examine your own role.

**Questions to Ask:**
- Am I seeing this situation clearly?
- What role did I play in the problem?
- What story am I telling myself?
- Am I the right person to address this?

**Step 2: Choose What**
Decide what conversation to hold.

**The CPR Method:**
- **C - Content**: The immediate problem
- **P - Pattern**: A pattern of behavior
- **R - Relationship**: How the pattern is affecting the relationship

**Start with Content:**
- Address the specific incident first
- Don''t jump to pattern or relationship issues
- Focus on facts, not interpretations

**Move to Pattern When:**
- The same problem keeps recurring
- Content conversations haven''t worked
- The pattern is affecting performance

**Address Relationship When:**
- The pattern is damaging trust
- You''re starting to question their character
- The relationship itself needs repair

**Step 3: Choose If**
Decide whether to hold the accountability conversation.

**When NOT to Hold the Conversation:**
- You''re too emotional
- The other person is in crisis
- You don''t have the facts
- It''s not your responsibility
- The relationship can''t handle it right now

**MASTER YOUR STORIES**

