'Eric Ries presents a methodology for developing businesses and products that aims to shorten product development cycles and rapidly discover if a proposed business model is viable. The Lean Startup methodology promotes developing products that consumers have already demonstrated they desire.

**THE LEAN STARTUP METHODOLOGY**

**What Is a Startup?**
A startup is a human institution designed to create a new product or service under conditions of extreme uncertainty.

**Key Characteristics:**
- Operates under extreme uncertainty
- Aims to create something new
- Seeks a sustainable business model
- Can exist within large corporations or as independent ventures

**The Fundamental Question:**
How can we learn what customers really want as quickly and cheaply as possible?

**THE BUILD-MEASURE-LEARN LOOP**

**The Core Engine of the Lean Startup:**
1. **Build**: Create a minimum viable product (MVP)
2. **Measure**: Gather data on how customers respond
3. **Learn**: Use data to validate or invalidate hypotheses

**The Goal:**
Minimize the time through the Build-Measure-Learn loop to accelerate learning and reduce waste.

**BUILD: MINIMUM VIABLE PRODUCT (MVP)**

**What Is an MVP?**
The minimum viable product is that version of a new product that allows a team to collect the maximum amount of validated learning about customers with the least effort.

**MVP Characteristics:**
- Has just enough features to enable learning
- Focuses on core value proposition
- Allows for maximum learning with minimum effort
- May be imperfect or incomplete

**Types of MVPs:**

**1. Concierge MVP**
Manually deliver the service to early customers to understand their needs.

**2. Wizard of Oz MVP**
Create the appearance of a fully functional product while manually performing the work behind the scenes.

**3. Landing Page MVP**
Create a simple webpage describing your product to test demand before building it.

**4. Video MVP**
Create a video demonstrating your product concept to gauge interest.

**5. Feature Fake MVP**
Add a button or feature that doesn''t work yet to test if customers want it.

**Common MVP Mistakes:**
- Making it too complex
- Focusing on perfection rather than learning
- Building features customers don''t want
- Taking too long to get to market

**MEASURE: INNOVATION ACCOUNTING**

**Beyond Vanity Metrics**
Traditional metrics like total customers, revenue, or page views can be misleading for startups.

**Actionable Metrics vs. Vanity Metrics:**

**Vanity Metrics:**
- Total number of users
- Total revenue
- Page views
- Downloads

**Actionable Metrics:**
- Customer acquisition cost
- Lifetime value
- Retention rates
- Conversion rates
- Cohort analysis

**The Three A''s of Metrics:**
- **Actionable**: Must demonstrate clear cause and effect
- **Accessible**: Must be understandable to everyone
- **Auditable**: Must be credible and verifiable

**Innovation Accounting Process:**
1. **Establish baseline**: Measure current performance
2. **Tune the engine**: Make improvements to move metrics toward ideal
3. **Pivot or persevere**: Decide whether to change direction or continue

**LEARN: VALIDATED LEARNING**

**What Is Validated Learning?**
The process of demonstrating empirically that a team has discovered valuable truths about a startup''s present and future business prospects.

**The Scientific Method for Startups:**
1. **Hypothesis**: Form testable assumptions about your business
2. **Experiment**: Design tests to validate or invalidate hypotheses
3. **Data**: Collect and analyze results
4. **Insight**: Learn what works and what doesn''t

**Types of Hypotheses:**

**Value Hypothesis:**
Tests whether a product or service really delivers value to customers once they''re using it.

**Growth Hypothesis:**
Tests how new customers will discover a product or service.

**PIVOT OR PERSEVERE**

**What Is a Pivot?**
A structured course correction designed to test a new fundamental hypothesis about the product, strategy, and engine of growth.

**Types of Pivots:**

**1. Zoom-in Pivot**
A single feature becomes the whole product.

**2. Zoom-out Pivot**
The whole product becomes a single feature of a larger product.

**3. Customer Segment Pivot**
The product stays the same but serves a different customer segment.

**4. Customer Need Pivot**
The target customer has a problem worth solving, just not the one originally anticipated.

**5. Solution Pivot**
The problem is real but the solution doesn''t solve it adequately.

**6. Revenue Model Pivot**
How the company makes money changes.

**7. Engine of Growth Pivot**
A company changes its growth strategy.

**8. Channel Pivot**
The mechanism by which a company delivers its product changes.

**9. Technology Pivot**
A company discovers it can solve the same problem with different technology.

**When to Pivot:**
- Metrics aren''t improving despite efforts
- Customer feedback indicates fundamental problems
- Market conditions have changed significantly
- Better opportunities have emerged

**When to Persevere:**
- Metrics are improving
- Customer feedback is positive
- Clear path to growth is visible
- Team remains motivated and aligned

**ENGINES OF GROWTH**

**Three Engines of Growth:**

**1. Sticky Engine of Growth**
Focuses on customer retention and engagement.

**Key Metrics:**
- Customer retention rate
- Churn rate
- Customer lifetime value
- Engagement metrics

**Strategy:**
- Make products habit-forming
- Improve customer experience
- Reduce churn
- Increase usage frequency

**2. Viral Engine of Growth**
Relies on customers bringing in new customers.

**Key Metrics:**
- Viral coefficient (how many new customers each customer brings)
- Viral cycle time (how long it takes for referrals to happen)
- Network effects

**Strategy:**
- Build sharing into the product
- Create incentives for referrals
- Make the product better with more users
- Reduce friction in the sharing process

**3. Paid Engine of Growth**
Uses advertising and sales to acquire customers.

**Key Metrics:**
- Customer acquisition cost (CAC)
- Customer lifetime value (LTV)
- LTV/CAC ratio
- Payback period

**Strategy:**
- Optimize advertising channels
- Improve conversion rates
- Increase customer lifetime value
- Reduce acquisition costs

