**THE GROWTH IMPERATIVE**

**Why Growth Matters**
Sustained profitable growth is the holy grail of management. Companies that achieve it create enormous value for shareholders, provide opportunities for employees, and contribute to economic prosperity.

**The Growth Challenge**
Most companies struggle to sustain growth because:
- They focus on sustaining innovations rather than disruptive ones
- They target existing customers instead of non-consumers
- They compete in established markets rather than creating new ones
- They optimize existing business models instead of creating new ones

**THE THEORY OF DISRUPTION**

**Sustaining vs. Disruptive Innovation**

**Sustaining Innovations:**
- Improve product performance along dimensions that mainstream customers value
- Can be breakthrough or incremental
- Help companies make better products for their best customers
- Usually captured by incumbent companies

**Disruptive Innovations:**
- Initially offer lower performance on mainstream attributes
- Provide different benefits (convenience, simplicity, affordability)
- Appeal to new or less-demanding customer segments
- Often ignored by incumbents until it''s too late

**Two Types of Disruption:**

**New-Market Disruption:**
- Competes against non-consumption
- Makes it possible for people to do something they couldn''t do before
- Creates entirely new markets
- Example: Personal computers vs. mainframes

**Low-End Disruption:**
- Targets overserved customers at the low end of the market
- Offers "good enough" performance at lower prices
- Gradually moves upmarket
- Example: Southwest Airlines vs. major carriers

**THE DISRUPTIVE GROWTH ENGINE**

**Step 1: Find the Right Customers**
Target customers who are either:
- **Non-consumers**: People who lack the skills, wealth, or access to use existing products
- **Overserved customers**: People for whom existing products are more than they need

**Step 2: Get the Business Model Right**
Disruptive business models typically feature:
- Lower gross margins
- Smaller target markets initially
- Simpler products and services
- Different cost structures

**Step 3: Get the Values Network Right**
Create a new values network that:
- Defines what good performance means
- Determines how companies make money
- Shapes competitive dynamics
- Influences customer priorities

**FINDING THE RIGHT CUSTOMERS**

**Circumstances-Based Segmentation**
Instead of segmenting by customer demographics, segment by the circumstances in which customers find themselves when trying to get a job done.

**The Job-to-be-Done Framework:**
- What job is the customer trying to get done?
- What are they currently using to get this job done?
- What are the limitations of current solutions?
- What would make it easier, cheaper, or more convenient?

**Non-Consumption Opportunities:**
