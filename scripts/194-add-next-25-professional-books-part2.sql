- Absolves us of responsibility
- Prevents us from taking action

**3. Helpless Stories**
"There''s nothing I can do."
- Makes us feel safe from risk
- Justifies inaction
- Keeps us stuck

**Tell the Most Respectful Story:**
- Assume positive intent
- Consider other explanations
- Focus on facts, not interpretations
- Give people the benefit of the doubt

