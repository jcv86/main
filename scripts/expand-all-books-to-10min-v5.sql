**Proyectos:** Objetivos con múltiples pasos
- Ejemplo: "Rediseñar home page del sitio web"
- Requiere: Investigación, diseño, desarrollo, testing, deploy

**Próximas Acciones:** El próximo paso específico para cada proyecto
