## CAPÍTULO 10: SOBRE EL TERRENO

### Seis Tipos de Terreno

**1. Terreno Accesible:**
Ambos lados pueden moverse libremente.

**Estrategia:** Ocupa posiciones altas y soleadas primero.

**2. Terreno Enredado:**
Fácil salir, difícil regresar.

**Estrategia:** Solo avanza si el enemigo está desprevenido.

**3. Terreno Temporal:**
Ningún lado gana ventaja ocupándolo.

**Estrategia:** No te dejes atraer, retírate y atrae al enemigo.

**4. Terreno Estrecho:**
Pasajes angostos.

**Estrategia:** Si llegas primero, ocupa y bloquea. Si el enemigo llegó primero, no lo sigas.

**5. Terreno Escarpado:**
Alturas y precipicios.

**Estrategia:** Ocupa alturas soleadas. Si el enemigo las tiene, retírate.

**6. Terreno Distante:**
Lejos de bases.

**Estrategia:** Con fuerzas iguales, es difícil provocar batalla.

**Aplicación a Mercados:**

- **Accesible:** Mercados abiertos (posiciónate primero)
- **Enredado:** Mercados con lock-in (entra solo si puedes ganar)
- **Temporal:** Modas pasajeras (no persigas)
- **Estrecho:** Nichos específicos (domina o evita)
- **Escarpado:** Mercados con ventajas posicionales (toma la altura)
- **Distante:** Mercados internacionales (requiere recursos)

### Seis Calamidades

**Errores Fatales del General:**

**1. Huida:**
Tropas 10 veces más débiles que el enemigo.

**Causa:** Subestimar al enemigo

**2. Insubordinación:**
Tropas fuertes pero oficiales débiles.

**Causa:** Falta de liderazgo

**3. Colapso:**
Oficiales fuertes pero tropas débiles.

**Causa:** Desconexión con realidad

**4. Ruina:**
Oficiales superiores enojados y desobedientes.

**Causa:** Falta de disciplina

**5. Desorden:**
General débil y sin autoridad.

**Causa:** Liderazgo inefectivo

**6. Derrota:**
General subestima al enemigo y ataca con fuerzas inferiores.

**Causa:** Arrogancia

**Lección:**
"Estas seis son el camino a la derrota. Es la responsabilidad suprema del general examinarlas cuidadosamente."

