## PARTE 2: LAS 7 HABILIDADES

### Habilidad 1: Aprende a Observar

**Observa tres cosas:**

1. **Contenido:** Lo que se dice
2. **Condiciones:** Señales de que la seguridad está en riesgo
3. **Tu comportamiento:** Cómo estás contribuyendo

**Señales de falta de seguridad:**
- Silencio (retener, evitar, retirarse)
- Violencia (controlar, etiquetar, atacar)

**Pregunta:** ¿Estoy en diálogo o en debate?

### Habilidad 2: Haz Seguro el Diálogo

**Verdad:** Las personas no comparten cuando no se sienten seguras.

**Dos condiciones de seguridad:**

1. **Propósito Mutuo:** Otros creen que te importan sus objetivos
2. **Respeto Mutuo:** Otros sienten que los respetas

**Cómo restaurar seguridad:**

**Paso 1: Disculparse**
"Siento haber..."

**Paso 2: Contrastar**
"No quiero que pienses [malentendido]. Lo que quiero es [intención real]."

**Paso 3: CRIB (Crear Propósito Mutuo)**
- Comprometerse a buscar propósito mutuo
- Reconocer el propósito detrás de la estrategia
- Inventar un propósito mutuo
- Brainstorm nuevas estrategias

### Habilidad 3: Domina Tus Historias

**Verdad:** No son los hechos los que nos molestan, sino las historias que contamos sobre los hechos.

**Ruta de Acción:**
Ver y Escuchar → Contar una Historia → Sentir → Actuar

**Tres historias inteligentes:**

1. **Historia de Víctima:** "No es mi culpa"
2. **Historia de Villano:** "Es todo tu culpa"
3. **Historia de Impotencia:** "No hay nada que pueda hacer"

**Solución:** Cuenta el resto de la historia

**Pregunta:** ¿Qué estoy fingiendo no saber sobre mi papel en esto?

### Habilidad 4: EXPÓN tu Camino

**EXPÓN = Compartir tu perspectiva de manera segura**

**E - Expresa tus hechos**
Comienza con lo menos controversial.
"He notado que..."

**X - eXplica tu historia**
Comparte tu interpretación.
"Estoy empezando a preguntarme si..."

**P - Pide el camino de otros**
Invita perspectivas contrarias.
"¿Ves esto diferente?"

**O - Observa con curiosidad**
Mantente abierto.
"¿Qué me estoy perdiendo?"

**N - Negocia un camino**
Construye una decisión juntos.
"¿Qué deberíamos hacer?"

### Habilidad 5: EXPLORA el Camino de Otros

**Cuando otros se callan o explotan:**

**E - Expresa interés genuino**
"Me gustaría escuchar tu perspectiva"

**X - eXplora con preguntas**
"¿Puedes ayudarme a entender?"

**P - Parafrasea**
"Entonces lo que estás diciendo es..."

**L - Labela emociones**
"Pareces frustrado"

**O - Observa señales**
Nota lenguaje corporal

**R - Refleja sentimientos**
"Puedo ver que esto es importante para ti"

**A - Acuerda o construye**
"Estoy de acuerdo con..." o "Además de eso..."

### Habilidad 6: Muévete a la Acción

**Cuatro métodos de decisión:**

1. **Comando:** Decisiones sin participación
   - Cuándo: Emergencias, decisiones triviales

2. **Consulta:** Input de otros, uno decide
   - Cuándo: Tienes experiencia, necesitas buy-in

3. **Voto:** Mayoría decide
   - Cuándo: Eficiencia importa, compromiso aceptable

4. **Consenso:** Todos deben estar de acuerdo
   - Cuándo: Decisión de alto riesgo, necesitas compromiso total

**Clarifica:**
- ¿Quién decide?
- ¿Cuándo?
- ¿Qué criterios?

### Habilidad 7: Sí, Y...

**Principio:** Construye sobre las ideas de otros en lugar de rechazarlas.

**En lugar de:** "Sí, pero..."
**Di:** "Sí, y además podríamos..."

**Beneficio:** Mantiene el diálogo fluyendo y construye soluciones mejores.

