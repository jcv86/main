## APLICACIONES PRÁCTICAS

### Conversación Difícil con tu Jefe

**Situación:** Necesitas feedback o un aumento

**Preparación:**
1. ¿Qué quiero realmente? (Para mí, para mi jefe, para la relación)
2. ¿Qué historia estoy contando?
3. ¿Cuáles son los hechos?

**Apertura:**
"Tengo algo importante que me gustaría discutir. ¿Es buen momento?"

**EXPÓN:**
"He notado que [hechos]. Estoy empezando a preguntarme si [historia]. ¿Cómo lo ves tú?"

### Conversación con Pareja

**Situación:** Conflicto recurrente

**Comienza con el corazón:**
"Quiero que nuestra relación sea fuerte. Quiero que ambos nos sintamos escuchados."

**Crea seguridad:**
"No quiero que pienses que te estoy atacando. Lo que quiero es encontrar una solución que funcione para ambos."

**EXPLORA:**
"Ayúdame a entender tu perspectiva sobre esto."

### Conversación con Colega Difícil

**Situación:** Alguien no cumple compromisos

**Observa:**
¿Estoy en silencio o violencia? ¿Qué historia estoy contando?

**EXPÓN:**
"He notado que los últimos tres proyectos se entregaron tarde. Estoy preocupado por el impacto en el equipo. ¿Qué está pasando desde tu perspectiva?"

**EXPLORA:**
"¿Hay algo que yo o el equipo podamos hacer para ayudar?"

