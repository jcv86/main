## PARTE 7: Gestión en el Mundo Plano

### Nuevos Principios de Gestión

#### Principio 1: De Comando-y-Control a Conectar-y-Colaborar

**Old way:**
- Jefe decide, empleados ejecutan
- Información fluye arriba, órdenes fluyen abajo
- Jerarquía rígida
- Lealtad valorada sobre innovación

**New way:**
- Equipos autoorganizados
- Información transparente para todos
- Estructuras líquidas
- Innovación valorada sobre lealtad ciega

**Ejemplo: W.L. Gore (makers of Gore-Tex)**
- Sin títulos de trabajo
- Sin jefes formales
- Equipos formados naturalmente alrededor de proyectos
- Resultado: Innovación consistente por 50+ años

#### Principio 2: De Optimización Local a Optimización Global

**Old way:**
- Cada departamento optimiza su función
- Silos organizacionales
- Competencia interna
- Sub-optimización global

**New way:**
- Optimización del sistema completo
- Colaboración entre funciones
- Competencia externa, cooperación interna
- Visión end-to-end

**Ejemplo: Zara (retail de moda)**
- Diseño, manufactura, distribución integrados
- Respuesta a tendencias en 2 semanas vs. 6 meses industria
- Inventario 10% vs. 30-40% industria
- Resultado: Líder en fast fashion

#### Principio 3: De Empleados como Costos a Empleados como Activos

**Old way:**
- Empleados = costo variable
- Despedir fácilmente en tiempos difíciles
- Invertir poco en desarrollo
