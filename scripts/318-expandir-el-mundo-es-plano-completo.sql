## PARTE 2: La Triple Convergencia

Friedman argumenta que tres convergencias simultáneas crearon un momento único en la historia:

### Convergencia 1: Los Diez Aplanadores Trabajando Juntos

No fue un solo aplanador, sino la sinergia de todos ellos lo que creó el mundo plano.

**Ejemplo de sinergia:**
Una startup en Estonia puede:
1. Usar **open source** (Linux, Apache) para infraestructura
2. **Outsourcing** desarrollo a India
3. **Offshoring** manufactura a China
4. **Supply-chain** con proveedores globales
5. **In-forming** para investigar mercados
6. **Esteroides** para coordinar equipo global

Todo esto mientras es una compañía de 5 personas. En 1995, esto habría sido imposible.

### Convergencia 2: Nuevo Modelo de Negocio Horizontal

**Del modelo vertical al horizontal:**

**Antes (Vertical):**
Compañía hace todo internamente
- Diseño
- Manufactura  
- Marketing
- Distribución
- Servicio al cliente

**Ahora (Horizontal):**
Compañía orquesta ecosistema
- Diseño (interno)
- Manufactura (China)
- Marketing (agencia en NY)
- Distribución (3PL global)
- Servicio al cliente (call center India)

### Convergencia 3: Nuevos Jugadores Entrando al Campo

**3 billones de personas se unieron a la economía global:**

**1989:** 
- Población en economías de mercado: ~1 billón
- Población aislada (China, India, ex-URSS): ~3 billones

**2000:**
- Población en economías de mercado: ~4 billones
- Población aislada: ~0

**Implicaciones:**
- Triplicación de la fuerza laboral global
- Explosión de talento disponible
- Competencia intensificada
- Oportunidades masivas

