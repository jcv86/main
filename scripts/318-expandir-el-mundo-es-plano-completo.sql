## Introducción: El Descubrimiento de que el Mundo es Plano

En el año 2004, Thomas Friedman viajó a Bangalore, India, para investigar sobre la industria tecnológica india. Lo que descubrió allí cambió fundamentalmente su comprensión de la globalización y la economía mundial. No solo encontró oficinas de alta tecnología y centros de llamadas manejando trabajo de Estados Unidos y Europa, sino que presenció el nacimiento de un fenómeno completamente nuevo: un campo de juego global nivelado donde la competencia ya no dependía de tu ubicación geográfica, sino de tu conectividad, creatividad y capacidad de colaboración.

### El Momento "Eureka"

**La llamada de despertar:**
Friedman entrevistó a Nandan Nilekani, CEO de Infosys, una de las compañías de tecnología más grandes de India. Nilekani le dijo algo que resonaría a través de todo el libro: "Tom, el campo de juego está siendo nivelado." En ese momento, Friedman se dio cuenta de que estaba presenciando un cambio fundamental en la historia humana.

**Lo que esto significaba:**
- Individuos en India, China, y otras partes del mundo en desarrollo podían competir directamente con trabajadores en países desarrollados
- Las barreras geográficas y económicas tradicionales estaban colapsando
- La tecnología había creado una plataforma global donde el talento y la ambición importaban más que la ubicación

