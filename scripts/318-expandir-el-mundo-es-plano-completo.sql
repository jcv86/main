## PARTE 4: Los No-Tan-Planos

### La Brecha Digital Persiste

Aunque el título es "El Mundo es Plano", Friedman reconoce que no todos tienen acceso igual.

**Estadísticas (2005):**
- 1 billón de personas usan internet
- 5 billones no tienen acceso
- 2.5 billones viven con menos de $2 diarios
- 1 billón son analfabetos

**Barreras al aplanamiento:**

#### 1. Infraestructura

**Acceso a tecnología:**
- Electricidad inconsistente
- Internet lento o inexistente
- Computadoras inaccesibles
- Redes telefónicas limitadas

**Ejemplo: África**
En 2005, más personas en Manhattan tenían acceso a internet que en todo el continente africano.

#### 2. Educación

**Calidad educativa:**
- Sistemas educativos obsoletos
- Enfoque en memorización vs. pensamiento crítico
- Falta de educación en tecnología
- Limitado acceso a educación superior

#### 3. Gobernanza

**Entorno institucional:**
- Corrupción endémica
- Derechos de propiedad débiles
- Regulaciones que inhiben negocios
- Inestabilidad política

### Países que Están Perdiendo

**Categorías de no-participantes:**

**1. Los No Conectados**
Países con infraestructura tecnológica casi inexistente
- La mayoría de África subsahariana
- Partes de Asia Central
- Regiones remotas de Latinoamérica

**2. Los Mal Gobernados**
Países con infraestructura pero instituciones disfuncionales
- Zimbabwe, Myanmar, Corea del Norte
- Corrupción que anula ventajas tecnológicas

**3. Los Auto-Aislados**
Países que deliberadamente se separan de globalización
- Cuba, Iran, partes del Medio Oriente
- Ideología sobre pragmatismo económico

