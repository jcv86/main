## PARTE III: MÁS ALLÁ DE LA IMAGINACIÓN

### Capítulo 3: Más Allá de la Imaginación

**Imaginación vs Creatividad:**

**Imaginación:**
- Proceso de traer a la mente cosas que no están presentes a los sentidos
- Todos la tenemos
- Base de todo logro humano

**Creatividad:**
- Proceso de tener ideas originales que tienen valor
- Imaginación aplicada
- Produce algo tangible

**Fórmula:**
**CREATIVIDAD = IMAGINACIÓN + ACCIÓN**

### Desarrollar Creatividad

**Mitos sobre Creatividad:**

**Mito 1:** "Solo algunas personas son creativas"
**Realidad:** Todos somos creativos en algo

**Mito 2:** "Creatividad es solo para las artes"
**Realidad:** Hay creatividad en todo: ciencia, negocios, deportes, cocina

**Mito 3:** "No puedes enseñar creatividad"
**Realidad:** Creatividad puede desarrollarse

**Mito 4:** "Creatividad es hacer cosas locas"
**Realidad:** Creatividad es resolver problemas de formas originales

### Proceso Creativo

**4 Etapas:**

**1. Preparación:**
- Inmersión en el problema
- Investigación
- Exploración
- Recopilación de información

**2. Incubación:**
- Dejar que la mente inconsciente trabaje
- Alejarse del problema
- Hacer otras cosas
- Permitir conexiones

**3. Iluminación:**
- ¡Eureka!
- La idea llega
- Momento "aha"
- Insight repentino

**4. Verificación:**
- Probar la idea
- Refinar
- Implementar
- Hacer real

