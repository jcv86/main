### Capítulo 10: Camina Lentamente, Pero Nunca Hacia Atrás

Los hábitos se forman según la frecuencia, no el tiempo. No importa si has estado realizando un hábito durante veintiún días o treinta días o trescientos días. Lo que importa es la tasa a la que realizas el comportamiento.

**El Movimiento vs. La Acción:**

- El movimiento es planificar, estrategizar y aprender
- La acción es el comportamiento que producirá un resultado

