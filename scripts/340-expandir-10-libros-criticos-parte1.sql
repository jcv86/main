### Capítulo 4: El Hombre que No Se Veía Bien

En 1898, el psicólogo Edward Thorndike realizó un experimento con gatos. Cada gato fue colocado en una caja. Después de algunos intentos, los gatos aprendieron a escapar en menos de 10 segundos.

Este proceso de prueba y error eventualmente llevó a un hábito. Los hábitos son, en pocas palabras, soluciones confiables a problemas recurrentes en nuestro entorno.

**La Ciencia de Cómo Funcionan los Hábitos:**

Los hábitos no restringen la libertad. Crean libertad. De hecho, las personas que no tienen sus hábitos bajo control son a menudo las menos libres.

**El Marcador de Hábitos:**

