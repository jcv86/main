## Hábito 1: Ser Proactivo

### Principios de la Visión Personal

Entre el estímulo y la respuesta, el hombre tiene la libertad de elegir. Dentro de la libertad de elegir están esos dones humanos únicos que nos hacen humanos: autoconciencia, imaginación, conciencia y voluntad independiente.

**Proactividad Definida:**

Ser proactivo significa más que tomar la iniciativa. Significa que como seres humanos, somos responsables de nuestras propias vidas. Nuestro comportamiento es una función de nuestras decisiones, no de nuestras condiciones.

Las personas proactivas reconocen su responsabilidad. No culpan a las circunstancias, condiciones o condicionamiento por su comportamiento. Su comportamiento es un producto de su propia elección consciente.

**Lenguaje Reactivo vs. Proactivo:**

Reactivo:
- "No hay nada que pueda hacer"
- "Así soy yo"
- "Me vuelve loco"
- "No lo permitirán"
- "Tengo que hacer eso"

Proactivo:
- "Veamos nuestras alternativas"
- "Puedo elegir un enfoque diferente"
- "Controlo mis propios sentimientos"
- "Puedo crear una presentación efectiva"
- "Elegiré una respuesta apropiada"

**El Círculo de Preocupación vs. El Círculo de Influencia:**

Las personas proactivas enfocan sus esfuerzos en el Círculo de Influencia. Trabajan en las cosas en las que pueden hacer algo: salud, hijos, problemas en el trabajo.

Las personas reactivas enfocan sus esfuerzos en el Círculo de Preocupación: debilidades de otras personas, problemas en el ambiente, circunstancias sobre las cuales no tienen control.

**Los Errores Proactivos:**

Cometemos errores. Los reconocemos, los corregimos y aprendemos de ellos. Esto literalmente convierte el fracaso en éxito.

"El éxito está en el lado opuesto del fracaso." - T.J. Watson, fundador de IBM

## Hábito 2: Comenzar con el Fin en Mente

### Principios del Liderazgo Personal

Comenzar con el fin en mente significa comenzar hoy con la imagen, imagen o paradigma de tu vida como marco de referencia mediante el cual todo lo demás es examinado.

**Todas las Cosas se Crean Dos Veces:**

Hay una creación mental (primera) y una creación física (segunda). La construcción de una casa comienza con un plano. Los padres crean la impronta de un niño.

Si no haces un esfuerzo consciente de visualizar quién eres y qué quieres en la vida, estás empoderando a otras personas y circunstancias para dar forma a ti y a tu vida por defecto.

**Liderazgo vs. Gestión:**

La gestión es hacer las cosas bien; el liderazgo es hacer las cosas correctas. La gestión es eficiencia en subir la escalera del éxito; el liderazgo determina si la escalera está apoyada contra la pared correcta.

Puedes estar muy ocupado, puedes ser muy eficiente, pero solo serás efectivo si estás haciendo las cosas correctas.

**Declaración de Misión Personal:**

Una declaración de misión personal es una constitución personal, la base sólida sobre la cual construyes tu vida.

Responde a preguntas fundamentales:
- ¿Quién quiero ser? (carácter)
- ¿Qué quiero hacer? (contribuciones y logros)
- ¿Cuáles son los valores sobre los cuales se basan el ser y el hacer?

Ejemplo de Declaración de Misión:
"Tener éxito en casa primero. No comprometeré mi integridad. Escucharé a ambos lados antes de juzgar. Seré fiel en el matrimonio. Me mantendré actualizado en mi campo."

## Hábito 3: Poner Primero lo Primero

### Principios de la Gestión Personal

Poner primero lo primero es la segunda creación, la creación física. Es la realización, la actualización, la emergencia natural de los Hábitos 1 y 2.

**La Matriz de Gestión del Tiempo:**

|              | Urgente | No Urgente |
|--------------|---------|------------|
| **Importante** | Cuadrante I: Crisis, problemas urgentes | Cuadrante II: Prevención, construcción de relaciones, planificación |
| **No Importante** | Cuadrante III: Interrupciones, algunas llamadas | Cuadrante IV: Trivialidades, pérdida de tiempo |

Las personas efectivas permanecen fuera de los Cuadrantes III y IV porque, urgentes o no, no son importantes. También reducen el Cuadrante I pasando más tiempo en el Cuadrante II.

**El Cuadrante II:**

El Cuadrante II es el corazón de la gestión personal efectiva. Trata con cosas que no son urgentes, pero sí importantes: construir relaciones, escribir una declaración de misión personal, planificación a largo plazo, ejercicio, preparación, todas esas cosas que sabemos que necesitamos hacer, pero de alguna manera rara vez llegamos a hacer.

**Delegar: Aumentando P y CP:**

La delegación efectiva es quizás la mejor indicación de la gestión efectiva. La transferencia de responsabilidad a personas hábiles y capacitadas te permite dar tu energía a actividades de alto apalancamiento.

Dos tipos de delegación:
1. **Delegación de recados:** "Ve a hacer esto, esto y esto."
2. **Delegación de mayordomía:** Enfocada en resultados, no en métodos. Da libertad de elección de métodos y responsabilidad por resultados.

## Hábito 4: Pensar Ganar-Ganar

### Principios del Liderazgo Interpersonal

Ganar-Ganar es un marco mental y corazón que busca constantemente el beneficio mutuo en todas las interacciones humanas. Ganar-Ganar significa que los acuerdos o soluciones son mutuamente beneficiosos, mutuamente satisfactorios.

**Seis Paradigmas de Interacción Humana:**

1. **Ganar-Ganar:** Ambas personas ganan. Los acuerdos son mutuamente beneficiosos.
2. **Ganar-Perder:** Si gano, tú pierdes. Mentalidad competitiva.
3. **Perder-Ganar:** Tú ganas, yo pierdo. Soy un apaciguador.
4. **Perder-Perder:** Ambas personas pierden. Mentalidad vengativa.
5. **Ganar:** Las personas con mentalidad Ganar pienan en términos de asegurar sus propios fines.
6. **Ganar-Ganar o No Hay Trato:** Si no podemos encontrar una solución mutuamente beneficiosa, acordamos estar en desacuerdo de manera agradable.

**Cinco Dimensiones de Ganar-Ganar:**

1. **Carácter:** Integridad, madurez, mentalidad de abundancia
2. **Relaciones:** Cuenta bancaria emocional
3. **Acuerdos:** Ganar-Ganar crea acuerdos de desempeño
4. **Sistemas:** Los sistemas deben apoyar Ganar-Ganar
5. **Procesos:** Procedimiento de cuatro pasos: Ver el problema desde el otro punto de vista, identificar problemas clave, determinar resultados aceptables, identificar nuevas opciones

