**La Ley del Menor Esfuerzo:**

De todas las posibles acciones, elegiremos la opción que entrega el mayor valor con la menor cantidad de esfuerzo.

Reduce la fricción asociada con buenos comportamientos. Aumenta la fricción asociada con malos comportamientos.

