## Paradigmas y Principios

### Visión General

La forma en que vemos el problema es el problema. Los paradigmas son poderosos porque crean los lentes a través de los cuales vemos el mundo. Si quieres hacer cambios menores en tu vida, trabaja en tu actitud. Pero si quieres hacer cambios significativos, importantes, trabaja en tus paradigmas básicos.

**La Ética del Carácter vs. La Ética de la Personalidad:**

Durante los primeros 150 años de historia estadounidense, el éxito se atribuyó a la ética del carácter: integridad, humildad, fidelidad, templanza, coraje, justicia, paciencia, industria, simplicidad, modestia y la Regla de Oro.

Después de la Primera Guerra Mundial, hubo un cambio hacia la "ética de la personalidad", donde el éxito se atribuyó a la personalidad, la imagen pública, las actitudes y los comportamientos.

La ética del carácter es el fundamento del éxito, mientras que la ética de la personalidad es secundaria.

**El Poder de un Cambio de Paradigma:**

Imagina que viajas en el metro un domingo por la mañana en Nueva York. Es tranquilo y pacífico. Entonces un hombre y sus hijos suben. Los niños son ruidosos y perturbadores. El hombre se sienta al lado tuyo y cierra los ojos, aparentemente ajeno a la situación.

