'**THINKING, FAST AND SLOW (Pensar Rápido, Pensar Despacio)**
*Por Daniel Kahneman*

**INTRODUCCIÓN: LOS DOS SISTEMAS**

Daniel Kahneman, ganador del Premio Nobel de Economía, dedicó su vida a estudiar cómo pensamos y por qué cometemos errores sistemáticos.

Su descubrimiento fundamental: Tenemos dos sistemas de pensamiento.

**SISTEMA 1: Pensamiento Rápido**

**Características:**
- Automático e involuntario
- Sin esfuerzo
- Emocional e intuitivo
- Siempre activo
- Responde instantáneamente

**Ejemplos:**
- Detectar que alguien está enojado por su tono
- Conducir en una ruta familiar
- 2 + 2 = ?
- Reconocer una cara conocida

**SISTEMA 2: Pensamiento Lento**

**Características:**
- Controlado y deliberado
- Requiere esfuerzo mental
- Lógico y calculador
- Se activa cuando es necesario
- Perezoso por naturaleza

**Ejemplos:**
- 17 x 24 = ?
- Llenar formulario de impuestos
- Estacionar en un espacio estrecho
- Comparar dos opciones complejas

**La Interacción:**

Sistema 1 genera impresiones y sentimientos constantemente.
Sistema 2 generalmente acepta estas sugerencias sin cuestionarlas.

**El problema:** Sistema 1 es propenso a sesgos y errores sistemáticos.

**PARTE 1: LOS DOS SISTEMAS**

**CAPÍTULO 1: PERSONAJES DE LA HISTORIA**

**El Experimento de las Pupilas:**

Kahneman descubrió que las pupilas se dilatan con el esfuerzo mental.

**Prueba:**
Pide a personas calcular mentalmente 23 x 78.

**Resultado:**
- Las pupilas se dilatan máximamente durante el cálculo
- Se contraen inmediatamente al dar la respuesta
- Medida objetiva del esfuerzo mental

**Lección:** El pensamiento profundo requiere esfuerzo real y medible.

**La Ley del Menor Esfuerzo:**

**Principio:** Los organismos evitan el esfuerzo innecesario.

**En humanos:**
- Sistema 1 trabaja automáticamente sin esfuerzo
- Sistema 2 es perezoso y prefiere no activarse
- Tomamos el camino fácil cuando es posible

**Ejemplo del Murciélago y la Pelota:**

**Pregunta:**
Un bate y una pelota cuestan 1.10 dólares en total.
El bate cuesta 1 dólar más que la pelota.
¿Cuánto cuesta la pelota?

**Respuesta intuitiva (Sistema 1):** 10 centavos
**Respuesta correcta (Sistema 2):** 5 centavos

Más del 50% de estudiantes de Harvard respondieron incorrectamente.

**Por qué:** Sistema 1 salta a la conclusión obvia.
Sistema 2 es perezoso y no verifica.

**CAPÍTULO 2: ATENCIÓN Y ESFUERZO**

**El Experimento del Gorila Invisible:**

Investigadores crearon un video de personas pasando una pelota de basketball.

**Instrucción:** Cuenta cuántas veces el equipo blanco pasa la pelota.

**Durante el video:** Una persona disfrazada de gorila camina por la escena, se detiene, golpea su pecho, y se va.

**Resultado:** 50% de los observadores NO VEN al gorila.

**Explicación:**
- Sistema 2 está concentrado en contar
- No hay atención disponible para procesar gorila
- Literalmente no lo vemos conscientemente

**Lección:** Cuando estás concentrado en una tarea, eres funcionalmente ciego a otras cosas obvias.

**La Ilusión de Atención:**

Creemos que vemos todo a nuestro alrededor.
**Realidad:** Solo vemos a lo que prestamos atención.

**Aplicación práctica:**
- Hablar por teléfono mientras conduces
- Multitasking en general
- Revisar emails en reuniones

**Todos estos reducen drásticamente tu capacidad real.**

