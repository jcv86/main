## LECCIÓN 2: POR QUÉ ENSEÑAR EDUCACIÓN FINANCIERA

No se trata de cuánto dinero ganas, sino de cuánto dinero guardas. La inteligencia financiera es la capacidad de resolver problemas financieros.

### La regla número uno

Debes conocer la diferencia entre un activo y un pasivo, y comprar activos. Esa es la regla número uno. Es la única regla. Puede sonar absurdamente simple, pero la mayoría de las personas no sabe lo simple que es.

Un activo es algo que pone dinero en tu bolsillo.
Un pasivo es algo que saca dinero de tu bolsillo.

### Los ricos compran activos

Si quieres ser rico, simplemente pasa tu vida comprando activos. Si quieres ser pobre o de clase media, pasa tu vida comprando pasivos.

Los ricos adquieren activos. Los pobres y la clase media adquieren pasivos, pero piensan que son activos.

### Tu casa no es un activo

Para la mayoría de las personas, su casa es su pasivo más grande, no su activo más grande. Una casa es un pasivo porque saca dinero de tu bolsillo cada mes en forma de pago de hipoteca, impuestos, seguro, mantenimiento y servicios públicos.

