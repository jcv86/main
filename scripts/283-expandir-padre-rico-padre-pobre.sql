## LECCIÓN 4: LA HISTORIA DE LOS IMPUESTOS Y EL PODER DE LAS CORPORACIONES

Los ricos usan corporaciones para protegerse de los impuestos. Saben cómo hacer que el sistema funcione para ellos.

### El origen del impuesto sobre la renta

Los impuestos comenzaron en Inglaterra en 1799 para pagar las guerras napoleónicas. En América, no hubo impuesto sobre la renta hasta 1913, cuando el gobierno necesitó pagar la Primera Guerra Mundial.

El problema fue que el gobierno se volvió adicto al dinero. Así que lo que alguna vez fue un impuesto a los ricos se convirtió en un impuesto para todos.

### El poder de la corporación

Los ricos juegan el juego de manera diferente. Ellos saben sobre el poder de las estructuras legales corporativas. La corporación protege a los ricos.

El empleado gana, paga impuestos, y luego gasta lo que queda. El negocio gana, gasta, y luego paga impuestos sobre lo que queda.

### Coeficiente intelectual financiero

El coeficiente intelectual financiero está formado por conocimiento de cuatro amplias áreas de experticia:

1. Contabilidad: capacidad de leer números
2. Inversión: la ciencia de hacer dinero con dinero
3. Comprensión del mercado: la ciencia de oferta y demanda
4. La ley: ventajas de impuestos y protección

