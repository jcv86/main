## LECCIÓN 1: LOS RICOS NO TRABAJAN POR DINERO

Las personas pobres y la clase media trabajan por dinero. Los ricos hacen que el dinero trabaje para ellos.

### La primera lección

Mi padre rico comenzó mis lecciones pagándome 10 centavos por hora para trabajar en su tienda. Después de algunas semanas, cuando me quejé de que no estaba aprendiendo nada y que estaba desperdiciando mi tiempo por 10 centavos, dejó de pagarme.

Continuó haciendo esto hasta que finalmente exigí ser enseñado. Ahí fue cuando aprendí la primera lección: los pobres y la clase media trabajan por dinero. Los ricos hacen que el dinero trabaje para ellos.

### El miedo y la codicia

La mayoría de las personas son controladas por dos emociones cuando se trata de dinero: el miedo y la codicia. Miedo de no tener dinero los empuja a trabajar duro, y luego cuando reciben su cheque de pago, la codicia comienza.

El patrón de trabajar, ganar dinero, pagar cuentas, trabajar, ganar dinero, pagar cuentas continúa. Sus vidas son controladas por esas dos emociones: miedo y codicia.

### La trampa de la carrera de ratas

La mayoría de las personas trabajan duro toda su vida, y al final de sus días no tienen nada que mostrar excepto deudas y necesidad de más dinero. Están atrapados en la Carrera de Ratas.

La Carrera de Ratas es simplemente el proceso de levantarse cada día, ir a trabajar, pagar cuentas, levantarse al día siguiente, ir a trabajar, pagar cuentas. Es un ciclo sin fin.

