## LECCIÓN 3: OCÚPATE DE TU PROPIO NEGOCIO

Los ricos se enfocan en su columna de activos mientras todos los demás se enfocan en sus columnas de ingresos.

### La diferencia entre tu profesión y tu negocio

Tu profesión puede ser un médico o un abogado, pero tu negocio es lo que posees que te produce ingreso. Los ricos se enfocan en construir su columna de activos.

Los activos reales caen en las siguientes categorías:
1. Negocios que no requieren mi presencia
2. Acciones
3. Bonos
4. Bienes raíces generadores de ingresos
5. Pagarés (IOUs)
6. Regalías de propiedad intelectual
7. Cualquier cosa más que tenga valor, produzca ingreso o se aprecie

