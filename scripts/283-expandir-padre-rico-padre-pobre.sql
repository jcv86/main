## LECCIÓN 5: LOS RICOS INVENTAN DINERO

A menudo en el mundo real, no son los inteligentes quienes se adelantan, sino los audaces.

### El poder del ingenio financiero

Hay dos tipos de inversores:
1. Los que compran paquetes de inversión
2. Los inversores profesionales que crean sus propias oportunidades

El inversor profesional tiene tres habilidades principales:
1. Cómo encontrar una oportunidad que todos los demás perdieron
2. Cómo levantar dinero
3. Cómo organizar personas inteligentes

### Las oportunidades están en todas partes

Las grandes oportunidades no se ven con los ojos. Se ven con la mente. La mayoría de las personas nunca se vuelven ricas simplemente porque no están entrenadas financieramente para reconocer oportunidades frente a ellos.

### El miedo excesivo

Para muchas personas, cuando se trata de dinero, jugar a lo seguro es la cosa más arriesgada que pueden hacer. El fracaso inspira a los ganadores. Y el fracaso derrota a los perdedores.

