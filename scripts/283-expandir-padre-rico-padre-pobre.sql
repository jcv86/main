## LECCIÓN 6: TRABAJA PARA APRENDER, NO TRABAJES POR DINERO

Hay una diferencia entre ser pobre y estar quebrado. Quebrado es temporal, pobre es eterno.

### El poder del aprendizaje

La mayoría de las personas necesitan aprender y dominar más de una habilidad. Yo recomendaría aprender una segunda habilidad. Muchas personas están desempleadas o con salario bajo simplemente porque se especializaron.

Las habilidades especializadas de ventas y marketing son difíciles de aprender para la mayoría de las personas, principalmente debido al miedo al rechazo. Entre mejor seas en comunicar, negociar y manejar tu miedo al rechazo, más fácil será tu vida.

### La importancia de dar

Los pobres son más codiciosos que los ricos. Si una persona es tacaña en las pequeñas cosas, será tacaña en las cosas grandes. La filosofía del mundo es: dame primero, y entonces daré. La filosofía de los ricos es: dar primero.

Siempre que te sientas corto o necesitado de algo, da primero lo que quieres y volverá a ti en cubetas. Es verdad para dinero, amor, felicidad, ventas y contactos.

