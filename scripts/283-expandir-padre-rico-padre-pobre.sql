## INTRODUCCIÓN: HAY UNA NECESIDAD

La escuela no enseña inteligencia financiera. Nos enseñan a trabajar duro y conseguir un buen empleo. Pero si quieres ser rico, necesitas aprender sobre el dinero.

Tuve dos padres, uno rico y uno pobre. Uno era altamente educado e inteligente. Tenía un doctorado. El otro padre nunca terminó el octavo grado. Ambos hombres fueron exitosos en sus carreras, trabajando duro toda su vida. Ambos ganaban ingresos sustanciales. Sin embargo, uno luchaba financieramente toda su vida. El otro se convirtió en uno de los hombres más ricos de Hawái.

### Los dos padres

Padre Pobre decía: El amor al dinero es la raíz de todo mal.
Padre Rico decía: La falta de dinero es la raíz de todo mal.

Padre Pobre decía: Estudia duro para que puedas trabajar para una buena compañía.
Padre Rico decía: Estudia duro para que puedas encontrar una buena compañía para comprar.

Padre Pobre decía: La razón por la que no soy rico es porque tengo hijos.
Padre Rico decía: La razón por la que debo ser rico es porque tengo hijos.

### La elección

A los 9 años, decidí escuchar y aprender de mi padre rico sobre el dinero. Al hacerlo, elegí no escuchar a mi padre pobre, aunque fuera el que tenía todos los títulos universitarios.

