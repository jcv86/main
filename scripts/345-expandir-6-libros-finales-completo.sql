**El Problema:**
Las emociones temporales distorsionan nuestro juicio.

### Técnicas para Obtener Distancia

**1. The 10/10/10 Rule**
Cómo te sentirás sobre esta decisión en:
- 10 minutos
- 10 meses  
- 10 años

Esta técnica revela si estás reaccionando a emociones pasajeras.

**2. What Would I Tell My Best Friend?**
Somos mejores aconsejando a otros que a nosotros mismos.

**Ejercicio:**
Escribe el problema como si un amigo te lo presentara. ¿Qué le dirías?

**3. Honor Your Core Priorities**
Define tus prioridades antes de que surjan las decisiones.

**Ejemplos de Prioridades:**
- Familia sobre trabajo
- Aprendizaje sobre dinero
- Salud sobre conveniencia
- Integridad sobre ventajas temporales

## P: Prepárate para Estar Equivocado

### El Villano: Exceso de Confianza

**El Problema:**
Sobreestimamos nuestra capacidad de predicción.

### Técnicas para Prepararse

**1. Bookend the Future**
Prepara para el mejor y peor escenario.

**Pregunta para el mejor escenario:**
"Si las cosas salen increíblemente bien, ¿cómo capitalizamos?"

**Pregunta para el peor escenario:**
"Si las cosas salen terriblemente mal, ¿cómo sobrevivimos?"

**2. Set a Tripwire**
Establece señales que activen reconsideración.

**Ejemplos:**
- "Si perdemos X dinero, reconsideramos"
- "Si pasan Y meses sin progreso, pivoteamos"
- "Si Z métrica cae, cambiamos de curso"

**3. Prepare to Be Wrong**
Pregúntate: "¿Qué tendría que ser verdad para que esta decisión fuera incorrecta?"

