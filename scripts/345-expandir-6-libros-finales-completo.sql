## Chip Heath y Dan Heath

### Introducción: La Ciencia de las Decisiones Cruciales

Los hermanos Heath investigan por qué algunas decisiones transforman vidas mientras otras nos llevan al arrepentimiento.

**La Pregunta Central:**
¿Por qué tomamos tantas decisiones de las que luego nos arrepentimos, incluso cuando tenemos tiempo para pensar?

### El Proceso WRAP

El marco WRAP ayuda a tomar mejores decisiones:

**W - Widen Your Options (Amplía tus opciones)**
**R - Reality-Test Your Assumptions (Prueba tus suposiciones)**
**A - Attain Distance (Obtén distancia)**
**P - Prepare to Be Wrong (Prepárate para estar equivocado)**

## W: Amplía Tus Opciones

### El Villano: Marcos Estrechos

**El Problema:**
Enmarcamos decisiones como "esto o aquello" cuando hay más alternativas.

**Ejemplos:**
- "¿Contrato a este candidato o no?" (Marco estrecho)
- "¿Cómo puedo encontrar al mejor candidato posible?" (Marco amplio)

### Técnicas para Ampliar Opciones

**1. La Prueba de Vanishing Options**
"¿Si ninguna de tus opciones actuales estuviera disponible, qué harías?"

Esto fuerza creatividad y descubre alternativas ocultas.

**2. Multitasking de Opciones**
Considera múltiples alternativas simultáneamente.

**Investigación:**
Estudios muestran que considerar más de dos opcativas aumenta significativamente la calidad de las decisiones.

**3. Find Someone Who''s Solved Your Problem**
Alguien en algún lugar ya resolvió un problema similar.

**Pregunta clave:**
"¿Quién más ha enfrentado este problema?"

## R: Prueba tus Suposiciones con la Realidad

### El Villano: El Sesgo de Confirmación

**El Problema:**
Buscamos información que confirme nuestras creencias preexistentes.

### Técnicas para Probar Suposiciones

**1. Consider the Opposite**
Pregunta activamente: "¿Qué pasaría si estuviera equivocado?"

**2. Zoom Out, Zoom In**

**Zoom Out (Vista Externa):**
¿Qué le pasó a otros en situaciones similares?
- Tasas base y estadísticas
- Experiencias de pares
- Patrones históricos

**Zoom In (Vista Interna):**
Experiencia directa y específica
- Hacer pruebas pequeñas
- Experimentos de bajo riesgo
- Prototipos y MVPs

**3. Ooch (Prueba Pequeña)**
En lugar de predecir, experimenta.

**Ejemplo:**
- No preguntes: "¿Me gustará este trabajo?"
- Mejor: Haz una pasantía de una semana

## A: Obtén Distancia Antes de Decidir

