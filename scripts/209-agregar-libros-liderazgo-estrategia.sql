**2. Precio:**
- ¿Tu precio es accesible para la masa de compradores?
- ¿Está alineado con el valor percibido?

**3. Costo:**
- ¿Puedes producir a un costo que permita ganancia?
- ¿Tu estructura de costos es sostenible?

**4. Adopción:**
- ¿Qué obstáculos de adopción debes superar?
- ¿Cómo educarás al mercado sobre tu innovación?

**Herramientas para Crear Océanos Azules:**

**El Marco de las Cuatro Acciones:**
Cuestiona la lógica estratégica de tu industria:

**1. Eliminar:**
- ¿Qué factores que la industria da por sentados deberían eliminarse?

**2. Reducir:**
- ¿Qué factores deberían reducirse muy por debajo del estándar de la industria?

**3. Incrementar:**
