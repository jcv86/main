- Productividad (mismas horas, más output)
- Calidad de decisiones (menos reverses)
- Clima de equipo (surveys)
- Resultados de negocio

**Salud:**
- Presión arterial
- Calidad de sueño (apps de tracking)
- Frecuencia de enfermedad
- Niveles de energía

