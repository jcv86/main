**Desafío mayor:**
- Inercia organizacional
- Escepticismo
- Sistemas establecidos
- Expectativas de stakeholders

**Enfoque:**

**1. Liderazgo comprometido:**
   - CEO/Board deben creer
   - Disposición a decisiones difíciles
   - Modelar personalmente
   - Paciencia para transformación

**2. Comenzar con por qué:**
   - Articular propósito claro
   - Conectar con historia
   - Invitar input amplio
   - Inspirar, no imponer

**3. Pilotos y experimentos:**
   - No transformación overnight
   - Teams voluntarios primero
   - Aprender y ajustar
   - Éxitos como ejemplos

**4. Comunicación constante:**
   - Por qué estamos haciendo esto
   - Qué estamos aprendiendo
   - Cómo progresamos
   - Escuchar preocupaciones

**5. Sistemas y estructuras:**
   - Incentivos alineados
   - Métricas expandidas
   - Procesos rediseñados
   - Governance evolucionado

