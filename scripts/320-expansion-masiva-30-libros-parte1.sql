### Mindfulness en Toma de Decisiones

**El problema:**
En negocios modernos, decisiones son constantes, rápidas, con información incompleta, bajo presión.

**Sin mindfulness:**
- Decisiones reactivas
- Sesgos no notados
- Información ignorada
- Emociones no procesadas

**Con mindfulness:**
- Decisiones reflexivas
- Sesgos reconocidos
- Información integrada
- Emociones informando, no dominando

#### Los Sesgos Cognitivos y Mindfulness

**Sesgos comunes:**

**1. Confirmation bias:**
Buscar información que confirma creencias existentes

**Cómo mindfulness ayuda:**
Notando impulso de buscar solo evidencia confirmatoria, puedes activamente buscar evidencia contradictoria

**2. Anchoring:**
Sobreconfiar en primera información recibida

**Cómo mindfulness ayuda:**
Awareness de cómo primer número/idea ancla pensamiento, puedes deliberadamente considerar rango más amplio

**3. Sunk cost fallacy:**
Continuar inversión porque ya invertiste, ignorando que costos pasados son irrelevantes

**Cómo mindfulness ayuda:**
Notando atamiento emocional a decisión pasada, puedes evaluarobjeto objetivamente situación presente

**4. Groupthink:**
Conformidad para mantener armonía de grupo

**Cómo mindfulness ayuda:**
Autoconciencia de tendencia a conformar, puedes elegir expresar disenso constructivo

#### Proceso de Decisión Consciente

**1. Pausa:**
No reacciones inmediatamente. Crea espacio para claridad.

**2. Observa:**
- ¿Qué información tengo?
- ¿Qué emociones estoy sintiendo?
- ¿Qué sesgos podrían estar activos?
- ¿Qué estoy asumiendo?

**3. Consulta:**
- Perspectivas diversas
- Datos y evidencia
- Intuición (informada, no reactiva)
- Valores y propósito

**4. Elige:**
Decisión informada por todo lo anterior, no dominada por emoción o sesgo

**5. Actúa:**
Con compromiso y apertura a ajustar

**6. Revisa:**
Feedback loop - ¿qué aprendiste?

