# HÁBITOS ATÓMICOS
## Por James Clear

### INTRODUCCIÓN: MI HISTORIA

La acumulación de muchas pequeñas victorias puede conducir a resultados extraordinarios. Esta es la historia de cómo los hábitos atómicos transformaron mi vida y pueden transformar la tuya.

Cuando tenía 16 años, un bate de béisbol me golpeó en la cara. Mi nariz se rompió en varios pedazos. Perdí el conocimiento antes de tocar el suelo. Cuando desperté en el hospital, mi cara estaba tan hinchada que apenas podía ver. Los médicos me dijeron que había sufrido una fractura múltiple del cráneo y que mi cerebro estaba sangrando.

Durante meses, mi vida fue una batalla constante. No podía hacer ejercicio. No podía estudiar. Apenas podía pensar con claridad. Pero poco a poco, día tras día, comencé a mejorar. No fue un cambio dramático, sino una serie de pequeñas mejoras que se acumularon con el tiempo.

### PARTE I: LOS FUNDAMENTOS

## CAPÍTULO 1: EL SORPRENDENTE PODER DE LOS HÁBITOS ATÓMICOS

Los hábitos son el interés compuesto de la superación personal. De la misma manera que el dinero se multiplica mediante el interés compuesto, los efectos de tus hábitos se multiplican a medida que los repites. Parecen marcar poca diferencia en un día cualquiera y, sin embargo, el impacto que generan a lo largo de los meses y años puede ser enorme.

**El poder del 1% de mejora**

Si mejoras un 1% cada día durante un año, terminarás siendo 37 veces mejor al final del año. Por el contrario, si empeoras un 1% cada día, llegarás casi a cero. Los pequeños cambios a menudo parecen no marcar ninguna diferencia hasta que cruzas un umbral crítico.

**Los hábitos son una espada de doble filo**

Los buenos hábitos hacen que el tiempo sea tu aliado. Los malos hábitos hacen que el tiempo sea tu enemigo. El impacto creado por un cambio en tus hábitos es similar al efecto de cambiar la ruta de un avión en unos pocos grados. Si un avión que sale de Los Ángeles a Nueva York ajusta su rumbo 3.5 grados al sur, aterrizará en Washington D.C. en lugar de Nueva York.

**El valle de la decepción**

Esperamos un progreso lineal, pero la realidad es que los resultados de nuestros esfuerzos suelen retrasarse. No es hasta meses o años después que nos damos cuenta del verdadero valor del trabajo previo que hemos realizado. Esto puede resultar en un "valle de la decepción" donde la gente se siente desanimada después de poner meses de arduo trabajo sin experimentar ningún resultado.

**Olvida las metas, concéntrate en los sistemas**

Las metas son los resultados que quieres lograr. Los sistemas son los procesos que sigues para lograr esos resultados. Si ignoras las metas y te concentras solo en el sistema, ¿aún tendrías éxito? Creo que sí.

Problemas con enfocarse solo en las metas:
1. Los ganadores y perdedores tienen las mismas metas
2. Lograr una meta es solo un cambio momentáneo
3. Las metas restringen tu felicidad
4. Las metas están en desacuerdo con el progreso a largo plazo

## CAPÍTULO 2: CÓMO TUS HÁBITOS MOLDEAN TU IDENTIDAD (Y VICEVERSA)

Cambiar nuestros hábitos es desafiante por dos razones: (1) tratamos de cambiar la cosa incorrecta y (2) tratamos de cambiar nuestros hábitos de la manera incorrecta.

**Los tres niveles de cambio**

Hay tres niveles en los que puede ocurrir el cambio:
1. **Cambio de resultados**: cambiar tus resultados (perder peso, publicar un libro, ganar un campeonato)
2. **Cambio de proceso**: cambiar tus hábitos y sistemas (implementar una nueva rutina en el gimnasio, organizar tu escritorio)
3. **Cambio de identidad**: cambiar tus creencias (tu visión del mundo, tu autoimagen, tus juicios sobre ti mismo y los demás)

La mayoría de las personas comienzan enfocándose en lo que quieren lograr. Esto nos lleva a hábitos basados en resultados. La alternativa es construir hábitos basados en la identidad. Con este enfoque, comenzamos enfocándonos en quién deseamos convertirnos.

**El proceso de dos pasos para cambiar tu identidad**

1. Decide el tipo de persona que quieres ser
2. Demuéstratelo a ti mismo con pequeñas victorias

Tus hábitos son cómo encarnas tu identidad. Cuando haces tu cama cada mañana, encarnas la identidad de una persona organizada. Cuando escribes cada día, encarnas la identidad de una persona creativa. Cuanto más repites un comportamiento, más refuerzas la identidad asociada con ese comportamiento.

## CAPÍTULO 3: CÓMO CONSTRUIR MEJORES HÁBITOS EN 4 SENCILLOS PASOS

Un hábito es un comportamiento que se ha repetido suficientes veces para volverse automático. El proceso de formación de hábitos comienza con prueba y error.

**El ciclo del hábito**

El proceso de construcción de un hábito se puede dividir en cuatro pasos simples: señal, anhelo, respuesta y recompensa.

1. **Señal**: desencadena tu cerebro para iniciar un comportamiento
2. **Anhelo**: la fuerza motivacional detrás de cada hábito
3. **Respuesta**: el hábito real que realizas
4. **Recompensa**: el objetivo final de cada hábito

Si un comportamiento es insuficiente en cualquiera de las cuatro etapas, no se convertirá en un hábito.

**Las cuatro leyes del cambio de comportamiento**

Para crear un buen hábito:
1. **Hacerlo obvio** (Señal)
2. **Hacerlo atractivo** (Anhelo)
3. **Hacerlo fácil** (Respuesta)
4. **Hacerlo satisfactorio** (Recompensa)

Para romper un mal hábito, invierte estas leyes:
1. Hacerlo invisible
2. Hacerlo poco atractivo
3. Hacerlo difícil
4. Hacerlo insatisfactorio

### PARTE II: LA PRIMERA LEY - HACERLO OBVIO

## CAPÍTULO 4: EL HOMBRE QUE NO SE VEÍA BIEN

El cerebro humano es una máquina de predicción. Está continuamente tomando la información que te rodea y analizando la información que llega. Con suficiente práctica, puedes captar las señales que predicen ciertos resultados sin pensar conscientemente en ello.

**El registro de hábitos**

Uno de nuestros mayores desafíos al cambiar hábitos es mantener la conciencia de lo que realmente estamos haciendo. Antes de que podamos construir efectivamente nuevos hábitos, necesitamos tener control sobre los actuales.

El proceso de cambio de comportamiento siempre comienza con la conciencia. Necesitas ser consciente de tus hábitos antes de que puedas cambiarlos. Aquí es donde entra el Registro de Hábitos.

**Ejercicio: El Registro de Hábitos**

Haz una lista de tus hábitos diarios. Una vez que tengas una lista completa, observa cada comportamiento y pregúntate: "¿Es este un buen hábito, un mal hábito o un hábito neutral?"

## CAPÍTULO 5: LA MEJOR MANERA DE COMENZAR UN NUEVO HÁBITO

La implementación de intenciones es una estrategia que puedes usar para emparejar un nuevo hábito con un tiempo y lugar específicos.

**La fórmula de implementación de intenciones**

"Yo [COMPORTAMIENTO] a las [TIEMPO] en [LUGAR]."

Ejemplos:
- Meditación: "Meditaré durante un minuto a las 7 a.m. en mi cocina."
- Ejercicio: "Haré ejercicio durante una hora a las 5 p.m. en mi gimnasio local."
- Estudio: "Estudiaré español durante 20 minutos a las 6 p.m. en mi dormitorio."

**Acumulación de hábitos**

Una de las mejores maneras de construir un nuevo hábito es identificar un hábito actual que ya haces cada día y luego apilar tu nuevo comportamiento encima.

La fórmula de acumulación de hábitos es:
"Después de [HÁBITO ACTUAL], yo [NUEVO HÁBITO]."

Ejemplos:
- "Después de servirme mi café matutino, meditaré durante un minuto."
- "Después de quitarme los zapatos del trabajo, inmediatamente me cambiaré a mi ropa de ejercicio."
- "Después de sentarme a cenar, diré una cosa por la que estoy agradecido ese día."

## CAPÍTULO 6: LA MOTIVACIÓN ESTÁ SOBREVALORADA; EL AMBIENTE A MENUDO IMPORTA MÁS

Las personas a menudo eligen productos no por lo que son, sino por dónde están. El ambiente es la mano invisible que moldea el comportamiento humano.

**Cómo diseñar tu ambiente para el éxito**

Cada hábito es iniciado por una señal, y somos más propensos a notar señales que se destacan. Haz que las señales de los buenos hábitos sean obvias en tu ambiente.

Si quieres hacer que un hábito sea una gran parte de tu vida, haz que la señal sea una gran parte de tu ambiente. Las señales más persistentes son las que están en nuestro entorno.

**El contexto es la señal**

Es más fácil construir nuevos hábitos en un nuevo ambiente porque no estás luchando contra viejas señales. Crea un espacio separado para el trabajo, el estudio, el ejercicio, el entretenimiento y la cocina.

## CAPÍTULO 7: EL SECRETO DEL AUTOCONTROL

Las personas con alto autocontrol tienden a pasar menos tiempo en situaciones tentadoras. Es más fácil evitar la tentación que resistirla.

**Cómo eliminar un mal hábito**

La inversión de la primera ley del cambio de comportamiento es hacerlo invisible. Una vez que un hábito se forma, es poco probable que se olvide. Reduce la exposición a la señal que lo causa.

### PARTE III: LA SEGUNDA LEY - HACERLO ATRACTIVO

## CAPÍTULO 8: CÓMO HACER UN HÁBITO IRRESISTIBLE

Cuanto más atractivo sea una oportunidad, más probabilidades hay de que se convierta en un hábito. Los hábitos son un circuito de retroalimentación impulsado por la dopamina.

**La agrupación de tentaciones**

Empareja una acción que quieres hacer con una acción que necesitas hacer. La fórmula es:
"Después de [HÁBITO ACTUAL], yo [HÁBITO QUE NECESITO]."
"Después de [HÁBITO QUE NECESITO], yo [HÁBITO QUE QUIERO]."

Ejemplo:
- "Después de sacar mi teléfono del bolsillo, haré diez respiraciones profundas (necesito)."
- "Después de hacer diez respiraciones profundas, revisaré Facebook (quiero)."

## CAPÍTULO 9: EL PAPEL DE LA FAMILIA Y LOS AMIGOS EN LA FORMACIÓN DE HÁBITOS

La cultura en la que vivimos determina qué comportamientos son atractivos para nosotros. Tendemos a adoptar hábitos que son elogiados y aprobados por nuestra cultura porque tenemos un fuerte deseo de encajar y pertenecer a la tribu.

**Cómo encontrar y arreglar las causas de tus malos hábitos**

Cada comportamiento tiene un anhelo superficial y un motivo subyacente más profundo. Tus hábitos son soluciones modernas a deseos antiguos.

### PARTE IV: LA TERCERA LEY - HACERLO FÁCIL

## CAPÍTULO 11: CAMINA LENTAMENTE, PERO NUNCA RETROCEDAS

La forma más efectiva de aprendizaje es la práctica, no la planificación. Concéntrate en tomar acción, no en estar en movimiento.

**La ley del mínimo esfuerzo**

La energía es preciosa, y el cerebro está programado para conservarla siempre que sea posible. Cuando decides qué hacer, naturalmente gravitas hacia la opción que requiere la menor cantidad de trabajo.

Reduce la fricción asociada con los buenos hábitos. Cuando la fricción es baja, los hábitos son fáciles.

## CAPÍTULO 12: LA LEY DEL MÍNIMO ESFUERZO

Crea un ambiente donde hacer lo correcto sea lo más fácil posible. Reduce la fricción asociada con el buen comportamiento. Cuando la fricción es alta, los hábitos son difíciles.

**Preparar el ambiente para uso futuro**

- Quieres comer más saludable: Cuando llegues del supermercado, corta frutas y verduras y colócalas en contenedores.
- Quieres hacer más ejercicio: Prepara tu ropa de gimnasio, zapatos, bolsa de gimnasio y botella de agua la noche anterior.
- Quieres mejorar tu dieta: Usa platos más pequeños para reducir las porciones de calorías.

## CAPÍTULO 13: CÓMO DEJAR DE PROCRASTINAR USANDO LA REGLA DE LOS DOS MINUTOS

Cuando comienzas un nuevo hábito, debe tomar menos de dos minutos hacerlo. Casi cualquier hábito puede reducirse a una versión de dos minutos:

- "Leer antes de dormir cada noche" se convierte en "Leer una página."
- "Hacer treinta minutos de yoga" se convierte en "Sacar mi tapete de yoga."
- "Estudiar para la clase" se convierte en "Abrir mis apuntes."
- "Correr tres millas" se convierte en "Atarme mis zapatos para correr."

La idea es hacer que tus hábitos sean lo más fáciles posible para comenzar. Cualquiera puede meditar durante un minuto, leer una página o poner un artículo de ropa en el cesto de la ropa sucia.

### PARTE V: LA CUARTA LEY - HACERLO SATISFACTORIO

## CAPÍTULO 15: LA REGLA CARDINAL DEL CAMBIO DE COMPORTAMIENTO

Somos más propensos a repetir un comportamiento cuando la experiencia es satisfactoria. El cerebro humano evolucionó para priorizar las recompensas inmediatas sobre las retrasadas.

**Cómo mantenerse con los buenos hábitos todos los días**

Una de las sensaciones más satisfactorias es la sensación de hacer progreso. Un rastreador de hábitos es una forma simple de medir si hiciste un hábito.

**Beneficios del seguimiento de hábitos:**
1. El seguimiento de hábitos es obvio
2. El seguimiento de hábitos es atractivo
3. El seguimiento de hábitos es satisfactorio

## CAPÍTULO 16: CÓMO MANTENER LOS BUENOS HÁBITOS TODOS LOS DÍAS

El primer error nunca es el que te arruina. Es la espiral de errores repetidos que sigue. Perder un día es un accidente. Perder dos días es el comienzo de un nuevo hábito.

**La regla de nunca perder dos veces**

Si pierdes un día, vuelve a la pista lo más rápido posible. Nunca pierdas dos veces seguidas.

