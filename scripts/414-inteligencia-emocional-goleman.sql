## INTRODUCCIÓN

La inteligencia emocional (IE) es la capacidad de reconocer, entender y manejar nuestras propias emociones, así como reconocer, entender e influir en las emociones de los demás.

**Las 5 Competencias de la Inteligencia Emocional:**

1. **Autoconciencia** - Conocer tus propias emociones
2. **Autorregulación** - Manejar tus emociones
3. **Motivación** - Motivarte a ti mismo
4. **Empatía** - Reconocer emociones en otros
5. **Habilidades Sociales** - Manejar relaciones

---

## PARTE I: EL CEREBRO EMOCIONAL

### La Amígdala: El Guardián Emocional

La amígdala es el centro de alarma del cerebro. Procesa emociones antes que la corteza prefrontal (cerebro pensante).

**Secuestro Amigdalar:**
Cuando la amígdala detecta peligro, puede "secuestrar" el cerebro racional, causando reacciones emocionales intensas e inmediatas.

**Ejemplo:**
Un conductor te corta el paso → Amígdala activa ira → Gritas antes de pensar → Luego te arrepientes

**Clave:** La amígdala reacciona 100 veces más rápido que el cerebro pensante.

