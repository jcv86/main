## AUTORREGULACIÓN

Manejar emociones para que faciliten la tarea entre manos.

**Estrategias:**

**1. Reevaluación Cognitiva:**
Cambiar cómo piensas sobre una situación.

Ejemplo:
- Situación: Tu jefe te critica
- Pensamiento automático: "Me odia, soy un fracaso"
- Reevaluación: "Está estresado, esto no es personal, puedo aprender"

**2. Respiración 4-7-8:**
- Inhala 4 segundos
- Sostén 7 segundos
- Exhala 8 segundos
- Repite 4 veces

**3. Manejo de la Ira:**
- Reconoce señales tempranas
- Desafía pensamientos que alimentan ira
- Toma tiempo fuera
- Ejercicio físico
- Aborda problema cuando estés calmado

