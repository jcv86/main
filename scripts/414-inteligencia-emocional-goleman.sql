## AUTOCONCIENCIA

La autoconciencia es reconocer un sentimiento mientras ocurre.

**Tres Estilos:**

1. **Consciente de Sí Mismo** - Reconoce emociones, las maneja bien
2. **Sumergido** - Abrumado por emociones, sin control
3. **Aceptante** - Claro sobre sentimientos pero no intenta cambiarlos

**Desarrollar Autoconciencia:**

**Diario Emocional:**
- Registra emociones 3 veces al día
- Identifica: ¿Qué siento? ¿Por qué? ¿Intensidad 1-10?

**Escaneo Corporal:**
- Pausa cada 2 horas
- Pregunta: ¿Qué siento en mi cuerpo?
- Tensión = estrés, Calor = ira, Pesadez = tristeza

