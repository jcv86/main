## MOTIVACIÓN

Capacidad de motivarse a uno mismo.

**Flujo: Estado Óptimo**

Concentración tan enfocada que equivale a absorción absoluta.

**Características:**
- Desafío óptimo (ni muy fácil ni muy difícil)
- Metas claras
- Retroalimentación inmediata
- Concentración intensa
- Pérdida de autoconciencia
- Distorsión del tiempo

**Optimismo Aprendido:**

**Técnica ABCDE:**
- **A - Adversidad:** Evento negativo
- **B - Creencia:** Tu interpretación
- **C - Consecuencia:** Cómo te sientes
- **D - Disputa:** Desafía la creencia negativa
- **E - Energización:** Resultado de disputa exitosa

