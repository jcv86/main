## EMPATÍA

Capacidad de saber lo que siente otra persona.

**Niveles:**
1. **Empatía Cognitiva** - Entender intelectualmente
2. **Empatía Emocional** - Sentir lo que el otro siente
3. **Preocupación Empática** - Actuar para ayudar

**Leer Emociones:**

**Rostro:**
- Cejas levantadas = Sorpresa
- Cejas fruncidas = Preocupación
- Labios apretados = Ira
- Sonrisa genuina = Arrugas en ojos

**Desarrollar Empatía:**

**Escucha Activa:**
- Enfócate 100%
- No planees tu respuesta
- Refleja: "Parece que te sientes..."
- Pregunta: "¿Es así?"

