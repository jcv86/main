### Los Once Arquetipos Sistémicos

Los arquetipos sistémicos son patrones de comportamiento recurrentes que ayudan a ver estructuras subyacentes a situaciones complejas.

#### 1. Límites del Crecimiento

**Estructura:** Un proceso de refuerzo genera un período de crecimiento acelerado, luego se encuentra con un proceso de balance que desacelera el crecimiento hasta detenerlo o revertirlo.

**Principio de gestión:** No presiones el proceso de refuerzo, elimina (o debilita) el factor limitante.

**Ejemplo empresarial:**
Startup tecnológica crece rápidamente hasta que la calidad del servicio al cliente se deteriora, causando cancelaciones que igualan las nuevas adquisiciones. La solución no es invertir más en marketing (presionar el refuerzo), sino mejorar el servicio al cliente (eliminar el límite).

#### 2. Desplazamiento de la Carga

**Estructura:** Se usa una solución de corto plazo para corregir un problema, con resultados inmediatos aparentemente positivos. A medida que esta corrección se usa cada vez más, las medidas fundamentales se aplican cada vez menos.

**Principio de gestión:** Concéntrate en la solución fundamental. Si se usa una solución sintomática, úsala para ganar tiempo mientras trabajas en la solución fundamental.

**Ejemplo:**
Empresa que constantemente "apaga incendios" con trabajo extra y horas adicionales (síntoma), en lugar de mejorar procesos y sistemas (fundamental). Con el tiempo, la capacidad de mejorar procesos se atrofia porque todos están ocupados apagando incendios.

#### 3. Erosión de Metas

**Estructura:** Un proceso de balance ajusta una meta o estándar en respuesta a presión de corto plazo, erosionando gradualmente la visión de largo plazo.

**Principio de gestión:** Mantén la visión. No comprometas la meta de largo plazo por alivio de corto plazo.

**Ejemplo corporativo:**
Empresa que gradualmente reduce estándares de calidad para cumplir plazos y reducir costos. Con el tiempo, la marca se asocia con baja calidad y es difícil recuperar el posicionamiento premium.

#### 4. Escalada

**Estructura:** Dos partes creen que su bienestar depende de ventaja relativa sobre la otra, llevando a una espiral de competencia destructiva.

**Principio de gestión:** Busca maneras de que ambas partes "ganen", o logra que una parte "pierda" unilateralmente.

**Ejemplo:**
Guerra de precios entre competidores que erosiona márgenes de toda la industria. La solución puede ser diferenciación, consolidación de mercado, o que un competidor se retire de ciertos segmentos.

#### 5. Éxito para quien Tiene Éxito

**Estructura:** Si un individuo o grupo gana más recursos que otro, tiende a tener más éxito, lo que justifica asignarle aún más recursos.

**Principio de gestión:** Busca el objetivo superior que puede ser servido al ayudar al que recibe menos recursos, o rompe (o debilita) el vínculo entre éxito y asignación de recursos.

**Ejemplo organizacional:**
Departamento estrella recibe más presupuesto y talento, mientras otros departamentos se marchitan. Con el tiempo, la organización pierde diversidad de capacidades y se vuelve vulnerable cuando cambian las condiciones del mercado.

