## Introducción: El Nuevo Paradigma Organizacional

En un mundo de cambio acelerado, las organizaciones que prosperarán en el futuro serán aquellas que descubran cómo aprovechar el compromiso y la capacidad de aprendizaje de las personas en todos los niveles de la organización. Las organizaciones inteligentes son aquellas donde la gente expande continuamente su capacidad de crear los resultados que realmente desea, donde se cultivan nuevos y expansivos patrones de pensamiento, donde la aspiración colectiva queda en libertad y donde la gente continuamente aprende a aprender en conjunto.

Peter Senge nos presenta cinco disciplinas fundamentales que toda organización debe dominar para convertirse en una organización que aprende:

### Las Cinco Disciplinas

**1. Dominio Personal (Personal Mastery)**
El dominio personal es la disciplina del crecimiento y el aprendizaje personal. Las personas con alto nivel de dominio personal viven en modo de aprendizaje continuo, nunca "llegan". La búsqueda del dominio personal es un proceso continuo de clarificar lo que es importante para nosotros, de desarrollar la capacidad de ver con mayor claridad la realidad actual, y de reconocer la brecha creativa entre nuestra visión y la realidad.

Las personas con dominio personal tienen:
- Visión personal clara
- Capacidad de sostener tensión creativa
- Compromiso con la verdad
- Consciencia de sus modelos mentales
- Capacidad de aprender de los errores

**2. Modelos Mentales (Mental Models)**
Los modelos mentales son supuestos profundamente arraigados, generalizaciones, o incluso imágenes que influyen sobre nuestro modo de comprender el mundo y actuar. Trabajar con modelos mentales implica aprender a desenterrar nuestras imágenes internas del mundo, llevarlas a la superficie y someterlas a un riguroso escrutinio.

**3. Visión Compartida (Shared Vision)**
Una visión compartida no es una idea, es una fuerza en el corazón de la gente, una fuerza de impresionante poder. Puede estar inspirada por una idea, pero si es tan convincente como para lograr el respaldo de más de una persona, cesa de ser una abstracción. Es palpable. La gente comienza a verla como si existiera.

**4. Aprendizaje en Equipo (Team Learning)**
El aprendizaje en equipo es el proceso de alinearse y desarrollar la capacidad de un equipo para crear los resultados que sus miembros realmente desean. Se construye sobre el dominio personal y la visión compartida, pero no es suficiente que los individuos sean brillantes; el equipo debe aprender a trabajar junto de manera efectiva.

**5. Pensamiento Sistémico (Systems Thinking)**
El pensamiento sistémico es la quinta disciplina que integra a todas las demás. Es la disciplina que nos ayuda a ver las interrelaciones en lugar de cadenas lineales de causa-efecto, y los procesos de cambio en lugar de instantáneas.

