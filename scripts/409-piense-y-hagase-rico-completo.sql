## CAPÍTULO 4: LA AUTOSUGESTIÓN - EL MEDIO PARA INFLUIR EN LA MENTE SUBCONSCIENTE

### ¿Qué es la Autosugestión?

La autosugestión es el medio de comunicación entre la mente consciente (donde se originan los pensamientos) y la mente subconsciente (donde se almacenan y actúan).

**Principio Clave:**
Tu mente subconsciente no distingue entre experiencias reales e imaginadas. Si imaginas algo vívidamente con emoción, tu subconsciente lo acepta como real.

### Cómo Usar la Autosugestión

**Paso 1: Retírate a un Lugar Tranquilo**
Donde no serás interrumpido.

**Paso 2: Lee Tu Declaración en Voz Alta**
Lee la declaración de tu meta (del Capítulo 2) con EMOCIÓN.

**Paso 3: Visualiza**
Cierra los ojos y VE el dinero (o tu meta) como si ya lo tuvieras.

**Paso 4: Siente**
SIENTE las emociones de ya tener tu meta. Alegría, gratitud, orgullo.

**Paso 5: Repite Dos Veces al Día**
Al despertar y antes de dormir, cuando tu mente subconsciente es más receptiva.

### Por Qué Funciona

Tu mente subconsciente trabaja 24/7. Cuando le das instrucciones claras y emocionales, comienza a:
1. Buscar oportunidades
2. Atraer personas y circunstancias
3. Darte ideas e inspiración
4. Guiar tus acciones automáticamente

### Ejemplo Práctico

**Meta:** Ganar $100,000 en un año

**Declaración:**
"Tengo $100,000 en mi cuenta bancaria. Puedo ver el estado de cuenta mostrando $100,000. Siento la seguridad y libertad que este dinero me da. Estoy agradecido por las oportunidades que me permitieron ganar este dinero sirviendo a otros."

**Práctica:**
- Mañana: 10 minutos visualizando y sintiendo
- Noche: 10 minutos visualizando y sintiendo
- Durante el día: Cada vez que pienses en tu meta, visualiza brevemente

