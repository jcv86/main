## CAPÍTULO 2: EL DESEO - EL PUNTO DE PARTIDA DE TODO LOGRO

### El Deseo Ardiente

No es suficiente "querer" algo. Debes tener un DESEO ARDIENTE, una obsesión, un anhelo que consume tu mente día y noche.

**Diferencia entre Deseo y Esperanza:**

**Esperanza:** "Sería bueno tener un millón de dólares"
**Deseo Ardiente:** "TENDRÉ un millón de dólares y no aceptaré nada menos"

### Los Seis Pasos para Transformar Deseo en Realidad

**PASO 1: Fija la Cantidad Exacta**
No digas "quiero mucho dinero". Di "quiero exactamente $100,000".

**PASO 2: Determina Qué Darás a Cambio**
No hay algo como "algo por nada". ¿Qué servicio darás? ¿Qué valor crearás?

**PASO 3: Establece una Fecha Límite**
"Tendré $100,000 para el 31 de diciembre de 2026"

**PASO 4: Crea un Plan Definido**
Comienza inmediatamente, esté listo o no. Mejora el plan sobre la marcha.

**PASO 5: Escribe una Declaración Clara**
Escribe los pasos 1-4 en una declaración concisa.

**PASO 6: Lee Tu Declaración Dos Veces al Día**
Lee en voz alta al despertar y antes de dormir. VISUALIZA y SIENTE que ya tienes el dinero.

### Ejemplo de Declaración:

"Para el 31 de diciembre de 2026, tendré $100,000 en mi posesión. Este dinero vendrá de mi negocio de consultoría, donde ayudaré a 50 empresas a aumentar sus ventas en un 30%. Creo que tendré este dinero. Mi fe es tan fuerte que puedo verlo ahora frente a mí. Está esperando que tome posesión de él. Estoy esperando un plan para acumular este dinero, y seguiré ese plan cuando llegue."

### La Historia de la Hija de Napoleon Hill

La hija de Hill nació sin orejas y los doctores dijeron que nunca podría oír. Hill RECHAZÓ aceptar esto. Él tenía un DESEO ARDIENTE de que su hija oyera.

**Lo que Hizo:**
1. Repetía constantemente que ella oiría
2. Le hablaba como si pudiera oír
3. Nunca usó la palabra "sordo" en su presencia
4. Desarrolló en ella la creencia de que oiría

**El Resultado:**
A través de un audífono especial y su fe inquebrantable, su hija desarrolló un 65% de audición normal y vivió una vida normal.

**La Lección:**
El deseo ardiente, combinado con fe, puede superar obstáculos "imposibles".

