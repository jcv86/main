Henry Ford fue demandado por un periódico que lo llamó "ignorante". En el juicio, los abogados le hicieron preguntas de conocimiento general que no pudo responder.

**Respuesta de Ford:**
"Si realmente quisiera responder la pregunta tonta que me acaba de hacer, o cualquiera de las otras que me ha hecho, déjeme recordarle que tengo una fila de botones eléctricos en mi escritorio, y presionando el botón correcto, puedo convocar a mi ayuda a hombres que pueden responder CUALQUIER pregunta que desee hacer."

**La Lección:**
No necesitas saber todo. Necesitas saber dónde encontrar el conocimiento cuando lo necesitas, y cómo organizarlo en planes de acción.

