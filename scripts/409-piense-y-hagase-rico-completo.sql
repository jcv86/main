## INTRODUCCIÓN

"Piense y Hágase Rico" es el resultado de más de 20 años de investigación de Napoleon Hill, quien estudió a más de 500 millonarios de su época, incluyendo a Andrew Carnegie, Henry Ford, Thomas Edison, y John D. Rockefeller.

El libro revela los secretos del éxito que estos hombres utilizaron para acumular sus fortunas. Pero más importante aún, revela que estos principios pueden ser aplicados por cualquier persona que desee alcanzar el éxito.

**La Filosofía del Logro Personal:**

Este libro no es solo sobre hacer dinero. Es sobre lograr cualquier objetivo que te propongas en la vida. Los principios funcionan para:
- Riqueza financiera
- Relaciones exitosas
- Salud y bienestar
- Logros profesionales
- Realización personal

**El Secreto:**

A lo largo del libro, Hill menciona "el secreto" que Andrew Carnegie le reveló. Este secreto aparece al menos 100 veces en el libro, pero nunca se menciona directamente. Carnegie creía que aquellos que están listos para el secreto lo reconocerán cuando lo vean.

**Pista del Secreto:** El secreto está en cada capítulo. Está en la acción, no solo en el conocimiento.

