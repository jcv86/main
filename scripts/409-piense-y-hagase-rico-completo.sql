## CAPÍTULO 3: LA FE - VISUALIZACIÓN Y CREENCIA EN EL LOGRO DEL DESEO

### ¿Qué es la Fe?

La fe es el "elixir eterno" que da vida, poder y acción al impulso del pensamiento.

**Fe = Pensamiento + Emoción Positiva**

La fe es un estado mental que puede ser inducido mediante afirmaciones o instrucciones repetidas a la mente subconsciente.

### Cómo Desarrollar Fe

**1. Autosugestión:**
Repite tus metas y deseos a tu mente subconsciente hasta que se conviertan en creencias automáticas.

**2. Visualización:**
Ve tu meta como ya lograda. Siente las emociones de haberla alcanzado.

**3. Emoción:**
Combina tus pensamientos con emoción fuerte. La emoción da poder al pensamiento.

**4. Repetición:**
Repite tus afirmaciones diariamente, especialmente al despertar y antes de dormir.

### La Fórmula de la Autoconfianza

Hill proporciona una fórmula específica para desarrollar autoconfianza:

**Primera Afirmación:**
"Sé que tengo la habilidad de lograr el objeto de mi Propósito Definido en la vida; por lo tanto, EXIJO de mí mismo acción persistente y continua hacia su logro, y aquí y ahora prometo tal acción."

**Segunda Afirmación:**
"Me doy cuenta de que los pensamientos dominantes de mi mente eventualmente se reproducirán en acción física externa y gradualmente se transformarán en realidad física; por lo tanto, concentraré mis pensamientos durante treinta minutos diarios en la tarea de pensar en la persona que pretendo llegar a ser, creando así en mi mente una imagen mental clara."

**Tercera Afirmación:**
"Sé que a través del principio de autosugestión, cualquier deseo que mantenga persistentemente en mi mente eventualmente buscará expresión a través de algún medio práctico de lograr el objeto detrás de él; por lo tanto, dedicaré diez minutos diarios a exigir de mí mismo el desarrollo de AUTOCONFIANZA."

**Cuarta Afirmación:**
"He escrito claramente una descripción de mi PROPÓSITO PRINCIPAL DEFINIDO en la vida, y nunca dejaré de intentar, hasta que haya desarrollado suficiente autoconfianza para su logro."

**Quinta Afirmación:**
"Me doy cuenta plenamente de que ninguna riqueza o posición puede durar mucho tiempo, a menos que se construya sobre la verdad y la justicia; por lo tanto, no participaré en ninguna transacción que no beneficie a todos a quienes afecta."

### Los Pensamientos Dominantes

Tu mente subconsciente actúa sobre los pensamientos que dominas. Si dominas pensamientos de:
- **Pobreza:** Atraerás pobreza
- **Miedo:** Atraerás lo que temes
- **Riqueza:** Atraerás riqueza
- **Éxito:** Atraerás éxito

**Ley de la Atracción:**
Los pensamientos que emocionalizas y mezclas con fe comienzan inmediatamente a traducirse en su equivalente físico.

