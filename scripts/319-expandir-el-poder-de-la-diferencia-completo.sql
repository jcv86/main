## PARTE 2: Tipos de Diversidad Cognitiva

### Diversidad que Importa vs. Diversidad Superficial

Page distingue entre:

**Diversidad de identidad (superficial):**
- Raza, género, edad, origen
- Visible, fácil de medir
- Importante socialmente

**Diversidad cognitiva (funcional):**
- Cómo procesamos información
- Herramientas mentales que usamos
- Perspectivas que traemos
- Heurísticas que aplicamos

**Relación entre ambas:**
Diversidad de identidad a menudo correlaciona con diversidad cognitiva (experiencias de vida diferentes generan formas de pensar diferentes), pero no siempre.

