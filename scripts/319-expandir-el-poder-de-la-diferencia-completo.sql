## PARTE 1: La Lógica de la Diversidad

### La Paradoja Fundamental

**La intuición convencional:**
Los mejores individuos forman los mejores equipos.

**La realidad matemática:**
Grupos diversos de personas capaces frecuentemente superan a grupos de expertos individuales.

#### El Teorema de Diversidad de Predicción

Page formula esto matemáticamente:

**Error Colectivo = Error Individual Promedio - Diversidad de Predicción**

**Traducción:** El error de un grupo en hacer predicciones es igual al error promedio de los miembros individuales, menos lo diversos que son en sus predicciones.

**Implicación revolucionaria:**
Agregar alguien que piensa diferente (incluso si es menos experto) puede mejorar el rendimiento del grupo, mientras que agregar alguien similar (incluso si es más experto) puede no agregar valor.

#### Ejemplo Ilustrativo: Estimar Peso del Buey

**Experimento clásico (Francis Galton, 1907):**
En una feria rural, 800 personas estimaron el peso de un buey.

**Resultados:**
- **Peso real:** 1,198 libras
- **Estimación promedio:** 1,197 libras
- **Error:** Solo 1 libra

**Ningún individuo fue tan preciso como el grupo.**

**Por qué funcionó:**
- Algunos estimaron alto, otros bajo
- Errores se cancelaron mutuamente
- Diversidad de perspectivas = precisión colectiva

