## Introducción: El Valor Oculto de la Diferencia

Durante décadas, asumimos que el talento individual era el factor determinante del éxito. Buscábamos a las personas más inteligentes, con el mejor pedigree, las credenciales más impresionantes. Pero Scott Page, a través de rigurosa investigación matemática y económica, demuestra algo revolucionario: **la diferencia importa más que la habilidad individual**.

En este libro, Page presenta evidencia convincente de que grupos diversos de personas con diferentes perspectivas, heurísticas, interpretaciones y modelos predictivos superan consistentemente a grupos de expertos homogéneos - incluso cuando los expertos individuales son más capaces que cualquier miembro del grupo diverso.

Este no es un argumento moral sobre diversidad. Es matemática pura que demuestra por qué la diversidad cognitiva es una herramienta poderosa para resolución de problemas e innovación.

