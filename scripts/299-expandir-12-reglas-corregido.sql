Por Jordan B. Peterson

PROLOGO

Este libro tiene un mensaje muy simple: Ponte de pie con los hombros hacia atras.

Defiendete. Deja de agacharte. Demuestra que eres una fuerza formidable. Las personas, incluido tu mismo, comenzaran a respetarte. Esto vale mas de lo que piensas.

Las 12 reglas en este libro son principios simples que pueden ayudarte a vivir una vida significativa. No son faciles de seguir, pero valen cada esfuerzo.

REGLA 1: PARATE DERECHO CON TUS HOMBROS HACIA ATRAS

Las langostas han estado en la Tierra por mas de 350 millones de años. Su jerarquia social se determina por el combate.

Cuando una langosta gana, su sistema nervioso se inunda con serotonina. Se vuelve mas confiada, ocupa mas espacio, es mas agresiva. Cuando pierde, su cerebro produce menos serotonina. Se encoge, se vuelve timida.

Los humanos operan de manera similar. Tu postura refleja y afecta tu estado emocional.

Cuando te paras derecho:
- Tu cerebro interpreta que estas en control
- Produces mas serotonina
- Te sientes mas confiado
- La gente te trata mejor
- Creas un circulo virtuoso

Cuando te encorvas:
- Tu cerebro interpreta que estas derrotado
- Tu quimica cerebral cambia
- Te sientes menos valioso
- La gente te trata peor
- Creas un circulo vicioso

La postura fisica es una eleccion. Elige presentarte al mundo como alguien que merece respeto.

REGLA 2: TRATATE A TI MISMO COMO ALGUIEN A QUIEN ERES RESPONSABLE DE AYUDAR

Las personas a menudo cuidan mejor a sus mascotas que a si mismas. Por que?

Porque ven sus propias fallas claramente pero dan el beneficio de la duda a otros.

Debes ver tu propia vida como algo de valor. No puedes cuidar a nadie mas si no te cuidas a ti mismo primero.

Preguntate: Que podria ser? Que deberia ser? Y luego: Que pasos debo dar para llegar ahi?

Negocia contigo mismo:
- Si hago esto (tarea desagradable), me recompensare con aquello (placer)
- Tratate como tratarias a alguien valioso a tu cuidado

No te sacrifiques completamente por otros. Una vida vivida completamente en sacrificio es una vida de resentimiento.

REGLA 3: HAZTE AMIGO DE PERSONAS QUE QUIEREN LO MEJOR PARA TI

No es falta de compasion desear asociarte con personas que te empujen hacia arriba en lugar de arrastrarte hacia abajo.

Si estas rodeado de personas que abusan de drogas, justifican su comportamiento destructivo y se burlan de tus intentos de mejorar, no estan mostrando amor - estan mostrando hostilidad.

Las amistades verdaderas:
- Te desafian a ser mejor
- Celebran tus exitos genuinamente
- Te dicen la verdad, incluso cuando duele
- Esperan que hagas lo mismo por ellos

No es amor permitir a alguien destruirse. No es compasion ser arrastrado hacia el abismo con ellos.

Antes de poder ayudar a alguien mas, asegurate de que ellos quieren ser ayudados.

REGLA 4: COMPARATE CON QUIEN FUISTE AYER, NO CON QUIEN ES OTRO HOY

Siempre habra alguien mejor que tu en algo. Si comparas continuamente, siempre perderas.

Tu unico competidor real es quien fuiste ayer.

Preguntas para hacerte cada dia:
- Que cosa podria mejorar hoy?
- Hice algo estupido repetidamente que deberia dejar de hacer?
- Hay algo que debo enfrentar que he estado evitando?

Incluso 1% de mejora cada dia resulta en una transformacion radical en un año.

El progreso requiere:
- Honestidad sobre donde estas
- Claridad sobre donde podrias estar
- Pequeños pasos diarios hacia adelante
- Celebracion de pequeñas victorias

No te preocupes por cuan lejos estan otros. Solo preocupate por moverte adelante.

REGLA 5: NO DEJES QUE TUS HIJOS HAGAN ALGO QUE TE HAGA NO QUERERLOS

Los niños no nacen socializados. Nacen pequeños tiranos llenos de deseo e impulso.

Es tu trabajo como padre enseñarles a comportarse de manera que la sociedad los acepte.

Si permites que tu hijo sea un pequeño monstruo:
- No sera querido por otros niños
- No sera querido por maestros
- Sufrira rechazo social
- Te resentira por no disciplinarlo

La disciplina apropiada requiere:
- Limites claros
- Consecuencias consistentes
- Razonamiento apropiado a la edad
- Amor genuino y cuidado

La disciplina bien hecha es un acto de amor. Prepara al niño para la realidad de que el mundo tiene reglas.

Los niños necesitan y desean limites. Los hace sentir seguros.

REGLA 6: PON TU CASA EN PERFECTO ORDEN ANTES DE CRITICAR AL MUNDO

Es mas facil culpar al mundo que asumir responsabilidad personal.

Antes de reorganizar el mundo, preguntate:
- He arreglado lo que puedo arreglar en mi propia vida?
- Estoy actuando con integridad?
- Estoy tomando responsabilidad por mi parte en mis problemas?

Comienza con tu cuarto:
- Limpia tu espacio fisico
- Organiza tus posesiones
- Crea orden del caos

Luego:
- Repara tus relaciones rotas
- Deja de mentir
- Haz lo que sabes que debes hacer
- Deja de hacer lo que sabes que esta mal

Solo despues de poner tu propia casa en orden tienes el fundamento moral para cambiar el mundo.

REGLA 7: PERSIGUE LO QUE ES SIGNIFICATIVO (NO LO QUE ES EXPEDIENTE)

La vida es sufrimiento. Esa es la naturaleza de la existencia.

Puedes responder a esto de dos maneras:

1. Busca placer inmediato (expediente)
2. Busca significado (sacrificio por el futuro)

Lo expediente:
- Mentir para evitar consecuencias
- Tomar atajos
- Gratificacion instantanea
- Evadir responsabilidad

Lo significativo:
- Decir la verdad
- Hacer el trabajo duro
- Gratificacion postergada
- Aceptar responsabilidad

El significado viene del sacrificio voluntario. Cuando pospones gratificacion y trabajas hacia algo mas grande que tu mismo, descubres proposito.

Viktor Frankl en los campos de concentracion descubrio que aquellos con significado (un por que) podian soportar casi cualquier como.

El hedonismo lleva a vacio. El significado lleva a cumplimiento.

REGLA 8: DI LA VERDAD O, AL MENOS, NO MIENTAS

La mentira corrompe tu percepcion de la realidad.

Cuando mientes:
- Distorsionas tu modelo del mundo
- Te vuelves incapaz de navegar adecuadamente
- Pierdes contacto con la realidad
- Creas consecuencias inesperadas

Las mentiras se multiplican. Una mentira requiere diez mas para sostenerla.

Decir la verdad:
- Simplifica tu vida (no necesitas recordar historias falsas)
- Construye tu caracter
- Gana respeto de otros
- Te mantiene anclado en realidad

No necesitas decir todo lo que piensas. Pero lo que dices debe ser verdad.

Si te encuentras mintiendo, preguntate: De que tengo miedo? La respuesta revelara algo importante.

La verdad es el fundamento sobre el cual puedes construir algo estable.

REGLA 9: ASUME QUE LA PERSONA A LA QUE ESTAS ESCUCHANDO PODRIA SABER ALGO QUE TU NO SABES

Escuchar es raro. La mayoria de las personas estan esperando su turno para hablar.

Escuchar verdaderamente significa:
- Suspender tu propia agenda
- Prestar atencion completa
- Hacer preguntas clarificadoras
- Resumir lo que escuchaste

Cuando escuchas genuinamente:
- Las personas te diran cosas extraordinarias
- Aprenderas cosas que nunca esperabas
- Resolveras problemas mas rapido
- Tus relaciones mejoraran dramaticamente

Carl Rogers, el psicoterapeuta, descubrio que simplemente escuchar a las personas - verdaderamente escucharlas - era terapeutico en si mismo.

Mucha gente solo necesita ser escuchada. No quieren consejos. No quieren soluciones. Quieren que alguien entienda.

Se esa persona.

REGLA 10: SE PRECISO EN TU HABLA

Lo que malentiende se multiplica.

Cuando eres vago:
- Los problemas se vuelven inmensos
- Los monstruos crecen en la oscuridad
- Las ansiedades se expanden sin forma

Cuando eres preciso:
- Los problemas se vuelven manejables
- Puedes ver exactamente que enfrentar
- Las soluciones se vuelven aparentes

Ejemplo:
Vago: Mi relacion es mala
Preciso: Mi esposo deja platos en el fregadero y eso me hace sentir no respetada

El segundo puede ser resuelto. El primero es abrumador.

Especifica:
- Que esta realmente mal
- Que necesitas que sea diferente
- Que puedes hacer al respecto

Los dragones siempre son mas aterradores antes de que los miras directamente.

REGLA 11: NO MOLESTES A LOS NIÑOS CUANDO ESTAN MONTANDO PATINETA

Los niños necesitan tomar riesgos para desarrollarse.

La sociedad moderna ha vuelto todo demasiado seguro. Protegemos a los niños de cada raspón y moreton.

El resultado:
- Los niños no aprenden sus limites
- No desarrollan competencia
- Se vuelven ansiosos y fragiles
- No estan preparados para los desafios reales de la vida

Los niños necesitan:
- Juego fisico arriesgado
- Oportunidades de fallar
- Posibilidad de lastimarse (dentro de razon)
- Espacio para resolver sus propios problemas

La peligrosidad se encuentra por encima de la competencia. Si eliminas toda peligrosidad, eliminas la oportunidad de desarrollar competencia.

Los niños saben instintivamente que necesitan esto. Por eso montan patinetas, trepan arboles y luchan.

No lo malinterpretes: Debes protegerlos de peligro real. Pero un parque de juegos que es perfectamente seguro es tambien perfectamente aburrido e inutil para el desarrollo.

REGLA 12: CUANDO ENCUENTRES UN GATO EN LA CALLE, ACARICIALO

La vida es sufrimiento. Es tambien tragedia. Perdida, enfermedad, muerte - estas son inevitables.

Como mantienes esperanza ante esto?

Presta atencion a la belleza pequeña. Acaricia el gato.

Cuando estes abrumado:
- Estrecha tu marco temporal a solo hoy
- Estrecha tu enfoque a lo que esta justo frente a ti
- Encuentra algo bueno, algo hermoso, algo significativo en este momento

No puedes arreglar todo. Pero puedes:
- Notar el sol en las hojas
- Apreciar la risa de tu hijo
- Disfrutar una buena taza de cafe
- Acariciar el gato

Estos momentos sostienen. Estas bellezas pequeñas hacen la vida soportable.

Viktor Frankl: Aquellos que tienen un por que para vivir, pueden soportar casi cualquier como.

Los gatos callejeros son un recordatorio: Incluso en medio del caos y sufrimiento, hay belleza, conexion, significado.

Presta atencion.

