Por Carol Dweck

INTRODUCCIÓN

Creer que tus cualidades están grabadas en piedra crea una urgencia de probarte a ti mismo una y otra vez. Si tienes una cantidad determinada de inteligencia, personalidad o carácter moral, ¿no querrás demostrar que tienes una dosis saludable de ellos? ¿No querrás verse inteligente y no tonto, talentoso y no incapaz, como una buena persona y no una mala?

He visto tantas personas con este único objetivo consumidor de probarse a sí mismas en el aula, en sus carreras y en sus relaciones. Cada situación requiere una confirmación de su inteligencia, personalidad o carácter. Cada situación es evaluada: ¿Tendré éxito o fracasaré? ¿Me veré inteligente o tonto? ¿Seré aceptado o rechazado? ¿Me sentiré como un ganador o un perdedor?

Pero hay otra mentalidad en la que estas características no están simplemente escritas en piedra. Aunque las personas pueden diferir de todas las formas posibles en sus talentos, aptitudes, intereses o temperamentos iniciales, todos pueden cambiar y crecer a través de la aplicación y la experiencia.

CAPÍTULO 1: LAS MENTALIDADES

¿Por qué algunas personas cumplen su potencial mientras que muchas otras igualmente talentosas no lo hacen?

Durante décadas, mis estudios de investigación me han mostrado la respuesta: depende de la mentalidad que elijas.

MENTALIDAD FIJA: Creer que tus cualidades están grabadas en piedra
- La inteligencia es estática
- Evitas desafíos
- Te rindes fácilmente ante obstáculos
- Ves el esfuerzo como infructuoso
- Ignoras retroalimentación útil
- Te sientes amenazado por el éxito de otros
- Resultado: Alcanzas menos de tu potencial completo

MENTALIDAD DE CRECIMIENTO: Creer que puedes desarrollar tus cualidades básicas
- La inteligencia puede desarrollarse
- Abrazas desafíos
- Persistes ante obstáculos
- Ves el esfuerzo como el camino a la maestría
- Aprendes de la crítica
- Te inspiras en el éxito de otros
- Resultado: Alcanzas niveles más altos de logro

La visión que adoptas de ti mismo afecta profundamente la manera en que llevas tu vida. Las personas con mentalidad fija se atascan en probarse a sí mismas. Las personas con mentalidad de crecimiento están comprometidas con mejorarse a sí mismas.

CAPÍTULO 2: DENTRO DE LAS MENTALIDADES

En la mentalidad fija, todo es sobre el resultado. Si fracasas, o si no eres el mejor, todo se ha desperdiciado.

La mentalidad de crecimiento permite a las personas valorar lo que están haciendo independientemente del resultado. Permiten abordar las cosas, se adhieren a ellas y generan progreso.

John Wooden, el legendario entrenador de baloncesto, no medía el éxito por victorias sino por esfuerzo y mejora. Su definición de éxito: "El éxito es la paz mental que es resultado directo de la autosatisfacción al saber que hiciste tu mejor esfuerzo para convertirte en lo mejor que eres capaz de ser."

LA MENTALIDAD CAMBIA EL SIGNIFICADO DEL ESFUERZO

En la mentalidad fija, el esfuerzo es para personas con deficiencias. Y cuando las personas piensan que son talentosas naturalmente, sienten que tener que trabajar duro significa que carecen de habilidad.

Nadal Federer trabajó incansablemente en sus habilidades. Michael Jordan era conocido por su ética de trabajo. Darwin se llamó a sí mismo un "trabajador muy lento."

El esfuerzo es lo que te hace inteligente o talentoso. Punto.

CAPÍTULO 3: LA VERDAD SOBRE LA HABILIDAD Y EL LOGRO

Benjamin Barber, sociólogo, dijo: "No divido al mundo entre los débiles y los fuertes, o los exitosos y los fracasados... Divido el mundo entre los que aprenden y los que no aprenden."

LA MENTALIDAD DE CRECIMIENTO EN LA ESCUELA

Los estudiantes con mentalidad de crecimiento:
- Ven las pruebas como oportunidades para aprender
- Valoran el esfuerzo más que el talento natural
- Buscan retroalimentación para mejorar
- Ven los errores como oportunidades de aprendizaje
- Continúan estudiando después de exámenes pobres

Los estudiantes con mentalidad fija:
- Ven las pruebas como medida de su inteligencia
- Evitan el esfuerzo para proteger su ego
- Ignoran retroalimentación negativa
- Se sienten devastados por errores
- Se rinden después de exámenes pobres

Estudio: Dimos problemas de razonamiento no verbal a cientos de estudiantes de primer grado. Después, alabamos a algunos por su inteligencia: "Debes ser inteligente en esto." Alabamos a otros por su esfuerzo: "Debes haber trabajado realmente duro."

Los alabados por inteligencia:
- Desarrollaron mentalidad fija
- Perdieron confianza cuando encontraron problemas difíciles
- Su disfrute disminuyó
- Su rendimiento cayó incluso en problemas más fáciles

Los alabados por esfuerzo:
- Desarrollaron mentalidad de crecimiento
- Mantuvieron confianza
- Mantuvieron disfrute
- Su rendimiento mejoró

CAPÍTULO 4: DEPORTES: LA MENTALIDAD DE UN CAMPEÓN

Muhammad Ali dijo: "El hombre que ve el mundo a los 50 igual que como lo veía a los 20 ha desperdiciado 30 años de su vida."

En deportes, la mentalidad de crecimiento es la diferencia entre:
- Michael Jordan (cortado del equipo de preparatoria, trabajó incansablemente)
- Tiger Woods (practicaba hasta perfeccionar cada aspecto)
- Mia Hamm (siempre el jugador más trabajador en la cancha)

Versus aquellos que dependieron solo del talento natural y nunca alcanzaron su potencial.

John Wooden: "Nunca mencioné ganar." Su UCLA ganó 10 campeonatos nacionales en 12 años. Enfocado en preparación y esfuerzo, no en victoria.

EL CARÁCTER

La mentalidad de crecimiento crea:
- Resiliencia ante la adversidad
- Capacidad de aprender de fracasos
- Persistencia a largo plazo
- Disfrute del proceso

"Los campeones no son los que siempre ganan carreras, los campeones son los que se levantan cuando caen." - Mia Hamm

CAPÍTULO 5: NEGOCIOS: MENTALIDAD Y LIDERAZGO

Lee Iacocca (Ford y Chrysler) tuvo éxito inicial pero mentalidad fija. Pasó tiempo probándose en lugar de mejorando la compañía. Resultado: declive.

Jack Welch (GE) tenía mentalidad de crecimiento. Creía que todos podían desarrollarse. Enfocado en crecimiento continuo de personas y compañía. Resultado: 4000% de incremento en valor.

Los líderes con mentalidad de crecimiento:
- Contratan las personas más capaces (no se sienten amenazados)
- Construyen equipos que colaboran
- Desarrollan talento continuamente
- Aceptan retroalimentación
- Aprenden de fracasos

Los líderes con mentalidad fija:
- Contratan personas menos capaces (protegen ego)
- Crean culturas de sí-personas
- Ignoran desarrollo de empleados
- Rechazan retroalimentación
- Culpan a otros por fracasos

GROUPTHINK vs TEAMTHINK

Mentalidad fija crea groupthink:
- Presión de conformidad
- Racionalización de decisiones pobres
- Ilusión de invulnerabilidad
- Censura de puntos de vista disidentes

Mentalidad de crecimiento crea teamthink:
- Perspectivas diversas valoradas
- Debate abierto alentado
- Toma de decisiones colaborativa
- Aprendizaje de errores

CAPÍTULO 6: RELACIONES: MENTALIDADES EN EL AMOR (O NO)

La mentalidad fija hace creer que:
- El amor perfecto debería ser instantáneo y fácil
- Los problemas significan incompatibilidad
- La pareja debería conocer automáticamente tus necesidades
- Trabajar en relación = relación defectuosa

La mentalidad de crecimiento entiende que:
- Las relaciones requieren esfuerzo
- Los desafíos son oportunidades para crecer juntos
- La comunicación debe aprenderse
- Las relaciones evolucionan con el tiempo

BULLYING

Los niños con mentalidad fija tienen tres veces más probabilidades de ser bullies. ¿Por qué? Necesitan demostrar su superioridad constantemente.

Los niños con mentalidad de crecimiento:
- No necesitan menospreciar a otros
- Ven diversidad como fortaleza
- Ayudan a compañeros
- Construyen en lugar de destruir

TIMIDEZ

La mentalidad fija ve la timidez como rasgo permanente: "Así soy yo."

La mentalidad de crecimiento ve la timidez como algo que puede trabajarse: "Puedo aprender habilidades sociales."

CAPÍTULO 7: PADRES, MAESTROS Y ENTRENADORES: ¿DE DÓNDE VIENEN LAS MENTALIDADES?

Las mentalidades no se heredan. Se aprenden. Los padres y maestros tienen enorme influencia.

MENSAJES QUE CREAN MENTALIDAD FIJA:
- "Eres tan inteligente" (alaba persona/talento)
- "Naciste con este talento"
- "No todos pueden ser buenos en matemáticas"
- "Déjame hacerlo por ti"
- Proteger de fracasos
- Enfocarse en resultados sobre proceso

MENSAJES QUE CREAN MENTALIDAD DE CRECIMIENTO:
- "Te esforzaste mucho en esto" (alaba proceso)
- "Todos pueden aprender cualquier cosa"
- "Los errores te ayudan a crecer"
- "Sigue intentando diferentes estrategias"
- Permitir luchas productivas
- Enfocarse en aprendizaje y mejora

CÓMO LOS MAESTROS MARCAN LA DIFERENCIA

Maestro con mentalidad fija:
- Piensa algunos estudiantes no pueden aprender
- Evita desafiar a estudiantes
- Ve errores como fracasos
- Enseña para la prueba

Maestro con mentalidad de crecimiento:
- Cree todos los estudiantes pueden aprender
- Proporciona desafíos apropiados
- Ve errores como información
- Enseña para comprensión

Marva Collins transformó estudiantes "no enseñables" en académicos ávidos. Su secreto: "Creo que todos ustedes son genios. Ustedes están llenos de inteligencia."

CAPÍTULO 8: CAMBIANDO MENTALIDADES

Las mentalidades son solo creencias. Pueden cambiar.

PASOS PARA DESARROLLAR MENTALIDAD DE CRECIMIENTO:

1. APRENDE A ESCUCHAR TU VOZ DE MENTALIDAD FIJA
Cuando enfrentas desafío, la voz fija dice:
- "¿Estás seguro de que puedes hacerlo?"
- "¿Qué si fracasas? Todos te verán."
- "Mejor no arriesgarte."

2. RECONOCE QUE TIENES UNA ELECCIÓN
Puedes elegir cómo interpretar desafíos, contratiempos, crítica.

3. HABLA DE VUELTA CON VOZ DE CRECIMIENTO
- Fija: "No soy bueno en esto."
- Crecimiento: "No soy bueno en esto... todavía."

- Fija: "Ya me rendí."
- Crecimiento: "Intentaré diferentes estrategias."

- Fija: "Esto es muy difícil."
- Crecimiento: "Esto puede tomar algo de tiempo y esfuerzo."

4. TOMA ACCIÓN DE MENTALIDAD DE CRECIMIENTO
- Abraza desafíos
- Aprende de fracasos
- Busca retroalimentación
- Célebra esfuerzo de otros
- Mantén aprendiendo

EL VIAJE

Cambiar mentalidad es un viaje, no un destino. Continúas trabajando en ello a lo largo de tu vida.

Falsos mensajes de crecimiento para evitar:
- Alabar esfuerzo sin resultados
- Decir "todos pueden hacer cualquier cosa" (no es realista)
- Culpar fracaso solo a falta de esfuerzo
- Usar mentalidad de crecimiento como excusa para bajo rendimiento

Verdadera mentalidad de crecimiento significa:
- Aceptar que las habilidades se pueden desarrollar
- Abrazar desafíos y aprender de fracasos
- Trabajar duro pero también estratégicamente
- Valorar proceso sobre perfección

CONCLUSIÓN

La pasión por estirarse y adherirse, incluso cuando las cosas no van bien, es el sello de la mentalidad de crecimiento. Esta es la mentalidad que permite a las personas prosperar durante algunos de los momentos más desafiantes en sus vidas.

