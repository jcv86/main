INTRODUCCIÓN

Este libro es tu puerta de entrada a la transformación interior. Representa la esencia de mi trabajo durante los últimos diez años con individuos y pequeños grupos de buscadores espirituales.

En la vida de cada ser humano llega un momento en el que se está maduro para la transformación. Para muchos ese momento llega a través del sufrimiento extremo.

CAPÍTULO UNO: NO ERES TU MENTE

El mayor obstáculo para experimentar esta realidad es la identificación con tu mente. Esto causa que el pensamiento se vuelva compulsivo.

La voz en la cabeza tiene vida propia. La mayoría de las personas están poseídas por su mente. No pueden dejar de pensar. Pensar compulsivamente se ha convertido en una enfermedad colectiva.

Cuando eres incapaz de dejar de pensar has vuelto adicto al pensamiento. Comienza a observar al pensador. Cuando observas un pensamiento, eres consciente no solo del pensamiento sino también de ti mismo como testigo del pensamiento.

Cuando escuchas ese pensamiento, lo sientes como una presencia testigo. Esta dimensión de la conciencia es el momento presente.

La emancipación de la identificación con la forma es tu destino como ser humano. El presente es tu verdadera naturaleza. Este es el Ahora.

ILUMINACIÓN

La iluminación es tu estado natural de unión con el Ser. Es simplemente estar en contacto con tu naturaleza esencial. Es un estado de conexión con algo inconmensurable e indestructible.

La iluminación no es solo el fin del sufrimiento sino también del pensamiento compulsivo. Qué increíble liberación es esto.

La palabra "iluminación" evoca la idea de algún logro sobrehumano. Sin embargo, es simplemente tu estado natural de unión con el Ser.

LIBERARSE DEL TIEMPO

La mente no puede comprender el Ahora. El momento presente es todo lo que tienes. No hay nunca un tiempo en el que tu vida no sea "este momento."

El tiempo no es precioso en absoluto porque es una ilusión. Lo que percibes como precioso no es el tiempo sino el único punto que está fuera del tiempo: el Ahora.

Nada existe excepto el Ahora. Todo lo que alguna vez sucedió, sucedió en el Ahora. Todo lo que sucederá alguna vez, sucederá en el Ahora.

CAPÍTULO DOS: LA CONCIENCIA: LA SALIDA DEL DOLOR

Todo lo que necesitas hacer es aceptar este momento completamente. Entonces estás a gusto en el aquí y ahora y a gusto contigo mismo.

El dolor que creas ahora es siempre alguna forma de no aceptación, alguna forma de resistencia inconsciente a lo que es.

Observa cualquier patrón defensivo de tu propia mente. Luego mira la emoción que está detrás. Siente la emoción y acepta que está ahí.

EL ORIGEN DEL MIEDO

El miedo psicológico siempre es de algo que podría suceder, no de algo que está sucediendo ahora. Estás en el aquí y ahora, mientras que tu mente está en el futuro.

La mayoría de las personas no viven en el presente. Viven sumergidas en la mente, que está continuamente ocupada con el pasado y el futuro.

No hay manera de que puedas lidiar con una situación que no ha sucedido todavía. Solo puedes manejar el momento actual.

LA BÚSQUEDA DEL EGO DE LA TOTALIDAD

Otro aspecto del cuerpo emocional del dolor es un profundo sentido de falta o incompletitud que siente la mayoría de las personas.

El ego se identifica con tener. Pero su satisfacción en tener es relativamente superficial y corta vida. Oculta debajo hay un profundo sentido de insatisfacción.

Mientras seas incapaz de acceder al poder del Ahora, cada dolor emocional que experimentes dejará un residuo de dolor que vive en ti.

CAPÍTULO TRES: MOVIÉNDOSE PROFUNDAMENTE EN EL AHORA

No dependas de ninguna relación para darte lo que solo puede venir de dentro. Usa la relación para llevarte más profundamente en el Ahora.

Trata de eliminar tiempo de tu conciencia tanto como sea posible. Si encuentras imposible vivir en el momento presente, usa el tiempo solamente para propósitos prácticos.

LA ESENCIA DE MEDITACIÓN

La meditación es estar conscientemente presente. Una manera simple de entrar en el estado de meditación es por sentir.

Cierra tus ojos. Di a ti mismo "Me pregunto cuál será mi próximo pensamiento." Entonces permanece alerta, esperando el próximo pensamiento.

Entre dos pensamientos hay una brecha breve de "no-mente." Al principio la brecha será corta, pero gradualmente se hará más larga.

RINDIÉNDOSE AL AHORA

La rendición es aceptación del momento presente. Es rendirse a lo que es, decir "sí" a la vida. Es rendirse al Ahora, no a una historia sobre el Ahora.

Rendirse no significa que no puedas tomar acción y hacer cambios. Pero viene de un estado diferente de conciencia y por lo tanto será una acción de calidad diferente.

La diferencia entre rendirse y resignación: Resignación es un estado mental negativo de "No puedo vivir con esto más." Rendición es "Está bien que esto esté aquí ahora."

