2. DEPRECIACION
Verifica si metodo de depreciacion es conservador.

3. OPCIONES DE ACCIONES
Ejecutivos recibiendo opciones diluyen tu participacion.

4. CONTABILIDAD AGRESIVA
Reconocimiento prematuro de ingresos, capitalizacion de gastos.

GANANCIAS AJUSTADAS

