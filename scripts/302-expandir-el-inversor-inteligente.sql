Por Benjamin Graham

INTRODUCCION

Este libro no promete hacerte rico rapidamente. Promete ensenarte a evitar perdidas serias y desarrollar estrategia de inversion a largo plazo.

El objetivo de inversiones no es superar mercado, sino crear plan que puedas seguir consistentemente.

