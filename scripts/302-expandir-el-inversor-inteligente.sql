CAPITULO 1: INVERSION VERSUS ESPECULACION

DEFINICION DE INVERSION

Una operacion de inversion es aquella que, tras analisis exhaustivo, promete seguridad del principal y retorno adecuado. Operaciones que no cumplen estos requisitos son especulativas.

Tres elementos:

1. ANALISIS EXHAUSTIVO
Debes estudiar hechos disponibles y aplicar principios solidos.

2. SEGURIDAD DEL PRINCIPAL
Proteger contra perdida es mas importante que crecimiento.

3. RETORNO ADECUADO
No esperes ganancias extraordinarias. Busca retornos razonables y consistentes.

ESPECULACION NO ES MALA

Especular esta bien si:
- Sabes que estas especulando
- Solo especulas con dinero que puedes perder
- Limitas especulacion a pequena porcion de capital

Problema: Mayoria de personas especulan pensando que estan invirtiendo.

CAPITULO 2: EL INVERSOR Y LA INFLACION

La inflacion erosiona poder adquisitivo. 100 hoy valdran menos en futuro.

PROTECCION CONTRA INFLACION

1. BONOS
Proporcionan ingreso estable pero no protegen contra inflacion.

2. ACCIONES
Historicamente, acciones han superado inflacion largo plazo.
Empresas pueden aumentar precios, protegiendo valor.

3. BIENES RAICES
Propiedad tiende a mantener valor contra inflacion.

BALANCE RECOMENDADO

Graham sugiere 50/50 entre acciones y bonos.
Ajusta segun edad, temperamento, condiciones mercado:
- Minimo 25% en cada categoria
- Maximo 75% en cualquier categoria

CAPITULO 3: UN SIGLO DE HISTORIA DEL MERCADO

El mercado es como pendulo que oscila entre optimismo insostenible y pesimismo injustificado.

LECCIONES DE HISTORIA

1. Los mercados son ciclicos
Booms seguidos por crashes son patron recurrente.

2. Las predicciones son inutiles
Nadie puede predecir consistentemente movimientos corto plazo.

3. El valor emerge largo plazo
Empresas solidas eventualmente son reconocidas por mercado.

CAPITULO 4: POLITICA GENERAL DE CARTERA

DOS TIPOS DE INVERSORES

INVERSOR DEFENSIVO:
- Busca seguridad y minimo esfuerzo
- Diversifica ampliamente
- Mantiene balance entre acciones y bonos
- Evita intentar cronometrar mercado

INVERSOR EMPRENDEDOR:
- Dispuesto a dedicar tiempo y esfuerzo
- Busca oportunidades especiales
- Hace analisis profundo
- Puede concentrar inversiones mas

REGLAS PARA INVERSOR DEFENSIVO

1. Nunca menos de 25% ni mas de 75% en acciones
2. Diversifica en al menos 10-30 acciones diferentes
3. Compra solo companias grandes, establecidas
4. Limita precio pagado en relacion a ganancias

CAPITULO 5: EL INVERSOR DEFENSIVO Y LAS ACCIONES COMUNES

CRITERIOS DE SELECCION

1. TAMANO ADECUADO
Empresa debe ser suficientemente grande (ventas anuales minimo 100 millones - ajustado por inflacion).

2. CONDICION FINANCIERA FUERTE
- Activos corrientes al menos 2x pasivos corrientes
- Deuda largo plazo no mas de capital de trabajo neto

3. ESTABILIDAD DE GANANCIAS
Ganancias positivas cada ano ultimos 10 anos.

4. REGISTRO DE DIVIDENDOS
Pagos ininterrumpidos minimo 20 anos.

5. CRECIMIENTO DE GANANCIAS
Minimo aumento 33% en ganancias por accion ultimos 10 anos.

6. PRECIO MODERADO
- Precio/ganancia ratio no mayor a 15
- Precio no mas de 1.5x valor de activos netos

CAPITULO 6: POLITICA DE CARTERA PARA INVERSOR EMPRENDEDOR

El inversor emprendedor debe buscar oportunidades donde puede tener ventaja sobre inversionistas pasivos.

AREAS DE OPORTUNIDAD

1. ACCIONES IMPOPULARES DE GRANDES COMPANIAS
Empresas solidas temporalmente fuera de favor.

2. EMPRESAS DE SEGUNDA LINEA
Companias mas pequenas con fundamentos solidos pero poco seguimiento.

3. SITUACIONES ESPECIALES
Fusiones, liquidaciones, reorganizaciones - donde analisis puede revelar valor oculto.

CAPITULO 7: POLITICA DE CARTERA: ENFOQUE NEGATIVO

QUE EVITAR

1. BONOS O ACCIONES PREFERENTES DE BAJA CALIDAD
Solo compra grado de inversion (BBB o superior).

2. ACCIONES DE CRECIMIENTO A PRECIOS ALTOS
No pagues multiples excesivos por crecimiento futuro.

3. NUEVAS EMISIONES
IPOs generalmente tienen precio excesivo.

4. TRADING ACTIVO
