CAPITULO 8: EL INVERSOR Y LAS FLUCTUACIONES DE MERCADO

COMO RESPONDER A VOLATILIDAD

El inversor inteligente no se emociona por fluctuaciones de mercado. Las usa a su favor.

SR. MERCADO

Imagina que posees parte de negocio privado con socio llamado Sr. Mercado.

Sr. Mercado te dice precio cada dia que pagaria por tu participacion o venderia su parte a ti.

Problema: Sr. Mercado es maniaco-depresivo.
- Algunos dias es eufórico y ofrece precios altos
- Otros dias es depresivo y ofrece precios bajos

ESTRATEGIA INTELIGENTE

1. Cuando Sr. Mercado es optimista (precios altos): Vende
2. Cuando Sr. Mercado es pesimista (precios bajos): Compra
3. Cuando precios son razonables: Ignora

No dejes que entusiasmo o depresion de Sr. Mercado afecten tu juicio.

FORMULA DE DOLLAR COST AVERAGING

Invierte cantidad fija regularmente sin importar precio.

Beneficios:
- Compras mas acciones cuando precios son bajos
- Compras menos acciones cuando precios son altos
- Eliminas emocion de decision

CAPITULO 9: INVERTIR EN FONDOS DE INVERSION

VENTAJAS DE FONDOS

1. Diversificacion automatica
2. Gestion profesional
3. Conveniencia

DESVENTAJAS DE FONDOS

1. Comisiones reducen retornos
2. Mayoria no supera indices
