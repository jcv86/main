- Entiende estrategia antes de implementarla

CAPITULO 11: ANALISIS DE VALORES PARA INVERSOR INEXPERTO

ANALISIS CUANTITATIVO BASICO

1. PRECIO/GANANCIA (P/E RATIO)
Precio accion dividido por ganancia por accion.
- P/E bajo (bajo 15) puede indicar valor
- P/E alto (sobre 25) puede indicar sobreprecio

2. PRECIO/LIBRO (P/B RATIO)
Precio dividido por valor en libros por accion.
- P/B bajo (bajo 1.5) puede indicar valor
- P/B alto puede indicar prima excesiva

3. RENDIMIENTO DE DIVIDENDO
Dividendo anual dividido por precio accion.
- Mayor rendimiento puede indicar valor
- Pero verifica sostenibilidad

4. DEUDA/CAPITAL
Deuda total dividido por capital accionista.
- Menos de 0.5 es conservador
- Mas de 1.0 puede indicar riesgo

ANALISIS CUALITATIVO

1. Modelo de negocio entendible
2. Ventaja competitiva duradera
3. Gestion competente e integra
4. Prospects razonables largo plazo

