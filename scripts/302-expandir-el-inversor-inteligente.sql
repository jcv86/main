CAPITULO 20: MARGEN DE SEGURIDAD COMO CONCEPTO CENTRAL

DEFINICION

Margen de seguridad es diferencia entre precio y valor intrinseco.

Cuanto mayor margen, menor riesgo y mayor retorno potencial.

APLICACIONES

1. EN BONOS
Capacidad de pagar interes debe exceder ampliamente requisito minimo.

2. EN ACCIONES PREFERENTES
Ganancias deben cubrir dividendos preferentes multiples veces.

3. EN ACCIONES COMUNES
Precio debe ser significativamente menor que valor conservador calculado.

PROTECCION CONTRA ERROR

Incluso con analisis cuidadoso, puedes equivocarte. Margen de seguridad proporciona cushion.

RELACION CON DIVERSIFICACION

Margen de seguridad + Diversificacion = Proteccion maxima

Si una inversion sale mal, otras con margenes adecuados compensan.

POSTSCRIPT: CONCEPTO DE INVERSION VERSUS ESPECULACION

DISTINCION CRUCIAL

Inversion: Basada en analisis exhaustivo, busca seguridad principal y retorno adecuado.

Especulacion: Basada en prediccion, busca ganancias extraordinarias, acepta riesgo de perdida.

ESPECULACION INTELIGENTE

Si especulas:
1. Reconocelo explicitamente
2. Limita a pequena porcion capital
3. Nunca agregues a posiciones perdedoras
4. Toma ganancias cuando las tienes

