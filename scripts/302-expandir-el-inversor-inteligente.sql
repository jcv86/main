- Fondos que prometen superar mercado

CAPITULO 10: EL INVERSOR Y SUS ASESORES

CUANDO NECESITAS ASESOR

Si eres inversor defensivo que no puede o no quiere hacer analisis propio.

COMO ELEGIR ASESOR

1. Busca independencia
Evita asesores que ganan comisiones por productos especificos.

2. Revisa credenciales
Certificaciones profesionales, experiencia, reputacion.

3. Verifica alineacion de intereses
Mejor si asesor invierte junto contigo.

ADVERTENCIAS

