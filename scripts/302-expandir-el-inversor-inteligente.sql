CAPITULO 15: SELECCION DE ACCIONES PARA INVERSOR EMPRENDEDOR

TRES ENFOQUES PRINCIPALES

1. ESTRATEGIA DE VALOR CLASICA
Compra companias vendiendo bajo valor intrinseco.

Busca:
- P/B ratio bajo (idealmente bajo 1.0)
- P/E bajo
- Rendimiento dividendo solido
- Deuda minima

2. SITUACIONES ESPECIALES
Fusiones, liquidaciones, reorganizaciones.
Requiere analisis detallado caso por caso.

3. EMPRESAS DE CRECIMIENTO A PRECIO RAZONABLE
Crecimiento genuino pero precio moderado.

MARGIN DE SEGURIDAD

Compra solo cuando precio esta significativamente bajo valor estimado.

Regla: Paga no mas de dos tercios de valor intrinseco calculado.

CAPITULO 16: VALORES CONVERTIBLES Y WARRANTS

BONOS CONVERTIBLES

Hibrido entre bono y accion. Paga interes pero puede convertirse en acciones.

Ventaja: Proteccion downside de bono con upside potencial de accion.

Desventaja: Usualmente ofrece menos de ambos - interes menor que bono regular, upside menor que accion directa.

WARRANTS

Derecho a comprar acciones a precio fijo.

Graham es esceptico: Warrants usualmente tienen precio excesivo basado en valor intrinseco.

