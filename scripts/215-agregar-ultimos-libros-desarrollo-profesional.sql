'El sistema GTD (Getting Things Done) es una metodología completa para gestionar tareas, proyectos y compromisos de manera que libere tu mente para enfocarse en lo que realmente importa.

**Los Cinco Pasos del GTD:**

**1. Capturar**
Recolecta todo lo que tiene tu atención en un sistema confiable fuera de tu cabeza.

**Principios de Captura:**
- **Todo fuera de la cabeza:** No confíes en tu memoria
- **Sistemas confiables:** Que siempre estén disponibles
- **Captura inmediata:** En el momento que surge la idea
- **Sin procesamiento:** Solo captura, no analices aún

**Herramientas de Captura:**
- **Bandeja de entrada física:** Para documentos y objetos
- **Aplicación de notas:** En tu teléfono o computadora
- **Libreta pequeña:** Para cuando no tienes tecnología
- **Grabadora de voz:** Para ideas mientras conduces

**2. Clarificar**
Procesa lo que significa cada elemento capturado.

**Preguntas Clave:**
- **¿Es accionable?** ¿Requiere alguna acción de tu parte?
- **¿Cuál es la próxima acción?** El siguiente paso físico específico
- **¿Es un proyecto?** ¿Requiere más de una acción para completarse?
- **¿Cuánto tiempo tomará?** ¿Menos de 2 minutos o más?

**Regla de los 2 Minutos:**
Si algo toma menos de 2 minutos, hazlo inmediatamente.

**3. Organizar**
Pon los elementos en las categorías apropiadas.

**Categorías Principales:**
- **Próximas Acciones:** Tareas específicas que puedes hacer ahora
- **Proyectos:** Resultados que requieren múltiples acciones
- **Esperando:** Cosas que esperas de otros
- **Algún Día/Tal Vez:** Ideas para el futuro
- **Referencia:** Información que podrías necesitar después

**Contextos:**
- **@Llamadas:** Llamadas telefónicas que hacer
- **@Computadora:** Tareas que requieren computadora
- **@Recados:** Cosas que hacer fuera de casa
- **@Casa:** Tareas domésticas
- **@Oficina:** Trabajo en la oficina

**4. Reflexionar**
Revisa regularmente tu sistema para mantenerlo actualizado y confiable.

**Revisión Semanal:**
- **Recolecta y procesa:** Todo lo pendiente
- **Revisa sistema:** Listas y proyectos
- **Actualiza listas:** Agrega, elimina, modifica
- **Revisa calendario:** Próximas citas y compromisos
- **Revisa proyectos:** Progreso y próximas acciones

**Revisión Diaria:**
- **Revisa calendario:** Citas del día
- **Revisa próximas acciones:** Por contexto
- **Captura nuevos elementos:** Que surgieron
- **Actualiza listas:** Según progreso

**5. Comprometerse**
