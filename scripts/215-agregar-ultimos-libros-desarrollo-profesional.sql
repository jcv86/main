- **Invita a corrección:** "¿Estoy viendo esto correctamente?"
- **Mantén humildad:** Podrías estar equivocado

**A - Ask (Preguntar) por el Camino de Otros**
Invita a otros a compartir sus hechos e historias.

**Preguntas Efectivas:**
- **"¿Cómo lo ves tú?"** Invita a su perspectiva
- **"¿Qué estoy perdiendo?"** Reconoce limitaciones
- **"¿Puedes ayudarme a entender?"** Muestra curiosidad genuina
- **"¿Qué piensas?"** Abre el diálogo

**T - Talk (Hablar) Tentativamente**
Presenta tus conclusiones como opiniones, no como hechos.

**Lenguaje Tentativo:**
- **"En mi opinión..."** En lugar de "Obviamente..."
- **"Me pregunto si..."** En lugar de "Claramente..."
- **"Podría estar equivocado, pero..."** Invita a corrección
- **"¿Qué piensas sobre la posibilidad de que...?"** Abre opciones

**E - Encourage (Alentar) Pruebas**
Invita activamente a otros a expresar puntos de vista diferentes.

**Cómo Alentar:**
- **Haz preguntas específicas:** Sobre áreas de desacuerdo
- **Juega el abogado del diablo:** "¿Qué pasa si...?"
- **Busca activamente desacuerdo:** "¿Dónde ves esto diferente?"
- **Agradece la honestidad:** Cuando otros comparten

**Escuchando para Entender:**

**Técnicas de Escucha:**
- **Parafrasear:** "Entonces lo que escucho es..."
- **Reflejar sentimientos:** "Pareces frustrado por..."
- **Hacer preguntas:** Para clarificar y profundizar
- **Resumir:** "Déjame ver si entiendo..."

**Qué Evitar:**
- **Preparar tu respuesta:** Mientras otros hablan
- **Juzgar o evaluar:** Lo que están diciendo
- **Interrumpir:** Antes de que terminen
- **Asumir:** Que entiendes sin verificar

**Moviendo hacia la Acción:**

**Cuatro Métodos de Toma de Decisiones:**
- **Comando:** Una persona decide
- **Consulta:** Una persona decide después de consultar
- **Votación:** La mayoría decide
- **Consenso:** Todos deben estar de acuerdo

**Elementos de un Buen Plan:**
- **¿Quién?** Hará qué
- **¿Qué?** Exactamente se hará
- **¿Cuándo?** Se completará
- **¿Cómo?** Se medirá el progreso
- **¿Qué pasa si?** No se cumple

**Aplicaciones Específicas:**

**Feedback de Rendimiento:**
- **Comienza con hechos:** Comportamientos específicos observados
- **Comparte el impacto:** Cómo afecta a otros o al trabajo
- **Pregunta por su perspectiva:** ¿Cómo lo ven ellos?
- **Colabora en soluciones:** Trabajen juntos en mejoras

**Conflictos con Colegas:**
- **Enfócate en comportamientos:** No en personalidad
- **Busca intereses comunes:** ¿Qué quieren ambos?
- **Explora opciones:** Múltiples formas de resolver
- **Acuerda próximos pasos:** Específicos y medibles

**Conversaciones con el Jefe:**
- **Prepárate bien:** Hechos, datos, opciones
- **Enfócate en resultados:** Que le importan al jefe
- **Presenta soluciones:** No solo problemas
