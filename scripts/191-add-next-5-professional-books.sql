**SUSTAINING VS. DISRUPTIVE TECHNOLOGIES**

**Sustaining Technologies**
Most new technologies foster improved performance. These sustaining technologies can be discontinuous or radical in character, but they all have the feature that they improve the performance of established products, along the dimensions of performance that mainstream customers in major markets have historically valued.

**Disruptive Technologies**
Occasionally, however, disruptive technologies emerge: innovations that result in worse product performance, at least in the near-term. Disruptive technologies bring to a market a very different value proposition than had been available previously.

Characteristics of Disruptive Technologies:
- They are typically simpler, more convenient, and less expensive
- They appeal to new or less-demanding customers
- They are often dismissed by mainstream customers initially
- They improve rapidly and eventually meet mainstream needs
- They create new markets and value networks

**THE PRINCIPLES OF DISRUPTIVE INNOVATION**

**Principle 1: Companies Depend on Customers and Investors for Resources**
Companies with the best resource allocation processes will not allocate resources to disruptive technologies because their customers don''t want them, and their financial models can''t justify the investment.

**Principle 2: Small Markets Don''t Solve the Growth Needs of Large Companies**
Disruptive technologies typically enable new markets to emerge. These markets are initially small, and most large companies cannot justify investing in small markets.

**Principle 3: Markets That Don''t Exist Can''t Be Analyzed**
Companies have excellent capabilities for analyzing existing markets, but these capabilities are not helpful when dealing with markets that don''t yet exist.

**Principle 4: An Organization''s Capabilities Define Its Disabilities**
Organizations have capabilities in certain areas and disabilities in others. What makes them successful in sustaining innovation often makes them unsuccessful with disruptive innovation.

**Principle 5: Technology Supply May Not Equal Market Demand**
The pace of technological progress often exceeds the rate of improvement that customers can utilize or absorb. This creates opportunities for disruptive technologies to enter from below.

**THE DISK DRIVE INDUSTRY**

Christensen uses the disk drive industry as a primary example. Each new generation of disk drives was disruptive:
- 14-inch drives were displaced by 8-inch drives
- 8-inch drives were displaced by 5.25-inch drives  
- 5.25-inch drives were displaced by 3.5-inch drives

In each case, the new technology was initially inferior in capacity but superior in other dimensions like size, weight, and eventually cost.

**VALUE NETWORKS**

A value network is the context within which a firm identifies and responds to customers'' needs, solves problems, procures input, reacts to competitors, and strives for profit.

Different value networks have different metrics of value:
- Mainframe computers valued capacity and speed
- Desktop computers valued convenience and cost
- Portable computers valued size and battery life

