Managers face a fundamental dilemma:
- Listening to customers and investing in technologies that give those customers what they want is both the right thing to do and the reason why companies fail
- Customers don''t know what they want when it comes to breakthrough innovations
- The most profitable customers are often the least interested in disruptive innovations

