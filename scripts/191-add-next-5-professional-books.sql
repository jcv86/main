- Don''t try to make disruptive technologies better faster
- Don''t try to apply them in mainstream markets initially
- Don''t expect large profits immediately
- Don''t use traditional planning and forecasting methods

**What to Do:**

**1. Give Responsibility to Organizations Whose Customers Need the Technology**
Create independent organizations that can develop disruptive technologies for the customers who value them.

**2. Match the Size of the Organization to the Size of the Market**
Small opportunities can be meaningful to small organizations but not to large ones.

**3. Plan to Fail Early and Inexpensively**
Markets for disruptive technologies are unpredictable. Plan for learning and iteration rather than execution of a predetermined plan.

**4. Don''t Count on Breakthroughs**
Disruptive technologies typically improve through normal engineering advances, not breakthrough innovations.

**CREATING NEW MARKETS**

Disruptive innovations create new markets in two ways:

**1. They Enable a Larger Population of Less-Skilled People to Do Things**
Personal computers enabled people without programming skills to use computers. Digital cameras enabled people without darkroom skills to take and share photos.

**2. They Enable People to Do Things in Settings Where It Wasn''t Previously Possible**
Portable devices enabled computing, communication, and entertainment in new contexts and locations.

