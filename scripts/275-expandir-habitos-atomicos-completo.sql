# CAPÍTULO 2: CÓMO TUS HÁBITOS MOLDEAN TU IDENTIDAD (Y VICEVERSA)

Hay tres capas de cambio de comportamiento:

1. **Cambio de resultados**: Se trata de cambiar tus resultados (perder peso, publicar un libro, ganar un campeonato)
2. **Cambio de procesos**: Se trata de cambiar tus hábitos y sistemas (implementar una nueva rutina en el gimnasio, desarrollar una práctica de meditación)
3. **Cambio de identidad**: Se trata de cambiar tus creencias (tu visión del mundo, tu autoimagen, tus juicios sobre ti mismo y los demás)

La mayoría de la gente comienza enfocándose en lo que quiere lograr. Esto nos lleva a cambios basados en resultados.

**El enfoque alternativo**

El enfoque alternativo es construir hábitos basados en la identidad. Con este enfoque, comenzamos enfocándonos en quién deseamos ser.

- No "Quiero leer más libros" sino "Soy un lector"
- No "Quiero correr un maratón" sino "Soy un corredor"
- No "Quiero aprender a tocar guitarra" sino "Soy un músico"

**Cómo cambiar tu identidad**

Tu identidad emerge de tus hábitos. Cada acción que tomas es un voto por el tipo de persona que deseas ser. Ninguna instancia única transformará tus creencias, pero a medida que los votos se acumulan, también lo hace la evidencia de tu nueva identidad.

El proceso de construcción de hábitos es en realidad el proceso de convertirse en ti mismo. Esta es la parte más poderosa de por qué los hábitos son importantes: no solo te permiten obtener más de lo que quieres, te convierten en el tipo de persona que deseas ser.

**El ciclo de retroalimentación de dos pasos**

Tus hábitos moldean tu identidad, y tu identidad moldea tus hábitos:

1. Decide el tipo de persona que quieres ser
2. Pruébatelo con pequeñas victorias

La formación de hábitos no se trata de tener la disciplina para mantener un hábito durante 30 días. Se trata de adoptar una nueva identidad y demostrar esa identidad con pequeños cambios consistentes.

