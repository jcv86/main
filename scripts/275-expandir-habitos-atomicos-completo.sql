# INTRODUCCIÓN: MI HISTORIA

En el segundo año de secundaria, un bate de béisbol me golpeó en la cara. Mi compañero estaba haciendo algunos swings de práctica y no se dio cuenta de que yo estaba parado detrás de él. El bate me golpeó directamente entre los ojos con un crujido sordo. No recuerdo ver el bate antes de que me golpeara, solo recuerdo sentir un dolor penetrante en mi cara cuando caí al suelo.

Mi nariz se rompió instantáneamente. El impacto fue tan fuerte que mi cerebro rebotó dentro de mi cráneo, causando una conmoción cerebral masiva. Perdí el conocimiento de inmediato. Cuando desperté en el hospital horas después, tuve una convulsión y vomité sangre.

Los doctores me dijeron que mi lesión cerebral era grave y que probablemente tendría problemas permanentes. Durante semanas, tuve dolores de cabeza constantes, mareos y náuseas. No podía concentrarme en la escuela. Tenía problemas para recordar cosas básicas.

Pero con el tiempo, lentamente, comencé a recuperarme. Y en ese proceso de recuperación, aprendí algo fundamental sobre el cambio y la mejora: **los pequeños cambios a menudo parecen no hacer ninguna diferencia hasta que cruzas un umbral crítico.**

