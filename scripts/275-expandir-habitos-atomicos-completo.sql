# TERCERA LEY: HACERLO FÁCIL

## CAPÍTULO 11: CAMINA LENTAMENTE, PERO NUNCA RETROCEDAS

La diferencia entre estar en movimiento y tomar acción:

- **Estar en movimiento**: planificar, estrategizar y aprender
- **Tomar acción**: comportamiento que producirá un resultado

A veces el movimiento es útil, pero nunca producirá un resultado por sí solo. No importa cuántas veces hables con un entrenador personal, ese tiempo en el gimnasio es lo que hace la diferencia.

**La ley del menor esfuerzo**

Los humanos naturalmente gravitamos hacia la opción que requiere la menor cantidad de trabajo. Por eso es importante hacer que tus hábitos sean tan fáciles como sea posible.

**Reduce la fricción**

Cuanto más fácil sea hacer algo, más probable es que lo hagas. Por ejemplo:

- Si quieres hacer más ejercicio, pon tu ropa de gimnasio la noche anterior
- Si quieres comer más saludable, corta frutas y verduras con anticipación
- Si quieres practicar guitarra, deja tu guitarra en medio de la sala

## CAPÍTULO 12: LA REGLA DE LOS DOS MINUTOS

Casi cualquier hábito puede reducirse a una versión de dos minutos:

- "Leer antes de dormir cada noche" se convierte en "Leer una página"
- "Hacer 30 minutos de yoga" se convierte en "Sacar mi estera de yoga"
- "Estudiar para clase" se convierte en "Abrir mis notas"
- "Correr 5 kilómetros" se convierte en "Atarme mis zapatos para correr"

La idea es hacer que tus hábitos sean lo más fáciles de comenzar posible. Una vez que comienzas a hacer lo correcto, es mucho más fácil continuar haciéndolo.

