# CAPÍTULO 3: CÓMO CONSTRUIR MEJORES HÁBITOS EN 4 SIMPLES PASOS

En 1898, un psicólogo llamado Edward Thorndike realizó un experimento que sentaría las bases para nuestra comprensión de cómo se forman los hábitos.

Thorndike colocó gatos dentro de una caja negra y midió cuánto tiempo tardaba cada gato en escapar. Al principio, los gatos tardaban mucho tiempo, arañando y mordiendo frenéticamente. Pero con cada repetición, los gatos aprendían. Eventualmente, podían escapar en pocos segundos.

**El ciclo del hábito**

El proceso de formación de hábitos se puede dividir en cuatro pasos simples:

1. **Señal**: La señal desencadena tu cerebro para iniciar un comportamiento
2. **Anhelo**: Los anhelos son la fuerza motivacional detrás de cada hábito
3. **Respuesta**: La respuesta es el hábito real que realizas
4. **Recompensa**: Las recompensas son el objetivo final de cada hábito

Si falta alguna de estas cuatro etapas, el comportamiento no se convertirá en un hábito.

**Las cuatro leyes del cambio de comportamiento**

Basándose en el ciclo del hábito, podemos desarrollar un marco para crear buenos hábitos y eliminar los malos:

**Cómo crear un buen hábito:**
- 1ª Ley (Señal): Hacerlo obvio
- 2ª Ley (Anhelo): Hacerlo atractivo
- 3ª Ley (Respuesta): Hacerlo fácil
- 4ª Ley (Recompensa): Hacerlo satisfactorio

**Cómo romper un mal hábito:**
- Inversión de la 1ª Ley (Señal): Hacerlo invisible
- Inversión de la 2ª Ley (Anhelo): Hacerlo poco atractivo
- Inversión de la 3ª Ley (Respuesta): Hacerlo difícil
- Inversión de la 4ª Ley (Recompensa): Hacerlo insatisfactorio

Cada vez que quieras cambiar tu comportamiento, puedes preguntarte:

1. ¿Cómo puedo hacerlo obvio?
2. ¿Cómo puedo hacerlo atractivo?
3. ¿Cómo puedo hacerlo fácil?
4. ¿Cómo puedo hacerlo satisfactorio?

