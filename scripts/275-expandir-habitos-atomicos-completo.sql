# PRIMERA LEY: HACERLO OBVIO

## CAPÍTULO 4: EL HOMBRE QUE NO SE VEÍA BIEN

El proceso de cambio de comportamiento siempre comienza con la conciencia. Necesitas ser consciente de tus hábitos antes de poder cambiarlos.

**El Cuadro de Mando de Hábitos**

Una de las mejores formas de crear conciencia sobre tus hábitos es crear un Cuadro de Mando de Hábitos. Simplemente haz una lista de tus hábitos diarios.

Por ejemplo:
- Despertar
- Apagar la alarma
- Revisar mi teléfono
- Ir al baño
- Pesarme
- Ducharme
- Cepillar mis dientes
- etc.

Una vez que tengas una lista completa, observa cada comportamiento y pregúntate: "¿Es este un buen hábito, un mal hábito o un hábito neutral?"

Si es un buen hábito, escribe "+" al lado. Si es un mal hábito, escribe "–". Si es neutral, escribe "=".

**El proceso de señalización**

Con suficiente práctica, tu cerebro captará las señales que predicen ciertos resultados sin pensar conscientemente en ello. Este es el poder y el problema de los hábitos: después de suficientes repeticiones, comienzan a ocurrir automáticamente.

## CAPÍTULO 5: LA MEJOR MANERA DE COMENZAR UN NUEVO HÁBITO

En 2001, investigadores en Gran Bretaña trabajaron con 248 personas para construir mejores hábitos de ejercicio durante dos semanas. Los participantes se dividieron en tres grupos:

- Grupo 1 (control): Se les pidió que registraran con qué frecuencia hacían ejercicio
- Grupo 2 (motivación): Leyeron material sobre los beneficios del ejercicio
- Grupo 3 (intención de implementación): Se les pidió que formularan un plan específico

**Resultados:**
- Grupo 1 (control): 38% hicieron ejercicio al menos una vez por semana
- Grupo 2 (motivación): 35% hicieron ejercicio
- Grupo 3 (plan): 91% hicieron ejercicio

**La fórmula de intención de implementación**

La fórmula que funcionó fue simple: "Haré [COMPORTAMIENTO] a las [HORA] en [UBICACIÓN]."

Por ejemplo:
- "Meditaré durante 5 minutos a las 7 a.m. en mi cocina"
- "Estudiaré español durante 20 minutos a las 6 p.m. en mi dormitorio"

Muchas personas piensan que carecen de motivación cuando en realidad lo que les falta es claridad. No es siempre obvio cuándo y dónde tomar acción.

**Acumulación de hábitos**

Una de las mejores maneras de construir un nuevo hábito es identificar un hábito actual que ya haces cada día y luego apilar tu nuevo comportamiento encima.

La fórmula es: "Después de [HÁBITO ACTUAL], yo [NUEVO HÁBITO]."

Por ejemplo:
- "Después de servirme mi café por la mañana, meditaré durante 60 segundos"
- "Después de quitarme los zapatos del trabajo, inmediatamente me cambiaré a mi ropa de entrenamiento"

