# CAPÍTULO 1: EL SORPRENDENTE PODER DE LOS HÁBITOS ATÓMICOS

Los hábitos son el interés compuesto de la superación personal. De la misma manera que el dinero se multiplica a través del interés compuesto, los efectos de tus hábitos se multiplican a medida que los repites.

**El 1% de mejora diaria**

Si puedes mejorar un 1% cada día durante un año, terminarás siendo 37 veces mejor al final del año. Por el contrario, si empeoras un 1% cada día durante un año, descenderás casi hasta cero.

- 1.01^365 = 37.78
- 0.99^365 = 0.03

Los hábitos son una espada de doble filo. Pueden trabajar a tu favor o en tu contra, por eso es crucial entender los detalles.

**Por qué los pequeños cambios generan una gran diferencia**

Imagina que vas en un avión desde Los Ángeles a Nueva York. Si el piloto que sale de LAX ajusta la dirección 3.5 grados al sur, aterrizarás en Washington D.C. en lugar de Nueva York. Un pequeño cambio en la dirección puede llevar a un destino muy diferente.

De manera similar, un ligero cambio en tus hábitos diarios puede guiar tu vida a un destino completamente diferente. Tomar una decisión mejor en un 1% o un 5% no parece importar en el momento, pero a lo largo de años y décadas, estas pequeñas mejoras se acumulan para crear una diferencia entre quien eres y quien podrías ser.

**El valle de la desilusión**

Uno de los mayores desafíos para formar nuevos hábitos es lo que llamo "el valle de la desilusión". Esperamos un progreso lineal: si ponemos esfuerzo, esperamos resultados inmediatos. Pero el progreso real no es lineal.

En las primeras semanas y meses de un nuevo hábito, a menudo hay un "valle de la desilusión" donde el trabajo que pones no parece producir resultados. Es extremadamente frustrante sentir que estás trabajando duro sin ver resultados.

Pero eventualmente, después de semanas o meses de trabajo consistente, llegas a lo que llamo el "Meseta del Potencial Latente". Es en este punto donde el valor de tus buenos hábitos se vuelve más evidente. La gente a menudo piensa que el éxito es el resultado de transformaciones masivas, pero en realidad es el resultado de cientos de pequeñas mejoras que se acumulan con el tiempo.

