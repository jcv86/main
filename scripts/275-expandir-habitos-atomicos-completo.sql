# CUARTA LEY: HACERLO SATISFACTORIO

## CAPÍTULO 15: LA REGLA CARDINAL DEL CAMBIO DE COMPORTAMIENTO

La regla cardinal del cambio de comportamiento: **Lo que se recompensa inmediatamente se repite. Lo que se castiga inmediatamente se evita.**

El problema con los buenos hábitos es que la recompensa generalmente viene después de un largo tiempo. Esto hace que sea difícil mantenerlos porque no obtienes satisfacción inmediata.

**Cómo mantener buenos hábitos todos los días**

Una de las formas más satisfactorias de rastrear tu progreso es usar un rastreador de hábitos visual. Ejemplos:

- Marca una X en un calendario cada día que haces ejercicio
- Mueve un clip de papel de un contenedor a otro por cada llamada de ventas
- Pon una moneda en un frasco cada vez que meditas

Los rastreadores de hábitos son obvios, atractivos y satisfactorios:

1. **Obvio**: Registrar tu último hábito crea un disparador para tu próximo
2. **Atractivo**: El método más efectivo de motivación es el progreso
3. **Satisfactorio**: Marcar tu progreso se siente bien

## CAPÍTULO 16: CÓMO ADHERIRSE A LOS BUENOS HÁBITOS TODOS LOS DÍAS

**Nunca falles dos veces**

La primera error nunca es la que te arruina. Es la espiral de errores repetidos que sigue. Perder un entrenamiento no hace que tengas sobrepeso. Pero perder entrenamientos durante cinco meses sí.

La clave es nunca fallar dos veces seguidas. Si te pierdes un día, vuelve al camino lo más rápido posible.

**Saber cuándo (y cuándo no) rastrear un hábito**

Los números dicen cuánto pero no todo. Solo porque puedas medir algo no significa que sea lo más importante.

