# TÁCTICAS AVANZADAS

## CAPÍTULO 18: LA VERDAD SOBRE EL TALENTO

La regla de Goldilocks establece que los humanos experimentamos la motivación máxima cuando trabajamos en tareas que están justo en el borde de nuestras habilidades actuales.

- Demasiado fácil = aburrimiento
- Demasiado difícil = frustración
- Justo = flujo

**La zona de flujo**

Necesitas tareas que sean aproximadamente un 4% más allá de tu habilidad actual. Esto te mantiene comprometido y motivado.

## CAPÍTULO 19: LA DESVENTAJA DE CREAR BUENOS HÁBITOS

**El poder de la reflexión**

Una de las mejores maneras de asegurar que tus hábitos permanezcan satisfactorios a largo plazo es establecer un tiempo para la reflexión y revisión.

Por ejemplo, cada diciembre puedes preguntarte:
- ¿Qué salió bien este año?
- ¿Qué no salió bien?
- ¿Qué aprendí?

La revisión anual te permite reflexionar sobre tus hábitos y tomar decisiones conscientes sobre cómo mejorarlos.

