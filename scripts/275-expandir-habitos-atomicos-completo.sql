# SEGUNDA LEY: HACERLO ATRACTIVO

## CAPÍTULO 8: CÓMO HACER QUE UN HÁBITO SEA IRRESISTIBLE

**El agrupamiento de tentaciones**

Una forma de hacer que tus hábitos sean más atractivos es agrupar una acción que quieres hacer con una acción que necesitas hacer.

Fórmula: Después de [HÁBITO QUE NECESITO], haré [HÁBITO QUE QUIERO].

Por ejemplo:
- "Después de sacar mi teléfono, haré 10 flexiones"
- "Después de recibir mi café matutino, diré una cosa por la que estoy agradecido"

## CAPÍTULO 9: EL PAPEL DE LA FAMILIA Y LOS AMIGOS

Los humanos somos animales de manada. Queremos encajar, vincularnos con otros y obtener el respeto y la aprobación de nuestros pares.

**Únete a una cultura donde tu comportamiento deseado es el comportamiento normal**

Si quieres desarrollar el hábito de leer, únete a un club de lectura. Si quieres empezar un negocio, rodéate de emprendedores.

Nada sostiene un comportamiento mejor que pertenecer a una tribu. El comportamiento es atractivo cuando nos ayuda a encajar.

