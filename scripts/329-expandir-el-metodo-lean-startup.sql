- Asumir que sabes qué quiere cliente

**2. MVP no es suficientemente M**
- Over-engineering del MVP
- Buscar perfección

**3. Métricas Vanidosas**
- Celebrar números que no importan
- Ignorar métricas accionables

**4. Miedo a Lanzar**
- Esperar el momento perfecto
- Preocupación por competidores copiando

**5. No Pivotar Cuando Necesario**
- Apego emocional a idea original
- Ignorar datos que contradicen hipótesis

