### El Propósito y el Espíritu

Las organizaciones verdaderamente grandes tienen un propósito que trasciende hacer dinero:
- **Apple**: Empoderar la creatividad individual
- **Patagonia**: Salvar el planeta
- **TOMS**: Mejorar vidas a través del negocio

El espíritu organizacional: Cuando las personas sienten que su trabajo contribuye a algo significativo, el compromiso se multiplica, la creatividad florece, la perseverancia aumenta, y el trabajo se vuelve vocación.

Pregunta esencial para líderes: ¿Qué diferencia en el mundo queremos hacer, más allá de ser rentables?

