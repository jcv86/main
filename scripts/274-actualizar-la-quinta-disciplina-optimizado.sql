### Superando las Barreras al Aprendizaje

**Barrera 1: "Yo soy mi puesto"**

Las personas se definen por su rol limitado, no por el sistema completo. Consecuencia: responsabilidad fragmentada, problemas pasan desapercibidos, nadie ve el cuadro completo. Solución: rotar roles, exponer a las personas a diferentes partes del sistema, fomentar perspectiva holística.

**Barrera 2: "El enemigo está allá afuera"**

Tendencia a culpar factores externos por problemas. Consecuencia: victimización, falta de responsabilidad, problemas recurrentes. Solución: buscar cómo contribuimos al problema, tomar responsabilidad sistémica, cambiar lo que está en nuestro control.

**Barrera 3: "La ilusión de hacerse cargo"**

Confundir reactividad emocional con acción proactiva. Consecuencia: apagar incendios constantemente, nunca abordar causas raíz, agotamiento crónico. Solución: distinguir entre reactivo y proactivo, invertir en prevención, crear tiempo para reflexión estratégica.

**Barrera 4: "La fijación en eventos"**

Enfocarse en eventos individuales vs. patrones a largo plazo. Consecuencia: soluciones superficiales, sorpresas constantes, incapacidad de prever problemas. Solución: buscar tendencias y patrones, analizar estructuras subyacentes, desarrollar visión de largo plazo.

**Barrera 5: "La parábola de la rana hervida"**

No percibir cambios graduales hasta que es demasiado tarde. Consecuencia: adaptación inadecuada, crisis repentinas, oportunidades perdidas. Solución: monitorear indicadores adelantados, crear alertas tempranas, cultivar sensibilidad al cambio gradual.

