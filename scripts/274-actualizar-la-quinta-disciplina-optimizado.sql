## Construyendo una Organización que Aprende

### La Arquitectura de una Organización que Aprende

Una organización que aprende no se crea por decreto. Requiere ideas guía (visión, valores, propósito), teoría y métodos, e innovaciones en infraestructura.

**Niveles de cambio organizacional:**

**Nivel 1: Habilidades y capacidades** - Entrenar en las cinco disciplinas, desarrollar competencias técnicas. Más fácil, impacto limitado.

**Nivel 2: Conciencia y sensibilidad** - Cambiar cómo vemos el mundo, desarrollar nuevas percepciones. Impacto moderado.

**Nivel 3: Actitudes y creencias** - Transformar modelos mentales profundos, cambiar qué valoramos. Más difícil, mayor impacto.

**Infraestructuras que apoyan el aprendizaje:**

**Estructuras organizacionales**: Equipos autodirigidos, redes horizontales, comunidades de práctica.

**Procesos de reflexión**: After Action Reviews regulares, sesiones de aprendizaje post-proyecto, tiempo protegido para reflexión.

**Sistemas de información**: Conocimiento accesible, feedback en tiempo real, transparencia de datos.

