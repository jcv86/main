## Reflexiones Profundas y Filosofía

### La Naturaleza del Cambio Profundo

Senge argumenta que hay dos tipos de cambio:

**Cambio técnico (E-Change)**: Cambios en estructuras y procesos, relativamente fácil, resultados rápidos pero superficiales.

**Cambio adaptativo (O-Change)**: Cambios en mentalidad y cultura, muy difícil, resultados lentos pero profundos.

La paradoja: La mayoría de organizaciones se enfocan en cambio técnico porque es más fácil y medible. Pero el cambio duradero requiere cambio adaptativo.

La solución: Equilibrar ambos tipos de cambio. Usar cambios técnicos para crear momentum, mientras se trabaja pacientemente en cambio adaptativo.

