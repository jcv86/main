### 2. Modelos Mentales (Mental Models)

Los modelos mentales son supuestos profundamente arraigados, generalizaciones o incluso imágenes que influyen en cómo entendemos el mundo y actuamos. Una organización puede tener la mejor estrategia del mundo, pero si los modelos mentales de sus líderes son limitantes, la estrategia fracasará.

**Tipos de modelos mentales limitantes:**

1. **"Los clientes solo quieren precio bajo"** - Realidad: Los clientes valoran calidad, experiencia, servicio. Consecuencia: Competencia destructiva por precio.

2. **"Los empleados necesitan supervisión constante"** - Realidad: Los empleados motivados se autodirigen efectivamente. Consecuencia: Micromanagement y desmotivación.

3. **"El cambio es peligroso"** - Realidad: El cambio es oportunidad. Consecuencia: Parálisis organizacional.

**Técnicas para trabajar con modelos mentales:**

**Reflexión**: Examinar nuestro propio pensamiento. ¿Qué estoy asumiendo? ¿Qué evidencia contradice mis creencias?

**Indagación**: Explorar el pensamiento de otros con genuina curiosidad, suspendiendo el juicio, buscando entender antes de ser entendido.

**Advocacy balanceada**: Expresar nuestras opiniones efectivamente haciendo explícito nuestro razonamiento, invitando a otros a cuestionar nuestra lógica, buscando activamente datos contradictorios.

**Caso de estudio: Xerox PARC**

En los años 70, Xerox PARC desarrolló tecnologías revolucionarias: interfaz gráfica, mouse, Ethernet. Sin embargo, Xerox no capitalizó estas invenciones. ¿Por qué? Modelo mental limitante: "Somos una compañía de copiadoras, no de computadoras". Resultado: Apple y otras compañías aprovecharon estas innovaciones mientras Xerox las desechó. Lección: Los modelos mentales pueden cegarnos ante oportunidades extraordinarias.

