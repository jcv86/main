### 3. Visión Compartida (Shared Vision)

Una visión compartida no es simplemente una idea, es una fuerza en el corazón de las personas, una fuerza de impresionante poder.

**Características de una visión compartida genuina:**

- **Inspiradora**: Conecta con valores profundos
- **Específica**: Clara y tangible, no vaga
- **Voluntaria**: Las personas eligen enrollarse, no son obligadas
- **Energizante**: Genera entusiasmo y compromiso genuino

**Diferencia entre visión compartida y visión impuesta:**

Visión impuesta produce cumplimiento superficial, resistencia pasiva, energía mínima y resultados mediocres.

Visión compartida genera compromiso profundo, iniciativa proactiva, energía sostenida y resultados excepcionales.

**Proceso de construcción de visión compartida:**

1. **Enrolling (Enrolamiento)** - Presentar la visión de manera inspiradora, invitar participación voluntaria, respetar diferentes niveles de compromiso.

2. **Conversaciones generativas** - Dialogar sobre aspiraciones individuales, encontrar puntos de conexión, co-crear elementos de la visión.

3. **Iteración continua** - La visión evoluciona con el tiempo, se enriquece con nuevas perspectivas, se mantiene viva mediante conversaciones constantes.

**Ejemplo: Southwest Airlines**

Visión compartida original: "Democratizar el vuelo" - Hacer que volar sea accesible para todos, con servicio amigable y eficiente, precios bajos sin comprometer calidad. Esta visión resonó profundamente con empleados (orgullo en servir a todos), clientes (gratitud por acceso) e inversionistas (modelo de negocio sólido). Resultado: 40+ años consecutivos de rentabilidad, empleados apasionados, clientes leales.

