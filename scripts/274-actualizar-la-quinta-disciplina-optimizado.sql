### 4. Aprendizaje en Equipo (Team Learning)

El aprendizaje en equipo es el proceso de alinear y desarrollar la capacidad de un equipo para crear los resultados que sus miembros realmente desean. En las organizaciones modernas, la unidad fundamental de aprendizaje no es el individuo, es el equipo.

**Enemigos del aprendizaje en equipo:**

1. **Rutinas defensivas** - Evitar temas incómodos, culpar a otros, proteger el status quo.

2. **Pensamiento grupal** - Conformidad forzada, supresión de disidencia, ilusión de unanimidad.

3. **Incompetencia diestra** - Ser experto en no aprender, defender posiciones tercamente, evitar vulnerabilidad.

**Prácticas de aprendizaje en equipo:**

**Diálogo**: Suspender suposiciones, pensar juntos, explorar temas complejos sin necesidad de decisión inmediata.

**Discusión**: Presentar diferentes puntos de vista, argumentar con evidencia, llegar a decisiones claras.

**Práctica reflexiva**: Revisar acciones pasadas, identificar patrones, extraer lecciones para el futuro.

**Caso: Equipo de Google Project Aristotle**

Google estudió 180 equipos para identificar qué hace efectivos a los equipos. Descubrieron que el factor número uno era "seguridad psicológica": los miembros se sienten seguros tomando riesgos, pueden admitir errores sin miedo, pueden hacer preguntas sin ser juzgados, pueden desafiar el status quo. Los equipos con alta seguridad psicológica aprendían 10 veces más rápido que otros.

