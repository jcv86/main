Miles de empresas ya lo practican. Millones de personas trabajan en ellas. Billones en valor han sido creados. La pregunta no es si el Capitalismo Consciente es posible, ya está sucediendo. La pregunta es: ¿Te unirás?

Como dijo Gandhi: Sé el cambio que quieres ver en el mundo. En negocios: Sé la empresa que el mundo necesita.

El capitalismo liberó el espíritu emprendedor humano. El Capitalismo Consciente lo eleva a su máximo potencial, creando abundancia mientras sirve al bien común.

Este es el capitalismo que merecemos. Este es el capitalismo que construiremos.'
