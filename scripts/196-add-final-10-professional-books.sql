- Industry boundaries are not defined
- Competitive rules are waiting to be set
- Competition is irrelevant
- Demand is created rather than fought over
- Opportunity for profitable growth
- Value-cost trade-off is broken

**Examples of Blue Ocean Creation:**
- **Cirque du Soleil**: Combined circus and theater
- **Southwest Airlines**: Low-cost, point-to-point travel
- **Yellow Tail Wine**: Simple, approachable wine
- **Nintendo Wii**: Gaming for everyone
- **Tesla**: Electric luxury vehicles

**THE STRATEGY CANVAS**

**What Is a Strategy Canvas?**
A diagnostic framework that captures the current state of play in the known market space and shows how companies compete.

**Components:**
- **Horizontal axis**: Factors the industry competes on
- **Vertical axis**: Level of offering buyers receive
- **Value curves**: How companies perform across factors

