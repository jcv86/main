**THE FLAWS OF MOTIVATION 2.0**

**When Rewards Work**
Rewards are effective for:
- Routine, algorithmic tasks
- Simple, mechanical work
- Tasks with clear rules and obvious destinations
- Work that requires little creativity or problem-solving

**When Rewards Don''t Work (And Can Backfire)**
For creative, conceptual tasks, rewards can:
- Diminish performance
- Crush creativity
- Crowd out good behavior
- Encourage cheating and shortcuts
- Become addictive
- Foster short-term thinking

