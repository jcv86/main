**1. They can extinguish intrinsic motivation**
External rewards can reduce internal drive to perform activities.

**2. They can diminish performance**
For creative tasks, rewards often lead to worse performance.

**3. They can crush creativity**
Rewards narrow focus and reduce innovative thinking.

**4. They can crowd out good behavior**
External motivators can replace ethical behavior with compliance.

**5. They can encourage cheating, shortcuts, and unethical behavior**
Focus on rewards can lead to cutting corners to achieve them.

**6. They can become addictive**
