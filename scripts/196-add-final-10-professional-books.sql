**RED OCEANS VS. BLUE OCEANS**

**Red Oceans**
- Represent existing market space
- Industry boundaries are defined and accepted
- Competitive rules are known
- Companies compete for greater market share
- Cutthroat competition turns water bloody red
- Demand is fought over
- Value-cost trade-off exists

**Blue Oceans**
