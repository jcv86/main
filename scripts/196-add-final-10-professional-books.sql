**THE HABIT LOOP**

**The Three-Step Process:**

**1. CUE**
The trigger that tells your brain to go into automatic mode and which habit to use.

**Types of Cues:**
- **Location**: Where you are
- **Time**: When it happens
- **Emotional state**: How you feel
- **Other people**: Who you''re with
- **Immediately preceding action**: What you just did

**2. ROUTINE**
The behavior itself, which can be physical, mental, or emotional.

**Types of Routines:**
- **Physical**: Actions you take
- **Mental**: Thoughts you think
- **Emotional**: Feelings you experience

**3. REWARD**
The benefit you gain from the behavior, which helps your brain figure out if this particular loop is worth remembering.

**Types of Rewards:**
- **Physical**: Food, exercise endorphins
- **Emotional**: Pride, relaxation, companionship
- **Mental**: Sense of accomplishment, learning

**THE GOLDEN RULE OF HABIT CHANGE**

**You Can''t Eliminate Bad Habits, But You Can Change Them**

**The Rule:**
Keep the same cue and reward, but change the routine.

**Why This Works:**
- The cue and reward stay the same
- Only the routine changes
- The brain''s craving remains satisfied
- The habit loop remains intact

