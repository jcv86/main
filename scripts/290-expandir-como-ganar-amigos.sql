Por Dale Carnegie

INTRODUCCIÓN

Este libro fue escrito para ayudarte a resolver el problema más grande que enfrentas: el problema de llevarte bien y tratar con la gente.

Durante los últimos treinta y cinco años, las compañías editoriales de Estados Unidos han impreso más de un tercio de millón de libros. La mayoría eran ficción. Sin embargo, según expertos, solo un libro de cada ocho publicado fue de no ficción.

Este es un libro de acción. Charles Schwab dijo que su personalidad y capacidad para despertar entusiasmo entre los hombres eran su mayor activo, y añadió que pagó un millón de dólares por esa capacidad.

PARTE UNO: TÉCNICAS FUNDAMENTALES PARA TRATAR CON LA GENTE

PRINCIPIO 1: No critique, no condene ni se queje

La crítica es inútil porque pone a la persona a la defensiva y usualmente la hace luchar para justificarse.

B.F. Skinner, el psicólogo mundialmente famoso, probó mediante experimentación que un animal recompensado por buena conducta aprenderá mucho más rápido que un animal castigado por mala conducta.

Abraham Lincoln aprendió esta lección. Durante la Guerra Civil criticó duramente a algunos generales. Después de ver el daño que causó, nunca volvió a criticar a nadie.

"No juzguéis para que no seáis juzgados" dijo Jesús hace diecinueve siglos.

Benjamin Franklin dijo: "No hablaré mal de ningún hombre y hablaré todo el bien que sepa de todos."

PRINCIPIO 2: Demuestre aprecio honesto y sincero

Solo hay una manera de conseguir que alguien haga algo. Hágale querer hacerlo. La única manera es dándole lo que quiere.

El deseo más profundo en la naturaleza humana es "el anhelo de ser importante."

Todos quieren la aprobación de aquellos con quienes entran en contacto. Todos quieren que se reconozca su verdadero valor. Todos quieren sentirse importantes en su pequeño mundo.

El cumplido sincero es uno de los instrumentos más efectivos que existen para motivar a la gente.

La diferencia entre aprecio y adulación es simple: uno es sincero y el otro insincero. Uno viene del corazón, el otro de los dientes hacia afuera.

PRINCIPIO 3: Despierte en los demás un deseo vehemente

¿Por qué hablamos de lo que queremos? Es infantil. Absurdo. Claro, te interesa lo que quieres. Pero nadie más está interesado. El resto de nosotros es como tú: nos interesa lo que queremos.

Henry Ford dijo: "Si hay algún secreto del éxito, reside en la capacidad para apreciar el punto de vista del otro y ver las cosas desde ese punto de vista así como del propio."

La única manera en la tierra de influir sobre el prójimo es hablar acerca de lo que él quiere y demostrarle cómo conseguirlo.

Las personas que pueden ponerse en el lugar del prójimo, que pueden comprender el funcionamiento de la mente ajena, no tienen que preocuparse por el futuro.

PARTE DOS: SEIS MANERAS DE AGRADAR A LOS DEMÁS

PRINCIPIO 1: Interésese sinceramente por los demás

Puedes hacer más amigos en dos meses interesándote en otras personas que en dos años tratando de que otras personas se interesen en ti.

Alfred Adler, el famoso psicólogo vienés, escribió un libro titulado "¿Qué debe significar la vida para ti?" En ese libro dice: "El individuo que no se interesa por sus semejantes es quien tiene las mayores dificultades en la vida."

Si queremos obtener amigos, dediquémonos a hacer cosas por los demás, cosas que requieren tiempo, energía, altruismo y consideración.

PRINCIPIO 2: Sonría

Las acciones dicen más que las palabras, y una sonrisa dice: "Me agradas. Me haces feliz. Me alegro tanto de verte."

Tu sonrisa es un mensajero de tu buena voluntad. Tu sonrisa ilumina las vidas de todos los que la ven.

Una persona sin una sonrisa en el rostro no debe abrir una tienda. Proverbio chino.

El valor de una sonrisa: No cuesta nada pero crea mucho. Enriquece a quienes reciben sin empobrecer a quienes dan.

PRINCIPIO 3: Recuerde que para toda persona, su nombre es el sonido más dulce e importante en cualquier idioma

Jim Farley descubrió temprano en la vida que la persona promedio está más interesada en su propio nombre que en todos los otros nombres juntos.

Recuerda ese nombre y lo llamarás fácilmente, y habrás hecho un cumplido sutil y muy efectivo. Pero olvida ese nombre o escríbelo mal, y te habrás colocado en una gran desventaja.

La información que estamos impartiendo, o la pregunta que estamos haciendo, toma una importancia especial cuando le agregamos el nombre de la persona.

PRINCIPIO 4: Sea un buen oyente. Anime a los demás a que hablen de sí mismos

Para ser interesante, sé interesado. Haz preguntas que a la otra persona le guste responder.

Escuchar es uno de los cumplidos más grandes que podemos dar a alguien.

La mayoría de las personas que tratan de ganarse a otros hablan demasiado de sí mismas. Si quieres agradar, escucha atentamente. Anima a otros a hablar de sí mismos.

PRINCIPIO 5: Hable siempre de lo que interese a los demás

El camino real al corazón de una persona es hablarle sobre las cosas que más aprecia.

Theodore Roosevelt estudiaba la noche anterior sobre temas que sabía que le interesaban particularmente a su visitante del día siguiente.

Hablar en términos de los intereses de la otra persona es beneficioso para ambas partes.

PRINCIPIO 6: Haga que la otra persona se sienta importante, y hágalo sinceramente

Siempre haga que la otra persona se sienta importante. "Haz al prójimo lo que quieras que el prójimo te haga a ti."

Casi todas las personas que conoces se sienten superiores a ti en alguna forma. Un camino seguro a sus corazones es hacerles comprender de alguna manera sutil que reconoces su importancia sinceramente.

La verdad es que casi todos los seres humanos se sienten superiores a nosotros en alguna forma, y un camino seguro a sus corazones es hacerles comprender de alguna manera sutil que reconocemos su importancia.

PARTE TRES: LOGRE QUE LOS DEMÁS PIENSEN COMO USTED

PRINCIPIO 1: La única forma de salir ganando de una discusión es evitándola

No puedes ganar una discusión. No puedes porque si pierdes, la pierdes; y si ganas, la pierdes.

Benjamin Franklin solía decir: "Si discutes y peleas y contradices, puedes lograr a veces un triunfo; pero será un triunfo vacío porque jamás obtendrás la buena voluntad del contrincante."

Un mal entendimiento nunca se resuelve mediante una discusión sino mediante tacto, diplomacia, conciliación y un sincero deseo de apreciar el punto de vista de los demás.

PRINCIPIO 2: Demuestre respeto por las opiniones ajenas. Jamás diga a una persona que está equivocada

Nunca comiences diciendo: "Te voy a demostrar tal y tal cosa." Esto es como decir: "Soy más listo que tú."

Si vas a demostrar algo, que no lo sepa nadie. Hazlo sutilmente, con tal destreza que nadie piense que lo estás haciendo.

Cuando decimos a alguien que está equivocado, ¿lo convencemos de que acepte nuestro punto de vista? Jamás. Herimos su orgullo y nos resentirá.

PRINCIPIO 3: Si usted está equivocado, admítalo rápida y enfáticamente

Cuando sabemos que de todas formas se va a demostrar nuestro error, ¿no es mucho mejor ganar la delantera y reconocerlo uno mismo?

Di sobre ti mismo todas las cosas derogatorias que sabes que la otra persona está pensando, y dilo antes de que esa persona tenga oportunidad de formularlo.

No hay mayor satisfacción que la que se deriva del hecho de poder decir: "Me equivoqué."

PRINCIPIO 4: Empiece en forma amigable

"Una gota de miel caza más moscas que un galón de hiel."

Si vienes con nosotros con los puños cerrados, te puedo decir que nuestros puños se cerrarán más fuerte que los tuyos. Lincoln.

El sol puede hacerte quitarte el abrigo más rápido que el viento. La amabilidad, el toque amigable y el aprecio pueden hacer que las personas cambien de opinión más fácilmente que toda la furia del mundo.

PRINCIPIO 5: Consiga que la otra persona diga "sí, sí" inmediatamente

Cuando hables con alguien, comienza con las cosas en las que están de acuerdo.

El secreto socrático de obtener una respuesta afirmativa consiste en hacer preguntas que puedan responderse afirmativamente.

Cuantos más "síes" logremos obtener al principio, más probabilidades tendremos de conseguir que se capte nuestra proposición.

PRINCIPIO 6: Permita que la otra persona sea quien hable más

Deja que la otra persona hable. Ella sabe más sobre su negocio y sus problemas que tú. Así que hazle preguntas. Permite que te diga algunas cosas.

Aun nuestros amigos prefieren hablarnos de sus hazañas antes que escucharnos hablar de las nuestras.

Si no estás de acuerdo con alguien, puedes sentirte tentado a interrumpir. Pero no lo hagas. Es peligroso. No te prestará atención mientras tenga todavía ideas propias que necesitan expresión.

PRINCIPIO 7: Permita que la otra persona sienta que la idea es de ella

¿No sería más prudente hacer sugerencias y dejar que los demás lleguen a la conclusión?

Las personas apoyan las ideas que ellos mismos crean con mucho más entusiasmo que las que se les dan en bandeja de plata.

A la gente le gusta sentir que compra según su propia voluntad o sus propias ideas. A nadie le gusta sentir que le están vendiendo algo o diciéndole que haga algo.

PRINCIPIO 8: Trate honradamente de ver las cosas desde el punto de vista de la otra persona

Recuerda que la otra persona puede estar totalmente equivocada. Pero no piensa que lo está.

Cooperación en el diálogo se logra cuando demuestras que consideras las ideas y sentimientos de la otra persona tan importantes como los tuyos propios.

PRINCIPIO 9: Muestre simpatía por las ideas y deseos de la otra persona

Tres cuartas partes de las personas con quienes te encontrarás están hambrientas de simpatía. Dales esa simpatía y te amarán.

"Lamento mucho que se sienta así." Estas palabras mágicas ayudan a suavizar la situación más difícil.

PRINCIPIO 10: Apele a los motivos más nobles

Una persona usualmente tiene dos razones para hacer algo: una que parece buena y digna, y una razón real. La persona pensará en la razón real por sí misma. No necesitas enfatizarla. Pero todos somos idealistas en el fondo. Nos gusta pensar en motivos que parecen buenos.

PRINCIPIO 11: Dramatice sus ideas

Esto es la era del espectáculo. No basta con decir una verdad. Debe ser vívida, interesante, dramática. Las películas lo hacen. La televisión lo hace. Y tú también debes hacerlo si quieres atención.

PRINCIPIO 12: Lance, con tacto, un reto amable

El deseo de superarse, el deseo de sobresalir, el deseo de sentirse importante: ese es el camino que funciona con personas con espíritu.

