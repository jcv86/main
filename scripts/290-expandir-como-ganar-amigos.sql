Siempre es más fácil escuchar cosas desagradables después de haber oído algún elogio a nuestros puntos buenos.

PRINCIPIO 2: Llame la atención sobre los errores de los demás indirectamente

Muchas personas comienzan criticando y encuentran fallas, y luego terminan con un elogio. Charles Schwab hacía lo opuesto: comenzaba con elogio y terminaba llamando la atención al error indirectamente.

PRINCIPIO 3: Hable de sus propios errores antes de criticar los de los demás

No es tan difícil escuchar una lista de defectos si el que la critica comienza admitiendo humildemente que también está lejos de la perfección.

PRINCIPIO 4: Haga preguntas en vez de dar órdenes

Hacer preguntas no solamente hace que la orden sea más fácil de aceptar, sino que frecuentemente estimula la creatividad de las personas.

PRINCIPIO 5: Permita que la otra persona salve su propio prestigio

No tenemos nada que ganar hiriendo el ego de un hombre. Pero sí tenemos mucho que ganar si preservamos el orgullo de una persona.

PRINCIPIO 6: Elogie el más pequeño progreso y, además, cada progreso

Las capacidades se marchitan bajo la crítica; florecen bajo el estímulo.

El elogio es como la luz del sol al espíritu humano; no podemos florecer y crecer sin él.

