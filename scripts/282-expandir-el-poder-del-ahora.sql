## CAPÍTULO 1: NO ERES TU MENTE

El mayor obstáculo para iluminación es la identificación con tu mente, que causa que el pensamiento se vuelva compulsivo.

### La voz en tu cabeza

No ser capaz de detener el pensamiento es una terrible aflicción, pero no nos damos cuenta de ello porque casi todos sufren de él, así que se considera normal. Este ruido mental incesante te impide encontrar ese reino de quietud interna que es inseparable del Ser.

El pensamiento compulsivo también crea un falso ser hecho por la mente, el ego, que arroja una sombra de miedo y sufrimiento.

### La iluminación

La palabra iluminación evoca la idea de algún logro sobrehumano, y el ego le gusta mantenerse inalcanzable. Pero es simplemente tu estado natural de sentir unicidad con el Ser.

Es un estado de conexión con algo inmensurable e indestructible, algo que, casi paradójicamente, es esencialmente tú y sin embargo es mucho más grande que tú. Es encontrar tu verdadera naturaleza más allá del nombre y forma.

### Liberarse de tu mente

La identificación con tu mente crea una pantalla opaca de conceptos, etiquetas, imágenes, palabras, juicios y definiciones que bloquea toda verdadera relación.

Eso interfiere entre tú y tú mismo, entre tú y tu prójimo humano, entre tú y la naturaleza, entre tú y Dios. Es esta pantalla de pensamiento la que crea la ilusión de separación.

El inicio de la libertad es la realización de que no eres la entidad poseedora, el pensador. Saber esto te permite observar la entidad. El momento en que comienzas a observar al pensador, un nivel más alto de conciencia se activa.

### Emoción: la reacción del cuerpo a tu mente

La mente, en la forma en que estoy usando la palabra, no es solo pensamiento. Incluye tus emociones así como todos los patrones reactivos inconscientes mentales y emocionales.

Emoción surge en el punto donde mente y cuerpo se encuentran. Es la reacción del cuerpo a tu mente, o puedes decir, un reflejo de tu mente en el cuerpo.

Observa la emoción en tu cuerpo. Si no hay conflicto aparente entre ellos, mira más profundamente dentro de ti mismo, en tu cuerpo, y siente lo que hay. Es ese un profundo sentido de inquietud, un fondo continuo de incomodidad? Mira tus patrones de pensamiento y verás que tu mente está tan resistente como lo está la emoción.

