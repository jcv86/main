## CAPÍTULO 2: LA CONCIENCIA: LA SALIDA DEL DOLOR

No crees que tu infelicidad últimamente justifica tu malestar porque, después de todo, no la creaste tú mismo. Si pudieras mirar en tu inconsciente, encontrarías que el dolor está allí.

### El origen del miedo

Si fueras consciente del miedo continuo que vive dentro de ti, probablemente te sorprenderías. Solo porque no lo sientes no significa que no esté allí. Está tan familiarmente presente que difícilmente puedes reconocerlo.

El miedo psicológico no tiene nada que ver con la amenaza real de peligro inminente. Toma formas variadas: incomodidad, preocupación, ansiedad, nerviosismo, tensión, temor, fobia, y así sucesivamente.

El miedo psicológico siempre es de algo que podría pasar, no de algo que está pasando ahora. Estás en el aquí y ahora, mientras que tu mente está en el futuro. Esto crea una brecha de ansiedad.

### El cuerpo del dolor

El cuerpo del dolor es el dolor emocional acumulado del pasado que todavía vive en tu cuerpo y mente. Es una entidad semi-autónoma de energía que temporalmente toma control de ti.

Quiere sobrevivir y solo puede sobrevivir si te hace identificarte inconscientemente con él. Entonces puede elevarse, tomar control de ti, convertirse en ti, y vivir a través de ti.

Cuando el cuerpo del dolor toma control, quieres sufrir más. Te vuelves víctima o perpetrador. Quieres infligir dolor, o quieres sufrir dolor, o ambos. Realmente no hay mucha diferencia entre los dos.

### Romper la identificación con el cuerpo del dolor

El cuerpo del dolor no quiere que lo observes directamente y lo veas por lo que es. En el momento en que lo observas, sientes su campo de energía dentro de ti, y tomas tu atención a él, la identificación se rompe.

Una dimensión más alta de conciencia ha llegado. La llamo presencia. Ahora eres el observador o el testigo del cuerpo del dolor. Esto significa que no puede usarte más fingiendo ser tú, y ya no puede reponerse a través de ti.

