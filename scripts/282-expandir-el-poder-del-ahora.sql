## CAPÍTULO 6: EL CUERPO INTERNO

Antes de entrar en el cuerpo, quiero que mires al cuerpo desde afuera, por así decirlo, lo cual es todavía mirarlo desde el punto de vista limitado de la mente. Verás el cuerpo como una forma física.

### Ser es tu más profunda identidad

Ser es la vida eterna que está presente ahora, y es la única y constante cosa en toda la existencia temporal. No puedes entender el Ser, solo puedes ser eso.

El Ser es la vida sin tiempo, sin edad, sin forma, sin comienzo y sin fin que vive dentro de toda forma de vida temporal. El Ser puede entenderse como Dios.

### Mirando más allá de la forma

Nada existe por sí mismo. Cada forma de vida está conectada con todas las otras formas. Tu percepción de todas las cosas cambia cuando estás presente. Ves a través de la forma y reconoces que eres inseparable del todo.

