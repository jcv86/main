## CAPÍTULO 10: EL SIGNIFICADO DE LA RENDICIÓN

Rendirse es la transformación simple pero profunda de cómo sientes la vida. Aceptar incondicionalmente el momento presente.

### Aceptación y rendición

Aceptación de lo que es te libera inmediatamente de la identificación mental y así reconecta con el Ser. Resistencia es la mente. La rendición es un fenómeno puramente interno.

Rendirse no transforma lo que es, al menos no directamente. La rendición te transforma. Cuando eres transformado, tu mundo entero es transformado, porque el mundo es solo un reflejo.

### De la energía mental a la energía espiritual

A través de la rendición, la energía espiritual entra a este mundo. No crea sufrimiento para ti mismo ni para otros. No contamina la Tierra. No está sujeta a la ley de polaridades.

La energía que emana de ti es una emanación de tu estado de conciencia. El nivel de conciencia determina lo que clase de energía fluyará a través de ti.

