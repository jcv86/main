## PRÓLOGO: EL ORIGEN DE ESTE LIBRO

Hasta los treinta años de edad, viví en un estado de ansiedad casi continuo intercalado con períodos de depresión suicida. Ahora me parece que estaba viviendo con una pesada carga de ansiedad que no tenía causa aparente.

Una noche, no mucho después de mi vigésimo noveno cumpleaños, desperté en las tempranas horas con un sentimiento de miedo absoluto. El pensamiento que me atravesaba la mente era: No puedo vivir conmigo mismo más. Entonces, de repente, me volví consciente de lo peculiar que era ese pensamiento.

Si no puedo vivir conmigo mismo, debe haber dos de mí: el yo y el ser con el cual el yo no puede vivir. Tal vez solo uno de ellos es real.

Fui atraído a un vórtice de energía. De pronto, ya no había miedo, y me dejé caer en ese vacío. No recuerdo qué pasó después.

Desperté por el canto de un pájaro afuera de la ventana. Nunca había escuchado tal sonido antes. Mis ojos todavía estaban cerrados, y vi la imagen de un diamante precioso. Entonces me di cuenta de que aunque la imagen era preciosa, era aún menos que lo que yo ahora estaba sintiendo.

### El despertar

Me levanté y caminé por la habitación. Reconocí la habitación, y sin embargo sabía que nunca antes la había visto realmente. Todo era fresco y prístino, como si acabara de venir a la existencia. Tomé cosas, un lápiz, una botella vacía, maravillándome de la belleza y vitalidad de todo.

Ese día caminé por la ciudad en completo asombro ante el milagro de la vida en la Tierra, como si hubiera nacido apenas en este mundo.

Durante los siguientes cinco meses, viví en un estado de intensa alegría ininterrumpida. Después de eso, disminuyó un poco, pero ese sentimiento de profunda paz y vitalidad permanece conmigo desde entonces.

