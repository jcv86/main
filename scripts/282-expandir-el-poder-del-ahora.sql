## CAPÍTULO 3: MOVIÉNDOSE PROFUNDAMENTE EN EL AHORA

No busques volverte libre de deseo o lograr iluminación. Vuélvete presente. Sé allí como el observador de la mente, de tus pensamientos y emociones así como de tus reacciones en varias situaciones.

### El pasado no tiene poder sobre el presente

Todo lo que existe o pasa es el Ahora. Mientras el tiempo, la mente y el mundo de forma existan, el futuro aparecerá ofrecer mejoramiento, y el pasado puede parecer más satisfactorio que el presente.

Pero no te engañes. Solo el presente está a tu alcance. El pasado te da una identidad y el futuro sostiene la promesa de salvación, de realización en cualquier forma. Ambos son ilusiones.

Cuanto más te enfocas en el tiempo, pasado y futuro, más pierdes el Ahora, lo más precioso que hay. Porque es lo único que hay. Tu vida entera se desarrolla en este constante Ahora.

### Accediendo al poder del Ahora

Momento a momento, mantente absolutamente alerta, presente con lo que es. Los problemas de la mente necesitan tiempo para sobrevivir. No pueden sobrevivir en el Ahora.

En el Ahora, en la ausencia de tiempo, todos tus problemas se disuelven. El sufrimiento necesita tiempo, no puede sobrevivir en el Ahora.

Tu pasado te da una identidad, pero no es lo que eres. El futuro lleva promesa, pero solo puedes cambiar en el ahora. La verdadera liberación es realizarse a sí mismo más allá del tiempo.

### La mente y el momento presente

Como regla general, cuanto más compartido está tu estado consciente con el pasado o futuro, más espeso tu nivel de dolor. Si tienes dificultad en estar presente, está de más decir que tienes resistencia interna.

Observa cualquier hábito defensivo, de evitación que tengas. Observa tu mente. Observa qué busca. La búsqueda implica que estás en el modo futuro. No eres genuinamente presente.

