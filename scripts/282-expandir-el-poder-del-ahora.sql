## CAPÍTULO 9: MÁS ALLÁ DE LA FELICIDAD Y LA INFELICIDAD HAY PAZ

La felicidad que es dependiente de algo externo nunca puede durar porque todo externo es impermanente. La felicidad que es independiente de todo externo surge de tu ser interior.

### El bien más alto

El bien más alto que puede surgir de tu vida no es lo que obtienes de ella, sino lo que te conviertes a través de ella. Tu vida externa y tu vida interna están profundamente conectadas.

Lo que hagas no es tan importante como el estado de conciencia que traes a lo que haces.

### La paradoja del tiempo

El tiempo no es precioso en absoluto, porque es una ilusión. Lo que percibes como precioso no es el tiempo sino el único punto que está fuera del tiempo: el Ahora. Eso es realmente precioso.

Cuanto más te enfocas en el tiempo, más pierdes el Ahora, lo más precioso que hay.

