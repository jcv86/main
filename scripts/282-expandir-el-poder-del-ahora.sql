## CAPÍTULO 4: ESTRATEGIAS MENTALES PARA EVITAR EL AHORA

El enfoque en el futuro, que es un aspecto del ego, es una parte integral de cómo vive la mayoría de las personas.

### La pérdida del ahora: la ilusión central

El ego cree que tu fuerza está en el pasado y que sin el pasado no eres nada. El ego usa el tiempo de esta manera: tu pasado te da una identidad, y el futuro sostiene la promesa de salvación.

La verdad es que tú no eres tu pasado. El pasado no puede sobrevivir en tu presencia. El momento en que te haces consciente del momento presente, el pasado pierde poder sobre ti.

### Enfermedad ordinaria inconsciente y profunda inconciencia

El modo egoico es un estado disfuncional de conciencia. Cuando miras atrás en tu vida, ves que pasaste la mayor parte de ella en tres estados de ser: inconciencia ordinaria, inconciencia profunda, o presencia.

La inconciencia ordinaria significa ser identificado con tus procesos de pensamiento y emociones, tu pasado, tu narrativa. La inconciencia profunda significa ser más fuertemente identificado con el dolor corporal y emociones negativas.

### El significado más profundo de rendición

Rendirse es aceptación interior de lo que es sin ninguna reserva. Estamos hablando de tu vida, este momento, donde sea que estés.

Si no puedes aceptar lo que es fuera, entonces acepta lo que es dentro. Si no puedes traer aceptación a lo que está pasando, entonces trae aceptación al hecho de que no puedes. Eso es rendirse.

