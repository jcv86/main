## CAPÍTULO 7: PORTALES HACIA LO NO MANIFESTADO

Hay portales en tu vida a través de los cuales puedes acceder a lo No Manifestado. Cada portal es un momento de presencia intensa, de total y absoluta presencia.

### El silencio

No hay nada que puedas hacer acerca de lo No Manifestado. No puedes entenderlo. No puedes saber nada acerca de él. Pero puedes ser consciente de eso. Puedes sentirlo profundamente dentro de ti como tu propia esencia más íntima, inseparable de quien eres.

El silencio es el lenguaje de Dios, todo lo demás es pobre traducción. Cuando eres capaz de aprender a escuchar más allá del ruido de tu mente, surge un vasto reino de inteligencia.

### El espacio

La mayoría de las personas están tan completamente identificadas con la dimensión del tiempo, con la interminable sucesión de pasado y futuro, que el Ahora apenas se registra en su conciencia.

Presta atención al silencio. Cuando escuchas a alguien hablar, no solo escuches las palabras, escucha el silencio entre las palabras. Cuando miras a un objeto, nota el espacio que lo rodea.

