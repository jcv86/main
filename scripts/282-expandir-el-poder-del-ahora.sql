## CAPÍTULO 8: RELACIONES ILUMINADAS

Las relaciones íntimas pueden ser el lugar más intenso para practicar presencia y desarraigarte de patrones mentales y emocionales.

### El amor y el odio

A menos que y hasta que accedas a la conciencia más allá de la forma, el amor y el odio son dos caras de la misma moneda. Ambos son emociones que surgen del ego.

El verdadero amor no tiene opuesto. Es un estado de ser que no deriva de tu ego. Emana desde más allá de la mente, desde la profundidad de tu Ser.

### Las relaciones como práctica espiritual

Si no logras estar en paz contigo mismo, la búsqueda de una relación para salvarte solo llevará a más dolor. Cualquier problema externo refleja tu propio estado interno de conciencia.

Cuando la base de tu relación es estar presente en lugar de necesidad psicológica, tu relación se vuelve una ofrenda, no una exigencia.

