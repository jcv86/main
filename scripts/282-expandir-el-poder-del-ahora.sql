## CAPÍTULO 5: EL ESTADO DE PRESENCIA

En el estado de presencia, tu conciencia ya no está totalmente absorbida por el pensamiento, típicamente por el incesante flujo de pensamientos compulsivos.

### No es lo que haces sino cómo lo haces

No es tanto lo que haces sino la calidad de conciencia que traes a lo que haces que determina si vas a cosechar sufrimiento o alegría.

La acción que surge de la comprensión de la vida no producirá sufrimiento. Tu tarea no es buscar el amor sino simplemente buscar y encontrar todas las barreras dentro de ti mismo que has construido contra él.

### El propósito interno y externo

El propósito externo es lo que haces. El propósito interno tiene que ver con tu estado de conciencia. Ambos están inseparablemente conectados.

Tu propósito externo puede cambiar con el tiempo, pero tu propósito interno no cambia nunca. Tu propósito interno es despertar. Es tan simple como eso. Compartirlo con los demás. Despertarlos a su propósito interno.

