## CAPÍTULO 6: RELACIONES: MENTALIDADES EN AMOR

### Mentalidad Fija en Relaciones

**Creencias:**
- "Si me ama, sabrá lo que necesito"
- "Los problemas significan que no somos compatibles"
- "Las relaciones deberían ser fáciles"
- "Mi pareja debería ser perfecta"

**Consecuencias:**
- No comunica necesidades
- Evita conflictos o se rinde ante ellos
- Culpa a la pareja
- Relaciones frágiles

### Mentalidad de Crecimiento en Relaciones

**Creencias:**
- "Debo comunicar mis necesidades"
- "Los problemas son oportunidades de crecer juntos"
- "Las relaciones requieren trabajo"
- "Ambos podemos crecer y mejorar"

**Consecuencias:**
- Comunicación abierta
- Enfrenta conflictos constructivamente
- Trabaja en la relación
- Relaciones resilientes

### Timidez

**Mentalidad Fija:**
"Soy tímido, así soy"

**Mentalidad de Crecimiento:**
"Puedo desarrollar habilidades sociales"

**Resultado:**
Mentalidad de crecimiento lleva a superar timidez con práctica.

