## CAPÍTULO 7: PADRES, MAESTROS Y ENTRENADORES

### Mensajes que Crean Mentalidades

**Mentalidad Fija:**
- "Eres muy inteligente"
- "Tienes talento natural"
- "Eres un genio"

**Mentalidad de Crecimiento:**
- "Trabajaste muy duro"
- "Usaste buenas estrategias"
- "Persististe y lo lograste"

**Estudio:**
Elogiar inteligencia → Mentalidad fija → Peor desempeño
Elogiar esfuerzo → Mentalidad de crecimiento → Mejor desempeño

### Cómo Elogiar

**Mal:**
- "Eres tan inteligente"
- "Eres un artista natural"
- "Tienes talento"

**Bien:**
- "Me gusta cómo trabajaste en eso"
- "Usaste estrategias efectivas"
- "Tu práctica está dando frutos"
- "Aprendiste de tus errores"

### Responder al Fracaso

**Mentalidad Fija:**
- "Está bien, no todos son buenos en matemáticas"
- "Tal vez esto no es para ti"

**Mentalidad de Crecimiento:**
- "¿Qué estrategias probaste?"
- "¿Qué puedes aprender de esto?"
- "Intentemos un enfoque diferente"
- "El esfuerzo y la estrategia te llevarán allí"

