## CAPÍTULO 3: LA VERDAD SOBRE HABILIDAD Y LOGRO

### Mentalidad y Rendimiento Escolar

**Estudio Longitudinal:**

Seguimiento de estudiantes desde 7mo grado:
- Inicio: Habilidades similares
- Mentalidad fija: Calificaciones declinaron
- Mentalidad de crecimiento: Calificaciones mejoraron

**Por qué:**
Cuando el trabajo se vuelve difícil:
- Mentalidad fija: "No soy bueno para esto" → Se rinde
- Mentalidad de crecimiento: "Necesito esforzarme más" → Persiste

### Mentalidad en Deportes

