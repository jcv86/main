## CAPÍTULO 8: CAMBIANDO MENTALIDADES

### Todos Tenemos Ambas Mentalidades

**Realidad:**
No es blanco o negro. Todos tenemos áreas con mentalidad fija y áreas con mentalidad de crecimiento.

**Ejemplos:**
- Mentalidad de crecimiento en trabajo, fija en relaciones
- Mentalidad de crecimiento en deportes, fija en arte

### Identificar tu Mentalidad Fija

**Preguntas:**
1. ¿En qué áreas evito desafíos?
2. ¿Dónde me rindo fácilmente?
3. ¿Cuándo veo el esfuerzo como inútil?
4. ¿Dónde ignoro retroalimentación?
5. ¿Cuándo me siento amenazado por el éxito de otros?

### El Camino al Cambio

**Paso 1: Aceptar**
Reconoce que tienes mentalidad fija en algunas áreas.

**Paso 2: Observar**
Nota cuándo tu mentalidad fija se activa.

**Paso 3: Nombrar**
Dale un nombre a tu mentalidad fija. "Ahí está mi voz de mentalidad fija."

**Paso 4: Educar**
Recuerda que puedes desarrollar habilidades con esfuerzo.

**Paso 5: Actuar**
Toma acción desde mentalidad de crecimiento.

### Ejercicio de Cambio

**Situación:** Enfrentas un desafío difícil.

**Voz de Mentalidad Fija:**
"Esto es muy difícil. Probablemente no puedo hacerlo. ¿Para qué intentar?"

**Respuesta de Mentalidad de Crecimiento:**
"Esto es difícil, pero puedo aprender. ¿Qué estrategias puedo probar? ¿Quién puede ayudarme? El esfuerzo me hará crecer."

**Acción:**
Divide el desafío en pasos pequeños. Comienza con el primero.

