## CAPÍTULO 5: NEGOCIOS: MENTALIDAD Y LIDERAZGO

### Líderes con Mentalidad Fija

**Características:**
- Necesitan ser la estrella
- Toman todo el crédito
- Culpan a otros por fracasos
- Rodean de "yes-men"
- Evitan retroalimentación

**Ejemplos:**
- Lee Iacocca (Chrysler): Éxito inicial, luego declive
- Albert Dunlap: Despidos masivos, sin desarrollo

**Resultado:** Éxito a corto plazo, fracaso a largo plazo.

### Líderes con Mentalidad de Crecimiento

**Características:**
- Desarrollan a otros
- Comparten crédito
- Aprenden de fracasos
- Buscan retroalimentación
- Construyen equipos fuertes

**Ejemplos:**
- Lou Gerstner (IBM): Transformó cultura
- Anne Mulcahy (Xerox): Salvó empresa escuchando

**Resultado:** Éxito sostenible, organizaciones que perduran.

### Groupthink y Mentalidad

**Mentalidad Fija → Groupthink:**
- Nadie cuestiona líder
- Evitan conflicto
- No admiten errores
- Resultado: Malas decisiones

**Mentalidad de Crecimiento → Pensamiento Crítico:**
- Cuestionan ideas
- Debate saludable
- Admiten errores rápido
- Resultado: Mejores decisiones

