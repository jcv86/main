## CAPÍTULO 4: DEPORTES: LA MENTALIDAD DEL CAMPEÓN

### Talento Natural vs Desarrollo

**Mito:** Los campeones nacen con talento natural.

**Realidad:** Los campeones se hacen con práctica deliberada.

**Estudio de 10,000 Horas:**
Excelencia en cualquier campo requiere ~10,000 horas de práctica deliberada.

**Práctica Deliberada:**
- Enfocada en mejorar debilidades
- Fuera de zona de confort
- Con retroalimentación
- Repetición intencional

### Carácter

**Mentalidad Fija:**
Carácter es fijo. "Así soy yo."

**Mentalidad de Crecimiento:**
Carácter puede desarrollarse.

**Ejemplo - Muhammad Ali:**
- Inicialmente tímido y miedoso
- Trabajó en confianza y coraje
- Se convirtió en "El Más Grande"

### Qué es el Éxito

**Mentalidad Fija:**
Éxito = Ganar, ser el mejor

**Mentalidad de Crecimiento:**
Éxito = Dar tu mejor esfuerzo, mejorar

**Resultado:**
Mentalidad de crecimiento lleva a más victorias porque el enfoque está en mejorar, no en probar algo.

