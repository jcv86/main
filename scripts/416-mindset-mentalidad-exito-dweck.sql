## CAPÍTULO 2: DENTRO DE LAS MENTALIDADES

### ¿Éxito o Aprendizaje?

**Mentalidad Fija:**
Éxito = Validar que eres inteligente/talentoso
Fracaso = Prueba de que no eres inteligente/talentoso

**Mentalidad de Crecimiento:**
Éxito = Aprender y mejorar
Fracaso = Oportunidad de aprender

**Experimento:**

Niños resuelven rompecabezas:
- Grupo 1: "Eres muy inteligente" (mentalidad fija)
- Grupo 2: "Trabajaste muy duro" (mentalidad de crecimiento)

Luego se les ofrece:
- Rompecabezas fácil (éxito garantizado)
- Rompecabezas difícil (aprenderán mucho)

**Resultados:**
- Grupo 1 (mentalidad fija): 67% eligió fácil
- Grupo 2 (mentalidad de crecimiento): 92% eligió difícil

### El Esfuerzo

**Mentalidad Fija:**
"Si necesito esforzarme, significa que no soy inteligente"

**Mentalidad de Crecimiento:**
"El esfuerzo es lo que me hace inteligente"

**Realidad:**
Todos los grandes logros requieren esfuerzo sostenido.

**Ejemplos:**
- Mozart: Practicó intensamente desde los 4 años
- Michael Jordan: Cortado del equipo de secundaria, practicó incansablemente
- Darwin: Trabajó 20+ años en teoría de evolución

