## OBSTÁCULOS COMUNES

### "Pero es su culpa"

**Trampa:** Culpar a otros por nuestros sentimientos

**Verdad:** Otros pueden ser el estímulo, pero nuestras necesidades son la causa de nuestros sentimientos.

**Cambio:**
- De: "Me haces enojar"
- A: "Me siento enojado porque necesito respeto"

### "Suena artificial"

**Realidad:** Al principio, sí. Como cualquier habilidad nueva.

**Solución:** Practica hasta que se vuelva natural. No necesitas usar la fórmula exacta cada vez.

### "¿Y si no cambian?"

**Verdad:** CNV no garantiza que otros cambien.

**Beneficio:** Te conecta con tus necesidades y te empodera para cuidarlas, independientemente de la respuesta de otros.

