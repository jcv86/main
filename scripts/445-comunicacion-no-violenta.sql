## EXPRESAR ENOJO PLENAMENTE

### El Enojo es una Señal

**Verdad:** El enojo indica que estamos pensando de manera que nos desconecta de nuestras necesidades.

**Proceso:**

1. **Para y respira**
2. **Identifica pensamientos de juicio**
   - "Es un idiota"
   - "No tiene derecho"
   - "Debería saber mejor"
3. **Conecta con necesidades insatisfechas**
   - ¿Qué necesito que no estoy recibiendo?
4. **Expresa necesidades**

**Ejemplo:**

**Situación:** Tu colega tomó crédito por tu idea

**Pensamiento de juicio:** "Es un ladrón sin ética"

**Necesidad:** Reconocimiento, integridad, justicia

**Expresión CNV:**
"Cuando escuché que presentaste mi idea como tuya, me sentí dolido porque necesito reconocimiento por mi trabajo y confianza en nuestro equipo. ¿Estarías dispuesto a aclarar en la próxima reunión que la idea fue mía?"

