## EXPRESAR APRECIO

### Aprecio vs Elogio

**Elogio:** "Eres increíble"
**Aprecio CNV:** Específico sobre acciones, sentimientos y necesidades satisfechas

**Fórmula de aprecio:**

"Cuando hiciste [ACCIÓN], me sentí [SENTIMIENTO] porque satisfizo mi necesidad de [NECESIDAD]."

**Ejemplos:**

❌ "Buen trabajo"
✅ "Cuando terminaste el reporte antes del plazo, me sentí aliviado porque satisfizo mi necesidad de confiabilidad y me permitió presentar con confianza."

❌ "Eres un buen amigo"
✅ "Cuando me escuchaste ayer sin juzgar, me sentí apoyado porque satisfizo mi necesidad de ser comprendido y aceptado."

