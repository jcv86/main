## INTRODUCCIÓN

La Comunicación No Violenta (CNV) es un proceso de comunicación que nos ayuda a conectar con nosotros mismos y con otros de manera compasiva y efectiva.

**Objetivo:** Expresar honestamente y recibir empáticamente.

**Resultado:** Relaciones más profundas y resolución pacífica de conflictos.

---

## LOS 4 COMPONENTES DE LA CNV

### 1. OBSERVACIONES (sin evaluación)

**Qué es:** Describir lo que vemos u oímos sin mezclar evaluación.

**Diferencia clave:**

❌ **Evaluación:** "Eres irresponsable"
✅ **Observación:** "No llegaste a las últimas tres reuniones"

❌ **Evaluación:** "Nunca me escuchas"
✅ **Observación:** "Cuando te hablé, estabas mirando tu teléfono"

❌ **Evaluación:** "Eres egoísta"
✅ **Observación:** "Tomaste la última porción sin preguntar"

**Por qué importa:** Las evaluaciones provocan defensividad. Las observaciones invitan al diálogo.

### 2. SENTIMIENTOS (no pensamientos)

**Qué es:** Expresar cómo nos sentimos en relación a lo que observamos.

**Diferencia clave:**

❌ **Pensamiento disfrazado:** "Siento que me ignoras"
✅ **Sentimiento:** "Me siento triste"

❌ **Pensamiento:** "Siento que no te importo"
✅ **Sentimiento:** "Me siento solo"

**Vocabulario de sentimientos:**

**Cuando necesidades están satisfechas:**
- Alegre, agradecido, esperanzado, inspirado, tranquilo, confiado, entusiasmado

**Cuando necesidades NO están satisfechas:**
- Triste, frustrado, asustado, confundido, preocupado, decepcionado, enojado

### 3. NECESIDADES (universales)

**Qué es:** Identificar las necesidades, valores o deseos que crean nuestros sentimientos.

**Verdad:** Todos los sentimientos surgen de necesidades satisfechas o insatisfechas.

**Necesidades universales:**

- **Autonomía:** Elegir sueños, metas, valores
- **Celebración:** Celebrar logros y pérdidas
- **Integridad:** Autenticidad, creatividad, significado
- **Interdependencia:** Aceptación, aprecio, cercanía, comunidad
- **Juego:** Diversión, risa
- **Comunión espiritual:** Belleza, armonía, inspiración, orden, paz
- **Necesidades físicas:** Aire, comida, descanso, agua, refugio

**Ejemplo:**

"Me siento frustrado [sentimiento] porque necesito claridad [necesidad] sobre las expectativas del proyecto."

### 4. PETICIONES (no demandas)

**Qué es:** Pedir claramente lo que queremos sin exigir.

**Diferencia clave:**

❌ **Demanda:** "Tienes que llegar a tiempo"
✅ **Petición:** "¿Estarías dispuesto a llegar a las 9am?"

**Características de peticiones efectivas:**

1. **Positivas:** Di lo que quieres, no lo que no quieres
   - ❌ "Deja de interrumpirme"
   - ✅ "¿Podrías esperar a que termine antes de hablar?"

2. **Específicas:** Acciones concretas
   - ❌ "Sé más considerado"
   - ✅ "¿Podrías avisarme con anticipación si vas a retrasarte?"

3. **Factibles:** Algo que pueden hacer ahora
   - ❌ "Nunca más me mientas"
   - ✅ "¿Podrías decirme qué pasó realmente?"

4. **Verificables:** Puedes confirmar si se cumplió
   - ❌ "Entiéndeme mejor"
   - ✅ "¿Podrías decirme qué escuchaste que dije?"

