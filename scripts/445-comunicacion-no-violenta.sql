## LA FÓRMULA CNV

**Estructura básica:**

"Cuando veo/escucho [OBSERVACIÓN], me siento [SENTIMIENTO] porque necesito [NECESIDAD]. ¿Estarías dispuesto a [PETICIÓN]?"

**Ejemplos:**

**Situación 1: Con pareja**
"Cuando veo los platos sucios en el fregadero por tercer día, me siento frustrado porque necesito orden y cooperación en nuestro hogar. ¿Estarías dispuesto a lavar tus platos después de usarlos?"

**Situación 2: En el trabajo**
"Cuando llegaste 20 minutos tarde a nuestra reunión, me sentí preocupado porque necesito confiabilidad para cumplir nuestros plazos. ¿Podrías avisarme con anticipación si vas a retrasarte?"

**Situación 3: Con hijo**
"Cuando escucho música alta a las 11pm, me siento cansado porque necesito descanso para trabajar mañana. ¿Podrías usar audífonos después de las 10pm?"

