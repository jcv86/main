## RECIBIR EMPÁTICAMENTE

### Escucha con Empatía

**Qué es:** Conectar con los sentimientos y necesidades detrás de las palabras de otros.

**Cómo:**

1. **Presencia:** Pon atención completa
2. **Parafrasea:** Refleja lo que escuchaste
3. **Adivina sentimientos:** "¿Te sientes...?"
4. **Adivina necesidades:** "¿Porque necesitas...?"

**Ejemplo:**

**Ellos:** "¡Nunca me ayudas con nada! ¡Siempre estás ocupado con tu trabajo!"

**Respuesta empática:**
"¿Te sientes frustrado porque necesitas más apoyo y conexión conmigo?"

**No empático:**
"Eso no es cierto, la semana pasada te ayudé con..."

### Los Cuatro Enemigos de la Empatía

**1. Aconsejar**
"Deberías hacer..."

**2. Competir**
"Eso no es nada, yo..."

**3. Educar**
"Esto podría ser una experiencia positiva si..."

**4. Consolar**
"No fue tu culpa, hiciste lo mejor que pudiste"

**En lugar de eso:** Simplemente refleja sentimientos y necesidades.

