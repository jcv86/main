## APLICACIONES PRÁCTICAS

### Con Niños

**Situación:** Niño no hace tarea

**Respuesta típica:**
"¡Eres tan flojo! ¡Haz tu tarea ahora!"

**Respuesta CNV:**
"Cuando veo que no has empezado tu tarea y es casi hora de dormir, me siento preocupado porque necesito que desarrolles hábitos de responsabilidad. ¿Qué te impide empezar? ¿Cómo puedo ayudar?"

### En el Trabajo

**Situación:** Jefe da feedback negativo

**Respuesta típica (interna):**
"Es un idiota que no aprecia mi trabajo"

**Respuesta CNV:**
"Cuando escucho que mi trabajo no cumplió expectativas, me siento decepcionado. ¿Podrías ayudarme a entender específicamente qué necesitas que sea diferente?"

### Con Pareja

**Situación:** Pareja llega tarde frecuentemente

**Respuesta típica:**
"¡Nunca llegas a tiempo! ¡No te importo!"

**Respuesta CNV:**
"Cuando llegas 30 minutos tarde sin avisar, me siento ansioso porque necesito consideración y poder planear mi tiempo. ¿Estarías dispuesto a enviarme un mensaje si vas a retrasarte más de 10 minutos?"

