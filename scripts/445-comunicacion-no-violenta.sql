## PLAN DE ACCIÓN: 30 DÍAS

### Semana 1: Observaciones

**Día 1-3:**
- Nota cuándo mezclas observación con evaluación
- Practica separar hechos de juicios
- Escribe 5 observaciones puras diarias

**Día 4-7:**
- En conversaciones, usa solo observaciones
- Nota cómo reduce defensividad
- Practica con situaciones de bajo riesgo

### Semana 2: Sentimientos y Necesidades

**Día 8-10:**
- Identifica tus sentimientos durante el día
- Usa vocabulario de sentimientos
- Conecta cada sentimiento con una necesidad

**Día 11-14:**
- Practica expresar sentimientos y necesidades
- "Me siento [sentimiento] porque necesito [necesidad]"
- Hazlo primero contigo mismo, luego con otros

### Semana 3: Peticiones

**Día 15-17:**
- Identifica tus demandas habituales
- Conviértelas en peticiones
- Hazlas positivas, específicas, factibles

**Día 18-21:**
- Usa fórmula CNV completa en conversación de bajo riesgo
- Observa reacciones
- Ajusta según necesidad

### Semana 4: Empatía

**Día 22-25:**
- Practica escucha empática
- Adivina sentimientos y necesidades de otros
- Evita los 4 enemigos de la empatía

**Día 26-30:**
- Aplica CNV en situación desafiante
- Usa tanto expresión como empatía
- Reflexiona sobre el proceso

