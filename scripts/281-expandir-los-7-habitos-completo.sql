## HÁBITO 1: SEA PROACTIVO

Entre estímulo y respuesta, el hombre tiene la libertad de elegir. Este es el hábito de la responsabilidad personal.

### La libertad de elegir

Viktor Frankl, prisionero en un campo de concentración nazi, descubrió una libertad fundamental: la libertad de elegir la actitud en cualquier conjunto de circunstancias, de elegir el propio camino.

Entre lo que nos sucede y nuestra respuesta hay un espacio. En ese espacio reside nuestra libertad y poder de elegir nuestra respuesta. En nuestra respuesta está nuestro crecimiento y libertad.

### Personas reactivas vs proactivas

Las personas reactivas están afectadas por sus condiciones físicas, su entorno. Si hace buen tiempo, se sienten bien. Si no, afecta sus actitudes y su conducta.

Las personas proactivas también están influenciadas por estímulos externos, ya sean físicos, sociales o psicológicos. Pero su respuesta es un valor, y tienen la libertad de elegir esa respuesta.

La habilidad para subordinar un impulso a un valor es la esencia de la persona proactiva. Las personas reactivas están impulsadas por sentimientos, circunstancias, condiciones y su ambiente. Las personas proactivas están impulsadas por valores.

### El círculo de influencia y preocupación

Podemos clasificar nuestras preocupaciones en dos círculos: el círculo de preocupación y el círculo de influencia.

Las personas proactivas enfocan sus esfuerzos en el círculo de influencia. Trabajan en las cosas sobre las que pueden hacer algo. Su energía es positiva, expandiendo y magnificando, causando que su círculo de influencia crezca.

Las personas reactivas enfocan sus esfuerzos en el círculo de preocupación. Se enfocan en la debilidad de otras personas, los problemas en el ambiente y circunstancias sobre las cuales no tienen control.

### Lenguaje reactivo vs proactivo

Lenguaje reactivo:
- No hay nada que pueda hacer
- Así soy yo
- Me vuelve loco
- No lo permitirán
- Tengo que hacer eso
- No puedo

Lenguaje proactivo:
- Examinemos nuestras alternativas
- Puedo elegir un enfoque diferente
- Controlo mis propios sentimientos
- Puedo crear una presentación efectiva
- Elegiré una respuesta apropiada
- Elijo

