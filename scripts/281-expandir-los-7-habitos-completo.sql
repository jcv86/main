## HÁBITO 5: PROCURE PRIMERO COMPRENDER Y DESPUÉS SER COMPRENDIDO

Este principio es la clave para la comunicación interpersonal efectiva.

### Escuchar con empatía

La mayoría de las personas no escuchan con la intención de comprender, escuchan con la intención de responder. Están hablando o preparándose para hablar.

Hay varios niveles de escucha:

1. Ignorar: No escuchar realmente
2. Fingir escuchar: Hacer ruidos ocasionales
3. Escuchar selectivamente: Solo ciertas partes
4. Escuchar atentamente: Prestar atención y enfocar energía
5. Escuchar empáticamente: Escuchar con la intención de comprender

Escuchar empáticamente es entrar en el marco de referencia de la otra persona. Es ver las cosas a través de ese marco, ver el mundo como ellos lo ven, comprender su paradigma, sentir cómo se sienten.

### Diagnóstico antes de prescripción

Imagina ir al doctor y él te dice, sin examinarte: Tengo un par de anteojos que funcionaron maravillosamente para mí durante años. Tómalos, te ayudarán.

Eso sería una locura. Pero eso es exactamente lo que hacemos en la comunicación cuando aconsejamos antes de diagnosticar, cuando no nos tomamos el tiempo para comprender profundamente el problema primero.

### Los cuatro respuestas autobiográficas

Tendemos a responder de una de cuatro maneras:

1. Evaluamos: Estamos de acuerdo o en desacuerdo
2. Sondeamos: Hacemos preguntas desde nuestro propio marco de referencia
3. Aconsejamos: Damos consejos basados en nuestra propia experiencia
4. Interpretamos: Tratamos de descifrar a alguien, explicar sus motivos

