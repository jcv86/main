## HÁBITO 6: SINERGICE

Sinergia significa que el todo es más que la suma de sus partes. Significa que la relación de las partes entre sí es una parte en y por sí misma, no solo las partes, sino la más catalizadora, más empoderadora, más unificadora, y más excitante parte.

### El poder de la sinergia

La esencia de la sinergia es valorar las diferencias. No solo tolerarlas o aceptarlas, sino celebrarlas.

Cuando las personas comienzan a interactuar juntas genuinamente, y están abiertas a la influencia de cada uno, comienzan a ganar nueva perspectiva. El diálogo produce perspectivas que ninguno de ellos había visto antes. Se vuelven excitados, creativos.

### Comunicación sinérgica

La comunicación sinérgica significa abrir tu mente, corazón y expresiones a nuevas posibilidades, nuevas alternativas, nuevas opciones.

Puede que no esté de acuerdo con tu punto de vista, pero cuando te escucho comprendo tu perspectiva. Ahora tengo una mejor comprensión del cuadro completo. Podemos crear una tercera alternativa mejor que cualquiera de nuestras propias ideas.

### Valorar las diferencias

La persona verdaderamente efectiva tiene la humildad y reverencia para reconocer sus propias limitaciones perceptuales y para apreciar los ricos recursos disponibles a través de la interacción con los corazones y mentes de otros seres humanos.

Esa persona valora las diferencias porque esas diferencias añaden a su conocimiento, a su comprensión de la realidad. Cuando nos volvemos conscientes de que no vemos el mundo como es, sino como somos, abrimos la puerta a la influencia real de otros.

