## HÁBITO 7: AFILE LA SIERRA

Este hábito preserva y mejora el mayor activo que tienes: tú mismo. Renueva las cuatro dimensiones de tu naturaleza: física, espiritual, mental y social-emocional.

### Dimensión física

La dimensión física involucra cuidar efectivamente de nuestro cuerpo físico: comer el tipo correcto de alimentos, descansar lo suficiente y hacer ejercicio regular.

El ejercicio es una actividad del Cuadrante II que no tenemos que hacer, pero que sabemos que necesitamos hacer porque tiene un tremendo impacto positivo en nosotros.

Un buen programa de ejercicio debe trabajar en tres áreas: resistencia, flexibilidad y fuerza.

### Dimensión espiritual

La dimensión espiritual proporciona liderazgo a tu vida. Está altamente relacionada al Hábito 2.

La dimensión espiritual es tu núcleo, tu centro, tu compromiso con tu sistema de valores. Es un área muy privada de la vida y una supremamente importante.

La renovación espiritual toma un compromiso de practicar. Y práctica requiere disciplina y paciencia.

### Dimensión mental

La mayoría de nuestro desarrollo mental viene de educación formal. Pero tan pronto como salimos de la disciplina externa de la escuela, muchos de nosotros dejamos que nuestras mentes se atrofien.

Leer ampliamente expone tu mente a otros grandes mentes. Ese es un ejercicio constante y continuo del músculo mental privado.

Escribir es otra poderosa manera de afinar nuestros procesos mentales. Mantener un diario personal o escribir cartas extensas estimula nuestro pensamiento.

### Dimensión social-emocional

La dimensión social y emocional se enfoca en los Hábitos 4, 5 y 6. Se centra en liderazgo de principios, comunicación empática y cooperación creativa.

La renovación en la dimensión social-emocional no toma tiempo en el mismo sentido que las otras dimensiones. Podemos hacerlo en nuestras interacciones normales con otras personas.

Pero ciertamente requiere ejercicio. Puede que tengamos que ir contra las tendencias naturales para poder lograr esta renovación.

