## HÁBITO 3: PONGA PRIMERO LO PRIMERO

Este hábito es la realización física, la creación segunda. Es el ejercicio de la voluntad independiente hacia ser dirigido por principios.

### La matriz de administración del tiempo

Hay cuatro generaciones de administración del tiempo:

Primera generación: Notas y listas de tareas
Segunda generación: Calendarios y agendas
Tercera generación: Priorización y planificación diaria
Cuarta generación: Enfocada en preservar y mejorar relaciones y lograr resultados

Las actividades se organizan en cuatro cuadrantes:

Cuadrante I: Urgente e Importante (Crisis, problemas apremiantes, proyectos con fechas límite)
Cuadrante II: No urgente e Importante (Prevención, construcción de relaciones, planificación, recreación)
Cuadrante III: Urgente y No importante (Interrupciones, algunas llamadas, correo, reportes)
Cuadrante IV: No urgente y No importante (Trivialidades, pérdidas de tiempo, actividades placenteras)

### El Cuadrante II

Las personas efectivas permanecen fuera de los Cuadrantes III y IV porque, urgentes o no, no son importantes. También reducen el Cuadrante I pasando más tiempo en el Cuadrante II.

El Cuadrante II es el corazón de la administración personal efectiva. Trata con cosas que no son urgentes, pero sí importantes. Trata con cosas como construir relaciones, escribir un enunciado de misión personal, planificación de largo alcance, ejercicio, preparación preventiva.

### Delegación

La delegación efectiva es quizás la mejor indicación de administración efectiva simplemente porque es muy básica tanto a la producción personal como a la organizacional.

Hay dos tipos de delegación: delegación de recadero y delegación de administración.

La delegación de recadero significa ir allí, hacer esto, hacer aquello, dime cuándo está hecho.
La delegación de administración se enfoca en resultados en lugar de métodos. Da a las personas una elección de método y las hace responsables de resultados.

