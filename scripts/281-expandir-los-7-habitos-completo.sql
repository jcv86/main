## HÁBITO 4: PIENSE GANAR-GANAR

Ganar-ganar es un marco mental y corazón que constantemente busca el beneficio mutuo en todas las interacciones humanas. Ganar-ganar significa que los acuerdos o soluciones son mutuamente beneficiosos, mutuamente satisfactorios.

### Los seis paradigmas de interacción humana

1. Ganar-Ganar: Ambas partes consiguen lo que quieren
2. Gano-Pierdes: Si gano yo, pierdes tú
3. Pierdo-Ganas: Permito que otros se aprovechen
4. Pierdo-Pierdes: Ambos perdemos
5. Gano: Me enfoco solo en conseguir lo que quiero
6. Ganar-Ganar o No Hay Trato: Si no podemos encontrar una solución que beneficie a ambos, acordamos no hacer trato

### Los cinco elementos de ganar-ganar

1. Carácter: Integridad, madurez y mentalidad de abundancia
2. Relaciones: De carácter fluyen las relaciones de confianza
3. Acuerdos: De las relaciones fluyen los acuerdos que dan definición y dirección
4. Sistemas: Los sistemas de la organización deben soportar ganar-ganar
5. Procesos: El proceso de cuatro pasos para alcanzar soluciones ganar-ganar

### La mentalidad de abundancia

La mayoría de las personas están profundamente programadas con el paradigma de escasez. Ven la vida como si tuviera solo un gran pastel. Si alguien obtiene un pedazo grande del pastel, eso significa menos para todos los demás.

Las personas con mentalidad de escasez tienen dificultad muy real siendo genuinamente felices por el éxito de otras personas, incluso de miembros de la familia o amigos cercanos.

La mentalidad de abundancia fluye de un profundo sentido interno de valor personal y seguridad. Es el paradigma de que hay mucho allá afuera para todos.

