## INTRODUCCIÓN: DE ADENTRO HACIA AFUERA

Hace más de 25 años, emprendí mi trabajo personal en busca de patrones de efectividad. Mientras investigaba sobre el éxito, me encontré con algo sorprendente: durante los primeros 150 años de historia estadounidense, la literatura sobre el éxito se centraba en la ética del carácter.

Esta literatura enseñaba que había principios básicos de vida efectiva y que las personas solo podían experimentar verdadero éxito y felicidad si aprendían esos principios y los integraban en su carácter básico.

Después de la Primera Guerra Mundial, la manera básica de ver el éxito cambió de la ética del carácter a la ética de la personalidad. El éxito se convirtió más en función de la personalidad, de la imagen pública, de actitudes y conductas, habilidades y técnicas.

### El paradigma del carácter

La ética del carácter enseñaba que había principios básicos como integridad, humildad, fidelidad, templanza, coraje, justicia, paciencia, diligencia, simplicidad y modestia.

Por otro lado, la ética de la personalidad es esencialmente dos caminos: uno de técnicas en las relaciones humanas e influencia pública, y otro de actitud mental positiva.

Sin embargo, algunas de estas filosofías de personalidad parecían manipuladoras, incluso engañosas. Alentaban a usar técnicas para gustar a otras personas, o fingir interés en los hobbies de otros para conseguir lo que uno quiere de ellos.

### Importancia de los paradigmas

Los paradigmas son poderosos porque crean los lentes a través de los cuales vemos el mundo. Si queremos hacer cambios pequeños en nuestras vidas, quizás podamos enfocarnos en nuestras actitudes y conductas. Pero si queremos hacer cambios significativos, tenemos que trabajar en nuestros paradigmas básicos.

