## HÁBITO 2: EMPIECE CON UN FIN EN MENTE

Este hábito se basa en el principio de que todas las cosas son creadas dos veces. Hay una creación mental, primera, y una creación física, segunda.

### La creación mental

Para comenzar con el fin en mente significa empezar con una clara comprensión de tu destino. Significa saber a dónde vas para que comprendas mejor dónde estás ahora y para que los pasos que des siempre sean en la dirección correcta.

Es increíblemente fácil quedar atrapado en una trampa de actividad, en el ajetreo de la vida, trabajar más y más duro para subir la escalera del éxito solo para descubrir que está apoyada contra la pared equivocada.

### Liderazgo y administración

La administración es eficiencia al subir la escalera del éxito. El liderazgo determina si la escalera está apoyada contra la pared correcta.

Podemos estar muy ocupados, podemos ser muy eficientes, pero también seremos verdaderamente efectivos solo cuando empecemos con el fin en mente.

### El enunciado de misión personal

Un enunciado de misión personal es una constitución personal, la base sólida desde la cual desarrollas tu vida. Te da una medida mediante la cual puedes medir todo lo demás en tu vida.

Para escribir un enunciado de misión personal, debes empezar en el centro mismo de tu círculo de influencia, ese centro compuesto de tus paradigmas más básicos.

Un buen enunciado de misión tiene las siguientes características:
- Representa los valores más profundos
- Es la visión y los valores que guiarán tu vida
- Aborda las necesidades físicas, sociales, mentales y espirituales

### Centros alternativos

Algunas personas están centradas en el cónyuge, la familia, el dinero, el trabajo, las posesiones, el placer, el enemigo, la iglesia o uno mismo. Cada uno de estos centros tiene limitaciones serias.

El centro de principios es el único centro que proporciona seguridad, guía, sabiduría y poder.

