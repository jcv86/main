## PARTE UNO: TÉCNICAS FUNDAMENTALES PARA TRATAR CON LAS PERSONAS

### PRINCIPIO 1: NO CRITIQUE, NO CONDENE, NO SE QUEJE

La crítica es fútil porque pone a una persona a la defensiva y usualmente hace que se esfuerce para justificarse. La crítica es peligrosa, porque hiere el orgullo precioso de una persona, lastima su sentido de importancia, y crea resentimiento.

B.F. Skinner, el psicólogo mundialmente famoso, probó a través de sus experimentos que un animal recompensado por buena conducta aprenderá mucho más rápido y retendrá lo que aprende mucho más efectivamente que un animal castigado por mala conducta.

Lo mismo aplica a humanos. Criticando, no hacemos cambios duraderos y a menudo incurrimos en resentimiento.

### La historia de Al Capone

Al Capone, el enemigo público más temido de Chicago, no se consideraba a sí mismo malo. En sus palabras: He pasado los mejores años de mi vida dando placer ligero, ayudando a las personas a tener un buen tiempo, y todo lo que consigo es abuso, la existencia de un hombre perseguido.

Eso era lo que Capone pensaba de sí mismo. Si Al Capone no se culpaba a sí mismo por nada, qué hay de las personas con quienes tú y yo estamos en contacto?

### La historia de Lincoln

Abraham Lincoln aprendió esta valiosa lección duramente. Como un joven abogado en Illinois, se deleitaba en criticar abiertamente a la oposición. Una vez incluso escribió una carta ridiculizando a un político vanidoso. Lincoln la dejó caer en un camino donde el político seguramente la encontraría.

El resultado fue una pelea de duelo físico. Lincoln aprendió de esta experiencia amarga una lección inolvidable en el arte de lidiar con las personas. Nunca más escribió una carta insultante. Nunca más ridiculizó a nadie.

### El principio

En lugar de condenar a las personas, tratemos de entenderlas. Tratemos de descubrir por qué hacen lo que hacen. Eso es mucho más provechoso y fascinante que la crítica; y genera simpatía, tolerancia y amabilidad.

Saber todo es perdonar todo. Como dice el Dr. Johnson: Dios mismo no propone juzgar al hombre hasta el fin de sus días. Entonces, por qué deberíamos tú y yo?

