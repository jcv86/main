### PRINCIPIO 3: RECUERDE QUE EL NOMBRE DE UNA PERSONA ES PARA ESA PERSONA EL SONIDO MÁS DULCE E IMPORTANTE

Jim Farley descubrió temprano en la vida que la persona promedio está más interesada en su propio nombre que en todos los otros nombres en la tierra juntos.

Recordar ese nombre y llamarlo fácilmente es un cumplido sutil pero muy efectivo. Pero olvidar o deletrear mal ese nombre te pone en una desventaja muy real.

### El poder de recordar nombres

Andrew Carnegie recordaba los nombres de miles de empleados. Theodore Roosevelt recordaba los nombres de miles de votantes. Napoleón se enorgullecía de su habilidad para recordar los nombres de cada persona que conocía.

### Cómo recordar nombres

Si quieres recordar el nombre de una persona, tómate tiempo para aprender a deletrearlo correctamente, repetirlo varias veces en la conversación, y asociarlo con las características físicas de la persona.

