## PARTE TRES: CÓMO GANAR A LAS PERSONAS A TU MANERA DE PENSAR

### PRINCIPIO 1: LA ÚNICA MANERA DE SACAR LO MEJOR DE UN ARGUMENTO ES EVITARLO

Nueve de cada diez veces, un argumento termina con cada participante más firmemente convencido que nunca de que tiene absolutamente la razón.

No puedes ganar un argumento. No puedes porque si lo pierdes, lo pierdes; y si lo ganas, lo pierdes. Por qué? Bien, supón que triunfas sobre el otro hombre y haces pedazos sus argumentos y pruebas que no sabe de qué está hablando. Entonces qué? Te sentirás bien. Pero qué hay de él? Le has hecho sentir inferior. Has herido su orgullo.

### Cómo evitar argumentos

1. Acepta el desacuerdo como una oportunidad de aprender
2. Desconfía de tu primera reacción instintiva
3. Controla tu temperamento
4. Escucha primero
5. Busca áreas de acuerdo
6. Sé honesto sobre los errores
7. Promete pensar y estudiar las ideas de tu oponente
8. Agradece sinceramente a tus oponentes
9. Pospón la acción para dar tiempo a ambos lados de pensar

