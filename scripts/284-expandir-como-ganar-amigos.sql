**Por Dale Carnegie**

## PREFACIO

Este libro creció de la experiencia de enseñar a adultos. Durante más de un cuarto de siglo, he conducido cursos educacionales para hombres y mujeres de negocios y profesionales en Nueva York.

Al principio, conduje cursos solo en oratoria pública. Pero gradualmente me di cuenta de que estos adultos necesitaban desesperadamente entrenamiento en el arte de llevarse bien con las personas.

## PARTE UNO: TÉCNICAS FUNDAMENTALES

### PRINCIPIO 1: NO CRITIQUE, NO CONDENE, NO SE QUEJE

La crítica es fútil porque pone a una persona a la defensiva. La crítica es peligrosa porque hiere el orgullo y crea resentimiento.

B.F. Skinner probó que un animal recompensado por buena conducta aprende mucho más rápido que un animal castigado por mala conducta. Lo mismo aplica a humanos.

**La historia de Al Capone:** Al Capone no se consideraba malo. Decía haber pasado los mejores años de su vida ayudando a las personas a tener un buen tiempo.

**La historia de Lincoln:** Abraham Lincoln aprendió duramente esta lección. Como joven abogado, se deleitaba en criticar abiertamente. Una vez escribió una carta ridiculizando a un político. El resultado fue casi un duelo físico. Nunca más escribió una carta insultante.

**Principio:** En lugar de condenar, tratemos de entender. Descubramos por qué hacen lo que hacen. Eso genera simpatía, tolerancia y amabilidad.

### PRINCIPIO 2: DÉ APRECIO HONESTO Y SINCERO

Hay solo una manera de conseguir que alguien haga algo: haciendo que la otra persona quiera hacerlo.

Freud dijo que todo surge de dos motivos: el impulso sexual y el deseo de ser grande. John Dewey dijo que el impulso más profundo en la naturaleza humana es el deseo de ser importante.

**El deseo de importancia:** William James dijo que el principio más profundo es el anhelo de ser apreciado. Este deseo diferencia a la humanidad de los animales.

**Gratificar este deseo:** Los seres humanos anhelan apreciación. Es el don más necesitado y menos dado. Explica por qué la gente valora sus genealogías, diplomas, medallas y honores.

**Diferencia entre apreciación y adulación:** Apreciación es sincera y viene del corazón. Adulación es insincera y sale de la boca. Una es desinteresada, la otra egoísta.

**Principio:** Demos aprecio honesto y sincero. Seamos de corazón en nuestra aprobación y pródigos en nuestra alabanza.

### PRINCIPIO 3: DESPIERTE UN DESEO ARDIENTE

La única manera de influenciar a otras personas es hablar sobre lo que ellos quieren y mostrarles cómo conseguirlo.

**Henry Ford:** Si hay algún secreto del éxito, reside en la capacidad de obtener el punto de vista de la otra persona y ver las cosas desde ese ángulo.

**El arte de persuadir:** La auto expresión es la necesidad dominante. Cuando tenemos una idea brillante, dejemos que otros la cocinen. Entonces la considerarán su propia idea.

## PARTE DOS: SEIS FORMAS DE AGRADAR

### PRINCIPIO 1: INTERÉSESE GENUINAMENTE EN OTROS

Puedes hacer más amigos en dos meses interesándote en otras personas que en dos años tratando de que se interesen en ti.

**Interés genuino:** Si queremos hacer amigos, hagamos algo por otras personas, cosas que requieren tiempo, energía y consideración.

**Las personas están más interesadas en sí mismas:** Si estás interesado solo en ti, siempre lo estarás. Pero si genuinamente te interesas en otros, harás amigos reales rápidamente.

Alfred Adler escribió: El individuo que no está interesado en sus semejantes tiene las mayores dificultades en la vida.

### PRINCIPIO 2: SONRÍA

Las acciones hablan más que las palabras. Una sonrisa dice: Me gustas. Me haces feliz. Me alegro de verte.

**El valor de una sonrisa:** Una sonrisa no cuesta nada pero crea mucho. Enriquece a quienes reciben sin empobrecer a quienes dan.

**Sonríe incluso sin ganas:** Si gruñes, recibes gruñidos. Si sonríes, recibes sonrisas. Tu actitud hacia otros te es devuelta.

### PRINCIPIO 3: RECUERDE LOS NOMBRES

El nombre de una persona es para ella el sonido más dulce e importante en cualquier idioma.

**El poder de recordar nombres:** Andrew Carnegie recordaba miles de nombres de empleados. Theodore Roosevelt recordaba miles de votantes. Napoleón se enorgullecía de recordar cada nombre.

**Cómo recordar:** Tómate tiempo para deletrearlo correctamente, repítelo varias veces, y asócialo con características físicas.

### PRINCIPIO 4: SEA BUEN OYENTE

Si quieres ser buen conversador, sé un oyente atento. Para ser interesante, sé interesado. Haz preguntas que otros disfruten responder.

**La importancia de escuchar:** Muchas personas no logran impresionar porque no escuchan atentamente. Están tan preocupados con lo que dirán que no mantienen sus oídos abiertos.

**El arte de conversar:** Lincoln fue uno de los más grandes conversadores porque fue uno de los más grandes oyentes. Escuchaba con gran interés.

### PRINCIPIO 5: HABLE DE SUS INTERESES

El camino al corazón es hablar sobre las cosas que atesoran más.

Theodore Roosevelt, cuando esperaba un visitante, se quedaba despierto leyendo sobre el tema en que su invitado estaba particularmente interesado.

### PRINCIPIO 6: HAGA QUE SE SIENTAN IMPORTANTES

Siempre haz que la otra persona se sienta importante, y hazlo sinceramente.

**El principio:** El deseo de importancia es fundamental como la comida o el sueño.

**Cómo hacerlo:** Pequeñas frases como lo siento molestarte, serías tan amable, por favor, gracias. Estas cortesías hacen funcionar la civilización.

## PARTE TRES: CÓMO GANAR A OTROS

### PRINCIPIO 1: EVITE ARGUMENTOS

Nueve de cada diez veces, un argumento termina con cada uno más convencido de que tiene razón.

No puedes ganar un argumento. Si lo pierdes, lo pierdes. Si lo ganas, también lo pierdes porque hieres el orgullo del otro.

**Cómo evitarlos:**
1. Acepta el desacuerdo como oportunidad
2. Desconfía de tu primera reacción
3. Controla tu temperamento
4. Escucha primero
5. Busca áreas de acuerdo
6. Sé honesto sobre errores
7. Promete pensar en las ideas del otro
8. Agradece sinceramente
9. Pospón la acción

### PRINCIPIO 2: RESPETE LAS OPINIONES

Nunca digas estás equivocado. Si vas a probar algo, hazlo sutilmente.

Es mejor comenzar diciendo: Pensé de otra manera, pero puedo estar equivocado. Frecuentemente lo estoy. Si estoy equivocado, quiero ser corregido.

### PRINCIPIO 3: ADMITA SUS ERRORES

Cuando estés equivocado, admítelo rápida y enfáticamente. Di sobre ti todas las cosas negativas que el otro está pensando, antes de que tenga oportunidad de decirlo.

**El poder de la auto-crítica:** Hay satisfacción en admitir errores. Limpia el aire de culpa y ayuda a resolver el problema.

### PRINCIPIO 4: COMIENCE AMIGABLEMENTE

Si vienes con puños cerrados, los míos se cerrarán más rápido. Pero si vienes a discutir amigablemente, llegaremos a un acuerdo.

**La amabilidad gana:** Una gota de miel atrapa más moscas que un galón de hiel. Si quieres ganar a alguien, convéncelo primero de que eres su amigo sincero.

### PRINCIPIO 5: CONSIGA QUE DIGA SÍ

Al hablar, no comiences discutiendo diferencias. Comienza enfatizando cosas en que están de acuerdo.

**Técnica socrática:** Sócrates hacía preguntas con las que su oponente estaría de acuerdo. Seguía ganando admisiones hasta tener una pila de síes.

### PRINCIPIO 6: DEJE QUE HABLEN

La mayoría habla demasiado tratando de convencer. Deja que la otra persona hable. Ellos saben más sobre su negocio que tú.

Si no estás de acuerdo, puedes estar tentado a interrumpir. No lo hagas. Es peligroso. No te prestarán atención mientras tengan ideas gritando por expresión.

### PRINCIPIO 7: DEJE QUE LA IDEA SEA SUYA

Nadie gusta sentir que se le está vendiendo algo. Preferimos sentir que compramos por voluntad propia o actuamos en nuestras propias ideas.

Es más sabio hacer sugerencias y dejar que el otro piense en la conclusión. Las personas tienen más fe en ideas que descubren por sí mismas.

### PRINCIPIO 8: VEA SU PUNTO DE VISTA

Otras personas pueden estar totalmente equivocadas. Pero no piensan eso. No las culpes. Trata de entenderlas.

**La empatía es poderosa:** El éxito en lidiar con personas depende de un entendimiento simpático de su perspectiva.

### PRINCIPIO 9: SEA SIMPÁTICO

La mayoría anhela simpatía. Los niños muestran heridas para ganar simpatía abundante.

Con adultos igual. Si quieres ganar personas, comienza: No te culpo por sentirte así. Si yo estuviera en tu lugar, me sentiría exactamente como tú.

### PRINCIPIO 10: APELE A MOTIVOS NOBLES

Una persona tiene dos razones para hacer algo: una que suena bien y una real.

Todos, siendo idealistas de corazón, gustan de pensar en motivos nobles. Para cambiar personas, apela a los motivos más nobles.

### PRINCIPIO 11: DRAMATICE SUS IDEAS

Meramente declarar una verdad no es suficiente. La verdad tiene que ser hecha vívida, interesante, dramática. Usa el espectáculo.

### PRINCIPIO 12: LANCE UN DESAFÍO

El estimulante en todos los trabajadores es el trabajo mismo. Si el trabajo es emocionante e interesante, el trabajador lo disfruta.

Charles Schwab lanzaba desafíos. Ese es el camino que funciona.

