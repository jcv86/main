### PRINCIPIO 2: MUESTRE RESPETO POR LAS OPINIONES DE LA OTRA PERSONA. NUNCA DIGA ESTÁS EQUIVOCADO

Si vas a probar algo, no dejes que nadie lo sepa. Hazlo tan sutilmente, tan hábilmente que nadie pensará que lo estás haciendo.

Nunca comiences anunciando: Te voy a probar tal y tal cosa. Eso es malo. Eso es equivalente a decir: Soy más inteligente que tú. Voy a decirte una o dos cosas y te haré cambiar de opinión.

### El respeto por las opiniones

Si alguien hace una declaración que piensas que está equivocada, sí, incluso que sabes que está equivocada, es mucho mejor comenzar diciendo: Bien, ahora, mira, pensé de otra manera, pero puedo estar equivocado. Frecuentemente lo estoy. Y si estoy equivocado, quiero ser corregido. Examinemos los hechos.

---

### PRINCIPIO 3: SI ESTÁ EQUIVOCADO, ADMÍTALO RÁPIDA Y ENFÁTICAMENTE

Cuando estés equivocado, admítelo rápida y enfáticamente. Di sobre ti mismo todas las cosas despectivas que sabes que la otra persona está pensando o quiere decir o pretende decir, y dilo antes de que esa persona tenga la oportunidad de decirlo, y quitarás el viento de sus velas.

### El poder de la auto-crítica

Hay una cierta satisfacción en tener el coraje de admitir los propios errores. No solo limpia el aire de culpa y actitud defensiva, sino que a menudo ayuda a resolver el problema creado por el error.

