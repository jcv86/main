### PRINCIPIO 5: CONSIGA QUE LA OTRA PERSONA DIGA SÍ, SÍ INMEDIATAMENTE

Al hablar con personas, no comiences discutiendo las cosas en las que difieren. Comienza enfatizando, y sigue enfatizando, las cosas en las que están de acuerdo.

Sigue enfatizando, si es posible, que ambos están luchando por el mismo fin y que tu única diferencia es de método y no de propósito.

### La técnica socrática

Sócrates, el filósofo griego, era conocido por su técnica de hacer preguntas. Hacía preguntas con las que su oponente tendría que estar de acuerdo. Seguía ganando una admisión tras otra hasta que tuvo una pila de síes.

