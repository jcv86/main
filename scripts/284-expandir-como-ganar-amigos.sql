### PRINCIPIO 12: LANCE UN DESAFÍO

Eso fue lo que hizo Charles Schwab. El estimulante en todos los trabajadores, el que inspira al ordinario a alcanzar logros por encima de lo ordinario es el trabajo mismo. Si el trabajo es emocionante e interesante, el trabajador lo mira hacia adelante y disfruta hacerlo.

Charles Schwab tenía una manera de estimular a las personas. Se llama: lanza un desafío. Ese es el camino que trabaja.

