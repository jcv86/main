### PRINCIPIO 2: DÉ APRECIO HONESTO Y SINCERO

Hay solo una manera bajo el cielo alto para conseguir que alguien haga algo. Alguna vez paraste a pensar en eso? Sí, solo una manera. Y eso es haciendo que la otra persona quiera hacerlo.

El famoso psicólogo Sigmund Freud dijo que todo lo que haces surge de dos motivos: el impulso sexual y el deseo de ser grande.

John Dewey, uno de los filósofos más profundos de América, formuló un poco diferente. Dr. Dewey dijo que el impulso más profundo en la naturaleza humana es el deseo de ser importante.

### El deseo de importancia

William James dijo: El principio más profundo en la naturaleza humana es el anhelo de ser apreciado.

Este deseo de ser importante es lo que diferencia a la humanidad de los animales. Es el impulso que ha sido responsable de la civilización misma.

Sin este deseo ardiente de importancia, la civilización habría sido imposible. Sin él, no tendríamos las grandes figuras de la historia.

### Cómo gratificar este deseo

Los seres humanos anhelan apreciación. Es el don más necesitado, no dado. El deseo profundo por la apreciación explica por qué la gente está tan ansiosa de sus genealogías, sus diplomas universitarios, sus medallas y honores.

Es por eso que millonarios coleccionan pinturas de medio millón de dólares, por eso puentes y estaciones de tren y bibliotecas llevan nombres de donantes, por eso cada editor estadounidense publica mil y un libros nuevos cada año.

### La diferencia entre apreciación y adulación

Apreciación es sincera. Adulación es insincera. Una es admirada universalmente; la otra es universalmente condenada.

Una viene del corazón; la otra sale de la boca. Una es desinteresada; la otra es egoísta. Una es admirada universalmente; la otra es universalmente condenada.

### El principio

Intentemos no pensar en nuestros logros, nuestros deseos. Tratemos de descubrir lo bueno de la otra persona. Luego olvidemos la adulación. Demos aprecio honesto, sincero.

Sé de corazón en tu aprobación y pródigo en tu alabanza, y las personas atesorarán tus palabras y las valorarán y las repetirán toda una vida.

