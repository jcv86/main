### PRINCIPIO 4: COMIENCE DE UNA MANERA AMIGABLE

Si vienes a mí con tus puños cerrados, creo que puedo prometerte que los míos se cerrarán más rápido que los tuyos. Pero si vienes a mí y dices: Sentémonos y discutamos, y si estamos en desacuerdo, entendamos por qué estamos en desacuerdo, qué es lo que estamos en desacuerdo, lo más probable es que lleguemos a un acuerdo.

### La amabilidad gana

Es un viejo y verdadero dicho que una gota de miel atrapa más moscas que un galón de hiel. Entonces con los hombres, si quieres ganar a un hombre a tu causa, primero convéncelo de que eres su amigo sincero.

