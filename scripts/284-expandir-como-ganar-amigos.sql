## PARTE DOS: SEIS FORMAS DE AGRADAR A LAS PERSONAS

### PRINCIPIO 1: VUÉLVASE GENUINAMENTE INTERESADO EN OTRAS PERSONAS

Puedes hacer más amigos en dos meses volviéndote interesado en otras personas que lo que puedes en dos años tratando de conseguir que otras personas se interesen en ti.

### El principio del interés genuino

Si queremos hacer amigos, pongámonos a hacer algo por otras personas, cosas que requieren tiempo, energía, desinterés y consideración.

Cuando el Duque de Windsor era Príncipe de Gales, estaba programado hacer un tour a Sudamérica, y antes de comenzar, pasó meses estudiando español para que pudiera hacer discursos públicos en el lenguaje de los países que visitaba.

### Las personas están más interesadas en sí mismas

Si estás interesado solo en ti mismo, siempre estarás interesado solo en ti mismo. Pero si genuinamente estás interesado en otras personas, harás amigos reales en dos meses.

Alfred Adler, el famoso psicólogo vienés, escribió: El individuo que no está interesado en sus semejantes humanos es quien tiene las mayores dificultades en la vida y proporciona las mayores lesiones a otros.

---

### PRINCIPIO 2: SONRÍA

Las acciones hablan más fuerte que las palabras, y una sonrisa dice: Me gustas. Me haces feliz. Me alegro de verte.

### El valor de una sonrisa

Una sonrisa no cuesta nada, pero crea mucho. Enriquece a quienes reciben, sin empobrecer a quienes dan. Sucede en un destello y la memoria a veces dura para siempre.

Nadie es tan rico que pueda pasar sin ella y nadie tan pobre que no pueda ser enriquecido por sus beneficios.

### Sonríe incluso cuando no tengas ganas

Todos saben que cuando dos perros se encuentran, si uno mueve su cola, el otro también lo hará. Pero si uno gruñe, el otro también gruñirá.

Lo mismo aplica a los encuentros humanos. Tu actitud y acción hacia otras personas te son devueltas. Si gruñes, recibes gruñidos. Si sonríes, recibes sonrisas.

