### PRINCIPIO 3: DESPIERTE EN LA OTRA PERSONA UN DESEO ARDIENTE

Por qué hablar de lo que queremos? Eso es infantil. Absurdo. Por supuesto, estás interesado en lo que quieres. Siempre estás interesado en lo que quieres. Pero nadie más lo está. El resto de nosotros somos como tú: estamos interesados en lo que queremos.

Entonces la única manera en la tierra de influenciar a otras personas es hablar sobre lo que ellos quieren y mostrarles cómo conseguirlo.

### El principio de Henry Ford

Si hay algún secreto del éxito, reside en la capacidad de obtener el punto de vista de la otra persona y ver las cosas desde ese ángulo así como desde el tuyo.

### El arte de persuadir

La auto expresión es la necesidad dominante de la naturaleza humana. Por qué no adoptamos la misma psicología en los negocios? Cuando tenemos una idea brillante, en lugar de hacer que la otra persona piense que es nuestra, por qué no dejarlos cocinarla y recogerla? Entonces la considerarán su propia idea; les gustará, y tal vez se coman un par de porciones.

### Acciones hablan

Recuerda: primero, despertar en la otra persona un deseo ansioso. Quien puede hacer esto tiene al mundo entero con él. Quien no puede, camina un camino solitario.

