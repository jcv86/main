Napoleón creó la Legión de Honor y distribuyó 15,000 cruces a sus soldados e hizo dieciocho generales Mariscales de Francia.

Napoleón fue criticado por dar juguetes a veteranos, pero respondió: Los hombres son gobernados por juguetes.

