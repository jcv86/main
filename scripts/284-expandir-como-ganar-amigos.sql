No es difícil escuchar un recuento de tus faltas si la persona crítica comienza humildemente admitiendo que ella también está lejos de ser impecable.

### PRINCIPIO 4: HAGA PREGUNTAS

Hacer preguntas no solo hace la orden más palatable; estimula la creatividad. Las personas aceptan mejor una orden si han tenido parte en la decisión.

### PRINCIPIO 5: PERMITA SALVAR LA CARA

General Electric removió a Charles Steinmetz de la cabeza del departamento. Steinmetz era un genio en electricidad pero un fracaso como jefe.

La compañía no se atrevía a ofenderle. Le dieron un nuevo título: ingeniero consultor, y permitieron que otro encabezara el departamento.

### PRINCIPIO 6: ELOGIE CADA MEJORA

Todos anhelamos apreciación y reconocimiento, y haremos casi cualquier cosa para conseguirlo. Pero nadie quiere adulación.

Las habilidades se marchitan bajo la crítica y florecen bajo el estímulo. Sé de corazón en tu aprobación y pródigo en tu alabanza.

### PRINCIPIO 7: DÉ UNA BUENA REPUTACIÓN

Si quieres mejorar a alguien en un respecto, actúa como si ese rasgo ya fuera una de sus características sobresalientes.

Asume y declara abiertamente que la otra persona tiene el rasgo que quieres que desarrolle. Dale una reputación fina para vivir según.

### PRINCIPIO 8: USE ALIENTO

Decirle a alguien que es estúpido o tonto destruye casi todo incentivo de mejorar.

Usa el enfoque opuesto: sé liberal con el aliento. Haz que la cosa parezca fácil de hacer. Deja que la otra persona sepa que tienes fe en su habilidad.

