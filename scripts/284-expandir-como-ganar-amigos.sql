### PRINCIPIO 4: SEA UN BUEN OYENTE. ANIME A OTROS A HABLAR DE SÍ MISMOS

Si quieres ser un buen conversador, sé un oyente atento. Para ser interesante, sé interesado. Haz preguntas que otras personas disfrutarán responder. Anímalos a hablar de sí mismos y sus logros.

### La importancia de escuchar

Isaac F. Marcosson, un maestro entrevistador, una vez comentó: Muchas personas no logran hacer una impresión favorable porque no escuchan atentamente. Están tan preocupados con lo que van a decir a continuación que no mantienen sus oídos abiertos.

### El arte de la conversación

La conversación exclusiva es un arte. Lincoln fue uno de los más grandes conversadores porque fue uno de los más grandes oyentes. Escuchó atentamente y con gran interés.

---

### PRINCIPIO 5: HABLE EN TÉRMINOS DE LOS INTERESES DE LA OTRA PERSONA

El camino real al corazón de una persona es hablar sobre las cosas que él o ella atesora más.

Theodore Roosevelt sabía la importancia de este principio. Siempre que Roosevelt esperaba un visitante, se quedaba despierto tarde la noche anterior leyendo sobre el tema en el que sabía que su invitado estaba particularmente interesado.

### Encuentra el interés de la otra persona

Todas las personas que conoces son superiores a ti en alguna manera. En esa manera, aprende de ellas. Descubre qué les interesa y háblales sobre eso.

---

### PRINCIPIO 6: HAGA QUE LA OTRA PERSONA SE SIENTA IMPORTANTE, Y HÁGALO SINCERAMENTE

Siempre haz que la otra persona se sienta importante. Jesús lo dijo: Haz a otros lo que te gustaría que te hicieran a ti.

### El principio de la importancia

El deseo de importancia es uno de los principales distintivos de la raza humana. Es el deseo que los diferencia de los animales. Es una necesidad humana tan fundamental como la comida o el sueño.

### Cómo hacer que otros se sientan importantes

Pequeñas frases como: Lo siento molestarte, Serías tan amable, Quieres por favor, Gracias, estas pequeñas cortesías hacen funcionar la maquinaria de la civilización.

