Siempre es más fácil escuchar cosas desagradables después de haber escuchado alabanza de nuestros buenos puntos.

Un barbero jabona a un hombre antes de afeitarlo. McKinley siempre comenzaba con algo que Roosevelt había hecho bien antes de mencionar algo desagradable.

