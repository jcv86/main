### PRINCIPIO 6: DEJE QUE LA OTRA PERSONA HAGA UNA GRAN PARTE DEL HABLA

La mayoría de las personas tratando de ganar a otros a su manera de pensar hacen demasiado hablar ellos mismos. Deja que la otra persona hable. Ellos saben más sobre su negocio y problemas que tú. Así que hazles preguntas. Déjalos decirte algunas cosas.

Si no estás de acuerdo con ellos, puedes estar tentado a interrumpir. Pero no lo hagas. Es peligroso. No te prestarán atención mientras todavía tengan una gran cantidad de ideas propias gritando por expresión.

---

### PRINCIPIO 7: DEJE QUE LA OTRA PERSONA SIENTA QUE LA IDEA ES DE ELLA

Nadie gusta sentir que se le está vendiendo algo o diciéndole que haga una cosa. Preferimos mucho más sentir que estamos comprando por nuestra propia voluntad o actuando en nuestras propias ideas.

Es mucho más sabio hacer sugerencias y dejar que la otra persona piense en la conclusión. Las personas tienen mucha más fe en ideas que descubren por sí mismas que en ideas que se les sirven en una bandeja de plata.

---

### PRINCIPIO 8: TRATE HONESTAMENTE DE VER LAS COSAS DESDE EL PUNTO DE VISTA DE LA OTRA PERSONA

Recuerda que otras personas pueden estar totalmente equivocadas. Pero no piensan eso. No las culpes. Solo las personas tontas hacen eso. Trata de entenderlas. Hay una razón por la que la otra persona piensa y actúa como lo hace. Ferreta esa razón oculta, y tienes la clave para sus acciones, tal vez para su personalidad.

### La empatía es poderosa

Cooperar en conversación es alcanzar eso sinceramente, honestamente tratando de ver las cosas desde el punto de vista de la otra persona. El éxito en lidiar con personas depende de un entendimiento simpático de la perspectiva de la otra persona.

---

### PRINCIPIO 9: SEA SIMPÁTICO CON LAS IDEAS Y DESEOS DE LA OTRA PERSONA

La mayoría de las personas anhelan simpatía. Los niños ansiosamente muestran sus heridas, incluso se cortan o magullan ellos mismos para ganar abundante simpatía.

Así con adultos. Si quieres ganar personas a tu manera de pensar, este es el modo de comenzar: Yo no te culpo ni un poquito por sentirte como lo haces. Si yo estuviera en tu lugar, no dudo que me sentiría exactamente como tú.

---

### PRINCIPIO 10: APELE A LOS MOTIVOS MÁS NOBLES

J. Pierpont Morgan observó en uno de sus perspicaces intercambios analíticos: Una persona usualmente tiene dos razones para hacer una cosa: una que suena bien y una real.

La persona misma pensará sobre la razón real. No necesitas enfatizar eso. Pero todos, siendo idealistas de corazón, gustan de pensar en motivos que suenan bien. Entonces, para cambiar personas, apela a los motivos más nobles.

---

### PRINCIPIO 11: DRAMATICE SUS IDEAS

Meramente declarar una verdad no es suficiente. La verdad tiene que ser hecha vívida, interesante, dramática. Tienes que usar el espectáculo. Las películas lo hacen. La televisión lo hace. Y tendrás que hacerlo si quieres atención.

